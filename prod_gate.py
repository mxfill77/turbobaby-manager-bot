import curator_claim
import curator_ops

# Метку ставит демон задаче доставки, читает `gate.py`. Имя в окружении, а не в тексте команды:
# окружение наследуется всеми детьми задачи, поэтому «забыть правило» исполнитель не может —
# гейт узнает о доставке сам, чем бы его ни позвали.
ENV_MARK = "CC_PROD_DELIVERY"
REASON_FLAG = "--selective-reason"

# Зеркало `orchestrator_daemon._CONVERT_MARK` (сверяется тестом — разойтись молча не должны).
CONVERT_HEAD = "[конверт одобренной заявки"
# Зеркало ключа семьи `curator_ops` («service:<юнит>») — перезапуск живого сервиса.
SERVICE_KEY_PREFIX = "service:"

# Ярлыки операции (`gate.py --for <op>`), которые САМИ называют доставку в прод. Нужны для двери
# без окружения демона (интерактив владельца, cron). Замер живого корпуса: `--for` вообще назван
# трижды — `restart_splinter` дважды и `push` один раз, — поэтому список НЕ задевает ничего, что
# работает сегодня. `push` и умолчание `prod` сюда НЕ входят намеренно: ими идут почти все живые
# прогоны, и они не перезапускают процесс.
_DELIVERY_OP_WORDS = ("restart", "рестарт", "перезапуск", "deliver", "доставк")

# Пустая причина правом не является. Отвергаем ровно заполнители — качество не судим.
_EMPTY_REASONS = {"", "-", "--", "—", ".", "..", "...", "?", "нет", "n/a", "na", "none", "tbd",
                  "причина", "без причины", "0"}


def service_ops(text):
    """Текст → семьи «перезапуск живого сервиса», названные ЗАЯВКОЙ (не под отрицанием).

    Связка ровно та, которой демон разводит кураторский пункт (`_curator_human_place`):
    occurrences → filter_claims → dedup. Своей копии правил здесь нет намеренно.
    """
    t = str(text or "")
    occs = curator_ops.occurrences(t)
    kept, _demoted = curator_claim.filter_claims(t, occs)
    return [o["key"] for o in curator_ops.dedup(kept)
            if str(o.get("key", "")).startswith(SERVICE_KEY_PREFIX)]


def is_convert(text):
    """Строка задачи — конверт одобренной заявки? Маркер обязан стоять ПЕРВЫМ (правило позиции:
    цитата маркера в прозе конвертом не делает — тот же приём, что у `_CONVERT_RE` демона)."""
    return str(text or "").lstrip().startswith(CONVERT_HEAD)


def is_delivery(text):
    """ТЗ задачи → это путь ДОСТАВКИ В ПРОД? (конверт + названный перезапуск живого сервиса).

    Fail-closed ВНУТРИ конвертов: конверт есть, а разбор операций упал → True (полный набор
    дешевле, чем прод по частичному). Не-конверт → False при любой ошибке: обычный заход не
    задеваем даже падением классификатора.
    """
    if not is_convert(text):
        return False
    try:
        return bool(service_ops(text))
    except Exception:                                                # noqa: BLE001
        return True                                                  # сомнение → полный набор


def why_delivery(text):
    """Человеческая строка «почему это доставка» для журнала демона | None."""
    try:
        if not is_convert(text):
            return None
        ops = service_ops(text)
        if not ops:
            return None
        return "конверт одобренной заявки называет перезапуск: " + ", ".join(ops)
    except Exception:                                                # noqa: BLE001
        return "конверт одобренной заявки; разбор операций не удался — считаю доставкой"


def env_says_delivery(env):
    """Окружение прогона гейта говорит «это задача доставки»? (метку ставит демон)."""
    try:
        return str((env or {}).get(ENV_MARK) or "").strip() == "1"
    except Exception:                                                # noqa: BLE001
        return False


def op_is_delivery(op):
    """Ярлык операции (`--for`) сам называет доставку в прод? `push`/`prod` — нет."""
    o = str(op or "").strip().lower()
    if not o or o in ("prod", "push"):
        return False
    return any(w in o for w in _DELIVERY_OP_WORDS)


def reason_named(reason):
    """Причина названа? Пусто/пробелы/заполнитель → нет (замок «пустая причина права не даёт»)."""
    if reason is None:
        return False
    r = " ".join(str(reason).split())
    return bool(r) and r.strip(" .,;:!—-").lower() not in _EMPTY_REASONS


def clean_reason(reason):
    """Причина в один ряд пробелов — для строки отчёта и журнала (ничего не выдумываем)."""
    return " ".join(str(reason or "").split())


def decide(delivery, selective, reason=None):
    """Факты прогона → вердикт: чем дано право и какой набор гонять.

    delivery — прогон обслуживает доставку в прод (метка демона или ярлык операции);
    selective — гейт СОБИРАЛСЯ гнать селективный набор (флаг цепи/одиночки, не финальный прогон);
    reason    — причина, названная флагом `--selective-reason`.

    Возврат: {"delivery", "authorizes", "run", "reason", "say"}.
      authorizes=False бывает РОВНО в одном случае — доставка просит права у селективного набора и
      причины не назвала; тогда `run="full"`: право не отзывается, а ЗАРАБАТЫВАЕТСЯ полным
      набором. Отказать вместо подъёма было бы хуже: доставка осталась бы вовсе без прогона.
    """
    sel = bool(selective)
    if not delivery:
        # Обычный заход — БАЙТ-В-БАЙТ прежнее поведение: набор тот, что выбрал гейт, слова нет.
        return {"delivery": False, "authorizes": True,
                "run": "selective" if sel else "full", "reason": "", "say": ""}
    if not sel:
        return {"delivery": True, "authorizes": True, "run": "full", "reason": "",
                "say": "право на доставку в прод даёт ПОЛНЫЙ набор — как и требуется."}
    if reason_named(reason):
        return {"delivery": True, "authorizes": True, "run": "selective",
                "reason": clean_reason(reason),
                "say": ("селективный набор допущен НАЗВАННОЙ причиной: «%s». Причину повтори в "
                        "отчёте и в cc_log — правом её делает видимость."
                        % clean_reason(reason))}
    return {"delivery": True, "authorizes": False, "run": "full", "reason": "",
            "say": ("СЕЛЕКТИВНЫЙ НАБОР ПРАВА НА ДОСТАВКУ В ПРОД НЕ ДАЁТ: перезапуск поднимает в "
                    "память ВЕСЬ HEAD, а не затронутые модули. Поднимаю набор до ПОЛНОГО. Если "
                    "полный здесь действительно не нужен (например, он уже зелёный на ЭТОМ "
                    "дереве и дерево не менялось) — назови причину: %s «…»." % REASON_FLAG)}
