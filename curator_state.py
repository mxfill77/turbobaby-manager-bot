"""СВЕРКА ПУНКТА КУРАТОРА С ЖИВЫМ СОСТОЯНИЕМ (11.08.2026) — чистая функция «факты → вердикт».

ПОВОД, четыре случая подряд. Конверт 437 просил «да» на перезапуск splinter, сделанный задачей
438 за 11 минут ДО нажатия. Карточка 460 просила рестарт демона через час после того, как О3
объявило расхождение диска. Карточка 463 просила удаление рабочего дерева без слова о его
содержимом. Карточка 429 просила заливку из папки, которая стёрла бы прод. Общее у всех одно:
куратор пишет владельцу о МИРЕ, ни разу этот мир не спросив — он читает отчёт задачи, а отчёт
стареет ровно с той минуты, как написан.

ПРИЗНАК ОДИН, И ЭТО НЕ ВИД ПУНКТА. Перечень видов протух бы на первом новом виде, поэтому здесь
не спрашивают «что это за пункт» — спрашивают «ПОДТВЕРДИЛ ЛИ ПРИБОР, что состояние, которого
пункт просит, уже достигнуто». Прибор — уже стоящий О3 («проверенный коммит дошёл до прода»):
пункт называет коммит, О3 говорит, живёт ли этот коммит в проде и ЧЕРЕЗ КАКОЙ процесс он туда
доехал. Операция засчитана, только если прибор САМ её назвал; всё, чего прибор не называет
(выкладка моста, живые таблицы, файл секретов, удаление файлов, любой вид, которого ещё нет), не
может быть засчитано ФИЗИЧЕСКИ — не списком, а тем, что в ответе прибора такой семьи не бывает.

ЗАМОК: «СОСТОЯЛОСЬ» ВОЗВРАЩАЕТСЯ ТОЛЬКО ПО ПОЛОЖИТЕЛЬНОМУ ПУТИ. Дырка в фактах, молчание прибора,
незасчитанная операция, отсутствие коммита, отсутствие операции — всё это НЕ «состоялось», а
значит пункт уезжает владельцу, как уезжал. Ошибка стоит лишнего вопроса; молчание стоило бы
съеденного «да», а это ровно тот класс, ради которого заведены `_HUMAN_MISSING` и дежурный.
Порядок силы взят у самого прибора (О3: «не доставлен» > «неизвестно» > «доставлен») — сомнение
не выдаётся за отрицание, отрицание не тонет в сомнении.

СЛОВАРЯ ПРИБОРА ЗДЕСЬ НЕТ НАМЕРЕННО: ответ приходит трёхзначным `ok` (True — доставлено,
False — доказанно нет, None — прибор сказать не смог), а его словами занимается рука. Так решение
не привязано к формулировкам О3 и переживёт их правку.
"""
import re

SETTLED = "состоялось"          # пункт закрывается сам, владельцу не показывается вовсе
OPEN = "не состоялось"          # прибор доказал обратное — вопрос настоящий
UNSEEN = "неизвестно"           # прибор подтвердить не смог — пункт выписывается (замок)

# Коммит в тексте пункта. Та же форма, что у `_series_commits` демона: разбирать хеш иначе, чем
# разбирает соседний счёт, значило бы завести вторую правду о том, что такое «названный коммит».
_SHA = re.compile(r"\b([0-9a-f]{7,40})\b")


def shas(text):
    """Коммиты, НАЗВАННЫЕ пунктом (в порядке появления, без повторов).

    Похожее на хеш английское слово («defaced») сюда попадёт — и это безопасно по построению:
    рука не найдёт его в origin/main, ответ придёт пустым, вердикт станет «неизвестно», то есть
    пункт уедет владельцу. Лишний вопрос — законная цена, съеденный вопрос — нет."""
    out, seen = [], set()
    for m in _SHA.finditer(str(text or "").lower()):
        s = m.group(1)
        if s not in seen:
            seen.add(s)
            out.append(s)
    return out


def verdict(ops, answers):
    """(операции пункта, ответы прибора) → {"state", "why", "credited", "shas"}.

    ops     — ключи операций, названных пунктом (`curator_ops.dedup` → 'key');
    answers — {коммит: {"ok": True|False|None, "state": <слово прибора для журнала>,
               "families": [семьи, которым прибор ЗАСЧИТАЛ доставку]}}. Ключ без словаря —
               прибор о коммите не сказал ничего.

    «Состоялось» требует ТРЁХ совпадений сразу: пункт назвал операцию, прибор назвал КАЖДЫЙ
    коммит доставленным, и КАЖДАЯ операция пункта попала в то, что прибор засчитал сам. Не сошлось
    хоть одно — пункт выписывается."""
    keys, seen = [], set()
    for k in (ops or []):
        k = str(k or "").strip()
        if k and k not in seen:
            seen.add(k)
            keys.append(k)
    if not keys:
        # Пункт без названной операции просит РЕШЕНИЕ, а не разрешение (карточки 122, 462):
        # подтверждать нечего, и выдавать это за «состоялось» нельзя ни в каком виде.
        return _out(UNSEEN, "операции в пункте не названо — подтверждать нечего", [], [])
    named = sorted(answers or {})
    if not named:
        return _out(UNSEEN, "коммита в пункте не названо — прибору не на что опереться", [], [])

    # Порядок силы прибора: доказанное отрицание сильнее дырки в фактах.
    no = [s for s in named if isinstance(answers[s], dict) and answers[s].get("ok") is False]
    if no:
        return _out(OPEN, "прибор: в проде не живёт %s (%s)"
                    % (", ".join(no), _word(answers[no[0]])), [], named)
    hole = [s for s in named if not isinstance(answers[s], dict) or answers[s].get("ok") is not True]
    if hole:
        return _out(UNSEEN, "прибор не подтвердил коммит %s (%s)"
                    % (", ".join(hole), _word(answers[hole[0]])), [], named)

    credited = set()
    for s in named:
        credited |= {str(f) for f in (answers[s].get("families") or ())}
    missing = [k for k in keys if k not in credited]
    if missing:
        # Коммит доехал, но НЕ через ту дверь, о которой просит пункт (либо семья такая, какой
        # прибор не наблюдает вовсе). Это не отрицание — это молчание прибора об ЭТОЙ операции.
        return _out(UNSEEN, "прибор не засчитал доставку операции %s (засчитано: %s)"
                    % (", ".join(missing), ", ".join(sorted(credited)) or "ничего"),
                    sorted(credited), named)
    return _out(SETTLED, "прибор подтвердил: %s уже в проде, доставка засчитана операции %s"
                % (", ".join(named), ", ".join(keys)), sorted(credited), named)


def _word(a):
    """Слово прибора о коммите — для журнала. Ответа нет вовсе → так и сказано."""
    return (str((a or {}).get("state") or "прибор промолчал")
            if isinstance(a, dict) else "прибор промолчал")


def _out(state, why, credited, named):
    return {"state": state, "why": why, "credited": list(credited), "shas": list(named)}
