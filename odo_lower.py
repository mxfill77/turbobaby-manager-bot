"""ПОНИЖЕНИЕ ПРОБЕГА ПРОХОДИТ С НАПИСАННЫМ ПОЯСНЕНИЕМ (23.08.2026, правило владельца).

ПРАВИЛО ВЛАДЕЛЬЦА (узел мозга `business_rules`, раздел «ПОНИЖЕНИЕ ПРОБЕГА 23.08.2026», прочитан
живьём этим заходом): глухой отказ отменяется — понижение возможно, но ТОЛЬКО с написанной
причиной. Пришло число меньше записанного — бот показывает расхождение ЧИСЛОМ: сколько записано,
сколько прислано, на сколько меньше. Формулировка «мост не принял запись» запрещена прямо: она
ничего не говорит человеку. Подтверждает ТОТ ЖЕ человек, который прислал число, — отдельный
подтверждающий не требуется. Пустое пояснение и односложное согласие причиной НЕ считаются.
Пояснение СОХРАНЯЕТСЯ вместе с записью и остаётся читаемым потом. Цена названа владельцем
сознательно: подтверждение автором не ловит ошибку в момент, но обязательное пояснение делает её
видимой потом — меняем предотвращение на прослеживаемость.

ЧТО БЫЛО ДО. Дверей понижения две, и обе нарушали правило с разных сторон. Мягкий гейт
(`splinter._ask_mileage_confirm`) расхождение числом показывал, но принимал РОВНО односложное
согласие — кнопку «✅ Да, намеренно» или текст «да»; причина не спрашивалась вовсе и нигде не
сохранялась. Дверь регистра (`_write_oil`) отвечала «новое N меньше прошлого M — не записал,
проверь число»: числа названы, а ДЕЙСТВИЯ нет — человеку не сказано, чем это лечится, и лечения
у него не было (ветка исправления моста существует с 04.08, но ни одна дверь её не звала).

ТРИ ПРИЧИНЫ, И ОНИ НЕ ОДИНАКОВЫ. `WRONG_NUMBER` — ошибся числом (правится ТО ЖЕ число);
`OLD_WRONG` — прежняя запись была неверной (правится ПРЕЖНЕЕ число); `ODO_REPLACED` — одометр
заменён. Третья по правилу владельца НЕ ошибка, а СОБЫТИЕ: «пробег начинается заново, это
отдельная строка истории байка, а не правка старой», — поэтому у неё `writes_history=True`, и
руки кладут строку истории вдобавок к правке регистра. Список закрытый: чужая причина причиной
не считается, иначе «прочее» стало бы дырой, через которую понижение проходит без разбора.

ЗАМОК ПРОТИВ ЛОЖНОГО ЗЕЛЁНОГО (тот же, что у О3, `write_fact` и `scan_result`): исход
`ACCEPTED` возвращается РОВНО ОДНИМ путём — текст непуст, он не односложное согласие, и в нём не
меньше `MIN_LETTERS` буквенно-цифровых знаков. Всё прочее — отказ, и КАЖДЫЙ отказ называет
действие человеку (правило 2 того же захода). Направление сомнения — В СТОРОНУ СЛОВ ЧЕЛОВЕКА:
белого списка «правильных пояснений» нет намеренно (тот же приём, что у `curator_claim`), потому
что судить качество объяснения машине нечем; судится ровно то, что правило назвало непричиной.

СЛОВАРЬ СОГЛАСИЯ — ЗЕРКАЛО `splinter._CONFIRM_YES`, и это названо ценой: второй реализации того
же смысла быть не должно, но импортировать splinter решению нечем (он тянет сеть и Telegram).
Поэтому словарь здесь ШИРЕ боевого, а тест `test_odo_lower.py` держит замок «каждое слово
`_CONFIRM_YES` ловится и здесь» — разойтись в опасную сторону (согласие прошло как пояснение)
они не могут по построению.

ПОРОГ `MIN_LETTERS` НЕ ДЕЛАЕТ ГЛАВНОЙ РАБОТЫ, и это сказано прямо: односложные согласия ловит
СЛОВАРЬ (у «правильно» девять букв — длиной его не отсечь), а порог стоит против шума вроде
«аа», «??», «1». Поэтому он низкий: любое настоящее слово его проходит.

ГРАНИЦА УСТРОЙСТВОМ: импорт РОВНО ОДИН — `re` (разобрать текст пояснения). Ни числа парка, ни
кто прислал, ни что записано — всё приносят руки (`splinter`). Будь у решения сеть, оно
спросило бы записанное число САМО, и «расхождение» снова зависело бы от того, КАК спросили;
будь у него запись — рядом с гейтом завёлся бы второй путь в живую таблицу мимо пояснения.
Проверяется разбором (ast) инвариантом `ODO_LOWER_PURE`, а не докстрингом.

Тесты `tests/test_odo_lower.py` (решение) и `tests/test_odo_lower_path.py` (путь целиком на
выдуманном байке). Артефакт `docs/artifacts/2026-08-23-never-silent-and-lower.md`.
"""
import re

#: Исходы приёмки пояснения. `ACCEPTED` — один, остальные — отказы, и каждый называет действие.
ACCEPTED = "accepted"
EMPTY = "empty"
AGREEMENT = "agreement"
TOO_SHORT = "too_short"

#: Пол пояснения в буквенно-цифровых знаках. Главную работу делает словарь согласия ниже.
MIN_LETTERS = 4

#: Односложное согласие — НЕ причина (правило владельца 23.08). Надмножество
#: `splinter._CONFIRM_YES`; замок зеркала держит тест.
AGREEMENT_WORDS = frozenset((
    "да", "ага", "агa", "угу", "верно", "правильно", "правильн", "точно", "ок", "окей", "океу",
    "конечно", "подтверждаю", "подтверждено", "согласен", "согласна", "именно", "так",
    "yes", "yep", "yeah", "ok", "okay", "sure", "right", "correct", "confirm", "confirmed",
    "ใช่", "ถูก", "ถูกต้อง", "ถูกต้องครับ", "ถูกต้องค่ะ", "ครับ", "ค่ะ", "โอเค",
))

#: Ключи причин. Список ЗАКРЫТЫЙ: чужая причина причиной не считается.
WRONG_NUMBER = "wrong_number"
OLD_WRONG = "old_wrong"
ODO_REPLACED = "odo_replaced"

#: Причина → как она называется человеку и что за собой тянет.
#: `writes_history` — правило владельца: замена одометра есть СОБЫТИЕ, а не правка старой записи.
REASONS = {
    WRONG_NUMBER: {
        "ru": "ошибся числом",
        "th": "พิมพ์เลขผิด",
        "writes_history": False,
    },
    OLD_WRONG: {
        "ru": "прежняя запись была неверной",
        "th": "ค่าที่บันทึกไว้เดิมผิด",
        "writes_history": False,
    },
    ODO_REPLACED: {
        "ru": "одометр заменён",
        "th": "เปลี่ยนมาตรวัดระยะทาง",
        "writes_history": True,
    },
}

#: Порядок показа кнопок — он же порядок правила владельца в узле мозга.
REASON_ORDER = (WRONG_NUMBER, OLD_WRONG, ODO_REPLACED)

#: Что оставляем от пояснения в строке записи. Режем ПОД потолок поля моста, а не наоборот.
EXPLANATION_MAX = 200

_WORD_SPLIT = re.compile(r"[\s,.;:!?\-—–()\[\]«»\"'`/\\|]+")
_ALNUM = re.compile(r"[^\W_]", re.UNICODE)
#: Тайские огласовки и тоны — НЕ декорация, а часть слова, хотя `\w` их не признаёт: без этой
#: оговорки «ใช่» теряет знак тона, превращается в «ใช» и проходит как пояснение. Живой случай
#: сьюта, а не предположение: замок зеркала `_CONFIRM_YES` покраснел ровно на нём.
_THAI_MARKS = "\u0e31\u0e34-\u0e3a\u0e47-\u0e4e"
#: Декорация, которую снимаем перед разбором: эмодзи, знаки, невидимые пробелы.
_STRIP_EDGE = re.compile(rf"^[^\w{_THAI_MARKS}]+|[^\w{_THAI_MARKS}]+$", re.UNICODE)


def _num(x):
    """Целое или None. Логическое числом не считается: `True` — это `true`, а не километр."""
    if isinstance(x, bool) or x is None:
        return None
    try:
        return int(str(x).replace(" ", "").replace(" ", "").replace(" ", "")
                   .replace(",", "").strip())
    except (TypeError, ValueError):
        return None


def diff(recorded, sent):
    """Расхождение ЧИСЛОМ: сколько записано, сколько прислано, на сколько меньше.

    Возвращает словарь всегда — но `lower` истинно РОВНО когда оба числа разобраны и присланное
    строго меньше записанного. Не разобрали хоть одно — `known=False`: о расхождении не заявляем
    (тот же замок, что у «неизвестно» в О3), а руки идут прежним путём."""
    old, new = _num(recorded), _num(sent)
    if old is None or new is None:
        return {"known": False, "lower": False, "recorded": old, "sent": new, "drop": None}
    return {"known": True, "lower": new < old, "recorded": old, "sent": new, "drop": old - new}


def _bare(text):
    """Текст без краевой декорации и в нижнем регистре. Пусто → пустая строка."""
    return _STRIP_EDGE.sub("", str(text or "")).strip().lower()


def _letters(text):
    """Сколько буквенно-цифровых знаков в тексте (эмодзи и знаки не в счёт)."""
    return len(_ALNUM.findall(str(text or "")))


def is_agreement(text):
    """Текст — односложное согласие? Считается СЛОВАМИ, а не подстрокой.

    «да» — согласие; «да, сменили одометр» — НЕ согласие, это пояснение, начатое с «да».
    Слово согласия внутри настоящего предложения ничего не отменяет — тот же приём позиции,
    что у `curator_claim` и правила заявляющей позиции."""
    bare = _bare(text)
    if not bare:
        return False
    words = [w for w in _WORD_SPLIT.split(bare) if w]
    if not words:
        return False
    return all(w in AGREEMENT_WORDS for w in words)


def explanation_verdict(text):
    """Письменное пояснение → исход + что сказать человеку.

    ЗАМОК: `ACCEPTED` приходит РОВНО ОДНИМ путём — непусто, не согласие, букв не меньше
    `MIN_LETTERS`. Каждый отказ несёт `say_ru`/`say_th` с ДЕЙСТВИЕМ, а не с диагнозом."""
    raw = str(text or "")
    bare = _bare(raw)
    if not bare or _letters(bare) == 0:
        return {
            "state": EMPTY, "ok": False, "text": "",
            "say_ru": ("Пояснение пустое — так понижение не пройдёт. "
                       "Напиши своими словами, что случилось с пробегом."),
            "say_th": ("ยังไม่ได้เขียนเหตุผล — ลดเลขไมล์ไม่ผ่านครับ "
                       "ช่วยพิมพ์เป็นคำพูดของคุณว่าเกิดอะไรขึ้น"),
        }
    if is_agreement(bare):
        return {
            "state": AGREEMENT, "ok": False, "text": "",
            "say_ru": ("Одного согласия мало — нужна причина словами. "
                       "Напиши, ЧТО случилось: ошибся числом, прежняя запись неверна "
                       "или заменили одометр."),
            "say_th": ("แค่ตอบว่าใช่ยังไม่พอครับ ต้องบอกเหตุผลเป็นคำพูด — "
                       "พิมพ์ผิด, ค่าเดิมผิด หรือเปลี่ยนมาตรวัด"),
        }
    if _letters(bare) < MIN_LETTERS:
        return {
            "state": TOO_SHORT, "ok": False, "text": "",
            "say_ru": (f"Слишком коротко ({_letters(bare)} знака) — я не пойму это потом. "
                       f"Напиши причину словами, хотя бы одним понятным словом."),
            "say_th": (f"สั้นเกินไป ({_letters(bare)} ตัว) — อ่านย้อนหลังแล้วไม่เข้าใจครับ "
                       f"ช่วยพิมพ์เหตุผลเป็นคำ"),
        }
    return {
        "state": ACCEPTED, "ok": True,
        "text": raw.strip()[:EXPLANATION_MAX],
        "say_ru": "", "say_th": "",
    }


def reason_ok(key):
    """Причина из закрытого списка? Чужая причина причиной не считается."""
    return str(key or "") in REASONS


def writes_history(key):
    """Эта причина обязана лечь ОТДЕЛЬНОЙ строкой истории байка?

    Только замена одометра: правило владельца называет её событием, а не правкой старой записи."""
    return bool(REASONS.get(str(key or ""), {}).get("writes_history"))


def record_line(reason_key, explanation, who=""):
    """Строка, которая уедет в запись вместе с числом и останется читаемой потом.

    Форма «<причина>: <слова человека> (кто)». Ярлык причины НЕ заменяет слова — он их
    предваряет: правило полноты истории («ярлык вместо слов запрещён») действует и здесь."""
    label = REASONS.get(str(reason_key or ""), {}).get("ru") or "причина не названа"
    words = str(explanation or "").strip()[:EXPLANATION_MAX]
    tail = f" ({who})" if str(who or "").strip() else ""
    return f"{label}: {words}{tail}" if words else f"{label}{tail}"


def ask(bike, recorded, sent, source=""):
    """Расхождение ЧИСЛОМ + выбор причины. Возвращает `None`, ТОЛЬКО если понижения нет вовсе.

    Числа названы все три — сколько записано, сколько прислано, на сколько меньше, — потому что
    правило владельца требует именно их, а не слова «меньше»."""
    d = diff(recorded, sent)
    if not d["lower"]:
        return None
    b_ru = f" по {bike}" if bike else ""
    b_th = f" ({bike})" if bike else ""
    src_ru = f" ({source})" if source else ""
    lines_ru = "\n".join(f"  {i + 1}) {REASONS[k]['ru']}" for i, k in enumerate(REASON_ORDER))
    lines_th = "\n".join(f"  {i + 1}) {REASONS[k]['th']}" for i, k in enumerate(REASON_ORDER))
    return {
        "recorded": d["recorded"], "sent": d["sent"], "drop": d["drop"],
        "th": (f"📟 เลขไมล์{b_th} ที่บันทึกไว้ {d['recorded']} กม. "
               f"ที่ส่งมา {d['sent']} กม. — น้อยกว่า {d['drop']} กม.{src_ru}\n"
               f"ลดได้ครับ แต่ต้องบอกเหตุผล เลือกข้อไหนครับ:\n{lines_th}\n"
               f"เลือกแล้วช่วยพิมพ์เหตุผลเป็นคำพูดของคุณด้วย — แค่ «ใช่» ไม่นับ"),
        "ru": (f"📟 Пробег{b_ru}: записано {d['recorded']} км, прислано {d['sent']} км — "
               f"меньше на {d['drop']} км{src_ru}.\n"
               f"Понизить можно, но нужна причина. Что случилось:\n{lines_ru}\n"
               f"Выбери причину и напиши пояснение своими словами — одного «да» не хватит."),
    }


def plan(reason_key, explanation, who=""):
    """Причина + пояснение → что делать. `ok` истинно РОВНО когда обе половины на месте.

    Отказ несёт `say_ru`/`say_th` с действием: причина не из списка — выбрать заново, пояснение
    не принято — дописать словами. Молчаливого «нет» тут не бывает по построению."""
    if not reason_ok(reason_key):
        return {
            "ok": False, "state": "no_reason", "reason": "", "explanation": "",
            "say_ru": ("Причина не выбрана. Нажми одну из трёх кнопок: "
                       + ", ".join(REASONS[k]["ru"] for k in REASON_ORDER) + "."),
            "say_th": ("ยังไม่ได้เลือกเหตุผลครับ กดปุ่มใดปุ่มหนึ่ง: "
                       + ", ".join(REASONS[k]["th"] for k in REASON_ORDER)),
            "writes_history": False, "line": "",
        }
    v = explanation_verdict(explanation)
    if not v["ok"]:
        return {
            "ok": False, "state": v["state"], "reason": str(reason_key), "explanation": "",
            "say_ru": v["say_ru"], "say_th": v["say_th"],
            "writes_history": False, "line": "",
        }
    return {
        "ok": True, "state": ACCEPTED, "reason": str(reason_key), "explanation": v["text"],
        "say_ru": "", "say_th": "",
        "writes_history": writes_history(reason_key),
        "line": record_line(reason_key, v["text"], who),
    }


def receipt(bike, recorded, sent, reason_key, explanation, who=""):
    """Квитанция понижения: числа + причина + слова человека ДОСЛОВНО.

    Пояснение стоит в квитанции целиком не ради вежливости: человек обязан увидеть, ЧТО именно
    сохранится и останется читаемым потом, — иначе «сохранено» проверить нечем."""
    d = diff(recorded, sent)
    label_ru = REASONS.get(str(reason_key or ""), {}).get("ru") or "причина не названа"
    label_th = REASONS.get(str(reason_key or ""), {}).get("th") or "ไม่ได้ระบุเหตุผล"
    words = str(explanation or "").strip()[:EXPLANATION_MAX]
    b_ru = f" по {bike}" if bike else ""
    b_th = f" ({bike})" if bike else ""
    drop_ru = f" (меньше на {d['drop']} км)" if d["drop"] is not None else ""
    drop_th = f" (น้อยกว่า {d['drop']} กม.)" if d["drop"] is not None else ""
    return {
        "th": (f"✅ ลดเลขไมล์{b_th} แล้วครับ: {d['sent'] if d['sent'] is not None else sent} กม."
               f"{drop_th}\nเหตุผล: {label_th} — «{words}»"),
        "ru": (f"✅ Пробег{b_ru} понижен: было {d['recorded'] if d['recorded'] is not None else recorded} км, "
               f"стало {d['sent'] if d['sent'] is not None else sent} км{drop_ru}.\n"
               f"Причина: {label_ru} — «{words}». Пояснение сохранено вместе с записью."),
    }
