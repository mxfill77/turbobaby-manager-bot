"""ТЕНЕВОЙ ПРОГОН ПРАВИЛА ЗЕЛЁНОГО — «каким был бы вердикт шага, будь правило включено»
(16.08.2026, пункт 3 контракта третьего исхода в БЕЗОПАСНОЙ форме: СЧИТАТЬ, НЕ ПРИМЕНЯТЬ).

ЧТО ТАКОЕ ПРАВИЛО ЗЕЛЁНОГО. Контракт третьего исхода (узел мозга `orchestrator_plan`, раздел
записан 16.08.2026) требует: шаг зелёный только тогда, когда по НАЗВАННОМУ ИМ АДРЕСУ и правда
лежит его продукт. Пункт 1 (`result_ref.py`, `55d2f1d`) завёл поле адреса, пункт 2
(`result_judge.py`, `25ade7b`) — читателя этого адреса с тремя исходами. Пункт 3 — само правило,
и включать его СЕГОДНЯ НЕЛЬЗЯ: адрес не пишет ни один боевой вызов, поэтому включённое правило
сделало бы КАЖДЫЙ шаг незелёным и остановило бы полосу целиком. Отсюда тень: правило считается
рядом с настоящим вердиктом и не касается его ни одним байтом.

ПРАВИЛО ОДНОСТОРОННЕЕ, И ЭТО ЕГО ГЛАВНОЕ СВОЙСТВО: оно умеет СНЯТЬ зелёное и не умеет его ДАТЬ.
Красный исход тень повторяет дословно, каким бы ни был вердикт судьи: «по адресу лежит продукт»
не значит «работа сделана» — упавший шаг мог оставить файл на диске и умереть следующей строкой.
Поэтому направление расхождения у тени ровно одно — СТРОЖЕ; проверяется тестом, а не обещанием.

СЛОВАРЯ ТРЕТЬЕГО ТУТ НЕТ. Зелёное называется тем же словом, каким его называет очередь (`done`),
несогласие — словами СУДЬИ (`не доказан` / `неизвестно`), и порядок силы берётся у него же
(`result_judge.strongest`: НЕ ДОКАЗАН > НЕИЗВЕСТНО > ДОКАЗАН). Импорт поэтому ровно один — тот же
приём, каким `result_judge` берёт вокабуляр у `result_ref`, а `deliver_card` — у `expectations`:
второе определение одного понятия рядом с первым и есть класс «две правды об одном».

НЕСКОЛЬКО АДРЕСОВ — СИЛЬНЕЙШИЙ. Сегодня `result_ref.parse` отдаёт один адрес (последний
названный), но правило обязано быть готовым к нескольким: доказанное отсутствие ХОТЬ ПО ОДНОМУ
адресу сильнее доказанного наличия по остальным. Пустой список исходов → НЕИЗВЕСТНО (пустого
зелёного не бывает — правило `strongest`).

ЧИСТОТА — УСТРОЙСТВОМ: ни файлов, ни сети, ни подпроцессов, ни очереди; страж `SHADOW_RULE_PURE`
(ast) в `invariants_check.py`, в гейте. Отсюда и граница захода: снять зелёное у ЖИВОГО шага этой
функции нечем физически — она не умеет ни закрыть задачу, ни двинуть цепь, ни тронуть счёт серии.
Руки живут в `orchestrator_daemon._shadow_note_terminal` и пишут ровно в одно место —
`reports/<дата>/shadow-rule.jsonl`, файл, который не читает ни один работающий механизм.
"""
import result_judge

GREEN = "done"          # как зелёное называет ОЧЕРЕДЬ (Bridge принимает только done|failed)

# Направление расхождения. Второго значения тут не бывает по построению правила — см. шапку.
DIR_STRICTER = "строже"
DIR_NONE = ""

# Слова причины: почему тень сказала не то же, что очередь. Причину судьи (`why`) они НЕ заменяют
# — та едет рядом дословно.
WHY_KEEP_GREEN = "адрес назван и продукт по нему прочитан — зелёное устояло"
WHY_LOST_UNPROVEN = "зелёное снято: по названному адресу пусто либо не то"
WHY_LOST_UNKNOWN = "зелёное снято: адрес не назван либо источник не прочитан"
WHY_NOT_GREEN = "исход не зелёный — правило зелёного его не касается (снять умеет, дать не умеет)"


def shadow(status, states=()):
    """Настоящий исход шага + исходы судьи по его адресам → теневой исход и разница.

    Возврат: {"real","shadow","judge","diff","dir","why"} — `diff` булев («разошлось ли»),
    `dir` называет сторону и бывает только «строже». Не бросает никогда: настоящий исход
    приходит из живой очереди, а исходы судьи — из живого текста, который пишут люди."""
    real = str(status or "")
    judge = result_judge.strongest(states)
    if real != GREEN:
        # Красное остаётся красным при ЛЮБОМ вердикте судьи, в том числе «доказан».
        return {"real": real, "shadow": real, "judge": judge, "diff": False,
                "dir": DIR_NONE, "why": WHY_NOT_GREEN}
    if judge == result_judge.PROVEN:
        return {"real": real, "shadow": GREEN, "judge": judge, "diff": False,
                "dir": DIR_NONE, "why": WHY_KEEP_GREEN}
    why = WHY_LOST_UNPROVEN if judge == result_judge.UNPROVEN else WHY_LOST_UNKNOWN
    # Теневой исход НАЗЫВАЕТСЯ словом судьи: «не доказан» и «неизвестно» — разные вещи, и
    # свернуть их в одно «не done» значило бы потерять ровно то, ради чего заведён третий исход.
    return {"real": real, "shadow": judge, "judge": judge, "diff": True,
            "dir": DIR_STRICTER, "why": why}


def render(rec):
    """Запись тени → одна строка для журнала демона. Совпало — так и говорим, а не молчим."""
    rec = rec or {}
    if not rec.get("diff"):
        return "настоящий=%s теневой=%s (совпало) — %s" % (
            rec.get("real"), rec.get("shadow"), rec.get("why"))
    return "настоящий=%s теневой=%s (разошлось, %s) — %s" % (
        rec.get("real"), rec.get("shadow"), rec.get("dir"), rec.get("why"))
