"""ТЕНЕВОЙ ПРОГОН ПРАВИЛА ЗЕЛЁНОГО — «каким был бы вердикт шага, будь правило включено»
(16.08.2026, пункт 3 контракта третьего исхода в БЕЗОПАСНОЙ форме: СЧИТАТЬ, НЕ ПРИМЕНЯТЬ).

ЧТО ТАКОЕ ПРАВИЛО ЗЕЛЁНОГО. Контракт третьего исхода (узел мозга `orchestrator_plan`, раздел
записан 16.08.2026) требует: шаг зелёный только тогда, когда по НАЗВАННОМУ ИМ АДРЕСУ и правда
лежит его продукт. Пункт 1 (`result_ref.py`, `55d2f1d`) завёл поле адреса, пункт 2
(`result_judge.py`, `25ade7b`) — читателя этого адреса с тремя исходами. Пункт 3 — само правило,
и включать его СЕГОДНЯ НЕЛЬЗЯ: адрес не пишет ни один боевой вызов, поэтому включённое правило
сделало бы КАЖДЫЙ шаг незелёным и остановило бы полосу целиком. Отсюда тень: правило считается
рядом с настоящим вердиктом и не касается его ни одним байтом.

ПРАВИЛО ОДНОСТОРОННЕЕ, И ЭТО ЕГО ГЛАВНОЕ СВОЙСТВО: оно умеет СНЯТЬ зелёное и не умеет его ДАТЬ.
Красный исход тень повторяет дословно, каким бы ни был вердикт судьи: «по адресу лежит продукт»
не значит «работа сделана» — упавший шаг мог оставить файл на диске и умереть следующей строкой.
Поэтому направление расхождения у тени ровно одно — СТРОЖЕ; проверяется тестом, а не обещанием.

СЛОВАРЯ ТРЕТЬЕГО ТУТ НЕТ. Зелёное называется тем же словом, каким его называет очередь (`done`),
несогласие — словами СУДЬИ (`не доказан` / `неизвестно`), и порядок силы берётся у него же
(`result_judge.strongest`: НЕ ДОКАЗАН > НЕИЗВЕСТНО > ДОКАЗАН). Импорт поэтому ровно один — тот же
приём, каким `result_judge` берёт вокабуляр у `result_ref`, а `deliver_card` — у `expectations`:
второе определение одного понятия рядом с первым и есть класс «две правды об одном».

НЕСКОЛЬКО АДРЕСОВ — СИЛЬНЕЙШИЙ. Сегодня `result_ref.parse` отдаёт один адрес (последний
названный), но правило обязано быть готовым к нескольким: доказанное отсутствие ХОТЬ ПО ОДНОМУ
адресу сильнее доказанного наличия по остальным. Пустой список исходов → НЕИЗВЕСТНО (пустого
зелёного не бывает — правило `strongest`).

────────────────────────────────────────────────────────────────────────────────────────────
ТЕНЬ СУДИТ ЦЕПОЧКУ, А НЕ КАЖДЫЙ ШАГ (16.08.2026, поправка Штаба к контракту).

Контракт третьего исхода повесил адрес результата на ШАГ, и первая редакция тени судила шаги
поштучно. Это ошибка единицы, и она того же рода, что запрещённый рамкой §8г плоский счёт
записей: **продукт принадлежит ЦЕПОЧКЕ** — корневой записи очереди со всеми её шагами.
Промежуточный служебный шаг («собери факты», «прочитай журнал», карточка вердикта, сводка)
своего продукта не имеет и иметь не должен; суди его по собственному адресу — и цепочка
обрывается на ровном месте, а прибор меряет не работу, а дисциплину заполнения поля у каждой
служебной строки.

Отсюда устройство `chain_shadow`:

  * адрес берётся у КОРНЕВОЙ записи, и его исход подаётся судье ВСЕГДА. Корень адреса не
    назвал → НЕИЗВЕСТНО: зелёное надо ЗАРАБОТАТЬ, и молчание корня им не является;
  * шаг БЕЗ своего адреса не подаётся судье ВООБЩЕ — не «неизвестно», а никак. Так п.2
    поправки держится УСТРОЙСТВОМ: обрывать цепочку такому шагу нечем физически;
  * шаг СО СВОИМ адресом судится дополнительно и идёт в тот же `strongest`. Порядок силы
    прежний, поэтому его НЕ ДОКАЗАН перекроет доказанный корень, а его НЕИЗВЕСТНО не даст
    цепочке зелёного: замок против ложного зелёного у цепочки ровно тот же, что у шага.

ЗЕЛЁНОЕ ЦЕПОЧКИ ПРИХОДИТ ГОТОВЫМ (`real_green`), и слова для него у тени нет намеренно.
Чистоту цепочки считает ЖИВОЙ СЧЁТ СЕРИИ — свой прибор со своим вокабуляром (чистая · обрыв ·
не разобрана) и своими фактами (сорт вмешательства, необъяснённый отказ, вес). Завести здесь
второе определение того же понятия значило бы развести две правды об одном — тот же класс,
ради которого у тени импорт ровно один; поэтому в этом файле нет даже ИМЕНИ того прибора, и
это проверяется тестом. Тень отвечает на СВОЙ вопрос: снимает ли правило зелёного зелёное с
этой цепочки, — и отдаёт `break`/`unresolved` в форме, которую счёт серии читает, не называя
её словами.

ПОШАГОВЫЙ СЧЁТ ОСТАЁТСЯ РЯДОМ (`shadow`), и это не вежливость к старому коду: два счёта на
один корпус — единственный способ увидеть, НАСКОЛЬКО цепочечное правило мягче пошагового, и
поймать день, когда мягче станет «слепее».

ЧИСТОТА — УСТРОЙСТВОМ: ни файлов, ни сети, ни подпроцессов, ни очереди; страж `SHADOW_RULE_PURE`
(ast) в `invariants_check.py`, в гейте. Отсюда и граница захода: снять зелёное у ЖИВОГО шага этой
функции нечем физически — она не умеет ни закрыть задачу, ни двинуть цепь, ни тронуть счёт серии.
Руки живут в `orchestrator_daemon._shadow_note_terminal` и пишут ровно в одно место —
`reports/<дата>/shadow-rule.jsonl`, файл, который не читает ни один работающий механизм.
"""
import result_judge

GREEN = "done"          # как зелёное называет ОЧЕРЕДЬ (Bridge принимает только done|failed)

# Направление расхождения. Второго значения тут не бывает по построению правила — см. шапку.
DIR_STRICTER = "строже"
DIR_NONE = ""

# Слова причины: почему тень сказала не то же, что очередь. Причину судьи (`why`) они НЕ заменяют
# — та едет рядом дословно.
WHY_KEEP_GREEN = "адрес назван и продукт по нему прочитан — зелёное устояло"
WHY_LOST_UNPROVEN = "зелёное снято: по названному адресу пусто либо не то"
WHY_LOST_UNKNOWN = "зелёное снято: адрес не назван либо источник не прочитан"
WHY_NOT_GREEN = "исход не зелёный — правило зелёного его не касается (снять умеет, дать не умеет)"


def shadow(status, states=()):
    """Настоящий исход шага + исходы судьи по его адресам → теневой исход и разница.

    Возврат: {"real","shadow","judge","diff","dir","why"} — `diff` булев («разошлось ли»),
    `dir` называет сторону и бывает только «строже». Не бросает никогда: настоящий исход
    приходит из живой очереди, а исходы судьи — из живого текста, который пишут люди."""
    real = str(status or "")
    judge = result_judge.strongest(states)
    if real != GREEN:
        # Красное остаётся красным при ЛЮБОМ вердикте судьи, в том числе «доказан».
        return {"real": real, "shadow": real, "judge": judge, "diff": False,
                "dir": DIR_NONE, "why": WHY_NOT_GREEN}
    if judge == result_judge.PROVEN:
        return {"real": real, "shadow": GREEN, "judge": judge, "diff": False,
                "dir": DIR_NONE, "why": WHY_KEEP_GREEN}
    why = WHY_LOST_UNPROVEN if judge == result_judge.UNPROVEN else WHY_LOST_UNKNOWN
    # Теневой исход НАЗЫВАЕТСЯ словом судьи: «не доказан» и «неизвестно» — разные вещи, и
    # свернуть их в одно «не done» значило бы потерять ровно то, ради чего заведён третий исход.
    return {"real": real, "shadow": judge, "judge": judge, "diff": True,
            "dir": DIR_STRICTER, "why": why}


def render(rec):
    """Запись тени → одна строка для журнала демона. Совпало — так и говорим, а не молчим."""
    rec = rec or {}
    if not rec.get("diff"):
        return "настоящий=%s теневой=%s (совпало) — %s" % (
            rec.get("real"), rec.get("shadow"), rec.get("why"))
    return "настоящий=%s теневой=%s (разошлось, %s) — %s" % (
        rec.get("real"), rec.get("shadow"), rec.get("dir"), rec.get("why"))


# ── ТЕНЬ ЦЕПОЧКИ ────────────────────────────────────────────────────────────────────────────
# Единица здесь — КОРНЕВАЯ ЗАПИСЬ СО СВОИМИ ШАГАМИ (рамка §8г), см. шапку модуля.
WHY_CHAIN_KEEP = ("адрес цепочки назван и продукт по нему прочитан — зелёное устояло")
WHY_CHAIN_UNPROVEN = ("зелёное снято с ЦЕПОЧКИ: по названному адресу пусто либо не то")
WHY_CHAIN_UNKNOWN = ("зелёное снято с ЦЕПОЧКИ: корневая запись адреса не назвала либо источник "
                     "не прочитан")
WHY_CHAIN_NOT_GREEN = ("цепочка и без правила не зелёная — правило зелёного её не касается "
                       "(снять умеет, дать не умеет)")


def chain_states(root=None, steps=()):
    """Что подаётся судье о ЦЕПОЧКЕ: исход корня ВСЕГДА + исходы шагов, НАЗВАВШИХ свой адрес.

    `root` — исход судьи по адресу КОРНЕВОЙ записи; пусто (корень адреса не назвал либо мы его
    ещё не видели) → НЕИЗВЕСТНО: зелёное надо заработать, молчание им не является.
    `steps` — [{'named': bool, 'state': …}]; шаг с `named=False` не попадает сюда ВООБЩЕ, и
    ровно этим держится «шаг без адреса цепочку не обрывает» — не правилом, а тем, что подать
    ему в судью нечего."""
    out = [str(root) if root else result_judge.UNKNOWN]
    for s in steps or ():
        if not isinstance(s, dict) or not s.get("named"):
            continue
        out.append(str(s.get("state") or result_judge.UNKNOWN))
    return out


def chain_shadow(real_green, root=None, steps=()):
    """Настоящее зелёное цепочки + исходы её адресов → теневой исход ЦЕПОЧКИ.

    `real_green` приходит ГОТОВЫМ (см. шапку): чистоту цепочки считает живой счёт серии, а тень
    отвечает только на свой вопрос — снимает ли правило зелёного это зелёное.

    Возврат: {"real_green","shadow_green","shadow","judge","diff","dir","why","break",
    "unresolved","root_state","root_named","steps_seen","steps_named"}. Ключи `break` и
    `unresolved` — форма, которую читает счёт серии: НЕ ДОКАЗАН обрывает цепочку,
    НЕИЗВЕСТНО оставляет её неразобранной (длины не даёт, в нуль не сбрасывает). Оба
    направления — прежние: обвинять без факта нельзя, утверждать без факта нельзя тем более."""
    steps = [s for s in (steps or ()) if isinstance(s, dict)]
    named = [s for s in steps if s.get("named")]
    judge = result_judge.strongest(chain_states(root, steps))
    out = {"real_green": bool(real_green), "judge": judge,
           "root_state": str(root) if root else result_judge.UNKNOWN,
           "root_named": bool(root), "steps_seen": len(steps), "steps_named": len(named)}
    if not real_green:
        # Правило ОДНОСТОРОННЕЕ и на цепочке: не зелёная — значит правилу зелёного тут нечего
        # снимать, каким бы ни был вердикт судьи (продукт по адресу мог остаться и от упавшей
        # работы). Причина настоящего исхода — не наша, её называет счёт серии.
        out.update({"shadow_green": False, "shadow": judge, "diff": False, "dir": DIR_NONE,
                    "why": WHY_CHAIN_NOT_GREEN, "break": False, "unresolved": False})
        return out
    if judge == result_judge.PROVEN:
        out.update({"shadow_green": True, "shadow": GREEN, "diff": False, "dir": DIR_NONE,
                    "why": WHY_CHAIN_KEEP, "break": False, "unresolved": False})
        return out
    unproven = judge == result_judge.UNPROVEN
    out.update({"shadow_green": False, "shadow": judge, "diff": True, "dir": DIR_STRICTER,
                "why": WHY_CHAIN_UNPROVEN if unproven else WHY_CHAIN_UNKNOWN,
                "break": unproven, "unresolved": not unproven})
    return out


def render_chain(rec):
    """Запись теневой цепочки → одна строка журнала. Числа, а не ощущения: сколько шагов видели
    и сколько из них назвали свой адрес, — иначе «неизвестно» цепочки не отличить от «шагов не
    было вовсе»."""
    rec = rec or {}
    tail = "адрес корня: %s · шагов %s, со своим адресом %s" % (
        rec.get("root_state"), rec.get("steps_seen"), rec.get("steps_named"))
    if not rec.get("diff"):
        return "цепочка: зелёная=%s теневая=%s (совпало) — %s [%s]" % (
            rec.get("real_green"), rec.get("shadow"), rec.get("why"), tail)
    return "цепочка: зелёная=%s теневая=%s (разошлось, %s%s) — %s [%s]" % (
        rec.get("real_green"), rec.get("shadow"), rec.get("dir"),
        ", обрыв" if rec.get("break") else ", не разобрана", rec.get("why"), tail)
