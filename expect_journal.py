def _hit(text):
    """Названы ли в тексте деньги, живая таблица или клиентский контур → причина | ""."""
    low = str(text or "").lower()
    if not low:
        return ""
    for tok in MONEY_OPS:
        if tok.lower() in low:
            return "названа операция живых таблиц/денег: %s" % tok
    for w in MONEY_WORDS:
        if w in low:
            return "названы деньги или живая таблица: %s" % w
    for w in LIVE_FILES:
        if w in low:
            return "назван файл поверхности живых таблиц: %s" % w
    for w in CLIENT_WORDS:
        if w in low:
            return "назван клиентский контур: %s" % w
    return ""


def subject(v, facts=None):
    """ПРЕДМЕТ наблюдения текстом — то, ЧЕМУ посвящено нарушение, а не то, как оно описано.
    → (текст, прочитан_ли). Второе поле честно отличает «предмет пуст» от «предмет не достался»:
    на непрочитанном предмете замок обязан сработать в сторону владельца."""
    v = v if isinstance(v, dict) else {}
    kind = str(v.get("kind") or "")
    if kind in ("o3_undelivered", "o3_unknown"):
        parts = [str(v.get("sha") or ""), str(v.get("subject") or "")]
        pairs = list(v.get("missing") or []) + list(v.get("unknown") or [])
        for pair in pairs:
            try:
                parts.append(str(pair[0]))
            except (TypeError, IndexError):
                continue
        # Заголовок коммита у О3 есть ВСЕГДА (его кладёт `_o3`); пустой заголовок при живом sha —
        # законно пустой предмет, а не потеря факта.
        return " ".join(p for p in parts if p), bool(v.get("sha"))
    if kind == "o1_new_vps":
        rows = ((facts or {}).get("queue") or {}).get("rows")
        if not isinstance(rows, list):
            return "", False                    # снимка нет — предмет не достался
        for r in rows:
            if isinstance(r, dict) and str(r.get("id")) == str(v.get("id")):
                return "%s %s" % (r.get("from") or "", r.get("text") or ""), True
        return "", False                        # строка ушла из снимка — судить нечем
    if kind == "o4_pc_silent":
        return str(v.get("line") or ""), True
    if kind == "o6_pc_task":
        # Предмет — ДОСЛОВНАЯ строка взятия: по ней и судим, чего задача касается.
        return str(v.get("line") or ""), True
    return "", True                             # у юнита и канала предмета-артефакта нет вовсе


def heavy(v, facts=None, frozen_client=True):
    """Задевает ли наблюдение деньги, живые таблицы или клиентский контур → (bool, причина).

    Вызывается ТОЛЬКО чтобы решить адрес. Вердикт от ответа не зависит ни в одном поле."""
    v = v if isinstance(v, dict) else {}
    kind = str(v.get("kind") or "")
    if kind in INFRA_KINDS:
        return False, "предмет — юнит или канал: денег и живых таблиц в нём не бывает"
    if kind == "o7_child_down":
        # ПРЕДМЕТ ЗДЕСЬ ДРУГОЙ, ЧЕМ У О4/О6, И ПОТОМУ ВЕС ДРУГОЙ. У тех предмет — МАШИНА полосы
        # ПК (дев-контур, который случайно несёт на себе клиентские боты); здесь предмет — САМ
        # НАЗВАННЫЙ КЛИЕНТСКИЙ ПРОЦЕСС, тот, что говорит с клиентами. `CONTOUR_FREEZE` замораживает
        # применение КОДА к клиентскому контуру (ворота коммитов, находки ревизора о коде идут
        # списком, а не вопросом) — он не означает, что владельцу стало всё равно, РАБОТАЕТ ли бот.
        # Прямой повод: 18.08 модербот пролежал 12 ч 10 м, и не сказал никто.
        # ЦЕНА ИЗМЕРЕНА: за 20.8 суток журнала эпизодов смерти детей 11, переживших отсрочку в
        # 60 минут — 2 (12.2 ч и 33.9 ч), то есть ≈0.1 сообщения владельцу в сутки при его же
        # потолке 5–10. Не согласен — ручка одна: `EXPECT_PC_CHILD_MIN=0` гасит ветку целиком.
        return True, "назван клиентский контур: ребёнок %s" % (v.get("child") or "?")
    if kind == "o7_pulse_lost":
        # ТРЕТИЙ ИСХОД ВЛАДЕЛЬЦУ НЕ АДРЕСОВАН: предмет — ОТСУТСТВИЕ сведений о детях, а не факт о
        # них. Решать по незнанию владельцу нечего, а починка публикации — работа соседней полосы,
        # и Штаб увидит строку в журнале мозга. Заметку это не отменяет: в мозг уходит ВСЁ.
        return False, "предмет — отсутствие сведений о детях, а не факт о них: решать нечего"
    if kind == "o8_lane_dead":
        # ПРЕДМЕТ ЗДЕСЬ НЕ МАШИНА ПК И НЕ КОД КОНТУРА, а ВНЕШНИЙ ДОСТУП, без которого не работает
        # НИ ОДНА полоса. `CONTOUR_FREEZE` его не касается вовсе: заморожено применение кода к
        # клиентскому контуру, а кончившийся способ оплаты или перегрузка API — не код и не контур.
        # Обе причины чинит ТОЛЬКО владелец (счёт, ожидание восстановления) — прибор не умеет ни
        # той, ни другой, поэтому молчать здесь значило бы ждать вечно, что и случилось 18.08.
        # ЦЕНА ИЗМЕРЕНА: за 21.1 суток живого журнала череда длиннее порога была ОДНА.
        return True, "внешний отказ подряд у %s заходов — чинит только владелец" % (v.get("run") or "?")
    if kind in ("o4_pc_silent", "o6_pc_task"):
        # ОДИН ПРЕДМЕТ — ОДИН ВЕС: и «следа нет», и «взяла и молчит» суть наблюдения о МАШИНЕ ПК,
        # а она несёт клиентский контур. Развести их весами значило бы дать одному решению
        # владельца («контур заморожен») две правды — ровно то, чего избегает `_frozen_client`.
        if frozen_client:
            # Контур заморожен решением владельца: по нему находки идут в список, а не в вопрос
            # (тот же довод, что у `revizor_route`). Разморозят — ветка оживёт сама.
            return False, "ПК несёт клиентский контур, но контур ЗАМОРОЖЕН решением владельца"
        return True, "ПК несёт клиентский контур, и контур НЕ заморожен"
    text, read = subject(v, facts)
    if kind not in NAMED_KINDS:
        # Вид не назван в этом модуле — значит он появился позже правила. К владельцу.
        return True, "вид ожидания «%s» этому правилу не известен — вес не назван" % kind
    if not read:
        return True, "предмет не прочитан — исключить деньги и живые таблицы нечем"
    why = _hit(text)
    return (True, why) if why else (False, "в предмете деньги, живые таблицы и клиентский "
                                           "контур не названы")


def address(v, facts=None, held=0.0, defer=0.0, frozen_client=True):
    """КУДА уходит наблюдение → (адрес, причина).

    Владельцу — только пережившее отсрочку И тяжёлое. Оба условия обязательны: тяжёлое, но
    мгновенное, — это и есть шум живого образца (мост встал сам за 9 минут); лёгкое, но долгое, —
    это работа наблюдателя, которой владельцу нечего решать."""
    try:
        held = float(held or 0.0)
        defer = float(defer or 0.0)
    except (TypeError, ValueError):
        held, defer = 0.0, 0.0
    is_heavy, why = heavy(v, facts, frozen_client)
    if not is_heavy:
        return BRAIN, why
    if held < defer:
        return BRAIN, "тяжёлое, но отсрочку ещё не пережило (%s из %s)" % (_age(held), _age(defer))
    return BRAIN_AND_OWNER, why


def _age(sec):
    """«9 мин» / «10 ч 42 мин». Журнал читают глазами, дроби здесь мешают.
    НЕТ факта → «?» по той же причине, что у `_num`: отсутствие измерения не есть ноль."""
    if sec is None:
        return "?"
    s = max(0, int(float(sec or 0)))
    h, rest = divmod(s, 3600)
    m = rest // 60
    if h >= 24:
        return "%d сут %d ч" % divmod(h, 24)
    return ("%d ч %d мин" % (h, m)) if h else ("%d мин" % m)


def _stamp(ts):
    """Метка UTC. Без неё строка непригодна для поиска по времени, а с локальной — врёт
    (класс 17.07: Bangkok UTC+7 даёт «09:xx» вместо «02:xx UTC»)."""
    try:
        t = float(ts or 0)
    except (TypeError, ValueError):
        return "?"
    if t <= 0:
        return "?"
    return datetime.datetime.utcfromtimestamp(t).strftime("%Y-%m-%d %H:%M:%S")


NO_NUMBER = "число не записано (эпизод заведён прежней редакцией)"


def number(v):
    """ЧИСЛО нарушения — то, ради чего строку и будут искать: сколько при каком пороге.

    ОТСУТСТВУЮЩИЙ ФАКТ НАЗЫВАЕТ СЕБЯ, А НЕ ПРИТВОРЯЕТСЯ НУЛЁМ. Живой случай 13.08: первый же
    эпизод, закрытый новым кодом, был ЗАВЕДЁН старым — тримованного вердикта в его записи нет, и
    строка сказала «опрос очереди 0 с при отведённых 0 с». Ноль здесь ложь того же рода, что
    «доставлено» вместо «неизвестно»: сравнивать можно только НАЗВАННОЕ."""
    v = v if isinstance(v, dict) else {}
    kind = str(v.get("kind") or "")
    if kind == "o5_bridge_slow":
        if v.get("dt") is None and v.get("limit") is None:
            return NO_NUMBER
        return "опрос очереди %s с при отведённых %s с" % (_num(v.get("dt")), _num(v.get("limit")))
    if kind == "o1_new_vps":
        if v.get("free") is None and v.get("limit") is None:
            return NO_NUMBER
        return "задача %s ждёт %s чистого ожидания при пороге %s" % (
            v.get("id"), _age(v.get("free")), _age(v.get("limit")))
    if kind in ("o3_undelivered", "o3_unknown"):
        if v.get("age") is None and v.get("limit") is None:
            return NO_NUMBER
        return "коммит %s лежит в origin/main %s при пороге %s" % (
            v.get("sha"), _age(v.get("age")), _age(v.get("limit")))
    if kind == "o6_pc_task":
        if v.get("age") is None and v.get("limit") is None:
            return NO_NUMBER
        # Предмет О6 — ЗАДАЧА, и число обязано её назвать: «3 ч 30 мин при пороге 3 ч 30 мин» без
        # номера не даёт связать строку журнала ни с заметкой, ни с полосой.
        return "задача #%s взята полосой ПК %s назад при пороге %s, записи об исходе нет" % (
            v.get("pc_task_id"), _age(v.get("age")), _age(v.get("limit")))
    if kind == "o7_child_down":
        if v.get("age") is None and v.get("limit") is None:
            return NO_NUMBER
        # Предмет О7 — РЕБЁНОК, и число обязано его назвать: возраст строки без имени не даёт
        # связать строку журнала ни с заметкой, ни с ребёнком.
        return ("ребёнок %s назван не живым в строке возрастом %s при пороге публикации %s"
                % (v.get("child"), _age(v.get("age")), _age(v.get("limit"))))
    if kind == "o7_pulse_lost":
        if v.get("age") is None and v.get("limit") is None:
            return NO_NUMBER
        return "строки о детях нет %s при пороге %s" % (_age(v.get("age")), _age(v.get("limit")))
    if kind == "o8_lane_dead":
        if v.get("run") is None and v.get("limit") is None:
            return NO_NUMBER
        # Число О8 — ДЛИНА ЧЕРЕДЫ (штуки, не время), и вместе с ней ДОСЛОВНЫЙ ответ: строку
        # журнала читает Штаб, и без текста ответа она не отличает перегрузку от денег так же,
        # как не отличала бы заметка.
        return ("заходов подряд с внешним отказом %s при пороге %s · ответ дословно: «%s»"
                % (_num(v.get("run")), _num(v.get("limit")),
                   str(v.get("err") or "")[:160] or "текст не записан"))
    if v.get("age") is None and v.get("limit") is None:
        return NO_NUMBER
    return "%s при пороге %s" % (_age(v.get("age")), _age(v.get("limit")))


def _num(x):
    """Секунды числом. НЕТ факта → «?», а не «0»: ноль есть измерение, знак вопроса — его отсутствие."""
    if x is None:
        return "?"
    try:
        return "%.0f" % float(x)
    except (TypeError, ValueError):
        return "?"


def line(v, lane="VPS", first=0.0, now=0.0, phase="закрыт", ticks=0, detail="", num=""):
    """СТРОКА В ЖУРНАЛ МОЗГА — одна на эпизод, пригодная для поиска по теме.

    `phase`: «закрыт» (начало, конец, длительность) либо «держится» (эпизод пережил отсрочку и
    ещё идёт — иначе о самом долгом нарушении в журнале не было бы ни слова до его конца).

    `num` — ГОТОВОЕ число замера, снятое руками В МОМЕНТ ОБНАРУЖЕНИЯ. Строка говорит «начало»,
    и число обязано принадлежать этому началу; но главное — к закрытию сам вердикт уже не
    существует, а его поля доезжают сюда через белый список имён (`expectations_run._KEEP_V`).
    Список — угадывание задним числом: эпизод, заведённый прежней редакцией, и вид, чьё поле в
    список не внесли, теряют ОБА числа сразу. Готовая строка через список не проходит вовсе.
    Её нет → считаем по полям, как считали (законный путь легаси и путь пробы)."""
    v = v if isinstance(v, dict) else {}
    kind = str(v.get("kind") or "")
    parts = [
        "%s %s" % (TAG, SHORT.get(kind, kind or "?")),
        str(lane or "VPS"),
        WHAT.get(kind, "нарушение ожидания"),
        str(num or "").strip() or number(v),
        "начало %s UTC" % _stamp(first),
    ]
    if str(phase) == "закрыт":
        parts.append("конец %s UTC" % _stamp(now))
        parts.append("длилось %s" % _age(float(now or 0) - float(first or 0)))
    else:
        parts.append("ещё идёт, уже %s" % _age(float(now or 0) - float(first or 0)))
    if ticks:
        parts.append("наблюдений %d" % int(ticks))
    parts.append("эпизод %s" % v.get("key"))
    if detail:
        parts.append(str(detail)[:200])
    return " · ".join(parts)
