_READ_CHUNK = 1 << 13      # r4 · verify5 п.4: кусок чтения журнала — 8 КиБ, как у текстового readlines()
#                            (io.DEFAULT_BUFFER_SIZE): сверх списка строк живёт один блок; 64 КиБ давали 2,27× размера
_READ_GROW_MAX = 1 << 22   # r5 · verify6: пока в кусках нет b"\n", кусок удваивается до 4 МиБ (живой журнал — 8 КиБ всегда)


def _read_log():
    """RCFIX2010 C · verify3 x4: журнал → (строки, None), когда прочитан ЦЕЛИКОМ (пустой файл — ([], None): «прочитан,
    строк нет» — факт); иначе (None, причина), и вердикт Polling — НЕИЗВЕСТНО с этой причиной, а не «нет строк»:
      · «не прочитан (<исключение>)» — файла нет, каталог вместо файла, нет прав, ошибка ввода-вывода;
      · «прочитан не целиком (…)» — прочитано меньше размера на открытии или файл укоротился за чтение (рост за
        чтение — норма: дописанное позже просто не вошло).
    Разбор: байты не UTF-8 не роняют чтение всего журнала (surrogateescape), а помечаются — такая строка в сегменте
    текущего запуска делает вердикт НЕИЗВЕСТНО (_run_verdict), строка истории не мешает. Концы строк — как у прежнего
    readlines() в текстовом режиме: \\r\\n и \\r → \\n.
    r4 · verify5 п.4 (память): файл читается кусками по _READ_CHUNK байт, и разбирается каждый раз блок до ПОСЛЕДНЕГО
    b"\\n" (хвост без перевода строки переходит в следующий кусок), а не весь файл одним куском с декодированием и двумя
    копиями replace: сверх списка строк живёт один блок, а каждая строка декодируется один раз, как у прежнего
    readlines() (verify4 n7 на 24 МБ: r3 — 7,0× размера, readlines — 2,25×). Разбор по блокам равен разбору целиком:
    блок режется bytes.splitlines(keepends) — ровно по \\n, \\r\\n и \\r (байтовые границы строк; \\x0b, \\x85, \\u2028
    строку не режут), байты 0x0A и 0x0D не входят ни в одну многобайтовую последовательность UTF-8 и после них декодер в
    начальном состоянии, пара \\r\\n через границу блока не рвётся (её \\n остаётся в блоке, одиночный \\r в конце — в
    хвосте).
    r5 · verify6 (время): перевод строки ищется ТОЛЬКО в новом куске (chunk.rfind), а хвост без b"\\n" копится списком
    кусков и склеивается один раз — при найденном переводе строки или в конце файла. В r4 каждый кусок склеивался с
    растущим хвостом (buf = tail + chunk) и весь буфер сканировался заново: одна строка 16 МБ без \\n — 13,5 с против
    0,05 с у r3 (verify6 v6_probes P4). Теперь каждый байт копируется и сканируется O(1) раз — порядок r3 (test_a13);
    пока перевода строки нет, кусок удваивается (до _READ_GROW_MAX) и сбрасывается к 8 КиБ на первом b"\\n" — длинная
    строка читается за O(log) вызовов, а живой журнал, где b"\\n" есть в каждом куске, — прежними 8 КиБ.
    Результат тот же, что у r4: хвост прежде тоже не содержал b"\\n", и последний b"\\n" буфера был последним b"\\n"
    нового куска."""
    lines = []

    def _block(raw):
        for b in raw.splitlines(True):
            s = b.decode("utf-8", "surrogateescape")
            if s.endswith("\r\n"):
                s = s[:-2] + "\n"
            elif s.endswith("\r"):
                s = s[:-1] + "\n"
            lines.append(s)

    try:
        with open(LOG, "rb") as f:
            size0 = os.fstat(f.fileno()).st_size
            got, tail = 0, []              # tail — куски после последнего найденного b"\n" (в них b"\n" нет)
            size = _READ_CHUNK
            while True:
                chunk = f.read(size)
                if not chunk:
                    break
                got += len(chunk)
                cut = chunk.rfind(b"\n") + 1   # r5: только в новом куске
                if cut:
                    tail.append(chunk[:cut])
                    _block(b"".join(tail))
                    tail = [chunk[cut:]]
                    size = _READ_CHUNK
                else:
                    tail.append(chunk)
                    size = min(size * 2, _READ_GROW_MAX)   # r5: длинная строка — чтений O(log), а не по 8 КиБ
            rest = b"".join(tail)
            if rest:
                _block(rest)
            size1 = os.fstat(f.fileno()).st_size
    except Exception as e:
        return None, "не прочитан (" + type(e).__name__ + ")"
    if got < size0 or size1 < size0:
        return None, ("прочитан не целиком (размер на открытии " + str(size0) + " байт, прочитано " + str(got)
                      + ", после чтения " + str(size1) + ")")
    return lines, None


def _last_match(lines, needle):
    for ln in reversed(lines):
        if needle in ln:
            return ln.rstrip()
    return None


def _parse_log_ts(line):
    """Метка в начале строки журнала: asctime процесса бота — его МЕСТНОЕ время (bot.py:71–74, converter по умолчанию
    time.localtime), принятое за UTC посылкой (проверка — _run_verdict). Цифры только ASCII."""
    m = re.match(r"(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}),(\d{3})", line, re.ASCII)
    if not m:
        return None
    try:
        return datetime.datetime.strptime(m.group(1), "%Y-%m-%d %H:%M:%S").replace(
            tzinfo=datetime.timezone.utc)
    except Exception:
        return None


def _stamp_own(m):
    """h3 · verify4 n2b: собственная дата-время строки с меткой неизвестной формы (совпадение _STAMPISH_RE) — только
    чтобы решить, относится ли строка к текущему запуску; вердикт по ней не выносится никогда. Невозможная дата —
    None."""
    try:
        return datetime.datetime(*(int(g) for g in m.groups()), tzinfo=datetime.timezone.utc)
    except ValueError:
        return None


