def check_polling(lines, run0=None, run1=None, now=None, log_err=None):
    """Polling ТЕКУЩЕГО запуска (RCFIX2010 C) → (ok, слова), форма прежняя. Без границы запуска — НЕИЗВЕСТНО:
    строка «Bot polling started» прошлого запуска больше не доказательство. log_err — причина от _read_log."""
    status, why = _run_verdict(lines, run0, run1, now if now is not None else _utcnow(), log_err)
    if status == "OK":
        return True, why
    if status == "UNKNOWN":
        return False, "запуск не доказан — НЕИЗВЕСТНО: " + why
    return False, why


def _recheck_run(pl_ok, pl_d, run0, run1, run2, svc):
    """RCFIX2010 C · verify3 x2: третье чтение границы — НЕПОСРЕДСТВЕННО перед вердиктом отчёта, после долгих проверок
    (мост ×3, мозг 4 дока, кредит, WA — до ~9 мин). Вердикт Polling судил запуск run1; если за отчёт юнит перезапущен
    (новый процесс мог встать в простой), прежнее «✅» относится к ушедшему процессу. → (ok, слова) для строки Polling:
      · run2 не прочитан, или ключ run2 ≠ ключ run1 (PID, старт, NRestarts, ActiveState, SubState) → НЕИЗВЕСТНО;
      · строка «Splinter сервис» (svc = (is-active == active, старт UTC, NRestarts) из check_service) не сходится с
        run2 — отчёт собран из фактов разных запусков → НЕИЗВЕСТНО;
      · граница не прочитана или сменилась уже при чтении журнала — вердикт и так НЕИЗВЕСТНО, слова прежние.
    Предел: окно между этим чтением и печатью сводки (доли секунды) не видно никому."""
    if run0 is None or run1 is None or _run_key(run0) != _run_key(run1):
        return pl_ok, pl_d
    if run2 is None:
        why = ("граница запуска не перечитана перед вердиктом (systemctl show) — вердикт по " + _run_word(run1)
               + " не подтверждён")
    elif _run_key(run2) != _run_key(run1):
        why = ("граница запуска сменилась за время отчёта (" + _run_word(run1) + " → " + _run_word(run2)
               + ") — вердикт относится к ушедшему запуску")
    elif svc != (run2["active"] == "active", run2["start"], str(run2["nrestarts"])):
        why = ("факты отчёта не согласованы: «Splinter сервис» (active " + ("да" if svc[0] else "нет") + ", старт "
               + (svc[1].strftime("%Y-%m-%d %H:%M:%S") + " UTC" if svc[1] else "?") + ", рестартов " + str(svc[2])
               + ") ≠ граница (" + _run_word(run2) + ")")
    else:
        return pl_ok, pl_d
    return False, "запуск не доказан — НЕИЗВЕСТНО: " + why + "; прежний вердикт: " + pl_d


def check_log_health(lines, start_dt):
    if not lines:
        return False, "лог пуст/недоступен", 0
    last_ts = None
    for ln in reversed(lines):
        last_ts = _parse_log_ts(ln)
        if last_ts:
            break
    age = _fmt_age(_utcnow() - last_ts) if last_ts else "?"
    # Лог копит записи всех прошлых запусков (не ротируется). Считаем ошибки ТОЛЬКО
    # текущего запуска: ведём «текущий timestamp» — строки-продолжения трейсбэка без
    # своей даты наследуют время родительской строки, поэтому датируются корректно.
    errors = 0
    cur_ts = None
    for ln in lines:
        ts = _parse_log_ts(ln)
        if ts:
            cur_ts = ts
        if start_dt and (cur_ts is None or cur_ts < start_dt):
            continue
        if "[ERROR]" in ln or "[CRITICAL]" in ln or "Traceback (most recent" in ln:
            errors += 1
    return True, "посл. строка " + age + " назад; ошибок с старта: " + str(errors), errors


