# ── ИСХОДЫ ────────────────────────────────────────────────────────────────────────────────────
ASK = "спросить"                 # покрытия нет ЛИБО его не доказать → прежний путь байт-в-байт
STANDING = "вопрос уже стоит"    # карточка об этом объекте висит перед владельцем прямо сейчас
ANSWERED = "ответ уже получен"   # владелец ответил; ответ прикладывается словом и номером

SEP = "|"                        # разделитель ключа: семья операции | предмет
HEX = "0123456789abcdef"
SHA_KEEP = 7                     # ровно столько знаков коммита называют обе двери сами
KEEP = 256                       # записей реестра (≈2 карточки в сутки — год с запасом)
UNNAMED = (":?", ":")            # хвосты семьи без имени юнита — объектом она не является


def _predmet(obj):
    """Предмет вопроса в канонической форме. Коммит приводится к 7 знакам — не потому, что так
    решил этот модуль, а потому, что ИМЕННО ТАК его называют обе двери (`deliver_card.mark`,
    `_curator_state_answers`). Прочий предмет остаётся собой: форма ключа переживёт появление
    объекта другого рода, и своего словаря видов тут не заводится."""
    s = str(obj or "").strip().lower()
    if not s:
        return ""
    if 7 <= len(s) <= 40 and all(c in HEX for c in s):
        return s[:SHA_KEEP]
    return s


def key(op, obj):
    """(семья операции, предмет) → устойчивый ключ | None.

    None — это «сравнивать нечего», а НЕ «совпадений нет»: имени нет у операции, нет у предмета
    либо семья не назвала юнита (`service:?`). Читатель обязан прочитать None как «спросить»."""
    o = str(op or "").strip()
    if not o or o.endswith(UNNAMED):
        return None
    p = _predmet(obj)
    if not p:
        return None
    return o + SEP + p


def card_keys(ops, objs):
    """Операции и предметы одной карточки → её ключи (без повторов, порядок сохранён).

    Пусто — законный ответ: карточка, не назвавшая операции ЛИБО предмета, дедупом не судится
    вовсе и идёт прежним путём."""
    out = []
    for o in (ops or ()):
        for p in (objs or ()):
            k = key(o, p)
            if k and k not in out:
                out.append(k)
    return out


def empty():
    """Пустой реестр. Отличать его от НЕПРОЧИТАННОГО обязан читатель: пустой = «никого не
    спрашивали» (законный ноль), непрочитанный = None (незнание) — тот же знаменатель, что у
    `chain_cards.load` и контракта `scan_result`."""
    return {"asks": {}, "skipped": 0}


def _asks(led):
    a = (led or {}).get("asks")
    return a if isinstance(a, dict) else {}


def _num(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return None


def verdict(ks, led, now=0.0, window=0.0):
    """Ключи карточки, которую дверь СОБИРАЕТСЯ поставить → {"state","why","key","prior"}.

    `led=None` (реестр не прочитан) → СПРОСИТЬ: незнание не смеет гасить вопрос владельцу.
    `window<=0` → окно не ограничивает (возрастом запись не выбрасывается).
    Глушим ТОЛЬКО когда покрыт КАЖДЫЙ ключ; первый непокрытый прекращает разбор."""
    try:
        ks = [k for k in (ks or ()) if k]
        if not ks:
            return {"state": ASK, "why": "объект не назван — сравнивать нечего",
                    "key": None, "prior": None, "covered": []}
        if led is None:
            return {"state": ASK, "why": "реестр вопросов не прочитан — вопрос задаём, как задавали",
                    "key": None, "prior": None, "covered": []}
        asks = _asks(led)
        covered, standing, answered = [], None, None
        for k in ks:
            rec = asks.get(k)
            if not isinstance(rec, dict):
                return {"state": ASK, "why": "об объекте «%s» ещё не спрашивали" % k,
                        "key": k, "prior": None, "covered": covered}
            at = 0.0
            try:
                at = float(rec.get("at") or 0)
            except (TypeError, ValueError):
                at = 0.0
            if window > 0 and now > 0 and (now - at) > window:
                return {"state": ASK,
                        "why": "вопрос об объекте «%s» старше окна (%.1f ч) — спрашиваем заново"
                               % (k, window / 3600.0),
                        "key": k, "prior": rec, "covered": covered}
            covered.append(k)
            if rec.get("answer"):
                answered = answered or (k, rec)
            else:
                standing = standing or (k, rec)
        if standing:
            k, rec = standing
            return {"state": STANDING, "key": k, "prior": rec, "covered": covered,
                    "why": "об этом объекте («%s») уже спрашивает дверь «%s» карточкой %s — "
                           "она висит перед владельцем и ответа ещё нет"
                           % (k, rec.get("door") or "?", rec.get("card"))}
        k, rec = answered
        return {"state": ANSWERED, "key": k, "prior": rec, "covered": covered,
                "why": "об этом объекте («%s») владелец уже ответил «%s» на карточку %s двери "
                       "«%s» — второй раз не спрашиваем"
                       % (k, rec.get("answer"), rec.get("card"), rec.get("door") or "?")}
    except Exception:                                                # noqa: BLE001
        return {"state": ASK, "why": "разбор реестра упал — вопрос задаём, как задавали",
                "key": None, "prior": None, "covered": []}


def _trim(asks):
    """Реестр не растёт бесконечно: держим KEEP самых свежих записей."""
    if len(asks) <= KEEP:
        return asks
    def age(kv):
        try:
            return -float((kv[1] or {}).get("at") or 0)
        except (TypeError, ValueError):
            return 0.0
    return dict(sorted(asks.items(), key=age)[:KEEP])


def remember(led, ks, door, card, at):
    """Записать ЗАДАННЫЙ вопрос. Зовётся только по факту вставшей карточки: реестр обещает
    «об этом уже спрашивали», и обещание должно быть правдой."""
    out = dict(led or empty())
    asks = dict(_asks(out))
    for k in (ks or ()):
        if not k:
            continue
        asks[str(k)] = {"door": str(door or ""), "card": _num(card),
                        "at": float(at or 0), "answer": None, "answered_at": None}
    out["asks"] = _trim(asks)
    return out


def answer(led, card, outcome, at):
    """Приложить к вопросам карточки ответ владельца → (реестр, сколько ключей его получили).

    Слово исхода НЕ разбирается и не толкуется: вокабуляр («разрешено», «отказ», «истекло»,
    «закрыто») принадлежит `chain_cards`, и заводить его второй раз здесь значило бы завести
    вторую правду об одном. Доказанный исход не перебивается: у записи с ответом он остаётся."""
    out = dict(led or empty())
    asks = dict(_asks(out))
    cid, n = _num(card), 0
    if cid is None:
        return out, 0
    for k, rec in list(asks.items()):
        if not isinstance(rec, dict) or _num(rec.get("card")) != cid or rec.get("answer"):
            continue
        r = dict(rec)
        r["answer"] = str(outcome or "")
        r["answered_at"] = float(at or 0)
        asks[k] = r
        n += 1
    out["asks"] = asks
    return out, n


def skip(led):
    """Засчитать снятый вопрос. Счётчик — не украшение: он единственное место, где видно, СКОЛЬКО
    внимания владельца дедуп сберёг, и по нему же видно, если он начнёт глотать лишнее."""
    out = dict(led or empty())
    out["skipped"] = (_num(out.get("skipped")) or 0) + 1
    return out


def skipped(led):
    """Сколько вопросов снято за всю жизнь реестра. Реестр не прочитан → None (не ноль)."""
    if led is None:
        return None
    return _num((led or {}).get("skipped")) or 0
