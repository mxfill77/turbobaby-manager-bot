"""АДРЕС РЕЗУЛЬТАТА ШАГА — чистая функция «вид + указатель ↔ строка очереди» (16.08.2026).

ПУНКТ 1 КОНТРАКТА ТРЕТЬЕГО ИСХОДА (узел мозга `orchestrator_plan`, раздел записан 16.08.2026):

    «АДРЕС РЕЗУЛЬТАТА. У шага появляется поле: ГДЕ обязан появиться его продукт. Виды
     адреса — коммит в origin/main · файл на диске · строка в базе · узел мозга · старт
     сервиса моложе коммита. Заполняется ПРИ СОЗДАНИИ шага, а не при закрытии.»

ЭТОТ МОДУЛЬ ДЕЛАЕТ РОВНО ОДНО: заводит МЕСТО, куда адрес можно положить, и умеет прочитать
его назад ДОСЛОВНО. По названному адресу здесь НИКТО НЕ ХОДИТ: вердикт шага не судится,
третьего исхода нет, правило «нет адреса — нет зелёного» не включено. Пункты 2–5 контракта —
следующие заходы, и порядок постройки назван самим контрактом («сначала форма и третий
исход → потом ОДНО место как проба, вместе с отрицательным тестом»).

ГДЕ ЖИВЁТ ПОЛЕ И ПОЧЕМУ НЕ ДЕСЯТАЯ КОЛОНКА — ПРЕДЕЛ НАЗВАН ПРЯМО. Очередь это лист Google
Sheets, которым правит Apps Script: `bridge_prod/BotData.js`, `BOTDATA.QUEUE_HEADERS` (девять
имён: id · created · from · task_text · status · result · approved_by · updated · lane) и
карта колонок `QUEUE_COL`. Десятая колонка означает правку ЭТОГО кода и его ВЫКЛАДКУ
(`clasp push` + `clasp redeploy`) — красная зона владельца, headless-заход её не проходит и
обходных путей к ней не ищет. Поэтому поле заведено в той колонке, которую очередь и так
несёт ПРИ СОЗДАНИИ шага, — в `task_text`, отдельной строкой строгой формы. Это ровно тот
приём, которым в этой системе уже живёт всё состояние цепи, переживающее рестарт:
`[шаг i/N родитель id]`, `[конверт одобренной заявки N]`, `[куратор цели G, шаг m]`,
`[коррекция плана K]`, `[доставка коммита X]`. Свойства поля от этого те же, что у колонки:
оно В ОЧЕРЕДИ (переживает рестарт демона, не файл на диске одной машины) и его видят ОБЕ
полосы — ПК-полоса прочитает ту же строку своим зеркалом этого модуля. Чего оно НЕ получает:
собственного заголовка в листе и фильтрации средствами таблицы. Отдельная колонка — заход
владельца с выкладкой моста; до неё адрес живёт строкой текста.

ПОЗИЦИЯ — ПОСЛЕДНЯЯ СТРОКА, И ЭТО НЕ ВКУС. Головные маркеры очереди разбираются С НАЧАЛА
текста (`[шаг i/N родитель id]`, `_is_convert`, кураторские маркеры, `_series_root`): адрес,
поставленный впереди, сломал бы их разбор — тот же класс, что правило исполняющей позиции.
Хвост не разбирает никто, поэтому адрес клеится ПОСЛЕДНЕЙ строкой, а читается сканом строк
С КОНЦА (берётся первая строка, целиком совпавшая с формой).

ТЕЛО РЕЖЕТСЯ ПОД АДРЕС, А НЕ АДРЕС ПОД ТЕЛО (приём `_stamp_self_origin`, класс 04.08.2026).
Мост режет текст задачи на CAP символов (`bridge_prod/BotData.js`, `enqueueTask_`:
`String(p.task_text || '').slice(0, 5000)`), и адрес, приклеенный последним, у длинного ТЗ
пропал бы МОЛЧА. Поэтому при нехватке места урезается ТЕЛО, а урезка НАЗЫВАЕТСЯ видимой
пометкой: молча из ТЗ не исчезает ничего.

ПУСТОЕ ЗНАЧЕНИЕ ДОПУСТИМО и означает «адрес не назван»: `attach` возвращает текст
БАЙТ-В-БАЙТ прежним — не «почти прежним», а тем же объектом значения, без единой правки, без
разбора и без урезки. Сегодня так создаётся КАЖДЫЙ шаг: адрес не пишет ни одно место в
репозитории, поэтому старый путь не задет ни одним байтом.

НАЗВАННЫЙ НЕВЕРНО АДРЕС НЕ ГЛОТАЕТСЯ. Неизвестный вид · пустой указатель при названном виде ·
перевод строки внутри указателя · потолок меньше самого адреса → `ValueError` у самой
функции, ДО всякой сети. Тихо «починить» такой адрес значило бы завести ровно тот класс,
против которого написан весь контракт: утверждение о мире, которого никто не проверял. Не
назвать адрес вовсе — законно (см. выше); назвать криво — узнаешь сразу.

ЧТЕНИЕ НЕ БРОСАЕТ НИКОГДА. `parse` читает ЖИВОЙ текст очереди, который писали и люди, и
чужие полосы: строка, похожая на адрес, но с неизвестным видом, адресом не считается —
разбор идёт дальше по тексту, а не падает и не выдумывает вид. Ничего не нашлось → `None`,
то есть «адрес не назван», и это ЗАКОННОЕ сегодняшнее состояние каждого шага.

ЧИСТОТА — УСТРОЙСТВОМ, А НЕ ОБЕЩАНИЕМ: импорт ровно один (`re`), ни файлов, ни сети, ни
подпроцессов, ни моста; страж `RESULT_REF_PURE` (ast) в `invariants_check.py`, в гейте.
Спросить мир, действительно ли по адресу что-то есть, этому модулю НЕЧЕМ — и это главная
защита от того, чтобы связь протянулась раньше времени.
"""
import re

# Потолок текста задачи — ЗЕРКАЛО прода: `bridge_prod/BotData.js`, enqueueTask_ режет
# `String(p.task_text || '').slice(0, 5000)`. Число живёт здесь, чтобы адрес не пропадал
# молча на длинном ТЗ; разойдётся с мостом — адрес просто урежется раньше, чем нужно.
CAP = 5000

# ПЯТЬ ВИДОВ АДРЕСА — дословно по контракту, шестого тут завести нельзя: вид, которого
# контракт не называет, это новая договорённость, а не новая строка словаря.
KINDS = {
    "commit":        "коммит в origin/main",
    "file":          "файл на диске",
    "row":           "строка в базе",
    "brain":         "узел мозга",
    "service_start": "старт сервиса моложе коммита",
}

_HEAD = "[адрес результата: "
# Указатель берётся ЖАДНО до последней «]» строки: путь, ключ строки и имя узла вправе нести
# скобку внутри себя, и терять на этом хвост адреса нельзя.
_MARK_RE = re.compile(r"^\[адрес результата:[ \t]*([A-Za-z_]+)[ \t]+(.*)\][ \t]*$")

# Видимый след урезки тела — молча из ТЗ не исчезает ничего.
TRIM_NOTE = "…⟨тело урезано под адрес результата⟩"


def render(kind="", pointer=""):
    """(вид, указатель) → строка адреса для очереди. Ничего не названо → пустая строка.

    Названо криво → ValueError (см. «НАЗВАННЫЙ НЕВЕРНО АДРЕС НЕ ГЛОТАЕТСЯ» в шапке).
    Указатель хранится ОБРЕЗАННЫМ по краям — пробел на краю не есть часть адреса."""
    k = str(kind or "").strip()
    p = str(pointer or "").strip()
    if not k and not p:
        return ""
    if k not in KINDS:
        raise ValueError(
            f"вид адреса «{k}» не из контракта: {sorted(KINDS)} — "
            f"шестой вид это новая договорённость, а не новая строка словаря")
    if not p:
        raise ValueError(f"вид «{k}» назван, а указатель пуст — адрес без указателя "
                         f"проверить нечем")
    if "\n" in p or "\r" in p:
        raise ValueError("указатель в одну строку: перевод строки внутри адреса разорвал бы "
                         "его на две записи очереди")
    return f"{_HEAD}{k} {p}]"


def parse(text):
    """Текст задачи → {'kind','pointer'} ПОСЛЕДНЕГО названного адреса либо None.

    None = «адрес не назван» — законное сегодняшнее состояние каждого шага. Не бросает
    никогда: живой текст очереди пишут и люди, и чужая полоса."""
    for line in reversed(str(text or "").splitlines()):
        m = _MARK_RE.match(line)
        if not m:
            continue
        k = m.group(1)
        p = m.group(2).strip()
        if k in KINDS and p:
            return {"kind": k, "pointer": p}
    return None


def as_pair(value):
    """Адрес в любой из двух форм → (вид, указатель). None → ('', ''), то есть «не назван».

    Форм две, потому что адрес ходит по системе двумя путями: его НАЗЫВАЮТ парой при создании
    шага и его ЧИТАЮТ словарём (`parse`/`of_task`) при чтении шага. Перенести прочитанный
    адрес в новый шаг обязано быть одним действием, а не ручной распаковкой."""
    if value is None:
        return "", ""
    if isinstance(value, dict):
        return str(value.get("kind") or ""), str(value.get("pointer") or "")
    if isinstance(value, (tuple, list)):
        if len(value) != 2:
            raise ValueError(f"адрес — пара (вид, указатель), а не {len(value)} значений")
        return str(value[0] or ""), str(value[1] or "")
    raise ValueError(f"адрес не разобрать: {type(value).__name__} — ожидались пара или словарь")


def of_task(row):
    """Строка очереди (dict из get_pending/claim_task) → адрес либо None. Чужая форма → None."""
    if not isinstance(row, dict):
        return None
    return parse(row.get("task_text"))


def strip_ref(text):
    """Текст без строк адреса — тело ТЗ, каким его писал автор. Обратен `attach`."""
    s = str(text or "")
    kept = []
    for line in s.splitlines():
        m = _MARK_RE.match(line)
        if m and m.group(1) in KINDS and m.group(2).strip():
            continue
        kept.append(line)
    return "\n".join(kept)


def attach(task_text, kind="", pointer="", cap=CAP):
    """Текст задачи + адрес → текст задачи со строкой адреса ПОСЛЕДНЕЙ.

    Адрес не назван → возврат БАЙТ-В-БАЙТ прежнего текста (строгий no-op: ни разбора, ни
    урезки, ни снятия чужой строки). Назван — прежняя строка адреса заменяется, а не
    удваивается. Тело не влезает в потолок → урезается ТЕЛО, с видимой пометкой."""
    s = str(task_text or "")
    marker = render(kind, pointer)
    if not marker:
        return s
    body = strip_ref(s)
    sep = "\n"
    room = int(cap) - len(marker) - len(sep)
    if room <= 0:
        raise ValueError(
            f"потолок {cap} меньше самого адреса ({len(marker)} симв.) — класть адрес некуда")
    if len(body) > room:
        body = body[:max(0, room - len(TRIM_NOTE))] + TRIM_NOTE
    return body + sep + marker
