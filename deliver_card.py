#!/usr/bin/env python3
"""ДОСТАВКА ПРОВЕРЕННОГО КОММИТА В ПРОД — ОДНА КНОПКА ВМЕСТО РУЧНОГО РЕСТАРТА (14.08.2026).

ПУТЬ C разбора цели 538 (read-only, `reports/2026-08-14/task-538.md`), выбранный владельцем
кнопкой на сводной карточке 541. Основание разбора числом: за наблюдение 10.08 19:30:55 →
14.08 11:00 было 13 перезапусков, машина сделала 11, руками 2 — и ровно ручные рвали серию
цепочек. Класс при этом не в границе, а в МОЛЧАНИИ: код в памяти процесса доезжает до прода
только рестартом, О3 умеет сказать «коммит не доставлен», но сказать это он умел ТОЛЬКО в
журнал — то есть в канал, на который не отвечают. Владелец узнавал о недоставке случайно.

ЧТО ЭТОТ МОДУЛЬ ДЕЛАЕТ: превращает вердикт прибора О3 «не доставлен» в ПРЕДЛОЖЕНИЕ карточки
владельцу и в текст задачи, которую поставит его «да». И ничего больше.

ГРАНИЦА ДЕРЖИТСЯ УСТРОЙСТВОМ, А НЕ ОБЕЩАНИЕМ. Перезапуск живого процесса — операция, и она
остаётся решением владельца: здесь нет ни одного способа её вызвать. Импорт ровно один
(`expectations` — вокабуляр прибора берётся ГОТОВЫМ, чтобы своего суждения о доставке в модуле
не завелось вовсе), ни файлов, ни сети, ни моста, ни очереди, ни подпроцессов. Стережёт это
`DELIVER_CARD_PURE` в `invariants_check.py` (ast, в гейте), а не докстринг. Худшее, что модуль
может физически сделать ошибкой в логике, — предложить лишний ВОПРОС; исполнить он не может
ничего.

ТРИ ЗАМКА ПРОТИВ ЛОЖНОГО ПРЕДЛОЖЕНИЯ (все в сторону «карточки нет»):
 1. ТОЛЬКО «НЕ ДОСТАВЛЕН». `неизвестно` картой не становится НИКОГДА: незнание — не повод
    просить владельца перезапускать прод. Это тот же порядок силы, что у самого прибора.
 2. ТОЛЬКО ПАМЯТЬ И ТОЛЬКО НАБЛЮДАЕМЫЙ ЮНИТ. Недоставку с именем юнита прибор выдаёт лишь для
    вида «код в памяти процесса» — выкладка наружу (мост) и конфиги владельца в `missing` не
    попадают по построению. Юнит, которого нет в списке наблюдаемых, отменяет предложение
    ЦЕЛИКОМ: чужой вид доставки лечится не рестартом, и предлагать его как рестарт — ложь.
 3. ДЕРЕВО СВЕРЕНО. Файл, которым диск расходится с origin/main, прибор кладёт в `unknown`, а
    не в `missing`, — значит карточка физически не может предложить доставку неизвестно чего.

ЧЕГО КАРТОЧКА НЕ ОБЕЩАЕТ. Гейт гоняет ЗАДАЧА, а не эта ветка: замер стоимости прост — полный
гейт ~3 минуты, а оборот демона минута, и гонять его на каждую находку значило бы платить за
вопрос ценой работы. Красный гейт в задаче = перезапуска не будет, и подпись карточки говорит
это ДО нажатия (приём подписи `3a95df7`: владелец видит ОБА исхода заранее).

КАКОЙ НАБОР ГЕЙТА ДАЁТ ПРАВО (17.08.2026, `prod_gate.py`). Только ПОЛНЫЙ: перезапуск поднимает в
память весь HEAD, а не затронутые модули. Замер того же дня: право получил селективный набор
трижды из пяти доставок (77/78/79 тестов при полном 216), и правило до сих пор жило только в
голове исполнителя. Теперь ТЗ ниже говорит это прямо, а гейт поднимает набор САМ по метке демона;
названная причина (`--selective-reason`) остаётся законным исключением и уезжает в журнал.
"""
import expectations

FLAG_ENV = "DELIVER_CARD"          # «0» гасит ветку целиком ДО сбора фактов (откат)
KIND_UNDELIVERED = "o3_undelivered"

MARK_HEAD = "[доставка коммита "
MARK_TAIL = "]"

# ПРАВИЛО САМОМОДИФИКАЦИИ (03.07.2026, урок задачи 43): задача-исполнитель живёт ВНУТРИ cgroup
# демона (`KillMode=control-group`), поэтому прямой рестарт демона убил бы её же claude-процесс
# вместе с отчётом. Отложенная единица даёт задаче 10 секунд договорить. Для splinter такого
# родства нет — там обычный рестарт.
DEFERRED_UNITS = ("orchestrator-daemon",)


def on(env):
    """Ветка жива? `DELIVER_CARD=0` → нет, и гасит она ДО единого обращения к миру.

    Дефолт «включено» законен ровно потому, что ветка умеет ТОЛЬКО задать вопрос: ни одной
    операции без «да» владельца из неё не следует."""
    try:
        return str((env or {}).get(FLAG_ENV) or "1").strip() != "0"
    except Exception:                                                # noqa: BLE001
        return False                                                 # сомнение → молчание


def mark(sha):
    """Маркер строки очереди. Несёт КОММИТ, поэтому дедуп restart-proof: карточка на тот же
    коммит второй раз не встаёт, даже если состояние на диске потерялось."""
    return MARK_HEAD + str(sha or "")[:7] + MARK_TAIL


def sha_of(text):
    """Текст строки очереди → коммит карточки доставки | None (чужая строка)."""
    t = str(text or "")
    if not t.startswith(MARK_HEAD):
        return None
    tail = t[len(MARK_HEAD):]
    cut = tail.find(MARK_TAIL)
    if cut <= 0:
        return None
    sha = tail[:cut].strip()
    return sha if sha and all(c in "0123456789abcdef" for c in sha.lower()) else None


UNITS_HEAD = " доставка в прод: "

# ЕДИНИЦА КАРТОЧКИ — ОПЕРАЦИЯ, А НЕ КОММИТ (22.09.2026). Прибор О3 судит КОММИТ и на каждый
# недоставленный даёт свою заметку — а лечит их всех ОДНО действие: перезапуск процесса. Пока
# карточка выписывалась на заметку, владельцу приходило столько вопросов, сколько коммитов
# накопилось, и второй вопрос не покупал ничего: рестарт поднимает в память ДЕРЕВО целиком.
# Живой замер 7 суток (14.09–21.09): 5 карточек, из них 4 — по два вопроса об ОДНОМ splinter в
# одном окне между перезапусками (149+150 20.09, 15+16 21.09, обе пары с разницей ~15 минут =
# ровно период замера DELIVER_EVERY_SEC).
#
# СКЛЕЙКА ЖИВЁТ ЗДЕСЬ, В ЧИСТОМ РЕШЕНИИ, а не в руках: она ничего не читает и никуда не шлёт —
# это перекладывание уже собранных заметок. Путь до человека правка не трогает ВООБЩЕ.
MARK_LIST_HEAD = "[коммиты "
MARK_LIST_TAIL = "]"


def commits_of(off):
    """Предложение → список коммитов карточки, СТАРЫЙ ПЕРВЫМ. Склеенное несёт их списком,
    одиночное (форма до 22.09 и любой прямой зов `offer`) — само себя."""
    out = []
    for c in (off or {}).get("commits") or ():
        sha = str((c or {}).get("sha") or "")[:7]
        if sha:
            out.append({"sha": sha, "subject": str(c.get("subject") or "")[:70],
                        "age": c.get("age")})
    if out:
        return out
    sha = str((off or {}).get("sha") or "")[:7]
    return [{"sha": sha, "subject": str((off or {}).get("subject") or "")[:70],
             "age": (off or {}).get("age")}] if sha else []


def fold(offers):
    """Предложения ПО КОММИТАМ (по одному на заметку О3) → предложения ПО ОПЕРАЦИИ.

    Единица — ПРОЦЕСС: один перезапуск — одно предложение, и в нём перечислены ВСЕ коммиты,
    которые этим перезапуском доедут. Коммит, не доехавший до ДВУХ процессов, попадает в ДВА
    предложения, и это не дубль вопроса, а две разные операции (то же правило, что у сводной
    карточки куратора: рестарт splinter и рестарт демона — две карточки).

    Порядок внутри: старый коммит первым (у прибора `age` тем больше, чем старше) — им и
    ключуется строка очереди, поэтому склейка не ломает чтение старых карточек.
    FAIL-SAFE: мусор на входе пропускается молча, пустой вход → пустой выход."""
    by = {}
    for off in offers or ():
        if not isinstance(off, dict):
            continue
        sha = str(off.get("sha") or "")[:7]
        if not sha:
            continue
        for unit in (off.get("units") or ()):
            u = str(unit)
            g = by.setdefault(u, {"commits": {}, "files": [], "unknown": [], "ran": [],
                                  "rest": 0})
            c = g["commits"].setdefault(sha, {"sha": sha,
                                              "subject": str(off.get("subject") or "")[:70],
                                              "age": off.get("age"), "files": []})
            for p in ((off.get("by_unit") or {}).get(unit) or ()):
                if p not in c["files"]:
                    c["files"].append(str(p))
                if p not in g["files"]:
                    g["files"].append(str(p))
            for pair in (off.get("unknown") or ()):
                if pair not in g["unknown"]:
                    g["unknown"].append(pair)
            for pair in (off.get("ran") or ()):
                if pair not in g["ran"]:
                    g["ran"].append(pair)
            try:
                g["rest"] = max(g["rest"], int(off.get("rest") or 0))
            except (TypeError, ValueError):
                pass
    out = []
    for unit in sorted(by):
        g = by[unit]
        commits = sorted(g["commits"].values(),
                         key=lambda c: (-float(c.get("age") or 0.0), c["sha"]))
        old = commits[0]
        out.append({"sha": old["sha"],                # ключ строки очереди: САМЫЙ СТАРЫЙ
                    "subject": old["subject"],
                    "age": old["age"],
                    "unit": unit,
                    "units": [unit],
                    "commits": commits,
                    "n": len(commits),
                    "rest": g["rest"],
                    "by_unit": {unit: sorted(g["files"])},
                    "files": sorted(g["files"]),
                    "unknown": list(g["unknown"]),
                    "ran": list(g["ran"])})
    return out


def row_text(off):
    """Строка ОЧЕРЕДИ карточки (не тело!): маркер + список коммитов + юниты. Формат один и тот же
    у писателя и у читателя (`units_of`/`shas_of`) — иначе ответ владельца пришлось бы разбирать
    из прозы тела, а тело очередь затирает вердиктом (класс `chain_cards`).

    СТАРЫЕ ЧИТАТЕЛИ НЕ СЛОМАНЫ НАМЕРЕННО: головной маркер остаётся первым и несёт САМЫЙ СТАРЫЙ
    коммит, список едет ОТДЕЛЬНОЙ скобкой ДО слов о юнитах — поэтому `sha_of` и `units_of`
    отвечают ровно то же, что отвечали, а карточка, висящая в очереди с прошлой редакции,
    разбирается новой (`shas_of` падает на `sha_of`)."""
    head = mark(off.get("sha"))
    shas = [c["sha"] for c in commits_of(off)]
    if len(shas) > 1:
        head += MARK_LIST_HEAD + " ".join(shas) + MARK_LIST_TAIL
    return head + UNITS_HEAD + ", ".join(off.get("units") or ())


def shas_of(text):
    """Строка очереди → ВСЕ коммиты карточки. Старая форма (один коммит в головном маркере)
    читается той же функцией: список не найден → отдаём головной. Пусто = разобрать не удалось."""
    t = str(text or "")
    i = t.find(MARK_LIST_HEAD)
    if i >= 0:
        tail = t[i + len(MARK_LIST_HEAD):]
        cut = tail.find(MARK_LIST_TAIL)
        if cut > 0:
            out = []
            for tok in tail[:cut].replace(",", " ").split():
                s = tok.strip()
                if s and all(c in "0123456789abcdef" for c in s.lower()) and s not in out:
                    out.append(s)
            if out:
                return out
    one = sha_of(t)
    return [one] if one else []


def units_of(text):
    """Строка очереди → юниты, которым коммит не доехал. Пусто = разобрать не удалось, и это
    ЧЕСТНЫЙ отказ: «да» владельца в таком случае гасить молча нельзя, но и угадывать юнит —
    значит перезапустить не то."""
    t = str(text or "")
    i = t.find(UNITS_HEAD)
    if i < 0:
        return []
    return [u.strip() for u in t[i + len(UNITS_HEAD):].split(",") if u.strip()]


def restart_cmd(unit):
    """Команда доставки для юнита. Слово о ФОРМЕ, а не о праве: право даёт «да» владельца."""
    u = str(unit or "")
    if u in DEFERRED_UNITS:
        return "systemd-run --on-active=10s systemctl restart " + u
    return "systemctl restart " + u


def offer(note, units):
    """Заметка О3 + список наблюдаемых юнитов → предложение карточки | None.

    None — на КАЖДОЙ дырке: не тот вид заметки, состояние не «не доставлен», список файлов пуст,
    отсрочка объявления не вышла, юнит не назван или не наблюдается, разбор упал. Сомнение здесь
    решается в сторону молчания намеренно: лишний вопрос владельцу о перезапуске прода стоит
    дороже, чем ещё одна строка в журнале наблюдения, которая и так пишется."""
    try:
        if not isinstance(note, dict):
            return None
        if note.get("kind") != KIND_UNDELIVERED:
            return None
        if note.get("state") != expectations.UNDELIVERED:
            return None                       # двойной замок: вид заметки И состояние прибора
        if float(note.get("defer") or 0) > 0:
            return None                       # объявление отложено — вопрос тем более ждёт
        sha = str(note.get("sha") or "")[:7]
        if not sha:
            return None
        known = {str(u) for u in (units or ())}
        if not known:
            return None
        by_unit, files = {}, []
        for row in (note.get("missing") or ()):
            path, unit = str(row[0]), str(row[1])
            if unit not in known:
                return None                   # чужой вид доставки → предложения нет ВОВСЕ
            by_unit.setdefault(unit, []).append(path)
            files.append(path)
        if not by_unit:
            return None
        return {"sha": sha,
                "subject": str(note.get("subject") or "")[:70],
                "age": note.get("age"),
                "units": sorted(by_unit),
                "by_unit": {u: sorted(p) for u, p in by_unit.items()},
                "files": sorted(set(files)),
                # Часть коммита, которую рестарт НЕ доставит (выкладка моста, конфиг владельца,
                # незакоммиченная правка рядом). Молчать о ней нельзя: иначе «да» будет прочитано
                # как доставка ВСЕГО коммита.
                "unknown": [(str(p), str(w)) for p, w in (note.get("unknown") or ())],
                # НАБЛЮДЁННОЕ ИСПОЛНЕНИЕ этих же байт (тик-потребитель поднимает код с диска).
                # Требование им не отменяется — память названных процессов и правда отстала, —
                # но без него карточка утверждала бы о живой системе неправду.
                "ran": [(str(p), str(w)) for p, w in (note.get("ran") or ())]}
    except Exception:                                                # noqa: BLE001
        return None


def render(off):
    """Предложение → тело карточки владельцу. Оба исхода названы ДО нажатия."""
    age = expectations.human_age(off.get("age"))
    commits = commits_of(off)
    lines = ["🚚 ДОСТАВКА ПРОВЕРЕННОГО КОММИТА В ПРОД — нужно твоё «да»", ""]
    # «ЖИВОЙ ПРОЦЕСС ЕГО НЕ ЧИТАЛ» — правда РОВНО тогда, когда исполнения этих байт никто не
    # наблюдал. Есть наблюдённый прогон → говорим о ПАМЯТИ названных процессов, а не о проде
    # целиком: прежняя формула была ложью о живой системе (случай 4e6e0ce, 18.08.2026).
    lines.append("Коммит `%s` («%s») лежит в origin/main, ему %s, а %s: "
                 "код держится в памяти и доезжает до прода только перезапуском."
                 % (off["sha"], off.get("subject") or "без заголовка", age,
                    "процессы ниже его в памяти НЕ ДЕРЖАТ" if off.get("ran")
                    else "живой процесс его НЕ ЧИТАЛ"))
    # ВОПРОС ОДИН НА ОПЕРАЦИЮ, поэтому карточка обязана назвать ВСЮ работу этой операции: рестарт
    # поднимает дерево целиком, и вместе со старшим коммитом доедут все, что легли после него.
    # Молчать о них нельзя — иначе «да» дано на одно, а случится другое (класс `_HUMAN_MISSING`).
    if len(commits) > 1:
        lines.append("")
        lines.append("ЭТИМ ЖЕ ПЕРЕЗАПУСКОМ ДОЕДУТ ВСЕ НАКОПЛЕННЫЕ КОММИТЫ — их %d:" % len(commits))
        for c in commits:
            lines.append("   %d. `%s` («%s») — %s"
                         % (commits.index(c) + 1, c["sha"], c.get("subject") or "без заголовка",
                            expectations.human_age(c.get("age"))))
        lines.append("Вопрос ОДИН, потому что действие одно: перезапуск поднимает в память ВСЁ "
                     "дерево, а не отдельный коммит. Отдельных карточек на каждый коммит больше "
                     "не будет.")
    if off.get("rest"):
        lines.append("Рядом ждут своей очереди ещё %d недоставленных коммита(ов) — прибор "
                     "показывает не больше трёх за замер; они попадут в следующую карточку, "
                     "если этот перезапуск их не заберёт." % int(off["rest"]))
    if off.get("ran"):
        lines.append("Часть этого коммита в проде УЖЕ исполняется: %s — перезапуск нужен не ей."
                     % ", ".join(p for p, _w in off["ran"][:4]))
    lines.append("")
    for unit in off["units"]:
        lines.append("• %s — файлы: %s" % (unit, ", ".join(off["by_unit"][unit][:6])))
    if off.get("unknown"):
        lines.append("• рестарт НЕ доставит: %s (%s)"
                     % (", ".join(p for p, _w in off["unknown"][:4]),
                        off["unknown"][0][1]))
    lines.append("")
    lines.append("✅ — ПОСТАВЛЮ ЗАДАЧУ: гейт (`venv/bin/python3 gate.py`) → ТОЛЬКО при зелёном "
                 "перезапуск (%s) → проверка `systemctl is-active` и чистого старта → отчёт в 328. "
                 "Гейт красный — перезапуска НЕ будет, придёт честный отчёт."
                 % "; ".join(restart_cmd(u) for u in off["units"]))
    lines.append("❌ — не делаю ничего: коммит остаётся в git, прод остаётся на прежнем коде, "
                 "перезапуск по-прежнему твой ручной ход.")
    # ОТКАТ НАЗЫВАЕТСЯ ОДИН И НАСТОЯЩИЙ. Перезапуск поднимает в память ДЕРЕВО, поэтому вернуть
    # процесс на прежний код можно ровно одним способом — вернуть дерево и перезапустить снова.
    # Два соседних хода выглядят откатом и им НЕ являются, и это сказано прямо: ❌ ничего не
    # откатывает (прод и так на прежнем коде), а `git revert` рождает НОВЫЙ коммит, который сам
    # потребует доставки тем же перезапуском. Названный откат — ход ВЛАДЕЛЬЦА: задача, которую
    # поставит «да», делает доставку и ничего больше.
    lines.append("")
    lines.append("ОТКАТ ОДИН И НАСТОЯЩИЙ — вернуть дерево на состояние ДО самого старого из "
                 "перечисленных и перезапустить снова: `git checkout %s^ -- .`, затем %s. "
                 "Откатом НЕ являются: ❌ на этой карточке (она ничего не меняет — прод и так на "
                 "прежнем коде) и `git revert` (рождает НОВЫЙ коммит, его придётся доставлять "
                 "тем же перезапуском)."
                 % (off["sha"], "; ".join(restart_cmd(u) for u in off["units"])))
    lines.append("")
    lines.append("Это ДОСТАВКА уже проверенного кода, а не работа над ним: правок, коммитов, "
                 "пушей и выкладки моста задача делать не будет. Если к моменту нажатия коммит "
                 "успеет доехать сам (любым другим рестартом) — задача не поставится вовсе, "
                 "прибор спрашивается второй раз перед исполнением.")
    return "\n".join(lines)


def tz(tid, off):
    """Предложение + номер карточки → ТЗ задачи-доставщика.

    Маркер конверта ПЕРВЫМ — этим включается весь готовый контур разрыва петли (слой 1
    process_new, пропуск самопочинки, пропуск куратора): ре-карточка на ту же доставку
    невозможна."""
    units = off["units"]
    commits = commits_of(off)
    shas = ", ".join("`%s`" % c["sha"] for c in commits)
    steps = ["[конверт одобренной заявки %s] Филипп нажал «да» на карточку ДОСТАВКИ в прод: "
             "перезапуск %s, и этим перезапуском доедут %d коммит(ов) — %s."
             % (tid, ", ".join(units), len(commits), shas),
             "ЗАДАЧА — довести ЭТИ коммиты до живого процесса ОДНИМ перезапуском, и ничего кроме:",
             "1) сверься: коммиты %s в origin/main, рабочее дерево от origin/main не "
             "расходится (`git status`, `git diff --name-only origin/main --`);" % shas,
             "2) прогони гейт: `venv/bin/python3 gate.py`. ТОЛЬКО exit 0 даёт право на шаг 3; "
             "красный гейт — перезапуска НЕ делай ВООБЩЕ, отчёт честный «не доставлено, гейт "
             "красный», это законный исход. ПРАВО НА ПРОД ДАЁТ ТОЛЬКО ПОЛНЫЙ НАБОР: перезапуск "
             "поднимает в память ВЕСЬ HEAD, а не затронутые модули, поэтому гейт сам поднимет "
             "набор до полного (метку доставки ставит демон). Если полный здесь действительно не "
             "нужен — например, он УЖЕ зелёный на ЭТОМ дереве и дерево после него не менялось, — "
             "назови причину флагом `--selective-reason «…»` и повтори её в отчёте и в cc_log; "
             "какой набор дал право, в отчёт вставь строкой гейта ДОСЛОВНО;",
             "3) перезапусти: %s. Рестарт демона — ТОЛЬКО отложенной единицей и САМЫМ ПОСЛЕДНИМ "
             "действием, после записи отчёта в cc_log (правило самомодификации: задача живёт в "
             "cgroup демона);" % "; ".join(restart_cmd(u) for u in units),
             "4) проверь живым фактом: `systemctl is-active %s` = active и первая строка лога "
             "после старта чистая;" % " ".join(units),
             "5) FACT: PID=<новый>, is-active=active, баннер=<первая строка лога после старта>.",
             "",
             "ЗАПРЕТЫ: кода не правь, не коммить, не пушь, мост не выкладывай, в рабочие таблицы "
             "ничего не пиши, ничего не удаляй. Работы себе не выдумывай: «да» владельца дано "
             "РОВНО на ОДИН перезапуск, доставляющий перечисленные коммиты, и ни на что сверх."]
    return "\n".join(steps)
