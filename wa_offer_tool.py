def book_said(text):
    """Слова брони в тексте черновика (`_RX_BOOK_SAID`): «бронь оформляет человек» — при любом входящем клиента (r3)."""
    return _RX_BOOK_SAID.search(str(text or "")) is not None


def _parts(s, a, b, keep=()):
    """Предложение s[a:b] → [(начало, конец, разделитель перед частью)] (`_RX_CLAUSE`; у первой — ""); разделитель
    внутри места из keep (диапазон дат) часть не делит."""
    out, at, sep = [], a, ""
    for m in _RX_CLAUSE.finditer(s, a, b):
        if any(x <= m.start() < y for x, y in keep):
            continue
        out.append((at, m.start(), sep))
        at, sep = m.end(), m.group()
    out.append((at, b, sep))
    return out


def _bare(part, allow=_BARE):
    """Часть без слов длиннее трёх букв, кроме слабого слова и слов allow — согласия, дат и сроков («Да, есть», «на эти
    даты есть»)."""
    return not [w for w in re.findall(r"[a-zа-яё]+", part.lower())
                if len(w) >= 4 and w not in allow and not _RX_WEAK.fullmatch(w)]


def _blank(text, spans):
    """Текст с местами spans, заменёнными пробелами (длина и места прочего те же)."""
    for a, b in spans:
        text = text[:a] + " " * (b - a) + text[b:]
    return text


def _inside(at, spans):
    return any(a <= at < b for a, b in spans)


def _marks(part, named=()):
    """Часть предложения (named — места моделей в ней) → исход сказанного: B.FREE | B.BUSY | UNSURE | None (слова
    наличия нет). Слово «свободно» без отрицания — свободно; с отрицанием прямо перед ним («не свободен», «нет в
    наличии», «свободных … нет») — занято; прямое слово «занято» без отрицания — занято, с отрицанием прямо перед ним
    («не занят», not booked) — свободно; голое «нет» — занято только в голой части («NMAX 155 — нет»); слабое слово —
    свободно, только если в части названа модель, байк или вариант или часть голая. «Не разобрано» (r3 приёмка) —
    отрицание где угодно ещё в части (никто, ничего, ещё не, nobody, no one, nothing, yet, hasn't been, «нет» не голой
    части), обороты «нет проблем», no problem, слова владения (ваш, yours, берите), «свободно» вместе с «занято»."""
    free = busy = False
    used = []                                       # отрицания, ставшие частью слова наличия: другим отрицанием не судятся
    for m in _RX_FREE.finditer(part):
        n = _RX_NEG.search(part[:m.start()])
        g = _RX_NET.search(part, m.end()) if _RX_GEN.search(m.group()) else None
        if n or g:
            busy = True
            used.append((n or g).span())
        else:
            free = True
    for m in _RX_BUSY.finditer(part):
        n = _RX_NEG.search(part[:m.start()])
        if n:
            free = True
            used.append(n.span())
        else:
            busy = True
    if _bare(_blank(part, named), _BARE_NET):       # голое «нет»: «NMAX 155 — нет», «на эти даты нет»
        for m in _RX_NET.finditer(part):
            if not _inside(m.start(), used):
                busy = True
                used.append(m.span())
    if not free and any(not _RX_NEG.search(part[:m.start()]) for m in _RX_WEAK.finditer(part)):
        free = bool(named or _RX_OBJECT.search(part) or _bare(part))
    if (free and busy) or _RX_IDIOM.search(part) or _RX_OWN.search(part) or \
            any(not _inside(m.start(), used) for m in _RX_NEGATOR.finditer(part)):
        return UNSURE
    return B.FREE if free else B.BUSY if busy else None


def _content(part):
    """Слова части «свободно» без модели парка, которые не служебные (r3 приёмка): от четырёх букв вне `_FILLER`, слов
    наличия, байка и аренды — «Нмакс», Forza; сокращение заглавными («ADV») — тоже. Пусто — часть голая."""
    t = part
    for rx in (_RX_FREE, _RX_BUSY, _RX_WEAK, _RX_OBJECT, _RX_RENT, _RX_ALSO, _RX_NEGATOR, _RX_ALT, _RX_ALL, _RX_ANY):
        t = rx.sub(" ", t)
    return [w for w in re.findall(r"[a-zа-яё]+", t.lower()) if len(w) >= 4 and w not in _FILLER] + \
        [w for w in _RX_CAPS.findall(t) if w not in _CAPS_OK]


def _mentions(s, bikes):
    """Модели в тексте → [(начало, конец, модель | None | False, слово)]: модель парка (`M.model_hits`; None —
    сокращение к нескольким), False — похожее на модель не из парка (сумма «THB 400» — не модель). Модель кириллицей
    («Нмакс») и без кубатуры не из парка («Forza», «ADV») моделью не находится — их судит `_loose_free` (r3 приёмка)."""
    hits = [(h[0], h[1], h[2], h[3]) for h in M.model_hits(s, bikes)]
    foreign = [(m.start(), m.end(), False, m.group()) for m in _RX_MODEL_LIKE.finditer(s)
               if not any(h[0] < m.end() and m.start() < h[1] for h in hits)
               and re.sub(r"[^a-z]", "", m.group().lower()) not in _NOT_MODEL
               and not _RX_MONEY_AFTER.match(s, m.end())]
    return sorted(hits + foreign)


def _dated(s):
    """Текст → он же для разбора дат, длина и места те же (r3 приёмка): суффиксы порядковых («18-го», «22-е», 18th) —
    пробелы, through/thru — till, «to the 15» — «to 15», «between X and Y» и «между X и Y» — «X to Y» и «X - Y»."""
    t = _RX_ORD.sub(lambda m: m.group(1) + " " * len(m.group(2)), s)
    t = _RX_THROUGH.sub(lambda m: "till".ljust(len(m.group())), t)
    t = _RX_THE.sub(lambda m: m.group(1) + m.group(2) + "   ", t)
    return _RX_BETWEEN.sub(lambda m: " " * len(m.group(1)) + m.group(2) + ("to " if len(m.group(3)) == 3 else "-"), t)


def _ranges(s, today):
    """Диапазоны дат текста → [(начало, конец, (выдача, возврат) | None, (день, день) | None, слова)] по месту: с
    месяцем — даты (`M.find_ranges` по `_dated`, год — от today, начало словом «с завтра» — от today), без месяца («с 10
    по 15», «на 18–22», «from the 18th to the 22nd») — только числа дней."""
    t = _dated(s)
    out = []
    for r in M.find_ranges(t, today, today):
        if r["ds"] is not None:
            out.append((r["a"], r["b"], (r["ds"], r["de"]), None, r["label"]))
        else:
            d = [int(x) for x in re.findall(r"\d{1,2}", t[r["a"]:r["b"]])]
            out.append((r["a"], r["b"], None, tuple(d[:2]), r["label"]))
    for rx in (_RX_DASH_DAYS, _RX_WORD_DAYS):
        for m in rx.finditer(t):
            a, b, d1, d2 = m.start(1), m.end(2), int(m.group(1)), int(m.group(2))
            if 1 <= d1 < d2 <= 31 and not any(g[0] < b and a < g[1] for g in out):
                out.append((a, b, None, (d1, d2), "%d–%d (месяц не назван)" % (d1, d2)))
    return sorted(out)


def _near(today, d, mo, y=None):
    """День и месяц (год — если назван) → date | None; без года — ближайшая будущая (сегодня включительно)."""
    try:
        if y is not None:
            y = int(y)
            return datetime.date(y + 2000 if y < 100 else y, int(mo), int(d))
        got = datetime.date(today.year, int(mo), int(d))
        return got if got >= today else datetime.date(today.year + 1, int(mo), int(d))
    except (ValueError, TypeError):
        return None


def _points(s, rngs, today):
    """Похожее на дату вне диапазонов `_ranges` (r3 приёмка) → [(начало, конец, вид, значение, слова)] по месту: "day"
    — дата (день с месяцем, дд.мм, ГГГГ-ММ-ДД, сегодня, завтра), "dom" — только число дня («18-го», 18th, «с 18», «до
    22», from 18), "vague" — срок словами (день недели, неделя, выходные, месяц словом; «в неделю» — цена, не срок),
    "year" — год."""
    t, taken, out = _dated(s), [(g[0], g[1]) for g in rngs], []

    def put(a, b, kind, value):
        if value is None or any(x < b and a < y for x, y in taken):
            return
        taken.append((a, b))
        out.append((a, b, kind, value, s[a:b].strip().rstrip(".")))
    for m in _RX_ISO_DAY.finditer(t):
        put(m.start(), m.end(), "day", _near(today, m.group(3), m.group(2), m.group(1)))
    for m in _RX_NUM_DAY.finditer(t):
        put(m.start(), m.end(), "day", _near(today, m.group(1), m.group(2), m.group(3)))
    for m in _RX_DAY_MON.finditer(t):
        put(m.start(), m.end(), "day", _near(today, m.group(1), _MON_NUM.get(m.group(2).lower()[:3])))
    for m in _RX_MON_DAY.finditer(t):
        put(m.start(), m.end(), "day", _near(today, m.group(2), _MON_NUM.get(m.group(1).lower()[:3])))
    for m in _RX_REL_DAY.finditer(t):
        w = m.group().lower()
        put(m.start(), m.end(), "day", today + datetime.timedelta(
            days=2 if w.startswith(("после", "day")) else 1 if w.startswith(("завтра", "tomorrow")) else 0))
    for m in _RX_ORD.finditer(s):
        put(m.start(), m.end(), "dom", int(m.group(1)) if 1 <= int(m.group(1)) <= 31 else None)
    for m in _RX_PREP_DAY.finditer(t):
        put(m.start(), m.end(1), "dom", int(m.group(1)) if 1 <= int(m.group(1)) <= 31 else None)
    for m in _RX_VAGUE.finditer(t):
        per = _RX_UNIT.match(m.group()) and _RX_PER.search(t[:m.start()])
        put(m.start(), m.end(), "vague", None if per else True)
    for m in _RX_YEAR.finditer(t):
        put(m.start(), m.end(), "year", int(m.group(1)))
    return sorted(out)


def _windows(o):
    """Факт offer → окна дат, которые он проверил: (с, по) факта; у «свободно» срока на минимум класса — ещё (с, по
    клиента): оно внутри проверенного («занято» на минимум о более коротком сроке клиента не говорит)."""
    out = [(day_arg(o.get("date_from")), day_arg(o.get("date_to")))]
    if o.get("avail") == B.FREE and o.get("asked_to") and o.get("asked_to") != o.get("date_to"):
        out.append((out[0][0], day_arg(o.get("asked_to"))))
    return [w for w in out if w[0] is not None and w[1] is not None]


def _covers(g, o):
    """Диапазон текста (`_ranges`) — окно факта offer? Без месяца — по числам дней."""
    return any((g[2] is not None and g[2] == w) or (g[3] is not None and g[3] == (w[0].day, w[1].day))
               for w in _windows(o))


def _ends(o):
    """Факт offer → его концы: начало, конец, конец клиента (до минимума класса)."""
    return {d for d in (day_arg(o.get("date_from")), day_arg(o.get("date_to")), day_arg(o.get("asked_to"))) if d}


def _infer(parts, i):
    """Модель в части без слова наличия → (исход сказанного о ней: B.FREE | B.BUSY | UNSURE | None, номер части, у
    которой он взят | None): следующая часть без модели со словом наличия («NMAX 155 — нет»); иначе ближайшая прежняя
    часть со словом — после «но», «а», but между ними обратный ей («…, but NMAX 155 is», «…, а NMAX 155 — да»), без них
    тот же («XMAX 300 тоже»); иначе ближайшая следующая; слова наличия в предложении нет — None. «Не разобрано» берётся
    как есть (r3 приёмка): ни обратного, ни «занято» у такой части нет."""
    nxt = parts[i + 1] if i + 1 < len(parts) else None
    if nxt is not None and not nxt["named"] and nxt["mark"]:
        return nxt["mark"], i + 1
    j = next((k for k in range(i - 1, -1, -1) if parts[k]["mark"]), None)
    if j is not None:
        mark = parts[j]["mark"]
        if mark != UNSURE and any(_RX_CONTRAST.fullmatch(parts[k]["sep"]) for k in range(j + 1, i + 1)):
            mark = B.BUSY if mark == B.FREE else B.FREE
        return mark, j
    k = next((k for k in range(i + 1, len(parts)) if parts[k]["mark"]), None)
    return (None, None) if k is None else (parts[k]["mark"], k)


def _judge(model, word, st, dates, by):
    """Упоминание (модель | None — сокращение | False — не из парка; исход сказанного; диапазоны его дат) + принятые
    факты по моделям → ("ok" | "bad" | "unsure" | "pending", почему): "bad" — расхождение, "unsure" — не сверено,
    "pending" — слова наличия о модели нет (судит другое её упоминание со словом; такого нет — не сверено). Исход «не
    разобрано» (r3 приёмка) — не сверено, даже когда даты совпали."""
    if model is False:
        return ("bad", M_FOREIGN % label_of(word)) if st == B.FREE else \
            ("unsure", U_FOREIGN % label_of(word)) if st == UNSURE else ("ok", "")
    if model is None:
        return ("bad", M_ALIAS % label_of(word)) if st == B.FREE else ("unsure", U_ALIAS % label_of(word))
    facts = by.get(model) or []
    if not facts:
        return ("bad", M_UNCHECKED % model) if st in (B.FREE, B.BUSY) else ("unsure", U_UNCHECKED % model)
    for g in dates or ():
        got = {o.get("avail") for o in facts if _covers(g, o)}
        if not got:
            return "bad", M_DATES % (model, g[4])
        if st in (B.FREE, B.BUSY) and got != {st}:
            return "bad", (M_BUSY if st == B.FREE else M_FREE) % model
    if st is None:
        return "pending", U_STANCE % model
    if st == UNSURE:
        return "unsure", U_STANCE % model
    got = {o.get("avail") for o in facts}
    if dates or got == {st}:
        return "ok", ""
    if st == B.FREE:
        return "bad", (M_BOTH if B.FREE in got else M_BUSY) % model
    return "bad", (M_FREE_SOME if B.BUSY in got else M_FREE) % model


def _judge_any(g, st, facts):
    """Диапазон дат в предложении без модели → ("ok" | "bad" | "unsure", почему): факт на эти даты у любой модели (со
    словом наличия — и исход тот же; «не разобрано» — не сверено)."""
    got = {(r.get("offer") or {}).get("avail") for r in facts if _covers(g, r.get("offer") or {})}
    if not got:
        return "bad", M_DATES_ANY % g[4]
    if st in (B.FREE, B.BUSY) and got != {st}:
        return "bad", M_DATES_DIFF % g[4]
    if st == UNSURE:
        return "unsure", U_DATES % g[4]
    return "ok", ""


def _judge_point(q, models, by, facts):
    """Похожее на дату вне диапазонов (`_points`) + модели его части (иначе предложения; нет — любые факты) → ("ok" |
    "unsure", почему): дата — начало или конец (конец клиента) факта этих моделей, число дня — их число, год — их год;
    срок словами — всегда не сверено."""
    kind, word = q[2], label_of(q[4])
    if kind == "vague":
        return "unsure", U_PERIOD % word
    pool = [o for m in models for o in by.get(m) or ()] if models else [r.get("offer") or {} for r in facts]
    ends = {d for o in pool for d in _ends(o)}
    ok = (q[3] in ends if kind == "day" else q[3] in {d.day for d in ends} if kind == "dom" else
          q[3] in {d.year for d in ends})
    if ok:
        return "ok", ""
    return "unsure", (U_YEAR if kind == "year" else U_DATE) % word


def _loose_free(part, p, parts, i):
    """Часть без модели парка → [(None, исход, почему)] о «свободно» в ней (r3 приёмка). Своё «свободно», не отданное
    модели предложения: «другие», «все», «остальные», other, all — расхождение; иное слово (любой, any, «Нмакс», Forza,
    ADV) — не сверено; голая часть — пусто (её судит M_BARE). Отданное модели («PCX 160 — свободен», «есть другой
    вариант — NMAX 155») судится с моделью, но иное слово в нём («PCX 160 или Нмакс свободны») — всё равно не сверено.
    Без своего слова наличия — с «другие модели», «все модели», любой, any или «тоже» при ином слове — не сверено, если
    предложение не говорит «занято» («другие модели проверю» — не она)."""
    words = _content(part)
    if p["lent"]:
        return [(None, "unsure", U_WORD % label_of(words[0]))] if p["mark"] == B.FREE and words else []
    alt, alls, anys = _RX_ALT.search(part), _RX_ALL.search(part), _RX_ANY.search(part)
    if p["mark"] == B.FREE:
        if alt or alls:
            return [(None, "bad", M_OTHERS % label_of((alt or alls).group()))]
        if anys or words:
            return [(None, "unsure", U_WORD % label_of(anys.group() if anys else words[0]))]
        p["bare_free"] = True
        return []
    if p["mark"] is not None or _RX_LATER.search(part):
        return []
    hit = alt.group() if alt else (alls or anys).group() if (alls or anys) and _RX_OBJECT.search(part) else None
    if hit is None and _RX_ALSO.search(part) and words:
        hit = words[0]
    # RC2010 (храповик слепых читателей): условие то же, что «hit is None or … == BUSY → []», записано утвердительно —
    # «нечего сказать» здесь честный ответ разбора, а не промах чтения
    if hit is not None and _infer(parts, i)[0] != B.BUSY:
        return [(None, "unsure", U_WORD % label_of(hit))]
    return []


def avail_check(text, facts, bikes, today=None):
    """Текст черновика + принятые факты offer + парк снимка → (расхождение, не сверено): списки «почему» по порядку, без
    повторов (см. шапку раздела). Оба пусты — текст с фактами сверен целиком; фактов нет — оба пусты (снимать нечего).
    today — «сегодня» сверки (год дат без года, начало «с завтра»); нет — по часам Пхукета."""
    if not facts:
        return [], []
    today = today or B.local_now(time.time()).date()
    by = {}
    for r in facts:
        o = r.get("offer") or {}
        by.setdefault(o.get("model"), []).append(o)
    busy_any = any(o.get("avail") == B.BUSY for v in by.values() for o in v)
    s = str(text or "")
    ments, rngs, seen = _mentions(s, bikes), _ranges(s, today), []          # seen: (модель | None, исход, почему)
    pts = _points(s, rngs, today)
    for a, b in _sentences(s):
        sr = [g for g in rngs if a <= g[0] < b]
        parts = []
        for c0, c1, sep in _parts(s, a, b, [(g[0], g[1]) for g in sr]):
            named = [x for x in ments if c0 <= x[0] < c1]
            parts.append({"sep": sep, "named": named, "rngs": [g for g in sr if c0 <= g[0] < c1], "a": c0, "b": c1,
                          "mark": _marks(s[c0:c1], [(x[0] - c0, min(x[1], c1) - c0) for x in named]), "lent": False})
        fleet = list(dict.fromkeys(x[2] for p in parts for x in p["named"] if x[2]))
        loose = [g for p in parts if not p["named"] and not p["mark"] for g in p["rngs"]]   # даты ничьей части
        stances = []
        for i, p in enumerate(parts):
            for x in p["named"]:
                st = p["mark"]
                if not st:
                    st, k = _infer(parts, i)
                    if k is not None:
                        parts[k]["lent"] = True           # «свободно» этой части судится с моделью, а не само
                stances.append(st)
                seen.append((x[2],) + _judge(x[2], x[3], st, p["rngs"] or loose, by))
        for i, p in enumerate(parts):
            if p["named"]:
                continue
            for g in p["rngs"]:                       # даты в части без модели — у моделей предложения или у любой
                if fleet:
                    seen += [(m,) + _judge(m, m, p["mark"], [g], by) for m in fleet]
                else:
                    seen.append((None,) + _judge_any(g, p["mark"], facts))
            seen += _loose_free(s[p["a"]:p["b"]], p, parts, i)
        if busy_any and B.FREE not in stances and any(p.get("bare_free") and not p["rngs"] for p in parts):
            seen.append((None, "bad", M_BARE))
        for q in pts:                                 # похожее на дату вне диапазонов — у моделей своей части
            if a <= q[0] < b:
                p = next((p for p in parts if p["a"] <= q[0] < p["b"]), None)
                own = [x[2] for x in p["named"] if x[2]] if p else []
                seen.append((None,) + _judge_point(q, own or fleet, by, facts))
    said = {m for m, v, _w in seen if v in ("ok", "bad") and m}    # о модели разобрано другое упоминание
    bad = [w for _m, v, w in seen if v == "bad"]
    unsure = [w for m, v, w in seen if v == "unsure" or (v == "pending" and m not in said)]
    return list(dict.fromkeys(bad)), list(dict.fromkeys(unsure))


def _mins(age):
    return int((age or 0) // 60)


# ── вызовы offer одной сверки ───────────────────────────────────────────────────────────────────────────────────

class Offers(object):
    """Вызовы offer ОДНОЙ сверки: предел, кеш пар, общая дверь цены (ответ на (юнит, даты) читается один раз), ответы по
    порядку. Двери — у адаптера: `book` (снимок), `door` (quote_price), `no_price_models`. since — время последнего
    входящего клиента (r3: «занято» по снимку раньше него — не факт; см. СВЕЖЕСТЬ в шапке)."""

    def __init__(self, adapter, today=None, limit=OFFER_MAX, since=None):
        self.adapter, self.today, self.limit, self.since = adapter, today, limit, since
        self.results, self.cache, self.memo = [], {}, {}
        self.calls = self.door_calls = self.cached = self.over = 0
        self.bikes = None                                            # парк последнего служащего снимка (`avail_check`)

    def door(self, unit, ds, de):
        """Общая дверь цены вызова: (юнит, даты) → ответ двери, прочитанный один раз; исключение — то же, повторно."""
        key = (B.qnorm(unit), str(ds), str(de))
        if key not in self.memo:
            self.door_calls += 1
            try:
                self.memo[key] = (True, self.adapter.door(unit, ds, de))
            except Exception as e:                                   # noqa: BLE001 — исход судят free_bikes/quote
                self.memo[key] = (False, e)
        ok, got = self.memo[key]
        if not ok:
            raise got
        return got

    def call(self, args, clock=time.time):
        """Вход модели → ответ инструмента (форма `T.result` + поле `offer`); записан в `results`."""
        at = clock()
        self.calls += 1
        if self.calls > self.limit:                                  # предел — ни снимка, ни двери
            self.over += 1
            asked = label_of(args.get("model")) if isinstance(args, dict) else ""
            res = self._res(T.REFUSED, at, W_LIMIT, {"code": "limit", "asked": asked})
        else:
            try:
                res = self._read(args if isinstance(args, dict) else {}, at, clock)
            except Exception as e:                                   # noqa: BLE001 — сбой инструмента: не факт
                res = self._res(T.UNKNOWN, at, L_FAIL % type(e).__name__, {"code": "fail"})
        self.results.append(res)
        return res

    @staticmethod
    def _res(outcome, at, reason="", offer=None, facts=None, read_at=None, ref="", window=""):
        o = {"model": None, "asked": "", "date_from": None, "date_to": None, "asked_to": None, "days": None, "min": None,
             "client": None, "avail": None, "units": 0, "free": 0, "busy": 0, "unchecked": 0, "unit": None, "age": None,
             "snap_old": None, "door_calls": 0, "quote": None, "gate": None, "code": None, "line": "", "cached": False}
        o.update(offer or {})
        res = T.result(OFFER_TOOL, outcome, SOURCE, ref=ref, at=at, window=window, reason=reason, facts=facts,
                       read_at=at if read_at is None else read_at)
        res["offer"] = o
        return res

    def _read(self, args, at, clock):
        a = self.adapter
        asked = label_of(args.get("model"))
        ds, de = day_arg(args.get("date_from")), day_arg(args.get("date_to"))
        base = {"asked": asked, "date_from": ds.isoformat() if ds else None, "date_to": de.isoformat() if de else None,
                "asked_to": de.isoformat() if de else None}                   # конец, названный моделью (до минимума)
        if ds is None or de is None:
            return self._res(T.REFUSED, at, W_DATES, dict(base, code="dates"))
        if de <= ds:
            return self._res(T.REFUSED, at, W_ORDER, dict(base, code="order"))
        today = self.today or B.local_now(at).date()
        if ds < today:
            return self._res(T.REFUSED, at, W_PAST % today.isoformat(), dict(base, code="past"))
        if getattr(a, "book", None) is None:
            return self._res(T.UNKNOWN, at, W_NO_BOOK, dict(base, code="no_book"))
        if getattr(a, "door", None) is None:
            return self._res(T.UNKNOWN, at, W_NO_DOOR, dict(base, code="no_door"))
        now = clock()
        rows, bikes, age, why = a.book.get(now)
        taken = now - age if isinstance(age, (int, float)) and not isinstance(age, bool) else None
        base["age"] = age
        if rows is None or not bikes:
            return self._res(T.UNKNOWN, at, W_NO_SNAP % (why or "парка в снимке нет"), dict(base, code="snapshot"),
                             read_at=taken)
        self.bikes = bikes
        model, code, why_m = model_of(args.get("model"), bikes)
        if model is None:
            return self._res(T.AMBIGUOUS if code in ("alias", "many") else T.UNKNOWN, at, why_m,
                             dict(base, code=code), read_at=taken)
        units = M.units_of(model, bikes)
        term = term_of(model, ds, de)
        base.update(model=model, date_to=term["de"].isoformat(), days=term["days"], min=term.get("min"),
                    client=term.get("client"), units=len(units))
        key = (model, term["ds"], term["de"])
        if key in self.cache:                                        # повтор пары — двери нет
            self.cached += 1
            got = self.cache[key]
            return dict(got, offer=dict(got["offer"], cached=True, door_calls=0),
                        reason=(got["reason"] + "; " if got["reason"] else "") + W_CACHED)
        res = self._pair(model, units, term, rows, age, why, now, at, taken, base)
        self.cache[key] = res
        return res

    def _pair(self, model, units, term, rows, age, why, now, at, taken, base):
        """Пара прошла вход: ворота цены (`K.quote` с заглушкой) → `free_bikes` → `K.quote` той же дверью."""
        a = self.adapter
        before = self.door_calls
        ref, window = model, "%s…%s" % (term["ds"].isoformat(), term["de"].isoformat())
        probe = []
        gate = K.quote(model, term["ds"], term["de"], lambda u, s, e: probe.append(u), lambda m: list(units),
                       a.no_price_models)
        if not probe:                                                # ворота: дверь не зовётся
            human = gate["outcome"] == K.PRICE_HUMAN
            gate = M.mark_minimum(gate, term)
            why_g = (W_GATE_HUMAN % K.REASON_WORDS[gate["reason"]] if human and gate.get("reason") in K.REASON_WORDS
                     else W_GATE_UNKNOWN % (gate.get("why") or "ворота цены"))
            return self._res(T.UNKNOWN, at, why_g, dict(base, code="gate", gate=gate.get("reason") if human else None,
                                                        quote=gate if human else None),
                             read_at=taken, ref=ref, window=window)
        seen = []

        def door(u, s, e):
            seen.append(u)
            return self.door(u, s, e)
        avail = B.free_bikes(model, units, term["ds"], term["de"], rows, age, why, B.local_now(now), door)
        old = not snap_fresh(taken, self.since)       # r3: снимок раньше последнего входящего (или время неизвестно)
        o = dict(base, avail=avail["outcome"], free=avail["free"], busy=avail["busy"], unchecked=avail["unchecked"],
                 line=avail["line"], unit=None, snap_old=old)
        if avail["outcome"] == B.UNKNOWN:
            o["door_calls"] = self.door_calls - before
            return self._res(T.UNKNOWN, at, avail["why"], dict(o, code="avail"), read_at=taken, ref=ref,
                             window=window)
        if avail["outcome"] == B.BUSY and old:     # r3: «занято» — только снимок, а он старше входящего: не факт
            return self._res(T.UNKNOWN, at, W_OLD_BUSY % _mins(age), dict(o, avail=None, code="old_busy"),
                             read_at=taken, ref=ref, window=window)
        q = None
        if avail["outcome"] == B.FREE:
            unit = seen[0]

            def quote_door(u, s, e):              # r3: слово двери «model», похожее на юнит, — в строку модель парка
                got = door(u, s, e)
                return dict(got, model=model) if isinstance(got, dict) and unit_like(got.get("model"), units) else got
            q = M.mark_minimum(K.quote(model, term["ds"], term["de"], quote_door,
                                       lambda m: [unit] + [u for u in units if u != unit], a.no_price_models), term)
            o.update(unit=unit, quote=q)
            if old:                                   # r3: число свободных — из старого снимка, модели не называется
                o["line"] = FREE_OLD_LINE % (_mins(age), model, avail["date_start"], avail["date_end"])
        else:
            o["line"] = BUSY_LINE % (_mins(age), model, avail["date_start"], avail["date_end"], avail["units"])
        o["door_calls"] = self.door_calls - before
        fact = {"kind": "offer", "model": model, "date_start": o["date_from"], "date_end": o["date_to"],
                "days": o["days"], "min_days": o["min"], "client_days": o["client"], "avail": avail["outcome"],
                "unit": o["unit"], "units": avail["units"], "free": avail["free"], "busy": avail["busy"],
                "age": age, "read_at": taken, "door_at": at, "snap_old": old,
                "price_outcome": q["outcome"] if q else None, "day_price": q["day_price"] if q else None,
                "total": q["total"] if q else None, "deposit": q["deposit"] if q else None,
                "discount": q["discount"] if q else None, "currency": "THB"}
        return self._res(T.FACT, at, "", o, facts=[fact], read_at=taken, ref=ref, window=window)

    # ── что видит модель и что пишет журнал ─────────────────────────────────────────────────────────────────────

    def render(self):
        """Ответы offer → блок запроса модели ("" — вызовов не было). Юнита в блоке нет: его видит только сотрудник."""
        if not self.results:
            return ""
        out = [HEAD % max(0, self.limit - self.calls)]
        for i, r in enumerate(self.results, 1):
            o = r["offer"]
            name = o["model"] or ("«%s»" % o["asked"] if o["asked"] else "модель не названа")
            dates = ("%s — %s" % (o["date_from"], o["date_to"])) if o["date_from"] and o["date_to"] else "даты не разобраны"
            out.append("%d) offer %s, %s → %s%s" % (i, name, dates, r["outcome"],
                                                    (" · " + r["reason"]) if r["reason"] else ""))
            if r["outcome"] == T.FACT:
                out.append("   " + o["line"])
                if o["quote"]:
                    out.append("   ЦЕНА: " + (o["quote"].get("line") or ""))
                continue
            if o["quote"]:                                           # ворота человека — строка цены как у «ЦЕНА»
                out.append("   ЦЕНА: " + (o["quote"].get("line") or ""))
            code = o["code"]
            adv = (ADV_LIMIT if code == "limit" else ADV_MODEL if code in ("alias", "many", "fleet", "no_model") else
                   ADV_DATES if code in ("dates", "order", "past") else ADV_HUMAN if code == "gate" else ADV_LATER)
            out.append("   " + NOT_LINE % (r["reason"], adv))
        if any(r["outcome"] == T.FACT for r in self.results):
            out.append(FACT_NOTE)
        return "\n".join(out)

    def summary(self):
        """Строка журнала «offer:» — только числа."""
        facts = [r for r in self.results if r["outcome"] == T.FACT]
        return LOG_HEAD + L_SUM % (self.calls, len(facts), sum(1 for r in facts if r["offer"]["avail"] == B.FREE),
                                   sum(1 for r in facts if r["offer"]["avail"] == B.BUSY),
                                   len(self.results) - len(facts), self.over, self.door_calls, self.cached)


class Journal(T.Journal):
    """Журнал сверки `wa_agent_tools.Journal` + строки фактов offer (модель, даты, юнит — сотруднику; без номера)."""

    def __init__(self, number_tail=""):
        super(Journal, self).__init__(number_tail)
        self.offers = []

    def lines(self):
        out = super(Journal, self).lines()
        for r in self.offers:
            if r["outcome"] != T.FACT:
                continue
            o = r["offer"]
            f = {"model": o["model"], "date_start": o["date_from"], "date_end": o["date_to"], "avail": o["avail"],
                 "unit": o["unit"], "units": o["units"], "free": o["free"], "busy": o["busy"],
                 "snapshot_min": _mins(o["age"]), "snapshot_old": bool(o["snap_old"]), "door_calls": o["door_calls"],
                 "cached": o["cached"]}
            q = o["quote"] or {}
            f.update({k: q[k] for k in ("day_price", "total", "deposit", "discount") if q.get(k) is not None})
            out.append("  offer факт %s" % json.dumps(f, ensure_ascii=False))
        return out


# ── цикл сверки: КОПИЯ `wa_agent_tools.run` (PARENT_SHA) с инструментом offer ────────────────────────────────────

def run(call, system, user, doors, offer, number="", clock=time.time, fresh=None, spend=None,
        max_calls=T.MAX_CALLS, max_sec=T.MAX_SEC, reserve=T.FALLBACK_SEC, handed=None, asked=None):
    """`wa_agent_tools.run` + инструмент offer (`offer` — `Offers` этой сверки). Правки помечены «OFFER»: строка
    инструмента в блоке «ИНСТРУМЕНТЫ»; блок ответов offer после блока результатов; вызов offer идёт в `offer`, а не в
    `results` (их судят `sift`/`judge`); журнал — `Journal` с ответами offer; в итоге — ключ `offers`. Предел вызовов
    модели и секунд — прежние и общие: offer — такой же ход модели и такая же дверь."""
    t0 = clock()
    deadline = t0 + max_sec
    stop = deadline - max(0.0, min(reserve, max_sec))
    jr = Journal(re.sub(r"\D", "", str(number))[-4:])                 # OFFER: журнал с ответами offer
    jr.asked = bool(asked)
    jr.offers = offer.results
    results, n = [], {"calls": 0, "doors": 0}

    def may_call():
        return clock() < stop

    def counted(fn):
        def door(**kw):
            n["doors"] += 1
            return fn(**kw)
        return door
    doors = {k: (counted(v) if callable(v) else v) for k, v in (doors or {}).items()}
    ctx = T.bind_ctx(number, doors, results, clock, may_call)
    tools_block = T.TOOLS_BLOCK % max_calls
    if T.CASE_TOOL in doors:                      # К4 (WA_AGENT_CASE): строка инструмента дела; выкл — блок прежний
        tools_block += "\n" + T.CASE_BLOCK
    tools_block += "\n" + OFFER_BLOCK                                # OFFER: строка инструмента
    head = tools_block + "\n\n" + user

    def out(state, raw=None, usage=None):
        return {"state": state, "raw": raw, "usage": usage, "results": results, "journal": jr, "calls": n["calls"],
                "doors": n["doors"], "sec": clock() - t0, "deadline": deadline, "asked": jr.asked,
                "offers": offer.results}                              # OFFER: ответы offer — отдельно от results
    while True:
        if fresh is not None and fresh():
            return out(T.ABORTED)
        if n["calls"] >= max_calls or not may_call():
            return out(T.OVER)
        block = T.render(results)
        more = offer.render()                                         # OFFER: ответы offer — после результатов
        if more:
            block = (block + "\n\n" + more) if block else more
        due = T.due_block(results)                        # итог «к оплате» — кодом, из факта аренды (часть B)
        if due:
            block = (block + "\n\n" + due) if block else due
        # K3-FIX3 п.2: расчёт сдачи — кодом, когда касса уже прочитана (до неё отказ «оплаты в кассе нет» был бы ложным)
        sums = T.change_block(results, handed) if any(r.get("tool") == "cash" for r in results) else ""
        if sums:
            block = (block + "\n\n" + sums) if block else sums
        raw, usage = call(system, head + ("\n\n" + block if block else ""))
        n["calls"] += 1
        if spend is not None:
            spend(usage)
        turn = T.parse_turn(raw)
        if turn is None or turn[0] == "final":
            if clock() > deadline:
                return out(T.OVER, usage=usage)
            return out(T.DONE, raw, usage)
        _, tool, args = turn
        if not may_call():                                # модель просит дверь, а времени на новый вызов нет
            return out(T.OVER, usage=usage)
        t1 = clock()
        if tool == OFFER_TOOL:                                        # OFFER: вызов offer — в `offer`, не в results
            before = offer.door_calls
            res = offer.call(args, clock)
            n["doors"] += offer.door_calls - before
        else:
            res = T.call_tool(tool, args, doors, clock, ctx)
            results.append(res)
        jr.call(len(results) + len(offer.results), tool, args, res, clock() - t1)


# ── примесь ─────────────────────────────────────────────────────────────────────────────────────────────────────

class OfferMixin:
    """Примесь к адаптеру модели: инструмент offer в сверке Т4а. Переопределяет ровно `_draft_tools`."""

    def _draft_tools(self, number, upto_id, hint=None):
        """КОПИЯ `ModelAdapter._draft_tools` (PARENT_SHA) с правками OFFER1910 (помечены «OFFER»): цикл — `run` этого
        модуля; опора денег, суток и дат — исход цены вместе с ценами принятых фактов offer; причины кода — с поправкой
        фактов offer (`offer_reasons`, `without_avail_words`); журнал — со строкой «offer:». Факты незавершённой сверки
        (предел) — не опора, и факты offer тоже."""
        if hint is None:
            system, user, info = self.build(number, upto_id)
        else:                                               # версия по пояснению со сверкой (Д2): блок пояснения
            system, user, info = self.build(number, upto_id, hint=hint)
        handed = T.cash_said(info.get("question"))         # K3-FIX3 п.2: переданные наличные — СЛОВА клиента
        asked = T.pay_asked(info.get("question"))          # K3-FIX шаг 3e: входящее клиента — об оплате (признак судье)
        # K3-FIX шаг 3g: тема оплаты открыта? — хвост и история перед ним блоками, от нашего последнего ответа назад, до
        # закрывающего события (признак правилу класса; блоков в сведениях нет — один обмен `before`, как в первой части)
        topic = T.pay_topic(info.get("question"), *(info.get("before") or ("", "")), blocks=info.get("blocks"),
                            now=info.get("judged"))
        offer = Offers(self, info.get("today"), since=info.get("last_in"))   # OFFER: вызовы offer этой сверки (r3: since)
        with M.door_budget(T.MAX_SEC - T.FALLBACK_SEC):        # плечо моста не переживёт срок сверки (AGENTDEDUP0410)
            out = run(self.call, system, user, self._tool_doors(number, upto_id), offer, number=number,
                      clock=self.clock, fresh=(lambda: self.fresh(number, upto_id)) if self.fresh else None,
                      spend=lambda u: self._spend(u, "сверка:"), handed=handed, asked=asked)
        jr = out["journal"]
        if offer.calls:                                    # OFFER: строка журнала числами — на каждую сверку с offer
            self.log(offer.summary())
        if out["state"] == T.ABORTED:
            for line in jr.lines():
                self.log(line)
            self.log("сверка прервана: новое входящее — черновика нет")
            self.last = {"info": info, "tools": out}
            return None
        reasons, raw, usage = [], out["raw"], out["usage"]
        offers = out["offers"]                             # OFFER: ответы offer этой сверки
        if out["state"] == T.OVER:
            if self.clock() >= out["deadline"]:              # общий предел — и для запасного пути (AGENTDEDUP0410)
                for line in jr.lines():
                    self.log(line)
                self.log("сверка: общий предел %d с исчерпан — запасной вызов не начат, черновика нет (повтор позже)"
                         % T.MAX_SEC)
                self.last = {"info": info, "tools": out, "fallback": False}
                return None
            raw, usage = self.call(system, user)                # тот же один вызов, что и без флага
            self._spend(usage, "черновик:")
            reasons = [T.INCOMPLETE_WORDS]
            out["results"] = []                                 # факты незавершённой сверки не опора
            offers = []                                         # OFFER: и ответы offer — тоже
        facts_o = accepted(offers, info.get("last_in"))     # OFFER: принятые факты offer (свежие, по паре один раз)
        price = judged_price(info["price"], facts_o)       # OFFER: «ЦЕНА» ∪ цены фактов offer — опора суда
        info_j = judged_info(info, price, facts_o)         # OFFER: то же — проверкам суток и дат
        if self._cut(usage, "модель:"):                         # обрыв пределом — черновика нет (WAOPUSHIGHC0510)
            for line in jr.lines():
                self.log(line)
            self.last = {"info": info, "usage": usage, "raw": raw, "parsed": None, "tools": out}
            return None
        got = M.parse_reply(raw)
        # процент скидки за срок, названной дверью, — с опорой (WAPRICECTX0410): судья сверки процент судит без
        # исхода цены, поэтому названная дверью скидка снимается из текста до суда; прочее — как было
        said = K.without_known_discount(got["text"], price) if got else ""
        # K3-FIX шаг 3i (вариант В): судье — и сам текст входящего (с шага 3j правилу важен сам факт текста, не слова)
        words_t, figures = T.judge(said, price, out["results"], jr, handed=handed, asked=asked,
                                   incoming=info.get("question"),
                                   since=info.get("last_in"))
        for line in jr.lines():
            self.log(line)
        self.last = {"info": info, "usage": usage, "raw": raw, "parsed": got, "tools": out, "figures": figures}
        if got is None:
            self.log("модель: ответ не JSON или без текста — черновика нет (сверка %s, вызовов %d)"
                     % (out["state"], out["calls"]))
            return None
        # OFFER: причины кода — с поправкой ответов offer (принятый факт снимает «агент их не видит», только если текст
        # сверен с фактами целиком и слов брони в нём нет: иначе причина остаётся; не совпало — «не совпадает с
        # проверкой», слова брони — «бронь оформляет человек»)
        mismatch, unsure = avail_check(got["text"], facts_o, offer.bikes, info.get("today"))
        promise = bool(offers) and book_said(got["text"])
        if mismatch:
            self.log(LOG_HEAD + L_MISMATCH % "; ".join(mismatch))
        if unsure:
            self.log(LOG_HEAD + L_UNSURE % "; ".join(unsure))
        if promise:
            self.log(LOG_HEAD + L_BOOK_SAID)
        words = [r["words"] for r in offer_reasons(info["code_reasons"], offers, facts_o, info.get("question"),
                                                   mismatch, unsure, promise)]
        if got["lang"] not in ("ru", "en") and K.REASON_WORDS[K.R_LANGUAGE] not in words:
            words.append(K.REASON_WORDS[K.R_LANGUAGE])
        # K3-FIX шаг 3g (правило класса): тема оплаты открыта, а оплата кодом не подтверждена (принятые факты ЭТОЙ сверки;
        # у незавершённой их нет) — причина кода при любом тексте ответа. Она встаёт к причинам кода ДО причин модели
        # (пересказ модели об оплате отпадает как повтор); оплату уже назвал код по входящему — второй такой нет
        why_t, rule = T.topic_reason(topic, jr.facts)
        rule = K.merge_reasons(words, rule)[len(words):]
        words = K.merge_reasons(words + rule, got["handoff"])
        words = self._days_check(got["text"], info_j, words)    # сутки у дат (WADAYS0410)
        words = self._arrival_check(got["text"], info_j, words)   # срок и приезд без опоры (WATIMECLAIMB0510)
        words = self._lang_check(got["text"], info, words)      # язык ответа против языка разговора (WALANGCONVB0510)
        for w in reversed(words_t + rule):                      # причины кода о деньгах — вперёд
            words = K.reason_first(words, w)
        if why_t != T.PT_NONE:
            self.log("правило класса: %s; причина кода %s" % (
                why_t, "добавлена" if rule else "не добавлена (оплату уже назвал код по входящему)"
                if why_t in T.PT_OPEN else "не нужна"))
        for w in reversed(reasons):                             # «сверка не завершена» — самой первой
            words = K.reason_first(words, w)
        words = without_avail_words(words, facts_o, mismatch or unsure or promise)   # OFFER: пересказ при факте снят
        self.log("модель: черновик %d симв. со сверкой (%s, вызовов %d, %.1f с), причин %d"
                 % (len(got["text"]), out["state"], out["calls"], out["sec"], len(words)))
        # проверка чисел кодом для низа карточки (WACARDUI0510): опора та же, что у судьи сверки — «ЦЕНА» ∪ факты
        known = T.known_amounts(price, jr.facts, figures)
        claims = T.money_claims(said, price, known)
        # USEFUL1310 A5: что установлено кодом — числа с опорой, подтверждена ли оплата (`pay_verdict` принятых фактов
        # этой сверки), предложения о деньгах при неподтверждённой оплате; вход модели не меняется
        checked = T.money_check(got["text"], price, known, judged=said, pay=T.pay_verdict(jr.facts)[0])
        res = dict({"text": got["text"], "handoff": words, "lang": got["lang"], "why": got["why"],
                    "claims": [list(c) for c in claims], "checked": checked}, **M.card_fields(info, got))
        if self.case is not None:
            # К4 (WA_AGENT_CASE): дело и версия, на которые написан черновик, и записи в дело по фактам сверки —
            # их делает ядро (`wa_agent.Core`, роль wa); адаптер только читает. Выкл — ответ прежний
            res["case"] = T.case_plan(out["results"], since=info.get("last_in"))
            self.log("дело: %s" % res["case"]["words"])
        return res


def with_offer(cls):
    """Класс адаптера → он же с примесью (один на cls). Уже с примесью — как есть. Копии не сверены (`drift`) или
    `_draft_tools` у cls уже свой — `ParentDrift`: примесь не надевается, адаптер прежний."""
    if issubclass(cls, OfferMixin):
        return cls
    if getattr(cls, "_draft_tools", None) is not M.ModelAdapter._draft_tools:
        raise ParentDrift("у %s свой _draft_tools — копия сверки его обошла бы" % cls.__name__)
    bad = drift()
    if bad:
        raise ParentDrift("исходник родителя изменился: %s" % ", ".join(bad))
    got = _CLASSES.get(cls)
    if got is None:
        got = _CLASSES[cls] = type("Offer" + cls.__name__, (OfferMixin, cls), {"__module__": __name__})
    return got
