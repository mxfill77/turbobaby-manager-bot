def _sha(fn):
    return hashlib.sha256(inspect.getsource(fn).replace("\r\n", "\n").encode("utf-8")).hexdigest()


def drift():
    """Родители копий → [имя, …] разошедшихся с `PARENT_SHA` (исходника нет — тоже разошёлся). Пусто — сверены."""
    out = []
    for name, fn in (("wa_agent_model.ModelAdapter._draft_tools", M.ModelAdapter._draft_tools),
                     ("wa_agent_tools.run", T.run)):
        try:
            ok = _sha(fn) == PARENT_SHA[name]
        except (OSError, TypeError):                                 # исходник не прочитан — не сверено
            ok = False
        if not ok:
            out.append(name)
    return out


def day_arg(value):
    """Дата аргумента модели → date | None: строго ГГГГ-ММ-ДД (иная запись — день и месяц не угадываем)."""
    s = str(value or "").strip()
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", s):
        return None
    try:
        return datetime.date.fromisoformat(s)
    except ValueError:
        return None


def label_of(value):
    """Слова модели о модели → под маской, не длиннее LABEL_MAX (в ответ и журнал)."""
    return K.mask(re.sub(r"\s+", " ", str(value or "")).strip())[0][:LABEL_MAX]


def model_of(value, bikes):
    """Слова модели о модели + парк снимка → (модель парка | None, код отсева | None, почему). Модель — ровно одна
    модель парка по ключу живых имён (`M.model_hits`); сокращение к нескольким моделям — "alias"; несколько моделей —
    "many"; модели нет (в том числе модель с кубатурой не из парка рядом с моделью парка) — "fleet"."""
    s = str(value or "").strip()
    if not s:
        return None, "no_model", W_NO_MODEL
    hits = M.model_hits(s, bikes)
    amb = [h for h in hits if h[2] is None]
    if amb:
        return None, "alias", W_ALIAS % (amb[0][3], " / ".join(amb[0][4]))
    models = sorted({h[2] for h in hits})
    if len(models) > 1:
        return None, "many", W_MANY % " / ".join(models)
    foreign = [m for m in _RX_MODEL_LIKE.finditer(s) if not any(h[0] < m.end() and m.start() < h[1] for h in hits)]
    if not models or foreign:
        return None, "fleet", W_FLEET % label_of(foreign[0].group(0) if foreign else s)
    if not M.units_of(models[0], bikes):
        return None, "fleet", W_FLEET % label_of(s)
    return models[0], None, ""


def term_of(model, ds, de):
    """Срок запроса → {ds, de, days[, min, client]}: короче минимума класса — на минимум (как цена, WAMINPRICE0510)."""
    days = (de - ds).days
    term = {"ds": ds, "de": de, "days": days}
    mn = M.term_minimum([model]).get(model)
    if mn is not None and 0 < days < mn:
        term = dict(term, de=ds + datetime.timedelta(days=mn), days=mn, min=mn, client=days)
    return term


def snap_fresh(read_at, since):
    """Снимок прочитан не раньше последнего входящего клиента? Входящего нет (время неизвестно) — не судим (как
    `T.stale`); времени снимка нет — нет (старый снимок свежим не делает ничто)."""
    if since is None:
        return True
    return isinstance(read_at, (int, float)) and not isinstance(read_at, bool) and read_at >= since


def accepted(offers, since=None):
    """Ответы offer → принятые: FACT, вызов не раньше последнего входящего клиента (`T.stale`: «свободно» и цена — ответ
    двери в момент вызова); «занято» — ещё и СНИМОК не раньше него (`snap_fresh` по `read_at`, r3: «занято» дверью не
    сверяется, время вызова старый снимок свежим не делает); каждая пара один раз (повтор из кеша — та же пара)."""
    out, seen = [], set()
    for r in offers or ():
        if r.get("outcome") != T.FACT or T.stale(r, since):
            continue
        o = r.get("offer") or {}
        if o.get("avail") == B.BUSY and not snap_fresh(r.get("read_at"), since):
            continue
        key = (o.get("model"), o.get("date_from"), o.get("date_to"))
        if key not in seen:
            seen.add(key)
            out.append(r)
    return out


# Слово двери «model» идёт в строку цены (`K.quote`: `model=q.get("model") or model`). По копии моста в дереве
# (bridge_prod/QuotePrice.js:270–271) это имя модели прайса («HONDA PCX 160»), а юнит — отдельное поле `bike`; совпадает ли
# с копией ЖИВОЙ скрипт — НЕИЗВЕСТНО (UNKNOWN: живой ответ двери не читался). Поэтому слово, похожее на юнит (имя юнита
# модели, хвост его имени за ключом модели — номер — или «… PHUKET 3011» в конце), в строку цены не идёт: вместо него —
# модель парка. Прочее — как было.
_RX_PLATE = re.compile(r"(?i)[a-zа-яё]{2,}\s+\d{4}\s*$")


def unit_like(name, units):
    """Слово двери «model» + юниты модели → похоже на юнит (имя с номером), а не на модель?
    RC2010 (храповик слепых читателей): пустое слово — не юнит; это честный ответ предиката, а не промах чтения (в
    строке цены `K.quote` пустое слово и так заменяется моделью парка). Разбор непустого — `_unit_like_norm`."""
    n = B.qnorm(name)
    return bool(n) and _unit_like_norm(n, units)


def _unit_like_norm(n, units):
    """Непустое нормализованное слово двери `n` + юниты модели → похоже на юнит?"""
    if _RX_PLATE.search(n):
        return True
    for u in units or ():
        toks = B.qnorm(u).split()
        tail = toks[len(B.model_key(u).split()):]                  # за ключом модели: цвет, город, номер
        if n.split() == toks or (tail and tail[-1] in n.split()):
            return True
    return False


def judged_price(price, facts):
    """Исход цены вызова + принятые факты offer → исход цены для суда денег, суток и дат: цены свободных пар offer —
    вариантами `K.price_set`. Цен offer нет — исход вызова как есть (тот же объект)."""
    extra = [r["offer"]["quote"] for r in facts or () if isinstance(r.get("offer", {}).get("quote"), dict)]
    if not extra:
        return price
    return K.price_set(K.quotes_of(price) + extra)


def judged_info(info, price, facts):
    """Сведения вызова для проверок суток и дат (`_days_check`, `_arrival_check`): исход цены — `judged_price`, сроки
    («СРОКИ») — плюс сроки принятых фактов offer. Фактов нет — сведения как есть (тот же объект)."""
    if not facts and price is info.get("price"):
        return info
    terms = list(info.get("terms") or ())
    for r in facts or ():
        o = r["offer"]
        terms.append({"ds": day_arg(o["date_from"]), "de": day_arg(o["date_to"]), "days": o["days"]})
        if o.get("client"):
            terms.append({"ds": None, "de": None, "days": o["client"]})
    return dict(info, price=price, terms=terms)


def offer_reasons(reasons, offers, facts, ask, mismatch=(), unsure=(), promise=False):
    """Причины кода + ответы offer этой сверки → причины ({reason, words, why}); прежние — в прежнем порядке, новые — в
    конце, ключ причины один раз. Принятый факт и текст с фактами сверен целиком (`mismatch` и `unsure` пусты, слов брони
    в тексте нет — `promise` ложь) — «наличие и брони — агент их не видит» снята, просьба о брони — «бронь оформляет
    человек»; иначе прежняя остаётся (как без флага): не совпало — в конце «наличие в тексте не совпадает с проверкой»,
    не разобрано — без новых слов; слова брони в тексте черновика — «бронь оформляет человек» при любом входящем (r3);
    ворота человека и скидка без числа у цен offer — причины `K.handoff`; ответ не факт (кроме ворот человека) —
    «наличие не проверено — решает человек»."""
    out = [dict(r) for r in reasons or ()]
    if not offers:
        return out
    if facts and not mismatch and not unsure and not promise:
        out = [r for r in out if r.get("reason") != K.R_AVAILABILITY]
        if B.book_intent(ask):
            out.append({"reason": B.R_BOOKING, "words": B.W_BOOKING, "why": "просьба о брони"})
    if promise:
        out.append({"reason": B.R_BOOKING, "words": B.W_BOOKING, "why": "offer: слова брони в тексте черновика"})
    quotes = [r["offer"]["quote"] for r in offers if isinstance((r.get("offer") or {}).get("quote"), dict)]
    out += K.handoff("", K.price_set(quotes))
    unknown = [r for r in offers if r.get("outcome") != T.FACT and not (r.get("offer") or {}).get("gate")]
    if unknown:
        out.append({"reason": B.R_AVAIL_UNKNOWN, "words": B.W_AVAIL_UNKNOWN, "why": "offer: не факт %d" % len(unknown)})
    if mismatch:
        out.append({"reason": R_AVAIL_MISMATCH, "words": W_AVAIL_MISMATCH, "why": "offer: " + "; ".join(mismatch)})
    keep, seen = [], set()
    for r in out:
        if r.get("reason") not in seen or r.get("reason") == K.R_MONEY:
            seen.add(r.get("reason"))
            keep.append(r)
    return keep


def _norm(s):
    return re.sub(r"[^0-9a-zа-яё]+", "", str(s or "").lower())


def without_avail_words(words, facts, held=()):
    """Принятый факт offer и текст с ним сверен целиком → слова «наличие и брони — агент их не видит» сняты и у
    пересказа модели (дословного); иначе (фактов нет или причина удержана — `held`: расхождение, не сверено, слова брони)
    как есть."""
    if not facts or held:
        return words
    gone = _norm(K.REASON_WORDS[K.R_AVAILABILITY])
    return [w for w in words if _norm(w) != gone]


