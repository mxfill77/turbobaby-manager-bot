"""КОНТРАКТ КЛЕТКИ ЛИСТА1 — транспорт, а не толкование (09.08.2026).

КЛАСС, который он закрывает — тот же «нуль по неразбору», что и у [[scan_result]], только на
входе, а не на выходе. Мост схлопывает ТРИ разных состояния клетки ТО в ОДИН ноль
(`ReadFleet.js:475-482`, `parseNumber`): пустую клетку (строка 476), не-число — прочерк, слово,
дата (строка 481) и настоящий числовой ноль. Наверх приезжает `0`, и «замену не делали никогда»
становится неотличимо от «замену сделали на нулевом пробеге». Перепись
`docs/artifacts/2026-08-08-park-overdue-35-of-38-census.md`: 12 просрочек из 35 — фантомы ровно
отсюда, а живое чтение 09.08 нашло 56 таких нулей из 152 клеток ТО.

ПОЧЕМУ КОНТРАКТ НЕ НОВЫЙ, А ВЗЯТ ГОТОВЫЙ — `ScanResult`. Вопрос у вызывающего ОДИН и ТОТ ЖЕ:
«этому числу можно верить?» — а именно на него `ScanResult` и отвечает исходом вместо голого
числа. Клетка ложится на его четыре исхода без единой натяжки, потому что чтение клетки — это
и есть проход читателя по источнику, просто источник размером в одну клетку:

    ЗНАЧЕНИЕ    осмотрено 1, разобрано 1   → ok          числу можно верить, оно в `payload`
    ПУСТО       осмотрено 0                → empty       содержимого нет: мерить было нечего
    НЕ-ЧИСЛО    осмотрено 1, разобрано 0   → mismatch    содержимое ЕСТЬ, числом не стало
    мост молчит осмотрено НЕИЗВЕСТНО       → unreadable  разметки не прислали — мы НЕ ЗНАЕМ

Заводить рядом второе перечисление на те же смыслы значило бы развести два словаря об одном
(класс, которым в этом репозитории уже платили), поэтому нового контракта здесь нет вовсе.

ЧЕТВЁРТЫЙ ИСХОД ЗДЕСЬ ГЛАВНЫЙ, А НЕ ЗАПАСНОЙ. Разметку клеток отдаёт только мост, обученный
`cellState_`, и только по явной просьбе (`fleet(cells=True)`). Пока он НЕ ЗАДЕПЛОЕН, честный
ответ на любой вопрос о клетке — `unreadable`: «источник не прочитан». Это не деградация, а
единственная не-ложь: сказать `empty` там, где мы просто не спросили, значит воспроизвести
ровно тот дефект, ради которого модуль написан.

ТРАНСПОРТ НИЧЕГО НЕ ЧИНИТ И НЕ СУДИТ. Отрицательный пробег (живой случай: `abs_last_km = −5000`
у байка 8969), настоящий ноль и число, добытое из живого текста «35200 Km, 05.07.2026», доезжают
как `ok` со своим значением. «−5000 км не бывает» — суждение о ДАННЫХ, его выносит тот, кто
считает просрочки, и выносит ЗНАЯ, что клетка не пуста. Смешать транспорт с суждением — значит
второй раз потерять различие, теперь уже в свою пользу.

ГРАНИЦА УСТРОЙСТВОМ: у модуля РОВНО ОДИН импорт — сам контракт `scan_result`. Ему нечем ни
читать, ни писать, ни ходить в сеть, ни звать подпроцесс: он только перекладывает разметку моста
в исход. Проверяется разбором (ast) инвариантом `FLEET_CELL_PURE`, а не докстрингом.
"""
from scan_result import ScanResult

# Что мост называет в разметке (`ReadFleet.js`, `cellState_`).
STATE_VALUE = "value"
STATE_EMPTY = "empty"
STATE_TEXT = "text"

# Поля строки парка ↔ колонки Лист1. Пробег H здесь же: он тот же транспорт и та же беда.
FIELD_COL = {
    "mileage": "H",
    "oil_last_km": "I",
    "gear_last_km": "J",
    "abs_last_km": "K",
    "airfilter_last_km": "L",
}

# Клетки ТО — четыре регистра, по которым считаются просрочки (пробег H в них не входит).
SERVICE_FIELDS = ("oil_last_km", "gear_last_km", "abs_last_km", "airfilter_last_km")

_NO_MARKUP = ("мост не прислал разметку клеток — старый деплой либо запрос без cells=1; "
              "различить «пусто» и «не число» отсюда невозможно")


def _subject(field):
    col = FIELD_COL.get(field)
    return f"клеток кол.{col}" if col else f"клеток «{field}»"


def _is_number(x):
    """Настоящее число, а не логическое: True в JSON — это `true`, а не единица пробега."""
    return isinstance(x, (int, float)) and not isinstance(x, bool)


def _plain(raw, num):
    """Сырое содержимое — это то же самое число, записанное просто?

    Нужно, чтобы отличить клетку «37000» от клетки «35200 Km, 05.07.2026»: обе дают ok, но во
    второй число ДОБЫТО из текста, и об этом стоит сказать вслух — читателю решать, верить ли."""
    try:
        return float(str(raw).strip()) == float(num)
    except (TypeError, ValueError):
        return False


def read(bike, field):
    """Клетка `field` строки парка `bike` → `ScanResult`. Наверх идёт ИСХОД, а не голое число.

    `bike` — элемент `bikes[]` из ответа моста, полученного с `cells=True`. Любое сомнение
    (не та форма, разметки нет, состояние незнакомо) — исход громкий, а не тихий ноль."""
    subject = _subject(field)
    if not isinstance(bike, dict):
        return ScanResult.unreadable(subject, detail="строка парка не словарь")

    cells = bike.get("cells")
    if not isinstance(cells, dict):
        return ScanResult.unreadable(subject, detail=_NO_MARKUP)

    if field not in cells:
        return ScanResult.unreadable(subject, detail=f"мост не назвал клетку «{field}» "
                                                     f"в разметке")
    cell = cells[field]
    if not isinstance(cell, dict):
        return ScanResult.unreadable(subject, detail=f"разметка клетки не словарь ({cell!r})")

    state = cell.get("state")
    raw = cell.get("raw", "")

    if state == STATE_EMPTY:
        return ScanResult(0, 0, subject=subject)

    if state == STATE_TEXT:
        return ScanResult(1, 0, subject=subject,
                          detail=f"в клетке «{raw}» — не число")

    if state == STATE_VALUE:
        num = cell.get("num")
        if not _is_number(num):
            # Мост сказал «значение», но числа не дал: содержимое есть, взять из него нечего.
            return ScanResult(1, 0, subject=subject,
                              detail=f"мост назвал клетку значением, а числа не дал ({num!r})")
        detail = "" if _plain(raw, num) else f"число добыто из текста «{raw}»"
        return ScanResult(1, 1, subject=subject, payload=num, detail=detail)

    return ScanResult.unreadable(subject,
                                 detail=f"мост назвал состояние «{state}» — контракт его не знает")
