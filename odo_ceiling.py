#: Ручка в .env. `0` (или пусто/мусор → дефолт) — см. `parse_limit`.
LIMIT_ENV = "ODO_CEILING_KM"

#: Порог по умолчанию, км. Выведен замером 14.08.2026 — см. шапку.
LIMIT_DEFAULT = 30000

#: Ярлык отказа записи. Исход ОПРЕДЕЛЁН (мост не звали вовсе), поэтому он относится к «не
#: записано», а не к «неизвестно»: `service_receipt` берёт вокабуляр определённых отказов у
#: `write_fact.SETTLED_ERRORS`, и этот ярлык добавлен туда же — второго словаря не заводим.
ERR = "odo_ceiling"

STATE_PASS = "pass"
STATE_ASK = "ask"
STATE_UNKNOWN = "unknown"
STATE_OFF = "off"


def parse_limit(raw, default=LIMIT_DEFAULT):
    """Порог из .env. Пусто/мусор → дефолт (ручка не должна ломаться опечаткой);
    явный `0` и отрицательное → 0, то есть ветка мертва."""
    if raw is None:
        return default
    s = str(raw).strip().replace(" ", "").replace(",", "")
    if not s:
        return default
    try:
        v = int(s)
    except (TypeError, ValueError):
        return default
    return v if v > 0 else 0


def km(x):
    """Число километров из живого формата ячейки/сообщения или None.
    Живой формат терпим тот же, что у `splinter._odo_km_int`: пробелы и запятые."""
    if x is None:
        return None
    s = str(x).strip().replace(" ", "").replace(",", "")
    if not s:
        return None
    try:
        v = int(s)
    except (TypeError, ValueError):
        return None
    return v if v > 0 else None


def verdict(new_km, cur_km, limit=LIMIT_DEFAULT):
    """Факты → вердикт. Возвращает словарь; `state` — одно из четырёх слов выше.

    `new_km` — число, которое просят записать; `cur_km` — текущий пробег байка
    (`splinter._odo_current`, единый источник правды; '' = не прочитан); `limit` — порог, км.
    """
    out = {"state": STATE_PASS, "new": None, "cur": None, "gap": None, "limit": limit}
    if not limit or limit <= 0:
        out["state"] = STATE_OFF
        return out
    n = km(new_km)
    if n is None:
        # Нечитаемое число — не наша забота: у писателя на него свой определённый отказ
        # (`bad_odometer`), и он должен сработать, а не быть подменён вопросом о разрыве.
        return out
    out["new"] = n
    c = km(cur_km)
    if c is None:
        out["state"] = STATE_UNKNOWN
        return out
    out["cur"] = c
    if n <= c:
        # Убывание и равенство — чужая дверь (floor, сторож Б, `km_decreasing` на мосту).
        return out
    gap = n - c
    out["gap"] = gap
    if gap > limit:
        out["state"] = STATE_ASK
    return out


def say(v):
    """Одна строка для журнала — чем именно кончилось сравнение."""
    st = v.get("state")
    if st == STATE_OFF:
        return "верхняя граница выключена (ODO_CEILING_KM=0)"
    if st == STATE_UNKNOWN:
        return "текущий пробег не прочитан — сравнивать не с чем, пишем как прежде"
    if st == STATE_ASK:
        return (f"разрыв вверх {v.get('gap')} км при пороге {v.get('limit')} "
                f"({v.get('new')} против {v.get('cur')}) — переспрашиваю, не пишу")
    if v.get("gap") is not None:
        return f"прирост {v.get('gap')} км в норме (порог {v.get('limit')})"
    return "верхняя граница не применялась"


