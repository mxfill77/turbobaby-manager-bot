"""КВИТАНЦИЯ ТО ГОВОРИТ ОДНО И ТО ЖЕ НА ОБОИХ ЯЗЫКАХ — чистая функция «исход записи → две
половины» (14.08.2026).

КЛАСС. У квитанции факта ТО две половины, тайская и русская, и складывались они РАЗНЫМИ
выражениями над ОДНИМ исходом. Русская несла отрицательную ветку
(`splinter.py:4361`: `rep_ru = "✅ Записано: …" if written else "⚠️ ничего не записано"`),
тайская — безусловный шаблон (`splinter.py:4368`: `🇹🇭 ✅ บันทึกแล้ว: {…} ที่ {odo} กม.`).
Пока запись проходила, обе говорили одно и то же; на отказе они расходились В ОДНОМ СООБЩЕНИИ:
механик читал успех, владелец — отказ. Второй путь (доверенный ответил числом вместо кнопки,
`splinter.py:6110–6112`) был хуже: там БЕЗУСЛОВНЫ ОБЕ половины, а отказ дописывался хвостом
только по-русски — тайская молчала о нём вовсе.

ЗАМЕР (splinter.log, 01.06–14.08, 74 суток, строки «ТО фаза2 запись по «да»»): квитанций 12,
противоречие половин несли 2 (16.7 %) — 13.08 05:19:07 NMAX 155 GREEN-B 4957,
`written=[] failed=[('abs','receipt_unknown')] odo=37015`, и 05:21:41 X MAX 300 NEW BLUE 4724,
то же на `odo=20747`. Квитанций второго пути за то же окно 0; частичных (часть записана, часть
нет) 0 — на них тайская половина промолчала бы об отказе, оставшись целиком зелёной. Обе
величины в Лист1 на самом деле ЛЕГЛИ (перечитывание живым мостом 13.08, `write_fact`), то есть
тайская половина случайно оказалась ближе к правде, чем русская. Оправданием это не является:
она говорила «записано» не потому, что знала, а потому, что не умела сказать иначе.

ТРИ ИСХОДА, А НЕ ДВА — тот же замок против ложного зелёного, что у `write_fact`, `card_deadline`
и О3. Исход берётся из того, ЧТО ответил мир, а не из того, что мы хотели сделать:
    ЗАПИСАНО     есть хоть одна принятая позиция      → ✅, названа поимённо
    НЕ ЗАПИСАНО   не принято ничего, и КАЖДЫЙ отказ вынесен самим мостом (исход определён) → ❌
    НЕИЗВЕСТНО    не принято ничего, и хоть один отказ есть молчание транспорта → ⚠️
«Неизвестно» — отдельное слово, а не вежливое «не записано»: расписка не пришла ≠ запись не
легла (13.08 легли обе), а повтор вслепую положил бы ВТОРУЮ строку — поэтому в этой ветке
квитанция прямо просит сперва проверить лист и не жать кнопку снова.

НАПРАВЛЕНИЕ СОМНЕНИЯ — В «НЕИЗВЕСТНО». Незнакомый код отказа, пустая строка ошибки, исключение
на нашей стороне — всё это не даёт права утверждать «не записано»: утверждение о мире требует
факта о мире, а у нас его нет. Вокабуляр определённых отказов берётся ГОТОВЫМ у `write_fact`
(`SETTLED_ERRORS` — те, что мост вынес сам, проверив номер, подтверждение и убывание пробега);
второго словаря о тех же смыслах здесь не заводится. Своё в нём одно — `bad_odometer`: при нём
цикл записи не начинался вовсе, писать было нечего, исход определён.

ИМЯ РАБОТЫ ЛИБО СТОИТ, ЛИБО НАЗЫВАЕТСЯ НЕОПРЕДЕЛЁННЫМ. Пустое тире после «บันทึกแล้ว:» — то же
незнание, только молча: `_sp_labels_*` отдаёт «—» на пустом списке, и в живой квитанции 13.08
механик прочёл ровно «บันทึกแล้ว: — ที่ 37015 กм.». Здесь список либо назван, либо сказано
«работа не названа» / «ไม่ได้ระบุงาน»; ключ вида, которого нет в словаре ярлыков, печатается
ключом — имя без перевода лучше тире.

ГРАНИЦА УСТРОЙСТВОМ: обе половины рендерит ОДНА функция ИЗ ОДНОГО вердикта (`verdict`), и
собрать их порознь у вызывающего нет способа — `receipt()` отдаёт их вместе с исходом. Импорт
РОВНО ОДИН (`write_fact`, у которого свой один — `scan_result`): ни сети, ни файлов, ни времени.
Модулю нечем ни узнать судьбу записи самому, ни отправить сообщение — он только называет
принесённое. Проверяется разбором (ast) инвариантом `SERVICE_RECEIPT_PURE`, а не докстрингом.
Руки — `splinter.handle_service_button` (кнопка «да») и `splinter.handle_service_result`
(ответ числом). Тесты `tests/test_service_receipt.py`.
"""
import write_fact

#: Исход всей квитанции. Три, и третий — не запасной.
STATE_WRITTEN = "written"
STATE_NONE = "none"
STATE_UNKNOWN = "unknown"

#: Порядок половин: 0 — тайская, 1 — русская (тот же порядок, что у `splinter._SP_KIND_LABEL`).
TH = 0
RU = 1

#: Отказы с ОПРЕДЕЛЁННЫМ исходом. Вокабуляр — готовый, `write_fact.SETTLED_ERRORS` (мост вынес их
#: сам). Своё одно: `bad_odometer` — одометр не разобран, цикл записи не начинался.
SETTLED_ERRORS = frozenset(write_fact.SETTLED_ERRORS | {"bad_odometer"})

#: Голова строки: исход называется ПЕРВЫМ словом, до всякого перечня.
HEAD = {
    STATE_WRITTEN: ("✅ บันทึกแล้ว", "✅ Записано"),
    STATE_NONE: ("❌ บันทึกไม่สำเร็จ", "❌ Не записано"),
    STATE_UNKNOWN: ("⚠️ ไม่ทราบผลการบันทึก", "⚠️ Исход записи НЕИЗВЕСТЕН"),
}
#: Отказ, при котором называть нечего (позиций не было вовсе).
NOTHING = ("❌ ไม่ได้บันทึกอะไร", "❌ ничего не записано")
#: Хвост «неизвестно»: повтор вслепую положил бы вторую запись — говорим это прямо.
ADVICE = (" — ต้องตรวจสอบในตารางก่อน อย่าเพิ่งกดซ้ำ", " — проверь Лист1, вслепую не повторять")
TAIL_SETTLED = (" · ไม่ผ่าน: ", " · не прошло: ")
TAIL_UNKNOWN = (" · ไม่ทราบผล: ", " · исход неизвестен: ")
NOT_NAMED = ("ไม่ได้ระบุงาน", "работа не названа")
NO_ODO = (" (ไม่ได้ระบุเลขไมล์)", " (пробег не назван)")

#: Псевдо-вид, который приходит от рук отдельной строкой отказа (не работа, а операнд).
OWN_LABELS = {"odo": ("เลขไมล์", "одометр")}


def settled(error):
    """Исход ЭТОГО отказа выяснен? Направление сомнения — в «неизвестно».

    Руки склеивают код моста с исходом перечитывания через `/` (`splinter._sp_write_done`:
    `f"{error}/{fact.state}"`), поэтому хвост решает первым: `absent` — величины в клетке нет,
    исход выяснен; `unknown` — перечитать не удалось, не выяснен. Голый код судится словарём.
    Пустая строка и незнакомое слово — НЕ выяснено: «не записано» есть утверждение о мире."""
    s = str(error or "").strip()
    if not s:
        return False
    head, sep, tail = s.partition("/")
    if sep:
        if tail == write_fact.STATE_ABSENT:
            return True
        return False
    return head in SETTLED_ERRORS


def verdict(written, failed):
    """(принятые виды, отказы) → ОДИН исход + поимённые списки. Обе половины рендерятся из него."""
    took = [str(k) for k in (written or [])]
    settled_kinds, unknown_kinds = [], []
    for item in (failed or []):
        if isinstance(item, (tuple, list)) and len(item) >= 2:
            kind, err = item[0], item[1]
        else:
            kind, err = item, ""
        (settled_kinds if settled(err) else unknown_kinds).append(str(kind))
    if took:
        state = STATE_WRITTEN
    elif unknown_kinds:
        state = STATE_UNKNOWN
    else:
        state = STATE_NONE
    return {"state": state, "written": took, "settled": settled_kinds, "unknown": unknown_kinds}


def _label(kind, labels, lang):
    """Ярлык вида на нужном языке. Нет в словаре → печатаем КЛЮЧ: имя без перевода лучше тире."""
    pair = (labels or {}).get(kind) or OWN_LABELS.get(kind)
    if not pair:
        return str(kind)
    try:
        return str(pair[lang])
    except (IndexError, KeyError, TypeError):
        return str(kind)


def _names(kinds, labels, lang):
    """Перечень работ либо честное «не названа» — пустого тире тут не бывает."""
    return ", ".join(_label(k, labels, lang) for k in kinds) or NOT_NAMED[lang]


def _odo(odo, lang):
    s = str(odo if odo is not None else "").strip()
    if not s:
        return NO_ODO[lang]
    return f" ที่ {s} กม." if lang == TH else f" на {s} км"


def _half(v, odo, labels, lang):
    """Одна половина строки. Голова несёт РОВНО ОДИН исход, хвосты называют остальные виды."""
    state = v["state"]
    if state == STATE_WRITTEN:
        head_kinds = v["written"]
    elif state == STATE_UNKNOWN:
        head_kinds = v["unknown"]
    else:
        head_kinds = v["settled"]
    if state == STATE_NONE and not head_kinds:
        line = NOTHING[lang] + _odo(odo, lang)
    else:
        line = f"{HEAD[state][lang]}: {_names(head_kinds, labels, lang)}{_odo(odo, lang)}"
    rest_settled = [k for k in v["settled"] if k not in head_kinds]
    rest_unknown = [k for k in v["unknown"] if k not in head_kinds]
    if rest_settled:
        line += TAIL_SETTLED[lang] + _names(rest_settled, labels, lang)
    if rest_unknown:
        line += TAIL_UNKNOWN[lang] + _names(rest_unknown, labels, lang)
    if v["unknown"]:
        line += ADVICE[lang]
    return line


def receipt(written, failed, odo, labels=None, ledger=None):
    """ЕДИНСТВЕННАЯ дверь квитанции: обе половины + исход, из одного вердикта.

    `labels` — словарь `вид → (тайский ярлык, русский ярлык)` (`splinter._SP_KIND_LABEL`).
    Возвращает `{"state", "written", "settled", "unknown", "th", "ru"}`; половины врозь не
    выдаются намеренно — расхождение половин и есть тот класс, ради которого модуль написан.

    `ledger` — ГОТОВЫЙ вердикт сторожа партии (`works_ledger.tally`, приносят руки
    `splinter._svc_ledger_take`): «принято N · записано M» и каждая не легшая позиция поимённо.
    Сюда он приходит УЖЕ РАЗЛОЖЕННЫМ на две половины намеренно — импорт у квитанции остаётся
    ровно один (`write_fact`, страж `SERVICE_RECEIPT_PURE`), а обе половины сторожа рендерит одна
    его функция из одного счёта, как и обе половины исхода здесь. Сторож умеет только ДОБАВИТЬ
    строку о потере: сошлось (`agree`) либо вердикта нет — квитанция БАЙТ-В-БАЙТ прежняя."""
    v = verdict(written, failed)
    out = dict(v)
    out["th"] = _half(v, odo, labels, TH)
    out["ru"] = _half(v, odo, labels, RU)
    tail_th = str((ledger or {}).get("th") or "")
    tail_ru = str((ledger or {}).get("ru") or "")
    if tail_th or tail_ru:
        # Половины расходиться не должны и здесь: пустая сторона получает то же, что и полная.
        out["th"] += "\n" + (tail_th or tail_ru)
        out["ru"] += "\n" + (tail_ru or tail_th)
        out["ledger"] = {"n": (ledger or {}).get("n"), "m": (ledger or {}).get("m"),
                         "lost": list((ledger or {}).get("lost") or [])}
    return out
