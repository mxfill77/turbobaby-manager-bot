import hashlib
import json
import os
import time

# Память живёт в /tmp и умирает с машиной — заход не переживает перезагрузку по определению.
STORE_LIVE = "/tmp/cc_repeat_ask"          # боевой каталог
STORE_TEST = "/tmp/cc_repeat_ask_test"     # безопасное умолчание тест-прогона
STORE_ENV = "CC_REPEAT_DIR"                # явная подмена каталога тестом (побеждает всё)
TTL = 6 * 3600                             # заход длиннее шести часов — уже не тот заход
PENDING_KEEP = 64                          # сколько заданных вопросов помним (хвост режем)

# КЛАССЫ-ПРИСВАИВАНИЯ: повтор подтверждает ТО ЖЕ состояние мира, нового факта нет.
# Всё остальное (деньги, отмена, создание, закрытие, удаление, процессы, SQL, DOWRITE, confirmed —
# флаг, за которым может стоять что угодно) — переходы: FAIL-CLOSED, вопрос остаётся.
SAME_STATE = frozenset(("set_fleet_oil", "set_fleet_service", "edit_event"))

_DASH = "—"
# Объект, который гард честно назвал НЕвычисленным: имени цели нет, сравнивать нечего.
_UNNAMED = ("значение вычисляется",)


def same_state(hit):
    """Повтор этого класса подтверждает то же состояние мира (а не рождает новый факт)?"""
    return (hit or "") in SAME_STATE


def store_dir(isolated=False):
    """Каталог памяти: явная подмена (env) → тест-умолчание → боевой. Читается В МОМЕНТ ОБРАЩЕНИЯ
    (как `block_dir` гарда) — поэтому подмена работает и для хука, запущенного подпроцессом."""
    explicit = (os.environ.get(STORE_ENV) or "").strip()
    if explicit:
        return explicit
    return STORE_TEST if isolated else STORE_LIVE


def run_key(data):
    """ЗАХОД: задача демона (`CC_TASK_ID`) либо сессия движка (`session_id` из входа хука).
    Ключ живёт в ИМЕНИ ФАЙЛА — чистим всё, кроме букв/цифр/дефиса. Не опознали → 'orphan'
    (общая корзина: она НЕ страшна, потому что тождество всё равно требует названного объекта)."""
    tid = (os.environ.get("CC_TASK_ID") or "").strip()
    raw = tid or str((data or {}).get("session_id") or "").strip() or "orphan"
    safe = "".join(c for c in raw if c.isalnum() or c in "-_")[:64]
    return safe or "orphan"


def fingerprint(hit, obj, num):
    """ОТПЕЧАТОК ОПЕРАЦИИ = класс + объект + число, то есть карточка, а не команда.
    → '' когда тождества нет: без класса, без названного объекта, при вычисляемом значении."""
    o = " ".join((obj or "").split())
    if not (hit or "").strip() or not o or o == _DASH:
        return ""
    if any(m in o for m in _UNNAMED):
        return ""
    raw = "\x00".join(((hit or "").strip(), o, " ".join((num or "").split())))
    return hashlib.sha1(raw.encode("utf-8", "replace")).hexdigest()[:16]


def cmd_key(cmd):
    return hashlib.sha1(" ".join((cmd or "").split()).encode("utf-8", "replace")).hexdigest()[:16]


def body_signature(cmd):
    """ОТПЕЧАТОК ТОГО, ЧТО ИСПОЛНИТСЯ: содержимое `.py`-файлов, названных в команде.

    ЗАЧЕМ. Связка «команда → операция» живёт по ключу ТЕКСТА, а у скрипта текст команды НЕ меняется,
    пока меняется его содержимое, — и это основной рабочий цикл репозитория («правлю фикстуру →
    запускаю → правлю → запускаю»). Без этой подписи ЗЕЛЁНЫЙ прогон той же строки засчитывался бы
    «да» за красную операцию, на которую владелец ответил «НЕТ» (ревизия 05.08.2026, воспроизведено
    сквозным прогоном живых хуков). Подпись живёт ЗДЕСЬ, а не по обе стороны: у гарда и у ленты
    один и тот же вызов, поэтому разойтись двум признакам, как в §9.2 артефакта, физически негде.

    Файла нет / не читается → в подпись идёт метка «?»: если он появится к моменту исполнения,
    подпись изменится, то есть сомнение всегда в сторону лишнего вопроса. Команда без `.py`
    (`rm -f …`, `sqlite3 …`, инлайн `-c "…"`) несёт свой смысл в САМОМ тексте — там тождество
    текста и есть тождество операции, и подпись у них общая по построению.

    ЧЕСТНЫЙ ПРЕДЕЛ: подпись видит только названные файлы. Скрипт, чьё ПОВЕДЕНИЕ поменял изменённый
    им импорт (соседний модуль), подписью не ловится."""
    try:
        import shlex
        toks = shlex.split(cmd or "")
    except Exception:
        toks = str(cmd or "").split()
    parts = []
    for t in toks:
        if not t.endswith(".py"):
            continue
        try:
            with open(t, "rb") as f:
                parts.append(t + ":" + hashlib.sha1(f.read()).hexdigest()[:16])
        except Exception:
            parts.append(t + ":?")
    raw = "\x00".join(sorted(parts))
    return hashlib.sha1(raw.encode("utf-8", "replace")).hexdigest()[:16]


def executed(resp):
    """ИСПОЛНИЛАСЬ ЛИ КОМАНДА — признак ПОЛОЖИТЕЛЬНЫЙ, форма измерена по живым транскриптам
    (1412 сессий, 05.08.2026): исполнение Bash приходит СЛОВАРЁМ с ключами stdout/stderr
    (`interrupted`, `isImage`, `noOutputExpected` рядом), а отказ — СТРОКОЙ «Error: …»
    («Error: This command requires approval», «Error: 🔴 КРАСНОЕ …», «Error: … was blocked»).
    Всё, что не опознано как исполнение, разрешением НЕ считается: строка, None, пустой словарь,
    прерванный запуск. Направление сомнения — в сторону лишнего вопроса, а не лишнего права."""
    if not isinstance(resp, dict):
        return False
    if not ("stdout" in resp or "stderr" in resp):
        return False
    itr = resp.get("interrupted")
    if itr is True or (isinstance(itr, str) and itr.strip().lower() == "true"):
        return False
    return True


def _path(key, isolated=False):
    return os.path.join(store_dir(isolated), str(key) + ".json")


def _load(path):
    """FAIL-SAFE: нет файла / битый / протух по TTL → пустая память = прежнее поведение гарда."""
    try:
        with open(path, "r", encoding="utf-8") as f:
            st = json.load(f)
        if not isinstance(st, dict):
            return {}
        # ВОЗРАСТ СЧИТАЕТСЯ ОТ РОЖДЕНИЯ, А НЕ ОТ ПОСЛЕДНЕЙ ЗАПИСИ (ревизия 05.08.2026). По `ts`
        # окно было СКОЛЬЗЯЩИМ: каждая пометка гарда обновляла его, и в постоянной сессии `cc`,
        # живущей сутками (рабочий режим проекта), «да» понедельника снимало вопрос в четверг.
        # Легаси-файлы без `born` судятся по `ts`, как раньше.
        if time.time() - float(st.get("born") or st.get("ts") or 0) > TTL:
            return {}
        st.setdefault("pending", {})
        st.setdefault("ok", {})
        return st if isinstance(st["pending"], dict) and isinstance(st["ok"], dict) else {}
    except Exception:
        return {}


def _save(path, st):
    """Best-effort: каталог/диск недоступен → молча мимо. Потерянная запись = вопрос будет задан
    ещё раз, то есть ровно сегодняшнее поведение — худшего исхода у сбоя здесь нет."""
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        st.setdefault("born", time.time())     # рождение захода: по нему считается TTL
        st["ts"] = time.time()                 # последняя запись: диагностика, на возраст не влияет
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(st, f, ensure_ascii=False)
        os.replace(tmp, path)
    except Exception:
        pass


def approved_count(key, fp, isolated=False):
    """Сколько раз ЭТА ЖЕ операция уже была разрешена владельцем в ЭТОМ заходе. 0 = ни разу."""
    if not fp:
        return 0
    st = _load(_path(key, isolated))
    try:
        return int((st.get("ok") or {}).get(fp) or 0)
    except Exception:
        return 0


def mark_asked(key, cmd, fp, isolated=False):
    """Гард СПРОСИЛ про эту команду, и вот какой операции вопрос принадлежит. Только связка
    «команда → отпечаток»; правом это не является и словом «разрешено» не становится."""
    if not fp:
        return
    path = _path(key, isolated)
    st = _load(path) or {"pending": {}, "ok": {}}
    pend = st.get("pending") or {}
    # Рядом с операцией кладём подпись ТЕЛА, которое гард судил: разрешение засчитается, только
    # если исполнится ОНО ЖЕ, а не другой скрипт под тем же именем (см. `body_signature`).
    pend[cmd_key(cmd)] = {"fp": fp, "sig": body_signature(cmd)}
    if len(pend) > PENDING_KEEP:                      # хвост режем, свежие вопросы важнее
        pend = dict(list(pend.items())[-PENDING_KEEP:])
    st["pending"] = pend
    _save(path, st)


def confirm(key, cmd, resp, isolated=False):
    """Команда ИСПОЛНИЛАСЬ → значит вопрос по ней уже получил «да». Засчитываем разрешение той
    операции, о которой гард спрашивал ЭТОЙ командой (связка из `mark_asked`). → True если
    засчитано. Команда, о которой гард не спрашивал, памяти не касается вовсе.

    ИСПОЛНИЛОСЬ ЛИ ТО ЖЕ САМОЕ — отдельный вопрос, и он решается ПОДПИСЬЮ ТЕЛА (`body_signature`).
    Без неё зелёный прогон той же строки погашал бы вопрос, на который владелец ответил «НЕТ», и
    красная операция проходила бы без карточки, ни разу не получив «да» (ревизия 05.08.2026,
    воспроизведено сквозным прогоном живых хуков).
    FAIL-CLOSED: подпись не совпала, запись легаси-формата (без подписи), любое сомнение → НЕ
    засчитываем: направление ошибки — лишний вопрос, а не лишнее право."""
    if not executed(resp):
        return False
    path = _path(key, isolated)
    st = _load(path)
    if not st:
        return False
    entry = (st.get("pending") or {}).get(cmd_key(cmd))
    if not isinstance(entry, dict):
        return False                  # легаси-запись (голый отпечаток) подписи не несёт — не «да»
    fp = entry.get("fp")
    if not fp or entry.get("sig") != body_signature(cmd):
        return False                  # исполнилось ДРУГОЕ тело под тем же текстом — не «да»
    ok = st.get("ok") or {}
    try:
        ok[fp] = int(ok.get(fp) or 0) + 1
    except Exception:
        ok[fp] = 1
    st["ok"] = ok
    _save(path, st)
    return True
