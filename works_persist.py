"""ПРИНЯТЫЕ РАБОТЫ ПЕРЕЖИВАЮТ СМЕРТЬ ПРОЦЕССА И ИСТЕЧЕНИЕ ТРЁХ ЧАСОВ (21.09.2026).

ПРАВИЛО УЧЁТА ПРОЧИТАНО ЖИВЬЁМ (узел мозга `business_rules`, 96 300 знаков, этим заходом), и оно
говорит ДВЕ вещи сразу, а не одну:

  • «ОБЯЗАТЕЛЬНЫЕ ПОЛЯ РАБОТЫ 23.08.2026 — У КАЖДОЙ записанной работы обязательны ДАТА и ПРОБЕГ.
    Нет любого из двух — работа не записывается.»
  • «ПОЛНОТА ИСТОРИИ РАБОТ 23.08.2026 — НИ ОДНА названная работа не теряется. […] Полнота важнее
    аккуратности: из свалки можно достать, из дыры нельзя.»

Первое ЗАПРЕЩАЕТ писать работу без пробега — значит ветка «записать сразу, пробег дозаполнить
позже» закрыта правилом ВЛАДЕЛЬЦА, а не вкусом, и здесь не строится. Второе запрещает ТЕРЯТЬ
принятую работу. Между ними ровно одна законная щель, и этот модуль занимает её: работа без
пробега в ИСТОРИЮ не идёт (правило цело), но факт её приёма ложится в место, переживающее
рестарт, и потеря перестаёт быть тишиной.

ЧТО БЫЛО ДО (факты кода, а не пересказ). Принятые работы жили в `splinter._PENDING_WORKS` —
словаре в ПАМЯТИ ПРОЦЕССА с TTL три часа (`_PENDING_WORKS_TTL`). Единственная дверь выгрузки
`_flush_pending_works` зовётся ТОЛЬКО по приходу подтверждённого пробега (`_km_door`, три двери).
Значит принятая работа исчезала ДВУМЯ дорогами, и обе молчали наружу: смерть процесса (за окно
переписи 22.08 splinter перезапускался 126 раз, ≈2 раза в сутки — там же и замерено) и истечение
трёх часов.

ПОЧЕМУ СОСЕДНИЕ МЕХАНИЗМЫ ЭТУ ДЫРУ НЕ ЗАКРЫВАЛИ — ПРОВЕРЕНО ЧТЕНИЕМ, А НЕ ПРЕДПОЛОЖЕНО.
`works_ledger` (сторож партии, 22.08) считает «принято N — записано M» и называет каждую потерю
поимённо, но его зовут РУКИ ЗАПИСИ, то есть уже внутри выгрузки буфера; нет пробега — нет
выгрузки, нет и сторожа. `_summary_note_failed` кладёт потерю в накопитель `_SVC_SUMMARY`, но он
сам живёт в памяти процесса, а печатает его `_emit_summary` на ТЕРМИНАЛЕ цикла ТО — которого без
пробега не наступает. Оба говорят о потере ГРОМКО и оба молчат ровно в том случае, ради которого
написан этот модуль: пробег не пришёл вовсе.

ЕДИНИЦА ЖУРНАЛА — ПОЗИЦИЯ, А НЕ ПАРТИЯ. Партия — то, что человек назвал одним сообщением, а
записывается и теряется ПОЗИЦИЯ: выгрузка пишет по строке на работу и вправе записать часть,
отказав в остальном (`_write_info_works` считает записанным `ok+saved`/`duplicate`, отказ —
потерей). Журнал партиями такой исход назвать не смог бы вовсе.

ЗАПИСЬ НЕ УДАЛЯЕТСЯ ПО ИСТЕЧЕНИИ СРОКА — У НЕЁ МЕНЯЕТСЯ ИСХОД. Это и есть «пережить истечение
трёх часов»: `expire` переводит `WAITING` → `LOST_NO_KM`, оставляя позицию вместе с её возрастом.
Срок годности решает, писать ли работу в историю (правило пробега), а не помнить ли о том, что её
приняли.

ЗАМОК ПРОТИВ ЛОЖНОГО ЗЕЛЁНОГО (тот же, что у `write_fact`, `works_ledger` и О3): `WRITTEN`
возвращается РОВНО ОДНИМ путём — ключ позиции назван в списке РЕАЛЬНО записанного, который отдаёт
`_write_info_works` (там только `ok+saved` либо `duplicate`; отказ туда не попадает). Всё прочее —
молчание моста, исключение, непонятый ответ — оставляет позицию ОТКРЫТОЙ. Направление сомнения в
сторону «работа ещё не записана»: лишняя открытая строка стоит взгляда, проглоченная работа — это
невыполненное ТО живого байка.

ВЛАСТЬ МОДУЛЯ СТРОГО ДОБАВЛЯЮЩАЯ. Он умеет завести позицию, сменить её исход и выбросить при
ротации ЗАКРЫТЫЕ; выбросить ОТКРЫТУЮ потерю он не умеет ни одной веткой (`prune` судит `state`,
проверяется тестом на журнале из одних открытых позиций). Иначе потолок файла молча съел бы ровно
то, ради чего файл заведён.

НОРМАЛИЗАЦИЯ ТЕКСТА РАБОТЫ СЮДА НЕ ПЕРЕЕЗЖАЕТ, и это не лень. У правила «что считать той же
работой» уже есть ОДИН дом — `splinter._pw_slot`, и его докстринг объясняет, почему там ТЕКСТ, а
не стем (`_work_key` склеивает «долив тормозной жидкости» и «прокачку тормозов» в один `колодки`).
Вторая реализация того же правила разошлась бы с первой в обе стороны, и журнал считал бы
записанной не ту позицию. Поэтому ключ позиции приходит ПАРАМЕТРОМ.

ГРАНИЦА УСТРОЙСТВОМ: импортов НОЛЬ. Ни файла, ни сети, ни моста, ни часов — «сейчас» и срок
годности приносят руки параметрами, поэтому записать мимо правила, солгать о времени или
отправить что-либо этот модуль не может физически. Проверяется разбором (ast) инвариантом
`WORKS_PERSIST_PURE`, а не докстрингом.

Руки — в `splinter.py` (`_wl_*`); файл памяти живёт рядом с `hint_dedup_state.json` и
`svc_tokens.json` и выбирается НА КАЖДОМ ЗОВЕ, а не на импорте (прогон тестов в боевое состояние
не пишет никогда — класс боевого `wallet_cache.json` с фикстурой внутри). Тесты
`tests/test_works_persist.py` (решение) и `tests/test_works_persist_path.py` (путь целиком, на
ВЫДУМАННЫХ байках и во временном файле).
"""

#: Ручка отката. `WORKS_PERSIST=0` + рестарт splinter → журнала нет вовсе, путь байт-в-байт прежний.
FLAG_ENV = "WORKS_PERSIST"

#: Срок, после которого работа без пробега в историю уже не пишется. Зеркалит
#: `splinter._PENDING_WORKS_TTL`; число остаётся у буфера, сюда приходит параметром.
TTL_DEFAULT = 3 * 3600

#: Сколько ЗАКРЫТЫХ позиций держим в файле. Открытые потери потолком не режутся вовсе.
KEEP_CLOSED = 300

# --- исходы позиции ---------------------------------------------------------------------------
#: работы приняты, пробега нет, срок не вышел — ещё не потеря
WAITING = "waiting"
#: срок вышел, пробег так и не пришёл — ПОТЕРЯ, и запись о ней остаётся
LOST_NO_KM = "lost_no_km"
#: писать было некуда либо мост отказал — ПОТЕРЯ с названной причиной
LOST_OTHER = "lost_other"
#: работа РЕАЛЬНО легла в историю — единственный закрытый исход
WRITTEN = "written"

#: Открытые исходы: позиция всё ещё числится за нами.
OPEN_STATES = (WAITING, LOST_NO_KM, LOST_OTHER)
#: Потери: приняли, а в истории нет.
LOST_STATES = (LOST_NO_KM, LOST_OTHER)


def key(chat_id, topic_id):
    """Ключ темы в журнале. Тот же адрес, которым ключуется буфер `_PENDING_WORKS`."""
    return f"{chat_id}:{topic_id}"


def empty():
    """Пустой журнал. Форма одна и та же у чтения, записи и ротации."""
    return {"items": []}


def _items(state):
    """Позиции журнала. Любой мусор на входе → пусто: читателю незачем падать на чужом файле."""
    if not isinstance(state, dict):
        return []
    got = state.get("items")
    return [i for i in got if isinstance(i, dict)] if isinstance(got, list) else []


def _num(v, default=0.0):
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


def accept(state, *, chat_id, topic_id, bike, pairs, now):
    """ПРИНЯТЫ работы, пробега нет → завести позиции. `pairs` = [(текст работы, ключ позиции)].

    Ключ позиции считает ВЫЗЫВАЮЩИЙ (`splinter._pw_slot`) — см. докстринг модуля, почему.
    Повтор тех же слов при ОТКРЫТОЙ позиции той же темы новой строки не заводит (иначе переспрос
    пробега плодил бы позиции); ЗАКРЫТАЯ позиция повтору не мешает — ту же работу законно делают
    второй раз на другом пробеге.

    Возвращает (новое состояние, число заведённых позиций)."""
    items = list(_items(state))
    k = key(chat_id, topic_id)
    open_slots = {str(i.get("slot") or "") for i in items
                  if i.get("key") == k and i.get("state") in OPEN_STATES}
    added = 0
    for work, slot in (pairs or []):
        slot = str(slot or "")
        if not slot or slot in open_slots:
            continue
        open_slots.add(slot)
        items.append({"key": k, "chat": chat_id, "topic": topic_id, "bike": str(bike or ""),
                      "work": str(work or ""), "slot": slot, "at": _num(now),
                      "state": WAITING, "km": "", "why": "", "closed_at": 0.0})
        added += 1
    return {"items": items}, added


def settle(state, *, chat_id, topic_id, slots, km, now):
    """РЕАЛЬНО записанные работы снимаются с ожидания.

    `slots` — ключи позиций, названные списком ЗАПИСАННОГО. Позиция закрывается, только если её
    ключ там ЕСТЬ: это и есть замок против ложного зелёного. Закрывается и позиция, уже помеченная
    потерей (пробег пришёл позже срока и работа всё-таки легла) — исход обязан следовать за миром,
    а не за нашей прошлой записью о нём.

    Возвращает (новое состояние, число снятых)."""
    want = {str(s) for s in (slots or []) if str(s)}
    if not want:
        return {"items": list(_items(state))}, 0
    k = key(chat_id, topic_id)
    items, done = [], 0
    for i in _items(state):
        if (i.get("key") == k and str(i.get("slot") or "") in want
                and i.get("state") in OPEN_STATES):
            i = dict(i)
            i["state"], i["km"], i["closed_at"] = WRITTEN, str(km or ""), _num(now)
            done += 1
        items.append(i)
    return {"items": items}, done


def lose(state, *, chat_id, topic_id, slots, why, now, outcome=LOST_OTHER):
    """Позиция НЕ легла по названной причине (мост молчит, запись отказана) → пометить потерей.

    `outcome` НАЗЫВАЕТ ВЫЗЫВАЮЩИЙ, и умолчание здесь не от лени: «пробег так и не пришёл»
    (`LOST_NO_KM`) — это ДРУГАЯ потеря, чем «мост не принял» (`LOST_OTHER`). Первую лечит человек,
    приславший число, вторую — тот, кто чинит мост; свалив их в один исход, журнал сказал бы обоим
    одно и то же. Буфер судит срок годности сам (`_pw_take`), поэтому руки приносят готовый исход,
    а не заставляют журнал пересчитывать время второй раз. Незнакомый исход считаем `LOST_OTHER`:
    молчать о потере, которой мы не поняли, нельзя.

    Исход остаётся ОТКРЫТЫМ: работа по-прежнему числится за нами, и позже она может лечь."""
    want = {str(s) for s in (slots or []) if str(s)}
    if not want:
        return {"items": list(_items(state))}, 0
    outcome = outcome if outcome in LOST_STATES else LOST_OTHER
    k = key(chat_id, topic_id)
    items, hit = [], 0
    for i in _items(state):
        if (i.get("key") == k and str(i.get("slot") or "") in want
                and i.get("state") in OPEN_STATES):
            i = dict(i)
            i["state"], i["why"] = outcome, str(why or "")[:200]
            hit += 1
        items.append(i)
    return {"items": items}, hit


def expire(state, *, now, ttl=TTL_DEFAULT):
    """Срок вышел → `WAITING` становится ПОТЕРЕЙ, но из журнала НЕ уходит.

    Ровно этим журнал и переживает истечение трёх часов: буфер к этому часу уже пуст, а запись
    «работы приняты, пробега нет» остаётся вместе с возрастом. `ttl<=0` → не судим вовсе."""
    if not ttl or ttl <= 0:
        return {"items": list(_items(state))}, 0
    items, hit = [], 0
    for i in _items(state):
        if i.get("state") == WAITING and (_num(now) - _num(i.get("at"))) > ttl:
            i = dict(i)
            i["state"] = LOST_NO_KM
            i["why"] = f"пробег так и не пришёл за {int(ttl // 3600)}ч"
            hit += 1
        items.append(i)
    return {"items": items}, hit


def open_items(state, *, chat_id=None, topic_id=None):
    """Открытые позиции (ждут пробега либо уже потеряны). Тема названа → только её."""
    k = key(chat_id, topic_id) if chat_id is not None else None
    return [i for i in _items(state)
            if i.get("state") in OPEN_STATES and (k is None or i.get("key") == k)]


def counts(state):
    """Сводка журнала числами: {исход: сколько}. Для строки в журнал и для сторожа."""
    out = {WAITING: 0, LOST_NO_KM: 0, LOST_OTHER: 0, WRITTEN: 0}
    for i in _items(state):
        s = str(i.get("state") or "")
        if s in out:
            out[s] += 1
    return out


def report(state, *, now, limit=10):
    """Человеческая строка об открытых позициях: сколько, по каким байкам и какого ВОЗРАСТА.

    Пусто → пустая строка: молчать не о чем. Возраст называется ЧИСЛОМ рядом с исходом — время
    без возраста читается как «только что» (класс 14.08, `revizor_age`)."""
    op = open_items(state)
    if not op:
        return ""
    waiting = sum(1 for i in op if i.get("state") == WAITING)
    shown = sorted(op, key=lambda x: _num(x.get("at")))[:max(0, limit)]
    parts = [f"«{i.get('work')}» {i.get('bike') or 'байк не назван'} "
             f"(тема {i.get('topic')}, "
             f"{max(0.0, _num(now) - _num(i.get('at'))) / 3600.0:.1f} ч, {i.get('state')})"
             for i in shown]
    tail = f"; и ещё {len(op) - len(shown)} — все в журнале" if len(op) > len(shown) else ""
    return (f"принятых работ без пробега {len(op)} "
            f"(ждут {waiting}, потеряны {len(op) - waiting}): " + "; ".join(parts) + tail)


def prune(state, *, keep=KEEP_CLOSED):
    """Ротация файла. Выбрасываются ТОЛЬКО закрытые позиции, от старых к новым.

    Открытая потеря не выбрасывается НИ ОДНОЙ веткой — иначе потолок съедал бы ровно то, ради чего
    журнал заведён."""
    items = _items(state)
    closed = [i for i in items if i.get("state") == WRITTEN]
    keep = max(0, keep)
    if len(closed) <= keep:
        return {"items": list(items)}
    order = sorted(range(len(items)),
                   key=lambda n: _num(items[n].get("closed_at")))
    drop, need = set(), len(closed) - keep
    for n in order:
        if need <= 0:
            break
        if items[n].get("state") == WRITTEN:
            drop.add(n)
            need -= 1
    return {"items": [i for n, i in enumerate(items) if n not in drop]}
