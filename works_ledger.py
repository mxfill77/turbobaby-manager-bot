"""СТОРОЖ ПАРТИИ РАБОТ — «принято N, записано M», и расхождение называется поимённо (22.08.2026).

КЛАСС. Во внутреннем обслуживании позиция, названная человеком, могла исчезнуть БЕЗ ЕДИНОГО
СЛОВА кому бы то ни было. Разбор 22.08 (`docs/artifacts/2026-08-22-service-5960-fate.md`) померил
это на двух живых сессиях одного байка (NMAX 155 GREY 5960): **01.08 принято 10 позиций —
записано 4**, 22.08 принято 2 — записано 2, но одна из двух легла в ЧУЖОЙ регистр. Четыре из шести
потерянных позиций не оставили в журнале ни строки: буфер отложенных работ ЗАМЕЩАЛСЯ присваиванием
(«долив тормозной жидкости» затёрт в 07:31:02 следующей партией), а выгружался только дверью
подтверждения пробега, которую фаза 2 не открывает — она берёт число своим разбором.

ПОЧЕМУ СТОРОЖ, А НЕ ТОЛЬКО ПОЧИНКА КОРНЯ. Корень чинится один раз, а класс — это ЛЮБАЯ будущая
дорога, по которой позиция уходит в никуда: отказ моста, протухший буфер, новая дверь записи,
которую забудут связать со старой. Поэтому у партии есть арифметика: сколько позиций она ПРИНЯЛА и
сколько ЛЕГЛО. Сходится — квитанция прежняя, байт-в-байт. Расходится — квитанция ОБЯЗАНА назвать
каждую не легшую позицию и причину. Молчание запрещено: потерянная работа — это невыполненное ТО
живого байка, а о нём человек узнаёт только из квитанции.

ИСХОДОВ У ПОЗИЦИИ ТРИ, И ТРЕТИЙ НЕ ЗАПАСНОЙ (тот же замок против ложного зелёного, что у
`write_fact`, `service_receipt` и О3):
    `register` — легла в РЕГИСТР Лист1 (кол.I/J/K/L), это состояние парка;
    `event`    — легла СОБЫТИЕМ в историю (регистра у работы нет — колодки, шина, чистка);
    `lost`     — НЕ легла никуда.
Записанной считается позиция, за которой стоит ответ мира, а не наше намерение: списки приносят
руки (`splinter._sp_write_done`) из расписок моста, сам модуль спросить мир не может ничем.

НАПРАВЛЕНИЕ СОМНЕНИЯ — В ГРОМКОСТЬ, И ОНО ОБРАТНО ГАРДУ НАМЕРЕННО. Гард решает, ИСПОЛНИТСЯ ли
команда, и ошибается в сторону вопроса; сторож не исполняет ничего — он решает, УЗНАЕТ ли человек.
Поэтому незнакомый исход, пустое имя и не названная причина считаются потерей и печатаются, а не
проглатываются: лишняя строка в квитанции стоит секунды, молчание — невыполненной работы.

ПРИЧИНА — КОД ИЗ ВОКАБУЛЯРА, А НЕ СВОБОДНАЯ СТРОКА. У квитанции две половины, и обе обязаны
говорить ОДНО И ТО ЖЕ (класс 14.08, `service_receipt`): свободная русская фраза в тайской половине
сделала бы их разными сообщениями. Поэтому руки передают КОД причины, а обе половины рендерит одна
функция из одного вердикта; машинный хвост моста (`km_decreasing`, `receipt_unknown`) печатается
как есть — он одинаков на любом языке. Имя работы даётся ПАРОЙ (как оно названо человеком и как
оно звучит по-тайски у `splinter._works_th_str`): второго имени одной работы здесь не заводится —
ровно этим 22.08 одна работа за 55 секунд стала «заменой ремня», «прочими работами» и «маслом
редуктора».

ИМПОРТОВ НОЛЬ — страж `WORKS_LEDGER_PURE` (ast, в гейте). Будь у сторожа мост, он спросил бы
судьбу записи САМ, и «записано» снова зависело бы от того, КАК спросили; будь у него отправка —
рядом с квитанцией завёлся бы второй путь наружу, и половины опять поехали бы врозь.
Руки — `splinter._sp_write_done` (считает) и три двери квитанции (печатают). Тесты
`tests/test_works_buffer.py`.
"""

#: Исходы позиции. Три, и третий не запасной.
IN_REGISTER = "register"
AS_EVENT = "event"
LOST = "lost"
OUTCOMES = (IN_REGISTER, AS_EVENT, LOST)

#: Порядок половин — тот же, что у `splinter._SP_KIND_LABEL` и `service_receipt`.
TH = 0
RU = 1

#: Вокабуляр причин. Ключ — код от рук; значение — ОДНА мысль на двух языках.
WHY = {
    "no_km":        ("ไม่ได้รับเลขไมล์ในเวลาที่กำหนด", "пробег так и не пришёл вовремя"),
    "write_failed": ("ระบบไม่รับบันทึก", "мост не принял запись"),
    "no_bridge":    ("ยังไม่ได้ส่งออกจากบัฟเฟอร์", "буфер не выгружен — писать было некуда"),
    "overwritten":  ("ถูกทับด้วยชุดถัดไป", "затёрта следующей партией"),
    "no_outcome":   ("ไม่ทราบผล", "исход не назван"),
    "no_reason":    ("ไม่ได้ระบุสาเหตุ", "причина не названа"),
}
#: Незнакомый код — не повод молчать: называем его как есть, рядом со своим «не знаю».
WHY_UNKNOWN = ("ไม่ทราบสาเหตุ", "причина неизвестна")
#: Имя, которого нет: позиция без имени — всё равно позиция, и потеря её называется.
NO_NAME = ("ไม่ได้ระบุงาน", "работа не названа")

#: Голова строки сторожа. Печатается ТОЛЬКО при расхождении.
HEAD = ("⚠️ ตรวจนับ", "⚠️ СТОРОЖ")
COUNT = ("รับงาน", "принято")
COUNT_W = ("บันทึกแล้ว", "записано")
LOST_HEAD = ("ไม่ได้บันทึก", "не легло")
#: Сколько имён печатаем в одной половине. Остальные названы ЧИСЛОМ и лежат в журнале целиком —
#: обрезка молчанием не становится (тот же приём, что у `_HUMAN_OVERFLOW` сводной карточки).
NAMES_MAX = 8
MORE = ("และอีก {n} รายการ (อยู่ในบันทึก)", "и ещё {n} — все названы в журнале")


def position(name, outcome, why="", detail="", name_th=""):
    """ОДНА позиция партии: как названа · что с ней стало · почему (если не легла).

    `name` — слова человека (или ярлык вида для колоночных); `name_th` — та же работа
    по-тайски (`splinter._works_th_str`), пусто → печатаем то же имя: одно имя лучше двух.
    `why` — КОД из `WHY`; `detail` — машинный хвост моста, если он есть."""
    return {"name": str(name or "").strip(), "name_th": str(name_th or "").strip(),
            "outcome": str(outcome or "").strip(), "why": str(why or "").strip(),
            "detail": str(detail or "").strip()}


def _why_text(pos, lang):
    """Причина потери на нужном языке. Незнакомый код печатается как есть — рядом со «не знаю»."""
    code = pos.get("why") or ""
    detail = pos.get("detail") or ""
    if not code:
        pair = WHY["no_reason"]
    elif code in WHY:
        pair = WHY[code]
    else:
        pair = (f"{WHY_UNKNOWN[TH]} ({code})", f"{WHY_UNKNOWN[RU]} ({code})")
    text = pair[lang]
    return f"{text} ({detail})" if detail else text


def _name_text(pos, lang):
    """Имя позиции. Пусто → честное «работа не названа», а не пустое тире."""
    name = pos.get("name_th") if lang == TH else pos.get("name")
    return name or pos.get("name") or NO_NAME[lang]


def tally(positions):
    """Партия → вердикт сторожа. Обе половины рендерятся ЗДЕСЬ, из одного счёта.

    Возвращает `{"n", "m", "register", "event", "lost", "agree", "th", "ru"}`.
    `agree=True` (всё принятое легло) → половины ПУСТЫ: квитанция остаётся байт-в-байт прежней,
    и это замок — сторож умеет только добавить строку о потере, отнять он не умеет ничем."""
    items = [p for p in (positions or []) if isinstance(p, dict)]
    reg, ev, lost = [], [], []
    for p in items:
        out = p.get("outcome")
        if out == IN_REGISTER:
            reg.append(p)
        elif out == AS_EVENT:
            ev.append(p)
        elif out == LOST:
            lost.append(p)
        else:
            # Незнакомый исход = потеря: молчать об исходе, которого мы не понимаем, нельзя.
            lost.append(dict(p, outcome=LOST, why=(p.get("why") or "no_outcome")))
    n, m = len(items), len(reg) + len(ev)
    verdict = {"n": n, "m": m,
               "register": [p.get("name") for p in reg],
               "event": [p.get("name") for p in ev],
               "lost": [(p.get("name"), p.get("why"), p.get("detail")) for p in lost],
               "agree": (not lost) and m == n, "th": "", "ru": ""}
    if verdict["agree"]:
        return verdict
    verdict["th"] = _half(verdict, lost, TH)
    verdict["ru"] = _half(verdict, lost, RU)
    return verdict


def _half(verdict, lost, lang):
    """Одна половина строки сторожа: сперва арифметика, затем каждая потеря поимённо."""
    head = f"{HEAD[lang]}: {COUNT[lang]} {verdict['n']} · {COUNT_W[lang]} {verdict['m']}"
    if not lost:
        return head
    shown = lost[:NAMES_MAX]
    parts = [f"«{_name_text(p, lang)}» — {_why_text(p, lang)}" for p in shown]
    tail = "; ".join(parts)
    if len(lost) > len(shown):
        tail += "; " + MORE[lang].format(n=len(lost) - len(shown))
    return f"{head} · {LOST_HEAD[lang]} {len(lost)}: {tail}"


def line(verdict):
    """Строка сторожа для ЖУРНАЛА — здесь названы ВСЕ потери, без потолка имён."""
    v = verdict or {}
    body = "; ".join(f"«{name or NO_NAME[RU]}» — {why or 'причина не названа'}"
                     + (f" ({detail})" if detail else "")
                     for name, why, detail in (v.get("lost") or []))
    out = f"сторож партии: принято {v.get('n')} · записано {v.get('m')}"
    if v.get("register"):
        out += f" · в регистр: {', '.join(str(x) for x in v['register'])}"
    if v.get("event"):
        out += f" · событием: {', '.join(str(x) for x in v['event'])}"
    return out + (f" · НЕ ЛЕГЛО {len(v.get('lost') or [])}: {body}" if body else " · потерь нет")
