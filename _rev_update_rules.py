#!/usr/bin/env python3
"""Ревизия 16.07: добавить три правила в KB_RULES."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dotenv import load_dotenv
load_dotenv(os.path.join(os.path.dirname(__file__), ".env"))
from bridge_client import BridgeClient

c = BridgeClient(timeout=90)

r = c._call("read_doc", name="rules")
assert r.get("ok"), f"read rules failed: {r}"
txt = r["text"]
print(f"KB_RULES: {len(txt)} chars")

NEW_SECTION = """
════════════════════════════════════════════════════════════════════
9. ДИСЦИПЛИНА ИСПОЛНЕНИЯ (заведено 16.07.2026 ревизией мозга)
════════════════════════════════════════════════════════════════════
ОДНО СОБЫТИЕ = ОДИН DONE — ПИШЕТ ИСПОЛНИТЕЛЬ, КУРАТОР/TERMUX ССЫЛАЮТСЯ:
После каждого завершённого действия строку DONE пишет ТОТ, кто его выполнял
(headless-задача, Termux-сессия, Cowork). Куратор/штаб/другой исполнитель ссылается
на эту строку ключом (дата/тема), а НЕ дублирует собственной записью.
Дублирование DONE от разных исполнителей за одно действие = ложная история
(мозг противоречит сам себе; счётчики/дедупы считают двойники).

ДЕКОМПОЗИРУЙ ТОЛЬКО ЕСЛИ >45 МИН ИЛИ НЕСКОЛЬКО СИСТЕМ — ИНАЧЕ ОДИНОЧНОЕ «ТЗ:»:
Критерий декомпозиции — ОБЪЁМ И ГРАНИЦА СИСТЕМ, не желание структурировать.
Декомпозируй ТОЛЬКО если: (1) задача затрагивает несколько сервисов/репо одновременно
ИЛИ (2) очевидно >45 мин работы. Во всех остальных случаях — одиночное «тз:».
Избыточный декомпозер: лишние синтетические шаги + задержки релиза + риск halt-on-fail
на промежуточных + куратор курирует каждый шаг вместо итога.

ОДИН ИНЦИДЕНТ = ОДИН ФИКС-КОММИТ + ОДИН ИНВАРИАНТ-ДЕТЕКТОР:
Инцидент (неожиданное поведение живой системы) → один headless-заход:
(1) диагноз причины, (2) фикс класса (не симптома), (3) инвариант-детектор
(что бы обнаружил инцидент заранее?) → добавить в registry_check.py / тест.
НЕ цепь декомпозера из 5+ шагов на разбор: это раздувает очередь, прячет суть,
плодит дополнительные куратор-консультации. Инвариант = живая страховка.
"""

# Добавляем в конец документа
new_txt = txt.rstrip() + "\n" + NEW_SECTION.rstrip() + "\n"
print(f"New size: {len(new_txt)} chars")

w = c.write_doc(name="rules", text=new_txt)
if w.get("ok"):
    print("KB_RULES updated OK via POST write_doc")
else:
    print(f"FAILED: {w}")
