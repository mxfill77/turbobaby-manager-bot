"""ЛИМИТ ПОСТАВЩИКА УЗНАЁТСЯ МАШИННЫМ ПОЛЕМ, А ПОВТОР ИДЁТ ПОД ВТОРЫМ СЛОТОМ (20.09.2026).

ПОВОД (живой, дословно из `orchestrator_daemon.log`): ряд 113, 19.09.2026 15:51:04 —
`claude -p exit=1`, `modelUsage пуст`, `tokens_in=0 tokens_out=0`, `dur_s=19.80`, и следом
`FAIL причина=exec_error id=113`. Исполнитель не узнал отказ поставщика ВООБЩЕ: он свалился в
самый общий код, а думатель самопочинки тем же отказом умер следом (`думатель exit=1`).

ЧЕМ ЭТО СУДИЛОСЬ ДО НАС — ОДНОЙ СТРОКОЙ. `status_truth.classify_exec` (`status_truth.py:95`)
ищет ПОДСТРОКУ английского текста в склейке stdout+stderr:

    if any(n in blob for n in _MODEL_NEEDLES):   # status_truth.py:95
        return "model_refusal"
    return UNKNOWN_CODE                          # status_truth.py:55 → "exec_error"

То есть признак — СОВПАДЕНИЕ АНГЛИЙСКОГО ТЕКСТА, а код выхода в решении не участвует вовсе:
параметр `rc` у `classify_exec` принимается и НЕ ЧИТАЕТСЯ ни одной веткой. Английский текст
поставщик волен переписать в любой день, и тогда отказ молча станет «ошибкой выполнения» —
ровно это и случилось с рядом 113.

ЧТО СУДИТ ЭТОТ МОДУЛЬ. Машинные поля конверта `--output-format json`, которые CLI отдаёт рядом
с `result`: `is_error` (булево «это отказ») и `api_error_status` (числовой статус ответа API).
Оба уже названы комментарием `orchestrator_daemon.py:1631` и до сих пор не читались НИ ОДНОЙ
боевой строкой — только тест-фикстурами. Код выхода основанием НЕ делается по прямому указанию:
у поставщика он известен ненадёжным (ряд 113 отдал 1 и на лимите, и на любой иной беде).

ТРИ ИСХОДА, И ТРЕТИЙ НЕ ЗАПАСНОЙ (тот же замок против ложного зелёного, что у О3 и `write_fact`):

  * `LIMIT`  — конверт разобран, `is_error` истинно И `api_error_status` назван статусом лимита.
               Только этот исход даёт право на повтор.
  * `CLEAN`  — машинного признака отказа нет (конверта нет · не разобрался · `is_error` ложно).
               Поведение вызывающего БАЙТ-В-БАЙТ прежнее.
  * `UNSURE` — `is_error` истинно, а статус не назван либо назван не лимитным. Отказ есть, но
               ЧЕЙ он — машина не доказала. Повтора нет; причина называется вслух.

НАПРАВЛЕНИЕ СОМНЕНИЯ — В «НЕ ПОВТОРЯТЬ». Повтор стоит второго полного захода (до 45 минут и
денег), поэтому всё, кроме доказанного лимита, оставляет прежний путь. Ошибка в эту сторону
стоит одного честно названного провала; ошибка в обратную — лишнего захода на каждую беду.

СЛОТ БЕРЁТСЯ ИЗ ОКРУЖЕНИЯ ЗАПУСКА, А НЕ ИЗ ТЕКСТА ОТЧЁТА (прямое требование задания и тот же
класс, что «судим по действию»): активным считается тот слот, чьё ЗНАЧЕНИЕ совпадает со значением
переменной, под которой заход реально шёл. Сравнение — равенством значений; НИ ОДНО значение и
ни одна его часть модулем не возвращается, не логируется и не кладётся в вердикт (в выводе
живут только имена `A`/`B` и имена переменных). Пустая строка слотом не является: пустой слот
нечем отличить от отсутствующего.

ИМПОРТОВ РОВНО НОЛЬ (страж `LIMIT_SLOT_PURE`, ast, в гейте). Модулю нечем спросить окружение,
запустить процесс или что-то напечатать: окружение приходит параметром, решение уходит словарём,
а руки живут в `orchestrator_daemon`. Поэтому «повторить» он умеет только СКАЗАТЬ.
"""

# --- вокабуляр исходов конверта ----------------------------------------------------------------
LIMIT = "limit"        # лимит поставщика ДОКАЗАН машинным полем
CLEAN = "clean"        # машинного признака отказа нет — путь прежний
UNSURE = "unsure"      # отказ есть, а лимит не доказан — повтора нет, причина названа

# Статусы ответа API, которыми поставщик называет исчерпание лимита. Список ЗАКРЫТЫЙ и узкий:
# 429 — единственный статус, который в HTTP означает «слишком много, приходи позже». Незнакомый
# статус НЕ становится лимитом (иначе всякая беда поставщика покупала бы второй заход) — он
# честно уходит в UNSURE.
LIMIT_STATUSES = frozenset((429,))

# --- имена слотов ------------------------------------------------------------------------------
SLOT_A = "A"
SLOT_B = "B"
SLOT_NONE = ""                       # слот не определён (не совпал ни с одним / значения пусты)

# Переменная, под которой заход РЕАЛЬНО идёт, и две переменные-слота. Имена живут ЗДЕСЬ одним
# списком: разъехавшись, две стороны читали бы разные слоты и «повтор под другим» стал бы
# повтором под тем же.
VAR_ACTIVE = "CLAUDE_CODE_OAUTH_TOKEN"
VAR_SLOT = {SLOT_A: "TB_CLAUDE_TOKEN_A", SLOT_B: "TB_CLAUDE_TOKEN_B"}
_OTHER = {SLOT_A: SLOT_B, SLOT_B: SLOT_A}

# --- действия, которые модуль умеет назвать -----------------------------------------------------
ACT_NONE = "none"        # ничего не меняем — прежний путь вызывающего
ACT_RETRY = "retry"      # повторить заход РОВНО ОДИН РАЗ под названным слотом
ACT_UNKNOWN = "unknown"  # лимит доказан, а идти некуда: исход НЕИЗВЕСТНО, чужая сторона


def _int_or_none(value):
    """Статус приходит то числом, то строкой (конверт CLI не обещает типа) → int | None.
    Булево числом НЕ считается: `True` не является статусом 1."""
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, int):
        return value
    try:
        return int(str(value).strip())
    except (TypeError, ValueError):
        return None


def envelope(parsed):
    """Разобранный конверт `--output-format json` → вердикт о ЛИМИТЕ машинными полями.

    → {"verdict": LIMIT|CLEAN|UNSURE, "status": int|None, "why": "<причина словами>"}

    Судятся РОВНО два поля, `is_error` и `api_error_status`. Код выхода сюда не передаётся
    вовсе — не «игнорируется», а физически отсутствует в сигнатуре: основанием ему не стать
    даже по недосмотру будущей правки.
    """
    if not isinstance(parsed, dict):
        return {"verdict": CLEAN, "status": None,
                "why": "конверта json нет (вывод не разобрался) — машинного признака отказа нет"}
    if "is_error" not in parsed:
        return {"verdict": CLEAN, "status": None,
                "why": "в конверте нет поля is_error — машинного признака отказа нет"}
    if parsed.get("is_error") is not True:
        return {"verdict": CLEAN, "status": None,
                "why": "is_error не истинно — конверт отказом себя не называет"}
    status = _int_or_none(parsed.get("api_error_status"))
    if status is None:
        return {"verdict": UNSURE, "status": None,
                "why": "is_error истинно, а api_error_status не назван числом — "
                       "отказ есть, лимит НЕ доказан"}
    if status in LIMIT_STATUSES:
        return {"verdict": LIMIT, "status": status,
                "why": "is_error истинно и api_error_status=%d — лимит поставщика" % status}
    return {"verdict": UNSURE, "status": status,
            "why": "is_error истинно, api_error_status=%d — это не статус лимита" % status}


def active_slot(env):
    """Окружение запуска → под каким слотом заход РЕАЛЬНО шёл: SLOT_A | SLOT_B | SLOT_NONE.

    Сравниваются ЗНАЧЕНИЯ, а наружу уходит только ИМЯ слота. Ни значение, ни его часть, ни его
    длина отсюда не возвращаются: модуль физически не имеет ветки, печатающей секрет.
    """
    env = env if isinstance(env, dict) else {}
    active = env.get(VAR_ACTIVE)
    if not active:
        return SLOT_NONE
    for slot in (SLOT_A, SLOT_B):
        value = env.get(VAR_SLOT[slot])
        if value and value == active:
            return slot
    return SLOT_NONE


def other_slot(slot):
    """Имя второго слота (A↔B); для неизвестного слота второго не бывает."""
    return _OTHER.get(slot, SLOT_NONE)


def slot_filled(env, slot):
    """Есть ли у названного слота непустое значение. Пустой слот — не слот."""
    env = env if isinstance(env, dict) else {}
    name = VAR_SLOT.get(slot)
    return bool(name) and bool(env.get(name))


def plan(parsed, env, retried=False):
    """ЕДИНСТВЕННАЯ дверь решения: конверт + окружение + «повтор уже был?» → что делать.

    → {"action": ACT_NONE|ACT_RETRY|ACT_UNKNOWN, "verdict", "status", "slot", "next", "why"}

    `slot` — под каким слотом шёл заход, `next` — под каким повторять (только у ACT_RETRY).

    ПОВТОР РОВНО ОДИН: `retried=True` закрывает ветку повтора НАВСЕГДА для этой задачи — второй
    лимит подряд означает, что кончились ОБА слота, и это ACT_UNKNOWN, а не третий заход.
    """
    v = envelope(parsed)
    base = {"verdict": v["verdict"], "status": v["status"], "why": v["why"],
            "slot": SLOT_NONE, "next": SLOT_NONE}
    if v["verdict"] != LIMIT:
        base["action"] = ACT_NONE
        return base

    slot = active_slot(env)
    base["slot"] = slot
    if slot == SLOT_NONE:
        # Лимит доказан, а под каким слотом шли — неизвестно. Повторять вслепую нельзя: с той же
        # вероятностью попадём в тот же исчерпанный слот. Причина называется адресом переменных.
        base["action"] = ACT_UNKNOWN
        base["why"] = (v["why"] + "; под каким слотом шёл заход — НЕИЗВЕСТНО: значение %s не "
                       "совпало ни с %s, ни с %s (повторять вслепую нельзя)"
                       % (VAR_ACTIVE, VAR_SLOT[SLOT_A], VAR_SLOT[SLOT_B]))
        return base

    if retried:
        base["action"] = ACT_UNKNOWN
        base["why"] = v["why"] + "; повтор под слотом %s уже был — исчерпаны ОБА слота" % slot
        return base

    nxt = other_slot(slot)
    if not slot_filled(env, nxt):
        base["action"] = ACT_UNKNOWN
        base["why"] = (v["why"] + "; второй слот %s пуст — повторять не подо что"
                       % VAR_SLOT.get(nxt, "?"))
        return base

    base["action"] = ACT_RETRY
    base["next"] = nxt
    base["why"] = v["why"] + "; повтор РОВНО ОДИН раз под слотом %s" % nxt
    return base


def reset_at(parsed):
    """Время сброса лимита, если поставщик его назвал. → строка | "".

    Оно едет в ленту вместе с исходом НЕИЗВЕСТНО (прямое требование задания). Поля названы
    списком и читаются только у словаря; выдумывать время мы не вправе — не назвал, значит "".
    """
    if not isinstance(parsed, dict):
        return ""
    for key in ("resets_at", "reset_at", "retry_after", "rate_limit_reset"):
        value = parsed.get(key)
        if value in (None, "", {}, []):
            continue
        return str(value)[:80]
    return ""
