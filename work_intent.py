import re

#: Исходы сообщения. Три, и третий — не запасной. Четвёртый (`AGREE`) — только при `plan=True`.
CLAIM = "claim"
QUESTION = "question"
UNCLEAR = "unclear"
AGREE = "agree"

#: Состояния КЛАУЗЫ. Четыре: `SILENT` — «признака нет вовсе», и это не то же, что «отписка».
SAYS_DONE = "says_done"
ASKS = "asks"
BOTH = "both"
SILENT = "silent"

#: Границы клауз. Знак `?` СОХРАНЯЕТСЯ при разрезе — он и есть признак, ради которого режем.
_CLAUSE_SPLIT = re.compile(r"([.!?;…]+|\n+)")

#: Человек САМ отделяет утверждение от вопроса внутри одной строки: «Я заменил масло, а
#: редуктор тоже?» — после «а/но/и» начинается ВТОРАЯ клауза, и знак принадлежит ей.
_SOFT_SPLIT = re.compile(r",\s*(?=(?:а|но|и)\s)", re.IGNORECASE)

#: Глагол СДЕЛАННОЙ работы. Список узкий намеренно: только формы, называющие завершённое
#: действие над предметом. Голых «да»/«ок»/«всё» здесь нет и быть не должно (см. докстринг).
_DONE_VERBS = (
    "заменил", "заменили", "заменен", "заменён", "замена", "замену", "поменял", "поменяли",
    "сменил", "сменили", "залил", "залили", "поставил", "поставили", "починил", "починили",
    "сделал", "сделали", "сделано", "закончил", "закончили", "готово", "устранил", "устранили",
    "เปลี่ยน", "เสร็จ", "เรียบร้อย", "ใส่",
    "replaced", "changed", "finished",
)

#: Тайская вопросительная ЧАСТИЦА. Тайский вопрос знака `?` часто не несёт вовсе — там весь
#: признак и есть частица, поэтому список обязателен, а не украшение к знаку.
_ASK_TH = ("ไหม", "มั้ย", "รึเปล่า", "หรือเปล่า", "เหรอ", "หรือยัง")

#: Вопросительная частица целым словом. Подстрокой нельзя: «ли» сидит внутри «заЛИл» и
#: «доЛИли», и подстрочный поиск сделал бы вопросом любую отписку.
_ASK_WORD = frozenset(("ли", "did", "should", "whether"))


def _words(s):
    """Слова клаузы в нижнем регистре (для поиска частицы ЦЕЛЫМ словом)."""
    return set(re.findall(r"[^\W\d_]+", str(s or "").lower(), re.UNICODE))


def clauses(text):
    """Сообщение → клаузы, КАЖДАЯ вместе со своим знаком препинания.

    Режем дважды: по концам предложений (знак `?` остаётся при своей клаузе) и по «, а/но/и».
    Пустые куски отбрасываем.
    """
    out, buf = [], ""
    for p in _CLAUSE_SPLIT.split(str(text or "")):
        if p is None:
            continue
        if _CLAUSE_SPLIT.fullmatch(p):
            out.append((buf + p).strip())
            buf = ""
        else:
            buf = p
    if buf.strip():
        out.append(buf.strip())
    res = []
    for c in out:
        for piece in _SOFT_SPLIT.split(c):
            if piece and piece.strip():
                res.append(piece.strip())
    return res


def asks(clause):
    """В клаузе есть вопросительный признак? Знак `?` ЛИБО частица (тайская — подстрокой,
    прочие — целым словом). Больше ничего: морфологии здесь нет намеренно."""
    s = str(clause or "")
    if "?" in s:
        return True
    if any(w in s for w in _ASK_TH):
        return True
    return bool(_words(s) & _ASK_WORD)


def claims(clause):
    """В клаузе есть глагол СДЕЛАННОЙ работы? Подстрокой — формы длинные и различимые."""
    low = str(clause or "").lower()
    return any(v in low for v in _DONE_VERBS)


#: Слово СОГЛАСИЯ или ПЛАНА: побуждение, будущее время, согласие на цену. Узко и целиком, как
#: знак вопроса: «давай», «сделаем», «ок делаем», «let's», «go ahead», «จัดไป», «ตกลง».
_PLAN_WORDS = frozenset((
    "давай", "давайте", "сделаем", "делаем", "делайте", "делай", "согласен", "согласна",
    "согласны", "договорились", "поменяем", "заменим", "меняем", "меняйте", "будем",
    "let's", "lets", "agree", "agreed", "go",
))
_PLAN_SUBSTR = ("go ahead", "do it", "will do", "ทำเลย", "จัดไป", "ตกลง", "เดี๋ยวทำ", "จะทำ",
                "จะเปลี่ยน", "โอเคทำ")

#: Глагол ЗАВЕРШЕНИЯ — прошедшее время / «готово». Отличается от `_DONE_VERBS` тем, что в нём нет
#: имён действия («замена», «замену») и тайского «เปลี่ยน» без показателя: они живут и в плане
#: («давай замену сделаем», «จะเปลี่ยน»), поэтому согласие против них не проигрывает.
_PAST_VERBS = tuple(v for v in _DONE_VERBS if v not in ("замена", "замену", "เปลี่ยน", "ใส่")) + (
    "แล้ว", "done",
)


def plans(clause):
    """В клаузе есть слово согласия/плана? Слова — целиком (кроме составных, они подстрокой)."""
    low = str(clause or "").lower()
    if any(p in low for p in _PLAN_SUBSTR):
        return True
    return bool(set(re.findall(r"[^\W\d_]+'?[^\W\d_]*", low, re.UNICODE)) & _PLAN_WORDS)


def done_past(clause):
    """В клаузе есть глагол ЗАВЕРШЕНИЯ (прошедшее / «готово»)? Подстрокой, как `claims`."""
    low = str(clause or "").lower()
    return any(v in low for v in _PAST_VERBS)


def of_clause(clause):
    """Одна клауза → одно из ЧЕТЫРЁХ состояний. Оба признака сразу — честное `BOTH`."""
    a, c = asks(clause), claims(clause)
    if a and c:
        return BOTH
    if a:
        return ASKS
    if c:
        return SAYS_DONE
    return SILENT


def verdict(text, works=None, plan=False):
    """Слова человека → намерение: заводить заявку, спрашивать или сомневаться.

    `plan=True` (26.09.2026) — руки просят четвёртый исход `AGREE`: ни одна клауза не говорит о
    ЗАВЕРШЁННОЙ работе (`done_past`), а хотя бы одна несёт согласие или план. Он сильнее вопроса
    («Сколько? Давай делаем» — согласие последнее слово) и слабее отписки и сомнения. Без
    `plan=True` ветка не спрашивается вовсе.

    `works` — перечень работ разборщика; НЕ судится и не читается ни одной веткой, принимается
    только ради журнала вызывающего. Судятся РОВНО слова человека: предмет работы разборщик уже
    назвал, а намерение живёт в том, КАК о нём сказано.

    Возврат: `state` (CLAIM/QUESTION/UNCLEAR), `why` — словами, `clause` — та клауза, которая
    решила (человеку и журналу видно, за что зацепились), `n` — сколько клауз разобрано.

    ПУСТОЙ ТЕКСТ — CLAIM: признака нет, демотировать нечем, путь прежний БАЙТ-В-БАЙТ. Модуль
    умеет ТОЛЬКО снимать заявку; молчание сообщения основанием снять её не является (заявка
    могла родиться из подписи к фото или из перечня разборщика).
    """
    cs = clauses(text)
    if not cs:
        return {"state": CLAIM, "why": "слов нет — судить нечем, путь прежний",
                "clause": "", "n": 0}
    seen = [(c, of_clause(c)) for c in cs]
    kinds = {st for _, st in seen}
    if plan and not any(done_past(c) for c in cs):
        agreed = [c for c in cs if plans(c)]
        if agreed:
            return {"state": AGREE,
                    "why": "согласие или план без глагола завершения — работа ещё не сделана",
                    "clause": agreed[-1], "n": len(cs)}
    if SAYS_DONE in kinds:
        return {"state": CLAIM, "why": "в сообщении есть клауза-отписка о сделанной работе",
                "clause": next(c for c, st in seen if st == SAYS_DONE), "n": len(cs)}
    if BOTH in kinds:
        return {"state": UNCLEAR,
                "why": "в одной клаузе и глагол сделанной работы, и вопрос — переспрашиваю",
                "clause": next(c for c, st in seen if st == BOTH), "n": len(cs)}
    if ASKS in kinds:
        return {"state": QUESTION,
                "why": "о работе спрашивают, отписки нет ни в одной клаузе",
                "clause": next(c for c, st in seen if st == ASKS), "n": len(cs)}
    return {"state": CLAIM, "why": "вопросительного признака нет ни в одной клаузе",
            "clause": "", "n": len(cs)}


def is_claim(text, works=None):
    """Заводить заявку? Только на CLAIM. Обёртка для рук — вокабуляр тот же."""
    return verdict(text, works)["state"] == CLAIM
