# стоит 5.0 п.п. Отсюда порог = дно − ОДНА цепочка того же окна = 35.0 − 5.0 = 30.0 %.
#   ПОЧЕМУ НЕ ВЫШЕ: 40 % отказало бы живому окну (1 из 118), 35 % совпало бы с дном (запас 0),
#   33 % (1/3) оставляет 1.7 п.п. = 0.33 цепочки — одна невезучая цепочка в худшем окне, и
