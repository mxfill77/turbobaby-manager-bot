def chain_closed(statuses):
    """Цепочка закрыта = НИ ОДНОЙ живой записи (new/in_progress/needs_approval/approved).
    Открытая цепочка в серию не входит вовсе: она ещё не исход, и зачесть её нельзя ни в одну
    сторону — ни продлить ею серию, ни оборвать."""
    st = [str(s or "") for s in (statuses or [])]
    return bool(st) and all(s in TERMINAL for s in st)


def chain_verdict(chain):
    """Накопленные факты цепочки → вердикт. Ключи входа: root, lane, created, closed_at,
    statuses [..], cards [{sort, why, id}], refusals [{id, reason}], weight {commits, restarts}.

    ОБРЫВ даёт шум, ремонт руками и необъяснённый отказ; воля и неизвестное — не дают.
    Причина обрыва называется ОДНА и в этом порядке: шум → ремонт → отказ (сначала то, что
    касается владельца, потом то, что касается контура)."""
    sorts = {s: [] for s in SORTS}
    for c in chain.get("cards") or []:
        s = str(c.get("sort") or "")
        if s in sorts:
            sorts[s].append(c)
    refusals = list(chain.get("refusals") or [])
    w = chain.get("weight") or {}
    weight = bool(w.get("commits")) or int(w.get("restarts") or 0) > 0
    known = bool(w.get("known", True))       # False → вес не наблюдаем (чужой репозиторий)
    cause, why = None, ""
    if sorts[NOISE]:
        cause, why = NOISE, str(sorts[NOISE][0].get("why") or "")
    elif sorts[MANUAL]:
        cause, why = MANUAL, str(sorts[MANUAL][0].get("why") or "")
    elif refusals:
        cause, why = "отказ", "%s (запись %s)" % (refusals[0].get("reason"), refusals[0].get("id"))
    return {
        "root": chain.get("root"), "lane": chain.get("lane"), "created": chain.get("created"),
        "closed_at": chain.get("closed_at"), "break": cause is not None, "cause": cause,
        "why": why, "weight": weight and known, "weight_known": known,
        "closed": chain_closed(chain.get("statuses")),
        "counts": {s: len(sorts[s]) for s in SORTS},
    }


def series(verdicts):
    """Вердикты цепочек В ПОРЯДКЕ КОРНЕЙ → состояние серии.

    → {"current", "best", "breaks": [...], "chains", "weight_share", "weight_in_current",
       "qualified"}. `qualified` — зачётная ли ИДУЩАЯ серия: длина ≥ SERIES_TARGET И доля
    цепочек с весом внутри неё ≥ WEIGHT_MIN_SHARE. Оба условия обязательны: длина без веса
    не считается (замок), вес без длины — не серия."""
    cur = best = 0
    cur_weight = cur_known = 0
    best_span, cur_span, breaks = [], [], []
    for v in verdicts or []:
        if not v.get("closed", True):
            continue                 # ещё идёт — не исход; в серию не входит ни в одну сторону
        if v.get("break"):
            breaks.append({"root": v.get("root"), "cause": v.get("cause"), "why": v.get("why"),
                           "at": v.get("closed_at") or v.get("created"), "lane": v.get("lane"),
                           "broke_len": cur})
            cur, cur_weight, cur_known, cur_span = 0, 0, 0, []
            continue
        cur += 1
        cur_span.append(v.get("root"))
        if v.get("weight_known", True):
            cur_known += 1
            if v.get("weight"):
                cur_weight += 1
        if cur > best:
            best, best_span = cur, list(cur_span)
    closed = [v for v in (verdicts or []) if v.get("closed", True)]
    total = len(closed)
    known_all = [v for v in closed if v.get("weight_known", True)]
    with_weight = sum(1 for v in known_all if v.get("weight"))
    share_cur = (cur_weight / cur_known) if cur_known else 0.0
    return {
        "chains": total,
        "current": cur, "current_span": cur_span, "current_weight": cur_weight,
        "current_known": cur_known, "current_weight_share": round(share_cur, 4),
        "best": best, "best_span": best_span,
        "breaks": breaks,
        "weight_share": round((with_weight / len(known_all)), 4) if known_all else 0.0,
        "weight_chains": with_weight, "weight_known": len(known_all),
        "open": len(list(verdicts or [])) - total,
        "qualified": (cur >= SERIES_TARGET and cur_known > 0
                      and share_cur >= WEIGHT_MIN_SHARE),
    }


def weight_windows(verdicts, size=None):
    """Доля цепочек с весом в КАЖДОМ скользящем окне длиной `size` (по умолчанию SERIES_TARGET).
    → отсортированный список долей. Отсюда и берётся порог веса: он ставится по форме живого
    распределения, а не по вкусу, — тем же приёмом, что пороги О3/дрейфа."""
    closed = [1 if v.get("weight") else 0 for v in (verdicts or [])
              if v.get("closed", True) and v.get("weight_known", True)]
    n = int(size or SERIES_TARGET)
    if n <= 0 or len(closed) < n:
        return []
    run = sum(closed[:n])
    out = [run / n]
    for i in range(n, len(closed)):
        run += closed[i] - closed[i - n]
        out.append(run / n)
    return sorted(out)


def render(state):
    """Одна строка для журнала/сводки. Числа, не ощущения."""
    return ("серия цепочек: идёт %d (вес %d из %d наблюдаемых), лучшая %d, всего цепочек %d, "
            "обрывов %d [шум %d · ремонт %d · отказ %d], вес по наблюдаемым %.1f%%"
            % (state.get("current", 0), state.get("current_weight", 0),
               state.get("current_known", 0),
               state.get("best", 0), state.get("chains", 0), len(state.get("breaks") or []),
               sum(1 for b in (state.get("breaks") or []) if b.get("cause") == NOISE),
               sum(1 for b in (state.get("breaks") or []) if b.get("cause") == MANUAL),
               sum(1 for b in (state.get("breaks") or []) if b.get("cause") == "отказ"),
               100.0 * float(state.get("weight_share") or 0.0)))
