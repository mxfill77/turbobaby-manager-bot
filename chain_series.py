# ПОРОГ ВЗЯТ ЗАМЕРОМ 11.08.2026 и не раньше (артефакт
# `docs/artifacts/2026-08-11-series-weight-threshold.md`). Мерили НА ТОЙ ЕДИНИЦЕ, к которой порог
