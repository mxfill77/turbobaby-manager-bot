# ВЕС ТОЖЕ ИМЕЕТ ТРИ СОСТОЯНИЯ, а не два, и это тот же замок против ложного зелёного. Цепочка
# полосы pc коммитит в ДРУГОЙ репозиторий, которого с этой машины нет: её вес НЕ «нулевой», он
