# 3. НЕОБЪЯСНЁННЫЙ ОТКАЗ ЦЕПОЧКИ (потеря задачи · зависание · тихий отказ)
# ────────────────────────────────────────────────────────────────────────────────────────────
# Список собран ИЗ ЖИВОГО КОРПУСА (451 запись очереди, 28.07–10.08), а не придуман: каждая форма
# ниже встречается в терминальных текстах хотя бы раз, и рядом посчитана. Честный провал С
# ДИАГНОЗОМ («гейт красный, откатился») сюда НЕ входит: система отработала как задумана.
_REFUSALS = (
    ("зависание",    re.compile(r"причина=heartbeat_timeout|причина=run_timeout|"
                                r"ПК-театр не отвечает|ПК-таймаут одиночки")),
    ("потеря",       re.compile(r"claude\s+(?:-p\s+)?упал \(exit=|claude exit=|"
                                r"процесс убит извне")),
    ("тихий отказ",  re.compile(r"причина=model_refusal|причина=unbacked_red")),
    ("халт",         re.compile(r"думатель:\s*halt|🛑 самопочинка не помогла")),
)
# Терминалы, которые отказом НЕ являются, хотя стоят в failed. Проверяются ПЕРВЫМИ: ответ
# владельца — воля (её считает ветка карточек), снятая дежурным карточка до владельца не дошла
# вовсе, пропуск сиблинга — следствие чужого обрыва, а не свой.
_NOT_REFUSAL = re.compile(r"КАРТОЧКА СНЯТА ДЕЖУРНЫМ|⏭ пропущен")

# ОТКАЗ ВЛАДЕЛЬЦА СУДИТСЯ ПО ПОЗИЦИИ, А НЕ ПО СОВПАДЕНИЮ СЛОВА (НАХОДКА 22.08.2026).
# Прежде этот маркер стоял в `_NOT_REFUSAL` и искался ГДЕ УГОДНО в теле терминала — и настоящее
# падение, чей отчёт лишь ЦИТИРУЕТ слова «отклонено Филиппом», переставало рвать серию. Живая
# проба на дословных телах очереди (21.08.2026): падение #21 («причина=run_timeout», 1055 симв.)
# даёт `зависание`, оно же с цитатой маркера в хвосте отчёта — пустоту, то есть счёт считал сбой
# волей владельца. Достижимость не гипотетическая: тело упавшей задачи несёт хвост её СОБСТВЕННОГО
# отчёта, а отчёт вправе писать об отказах владельца — эта запись тем и занята.
# Класс ровно тот, что закрыт для маркера красной зоны (`6a7baf9`), литерала в теле (`40c8425`) и
# исполняющей позиции гарда (`5ca761d`): решает МЕСТО слова. Отказ владельца пишет devbot ОДНОЙ
# строкой и целиком, поэтому заявляющая позиция одна — начало ПЕРВОЙ непустой строки; декорация
# форматирования перед маркером цитатой не является (зеркало `_NA_DECOR`).
# ЦЕНА НАЗВАНА: признак живёт в ДВУХ реализациях — здесь и в `owner_refusal.py` (его хозяин).
# Импортировать хозяина сюда нельзя: страж CHAIN_SERIES_PURE держит у счёта ровно один импорт
# (`re`), и это тот же выбор, что у правила зелёного — вердикт приходит готовым, а не ввозится
# импортом. Расхождение двух реализаций ловит тест (`tests/test_owner_refusal.py`, секция сверки).
_OWNER_SAID = re.compile(r"[ \t\-–—•*+_#]*отклонено Филиппом")


def _owner_said(text):
    """Маркер отказа владельца в ЗАЯВЛЯЮЩЕЙ позиции — начало первой непустой строки терминала."""
    for line in str(text or "").splitlines():
        if not line.strip():
            continue
        return bool(_OWNER_SAID.match(line))
    return False


def refusal(status, result):
    """(статус, текст терминала) → вид необъяснённого отказа | ''. Не failed → ''."""
    if str(status or "") != "failed":
        return ""
    t = str(result or "")
    if _owner_said(t) or _NOT_REFUSAL.search(t):
        return ""
    for name, rx in _REFUSALS:
        if rx.search(t):
            return name
    return ""


