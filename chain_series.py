# 1. ЕДИНИЦА: маркер начала текста → чей это ребёнок
# ────────────────────────────────────────────────────────────────────────────────────────────
# ПОРЯДОК РЕШАЕТ. Перерождение самопочинки шага несёт ОБА маркера подряд («[шаг i/N родитель P]
# [самопочинка шага i, попытка 1] …»), и число в маркере самопочинки ШАГА — это НОМЕР ШАГА, а не
# id задачи; поэтому шаг проверяется первым, а родителя из «самопочинки» берём только у формы
# «задачи» (там число — настоящий id). Перепутать их значит приписать цепочку чужому корню.
_MARKERS = (
    ("step",            re.compile(r"^\s*\[шаг \d+/\d+ родитель (\d+)\]")),
    ("summary",         re.compile(r"^\s*\[сводка родитель (\d+)\]")),
    ("adapt_card",      re.compile(r"^\s*\[коррекция плана родитель (\d+)\]")),
    ("pc_card",         re.compile(r"^\s*\[карточка родитель (\d+)\]")),
    ("curator_verdict", re.compile(r"^\s*\[куратор (?:задача|родитель) (\d+)\]")),
    ("curator_step",    re.compile(r"^\s*\[куратор цели (\d+), шаг \d+\]")),
    ("owner_card",      re.compile(r"^\s*\[куратор владельцу цель (\d+)(?:, операция [^\]]*)?\]")),
    ("envelope",        re.compile(r"^\s*\[конверт одобренной заявки (\d+)\]")),
    ("selfheal",        re.compile(r"^\s*\[самопочинка задачи (\d+), попытка \d+\]")),
    ("revizor_card",    re.compile(r"^\s*\[ревизор[^\]]*\]")),
)

# Служебные виды: контур породил их сам. В счёт цепочек не идут НИКОГДА (иначе серия росла бы
# от собственной болтовни контура) — но вмешательства и отказы, живущие в них, идут.
SERVICE_KINDS = frozenset((
    "summary", "adapt_card", "pc_card", "curator_verdict", "owner_card", "envelope",
))


def parent_of(text):
    """Текст записи очереди → (вид, id родителя | None). Маркера нет → ('root', None)."""
    t = str(text or "")
    for kind, rx in _MARKERS:
        m = rx.match(t)
        if not m:
            continue
        if not m.groups():
            return kind, None
        try:
            return kind, int(m.group(1))
        except (TypeError, ValueError):
            return kind, None
    return "root", None


def resolve_roots(entries):
    """[{id, text}] → {id: (корень, вид)}. Разрешение ТРАНЗИТИВНОЕ: конверт → карточка владельцу
    → цель → корневая задача. Родителя нет в очереди (обрезана история) → корнем становится сама
    запись: потерять цепочку хуже, чем показать её отдельной. Петля (взаимные ссылки, битый
    маркер) обрывается на длине цепи — молча зациклиться модуль не имеет права."""
    kinds, parents, known = {}, {}, set()
    for e in entries or []:
        try:
            i = int(e.get("id"))
        except (TypeError, ValueError):
            continue
        known.add(i)
        kinds[i], parents[i] = parent_of(e.get("text") if "text" in e else e.get("task_text"))
    out = {}
    for i in known:
        seen, cur = {i}, i
        while True:
            p = parents.get(cur)
            if p is None or p not in known or p in seen:
                break
            seen.add(p)
            cur = p
        out[i] = (cur, kinds[i])
    return out


