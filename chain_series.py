# ОДНО окно из 109 под порогом) и прибором, читавшим текст; новый строже и при этом не оставляет
# под собой НИ ОДНОГО окна живой работы.
WEIGHT_MIN_SHARE = 0.30
# ЗНАМЕНАТЕЛЬ У НУЛЯ ОБЯЗАТЕЛЕН И ЗДЕСЬ. Порог применяется только там, где есть на чём судить:
# в окне из 30 чистых цепочек наблюдаемых бывает и НОЛЬ (полоса pc целиком — так выглядит нынешний
# рекорд 17: цепочки 164–181, вес не наблюдаем ни у одной). Тонкая почва — не «незачёт», а
# НЕИЗВЕСТНО: карать за чужой репозиторий значит наказывать систему не за слабую работу.
# ЧИСЛО 10 — оттуда же, из замера: дно распределения СТАБИЛЬНО (35.0 %) при знаменателе ≥10, ≥15
# и ≥20 и обваливается до 0.0 % ниже десяти (7 окон из 152 — все со знаменателем 1–3); при этом
# знаменатель ≥10 достижим в 76 % окон, а ≥24 — лишь в 10 %, то есть порог, требующий полной
# наблюдаемости, молчал бы почти всегда.
WEIGHT_MIN_KNOWN = 10
SERIES_TARGET = 30            # критерий выхода из фазы (рамка §8г), порогов не двигаем

# ЗАЧЁТНОСТЬ СЕРИИ — ТРИ ИСХОДА, А НЕ ДВА (тот же замок, что у веса цепочки и у О3/О4/О5).
QUAL_YES, QUAL_NO, QUAL_UNKNOWN = "да", "нет", "неизвестно"

# ── ПРАВИЛО ЗЕЛЁНОГО В СЧЁТЕ (16.08.2026, пункт 3 контракта третьего исхода) ─────────────────
# ЧИСТОЙ СЧИТАЕТСЯ ТОЛЬКО ДОКАЗАННАЯ ЦЕПОЧКА: по адресу, названному её корневой записью, и
# правда лежит её продукт. НЕ ДОКАЗАН и НЕИЗВЕСТНО — обрыв (решение владельца 16.08, узел
# `orchestrator_plan`): длина есть УТВЕРЖДЕНИЕ о сделанной работе, и утверждать её без факта
# нельзя. Прежде «неизвестно» оставляло цепочку неразобранной — та ветка осталась ровно за
# молчанием ПРИБОРА (вердикта нет вовсе), и это разные вещи: судья сказал «не знаю» — это факт о
# цепочке; прибор не считал — это факт о нас.
#
# ВОКАБУЛЯРА ТРЕТЬЕГО ТУТ НЕТ. Исход правила приходит ГОТОВЫМ, в той форме, которую отдаёт
# `shadow_rule.chain_shadow` (`green`/`judge`/`why`), — чтобы второго определения одного понятия
# не завелось рядом. Отсюда и импорт этого модуля по-прежнему ровно один (`re`): судить адреса
# счёту нечем ФИЗИЧЕСКИ, он только читает уже вынесенный вердикт.
#
# ПРАВИЛО ОДНОСТОРОННЕЕ И ЗДЕСЬ: оно умеет СНЯТЬ чистоту и не умеет её ДАТЬ. Цепочку, оборванную
# шумом, ремонтом или отказом, доказанный адрес не спасает — причина обрыва называется прежняя и
# в прежнем порядке, а `правило` встаёт последним.
RULE_CAUSE = "правило"


TERMINAL = frozenset(("done", "failed", "rejected"))


def chain_closed(statuses):
    """Цепочка закрыта = НИ ОДНОЙ живой записи (new/in_progress/needs_approval/approved).
    Открытая цепочка в серию не входит вовсе: она ещё не исход, и зачесть её нельзя ни в одну
    сторону — ни продлить ею серию, ни оборвать."""
    st = [str(s or "") for s in (statuses or [])]
    return bool(st) and all(s in TERMINAL for s in st)


def chain_verdict(chain, since=""):
    """Накопленные факты цепочки → вердикт. Ключи входа: root, lane, created, closed_at,
    statuses [..], cards [{sort, why, id}], refusals [{id, reason}], weight {commits, restarts},
    а с 16.08.2026 ещё kinds {id: вид} и rule {green, judge, why} — факты правила зелёного.

    ОБРЫВ даёт шум, ремонт руками и необъяснённый отказ; воля и неизвестное — не дают.
    Причина обрыва называется ОДНА и в этом порядке: шум → ремонт → отказ → правило (сначала то,
    что касается владельца, потом то, что касается контура, и последним — правило зелёного:
    оно судит ПРОДУКТ, а не жизнь цепочки).

    ЗАМОК ТРЕТЬЕГО ИСХОДА: обрыв — ФАКТ, поэтому он сильнее незнания и судится первым; если же
    факта обрыва нет, а сорт хотя бы одного вмешательства не определён (неизвестно · сорт не
    читается), цепочка НЕ РАЗОБРАНА — ни чистая, ни обрыв.

    `since` — МОМЕНТ ВКЛЮЧЕНИЯ ПРАВИЛА ЗЕЛЁНОГО, и он же его выключатель: пусто → правило
    выключено и вердикт БАЙТ-В-БАЙТ прежний (все ветки ниже мертвы ДО чтения фактов). Непусто →
    (1) служебные корни в счёт не входят вовсе, (2) цепочка старше момента включения не входит
    тоже — прошлое не пересчитывается, счёт начинается с нуля, (3) чистой остаётся только
    ДОКАЗАННАЯ."""
    sorts = {s: [] for s in SORTS}
    unread, hanging = [], []
    for c in chain.get("cards") or []:
        if c.get("open"):
            # КАРТОЧКА ЕЩЁ ВИСИТ У ВЛАДЕЛЬЦА: сорт ей ставят при закрытии, и до тех пор он не
            # «отсутствует», а НЕИЗВЕСТЕН. Прежде обе руки такие карточки просто отбрасывали, и
            # цепочка, все записи которой уже терминальны, шла в серию ЧИСТОЙ, пока вопрос ещё
            # стоял перед владельцем. Это та же догадка, вид сбоку.
            hanging.append(c)
            continue
        s = str(c.get("sort") or "")
        (sorts[s] if s in sorts else unread).append(c)
    refusals = list(chain.get("refusals") or [])
    w = chain.get("weight") or {}
    weight = bool(w.get("commits")) or int(w.get("restarts") or 0) > 0
    known = bool(w.get("known", True))       # False → вес не наблюдаем (чужой репозиторий)
    cause, why = None, ""
    if sorts[NOISE]:
        cause, why = NOISE, str(sorts[NOISE][0].get("why") or "")
    elif sorts[MANUAL]:
        cause, why = MANUAL, str(sorts[MANUAL][0].get("why") or "")
    elif refusals:
        cause, why = "отказ", "%s (запись %s)" % (refusals[0].get("reason"), refusals[0].get("id"))
    # ── ПРАВИЛО ЗЕЛЁНОГО: КТО ВООБЩЕ ЕДИНИЦА И ЧТО СЧИТАЕТСЯ ЧИСТЫМ ──────────────────────────
    rl = dict(chain.get("rule") or {})
    svc, counted, skip_why, silent = "", True, "", False
    if since:
        svc = service_root(chain)
        born = stamp(chain.get("created"))
        if svc:
            counted = False
            skip_why = ("служебный корень (%s): запись породил контур сам, продукта у неё нет и "
                        "адреса ей не полагается — единицей метрики она не является" % svc)
        elif not born or born < stamp(since):
            counted = False
            skip_why = ("цепочка старше включения правила (создана %s, правило с %s) — прошлое "
                        "не пересчитываем" % (born or "время неизвестно", stamp(since)))
        elif not rl:
            # МОЛЧАНИЕ ПРИБОРА, А НЕ «НЕИЗВЕСТНО» СУДЬИ. Вердикта адреса нет вовсе (ветка правила
            # не отработала) — это факт о нас, а не о цепочке: ни +1, ни обрыва.
            silent = True
        elif not rl.get("green") and cause is None:
            cause = RULE_CAUSE
            why = ("%s [вердикт адреса: %s%s]"
                   % (rl.get("why") or "правило зелёного сняло зелёное с цепочки",
                      rl.get("judge") or UNKNOWN,
                      (", " + str(rl.get("judge_why"))) if rl.get("judge_why") else ""))
    unresolved, u_why = False, ""
    if cause is None and silent and not (sorts[UNKNOWN] or unread or hanging):
        unresolved = True
        u_why = ("правило зелёного эту цепочку не судило: вердикта адреса нет — прибор молчал, "
                 "а молчание прибора не факт о цепочке")
    elif cause is None and (sorts[UNKNOWN] or unread or hanging):
        unresolved = True
        if hanging:
            u_why = ("вмешательство ещё висит (запись %s) — сорт станет известен, когда карточка "
                     "закроется" % hanging[0].get("id"))
        elif sorts[UNKNOWN]:
            u_why = str(sorts[UNKNOWN][0].get("why") or "сорт вмешательства не определён")
        else:
            u_why = ("сорт вмешательства (запись %s) не читается — угадывать его счёт не будет"
                     % (unread[0].get("id") if isinstance(unread[0], dict) else "?"))
    return {
        "root": chain.get("root"), "lane": chain.get("lane"), "created": chain.get("created"),
        "closed_at": chain.get("closed_at"), "break": cause is not None, "cause": cause,
        "why": why, "weight": weight and known, "weight_known": known,
        "closed": chain_closed(chain.get("statuses")),
        "unresolved": unresolved, "unresolved_why": u_why, "unreadable": len(unread),
        "hanging": len(hanging),
        "counts": {s: len(sorts[s]) for s in SORTS},
        # ── ПРАВИЛО ЗЕЛЁНОГО. `counted` — входит ли цепочка в счёт ВООБЩЕ (служебный корень и
        # прошлое не входят), `service` — вид служебного корня, `rule_state` — что сказал прибор.
        "counted": counted, "service": svc, "skip_why": skip_why,
        "rule_state": {"judged": bool(rl), "green": bool(rl.get("green")) if rl else None,
                       "judge": str(rl.get("judge") or "") if rl else ""},
    }


def series(verdicts, since=""):
    """Вердикты цепочек В ПОРЯДКЕ КОРНЕЙ → состояние серии.

    `since` — момент включения правила зелёного; пусто → счёт БАЙТ-В-БАЙТ прежний. Непусто →
    цепочки, помеченные вердиктом как `counted=False` (служебный корень · прошлое), пропускаются
    ВОВСЕ: они не дают ни длины, ни обрыва. МОЛЧАЛИВОГО ПРОПУСКА НЕТ — и те, и другие названы
    числом (`service` · `before_rule`) и попадают в строку `render`.

    → {"current", "best", "breaks": [...], "last_break", "chains", "weight_share",
       "weight_in_current", "qualified"}. `qualified` — зачётная ли ИДУЩАЯ серия, и это НЕ
    булево: исходов ТРИ — `QUAL_YES` · `QUAL_NO` · `QUAL_UNKNOWN`. Зачёт требует длины ≥
    SERIES_TARGET И доли цепочек с весом ≥ WEIGHT_MIN_SHARE; оба условия обязательны — длина без
    веса не считается (замок), вес без длины не серия.

    ТРЕТИЙ ИСХОД — ГЛАВНОЕ ЗДЕСЬ. Длина наблюдаема ВСЕГДА, поэтому «короче тридцати» есть ФАКТ и
    честное «нет». А вес наблюдаем не у всех: цепочка полосы pc коммитит в чужой репозиторий.
    Если наблюдаемых цепочек в серии меньше WEIGHT_MIN_KNOWN, судить не на чем — и ответ
    `QUAL_UNKNOWN`, а не «нет»: отказ по причине СЛЕПОТЫ наказал бы систему за чужой
    репозиторий, а не за слабую работу. Ровно так выглядит нынешний рекорд 17 (цепочки 164–181,
    полоса pc целиком): его зачётность НЕ ОПРОВЕРГНУТА, она НЕ СУДИМА.

    `last_break` — ПОСЛЕДНИЙ обрыв отдельным полем (дата · сорт · цепочка · почему), а не только
    хвост списка. Так требует рамка §8г от файла состояния, и так он переживает урезку: список
    `breaks` живёт ровно столько цепочек, сколько их помнит состояние (SERIES_KEEP), а «когда и
    чем оборвалось в последний раз» — это факт о прошлом, который от забывания старых цепочек
    ложным не становится.

    НЕРАЗОБРАННАЯ ЦЕПОЧКА ПРОПУСКАЕТСЯ, КАК ОТКРЫТАЯ: длину не даёт (утверждать без факта
    нельзя) и в нуль не сбрасывает (обвинять без факта нельзя). Чтобы пропуск не стал тихой
    подпоркой длины, серия НАЗЫВАЕТ ЧИСЛОМ, сколько неразобранных цепочек она перешагнула:
    `current_unresolved` — в идущей, `best_unresolved` — в рекордной, `unresolved` — всего."""
    cur = best = 0
    cur_weight = cur_known = 0
    cur_unres = best_unres = 0
    unres_roots = []
    svc_roots, old_roots = [], []
    best_span, cur_span, breaks = [], [], []
    for v in verdicts or []:
        if not v.get("closed", True):
            continue                 # ещё идёт — не исход; в серию не входит ни в одну сторону
        if not v.get("counted", True):
            # ЕДИНИЦЕЙ НЕ ЯВЛЯЕТСЯ. Пропускаем как открытую — ни +1, ни в нуль; но считаем и
            # называем: молчаливый пропуск снова выдавал бы «не судили» за «чисто».
            (svc_roots if v.get("service") else old_roots).append(v.get("root"))
            continue
        if v.get("break"):
            breaks.append({"root": v.get("root"), "cause": v.get("cause"), "why": v.get("why"),
                           "at": v.get("closed_at") or v.get("created"), "lane": v.get("lane"),
                           "broke_len": cur, "stepped_over": cur_unres})
            cur, cur_weight, cur_known, cur_span, cur_unres = 0, 0, 0, [], 0
            continue
        if v.get("unresolved"):
            # НЕ РАЗОБРАНА: ни +1, ни в нуль. Считаем и запоминаем — молчаливого пропуска нет.
            unres_roots.append(v.get("root"))
            cur_unres += 1
            continue
        cur += 1
        cur_span.append(v.get("root"))
        if v.get("weight_known", True):
            cur_known += 1
            if v.get("weight"):
                cur_weight += 1
        if cur > best:
            best, best_span, best_unres = cur, list(cur_span), cur_unres
    closed = [v for v in (verdicts or []) if v.get("closed", True) and v.get("counted", True)]
    total = len(closed)
    known_all = [v for v in closed if v.get("weight_known", True)]
    with_weight = sum(1 for v in known_all if v.get("weight"))
    share_cur = (cur_weight / cur_known) if cur_known else 0.0
    if cur < SERIES_TARGET:
        qual = QUAL_NO
        qual_why = "длины нет: %d из %d цепочек" % (cur, SERIES_TARGET)
    elif cur_known < WEIGHT_MIN_KNOWN:
        qual = QUAL_UNKNOWN
        qual_why = ("вес судить не на чем: наблюдаемых цепочек %d, нужно %d — остальные меняют "
                    "состояние там, куда с этой машины не видно. Это НЕ незачёт"
                    % (cur_known, WEIGHT_MIN_KNOWN))
    elif share_cur >= WEIGHT_MIN_SHARE:
        qual = QUAL_YES
        qual_why = ("длина %d ≥ %d и вес %.0f%% ≥ %.0f%% (%d из %d наблюдаемых)"
                    % (cur, SERIES_TARGET, 100 * share_cur, 100 * WEIGHT_MIN_SHARE,
                       cur_weight, cur_known))
    else:
        qual = QUAL_NO
        qual_why = ("длина есть, веса нет: %.0f%% ниже порога %.0f%% (%d из %d наблюдаемых) — "
                    "длину набрали цепочками, не менявшими операционного состояния"
                    % (100 * share_cur, 100 * WEIGHT_MIN_SHARE, cur_weight, cur_known))
    return {
        "chains": total,
        "current": cur, "current_span": cur_span, "current_weight": cur_weight,
        "current_known": cur_known, "current_weight_share": round(share_cur, 4),
        "best": best, "best_span": best_span,
        "breaks": breaks,
        "last_break": dict(breaks[-1]) if breaks else None,
        "unresolved": len(unres_roots), "unresolved_roots": unres_roots[-40:],
        "current_unresolved": cur_unres, "best_unresolved": best_unres,
        "clean": total - len(unres_roots) - len(breaks),
        "weight_share": round((with_weight / len(known_all)), 4) if known_all else 0.0,
        "weight_chains": with_weight, "weight_known": len(known_all),
        "open": sum(1 for v in (verdicts or []) if not v.get("closed", True)),
        "qualified": qual, "qualified_why": qual_why,
        # ── ПРАВИЛО ЗЕЛЁНОГО: что в счёт не вошло и почему (при выключенном правиле — нули).
        "rule_since": stamp(since) or "",
        "service": len(svc_roots), "service_roots": svc_roots[-40:],
        "before_rule": len(old_roots), "before_rule_roots": old_roots[-40:],
        "rule_breaks": sum(1 for b in breaks if b.get("cause") == RULE_CAUSE),
    }


def weight_windows(verdicts, size=None):
    """Доля цепочек с весом в КАЖДОМ скользящем окне длиной `size` (по умолчанию SERIES_TARGET).
    → отсортированный список долей. Отсюда и берётся порог веса: он ставится по форме живого
    распределения, а не по вкусу, — тем же приёмом, что пороги О3/дрейфа."""
    closed = [1 if v.get("weight") else 0 for v in (verdicts or [])
              if v.get("closed", True) and v.get("weight_known", True)]
    n = int(size or SERIES_TARGET)
    if n <= 0 or len(closed) < n:
        return []
    run = sum(closed[:n])
    out = [run / n]
    for i in range(n, len(closed)):
        run += closed[i] - closed[i - n]
        out.append(run / n)
    return sorted(out)


def qualify_windows(verdicts, size=None, min_known=None):
    """Доля веса в скользящем окне из `size` ЧИСТЫХ цепочек подряд — ТОЙ САМОЙ единицы, к которой
    применяется порог («серия длиной 30»). Возвращает (отсортированные доли судимых окон, сколько
    окон осталось без судейства из-за тонкой почвы).

    ЧЕМ ОТЛИЧАЕТСЯ ОТ `weight_windows`: та считает окна по НАБЛЮДАЕМЫМ цепочкам подряд, выбрасывая
    из ряда всё, чего не видно, — форма распределения выходит плотнее живой и дно у неё ниже.
    Порог же встречает серию как есть: тридцать чистых цепочек, среди которых наблюдаемых бывает
    и семнадцать, и ноль. Отсюда и два числа порога — сама доля и минимальный знаменатель, при
    котором её вообще позволено объявлять."""
    clean = [(bool(v.get("weight_known", True)), bool(v.get("weight")))
             for v in (verdicts or [])
             if v.get("closed", True) and not v.get("break") and not v.get("unresolved")]
    n = int(size or SERIES_TARGET)
    k = int(min_known if min_known is not None else WEIGHT_MIN_KNOWN)
    if n <= 0 or len(clean) < n:
        return [], 0
    out, thin = [], 0
    for i in range(0, len(clean) - n + 1):
        win = clean[i:i + n]
        known = sum(1 for kn, _ in win if kn)
        if known < k:
            thin += 1
            continue
        out.append(sum(1 for kn, w in win if kn and w) / known)
    return sorted(out), thin


def render(state):
    """Одна строка для журнала/сводки. Числа, не ощущения. Неразобранные названы ЗДЕСЬ ЖЕ и
    рядом с длиной: строка, молчащая о них, снова выдавала бы пропуск за чистоту.

    Правило зелёного выключено → строка БАЙТ-В-БАЙТ прежняя. Включено → хвост называет момент
    включения и всё, что в счёт не вошло: служебные корни и цепочки старше включения."""
    tail = ""
    if state.get("rule_since"):
        tail = (" | правило зелёного с %s: обрывов по правилу %d, служебных корней %d, прежних "
                "цепочек %d (в счёт не входят)"
                % (state.get("rule_since"), state.get("rule_breaks", 0),
                   state.get("service", 0), state.get("before_rule", 0)))
    return tail and (_render_base(state) + tail) or _render_base(state)


def _render_base(state):
    return ("серия цепочек: идёт %d (вес %d из %d наблюдаемых, перешагнула неразобранных %d), "
            "лучшая %d, всего цепочек %d, не разобрано %d, "
            "обрывов %d [шум %d · ремонт %d · отказ %d], вес по наблюдаемым %.1f%%, "
            "зачётная: %s"
            % (state.get("current", 0), state.get("current_weight", 0),
               state.get("current_known", 0), state.get("current_unresolved", 0),
               state.get("best", 0), state.get("chains", 0), state.get("unresolved", 0),
               len(state.get("breaks") or []),
               sum(1 for b in (state.get("breaks") or []) if b.get("cause") == NOISE),
               sum(1 for b in (state.get("breaks") or []) if b.get("cause") == MANUAL),
               sum(1 for b in (state.get("breaks") or []) if b.get("cause") == "отказ"),
               100.0 * float(state.get("weight_share") or 0.0),
               state.get("qualified", QUAL_UNKNOWN)))
