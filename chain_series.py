# 3. НЕОБЪЯСНЁННЫЙ ОТКАЗ ЦЕПОЧКИ (потеря задачи · зависание · тихий отказ)
# ────────────────────────────────────────────────────────────────────────────────────────────
# Список собран ИЗ ЖИВОГО КОРПУСА (451 запись очереди, 28.07–10.08), а не придуман: каждая форма
# ниже встречается в терминальных текстах хотя бы раз, и рядом посчитана. Честный провал С
# ДИАГНОЗОМ («гейт красный, откатился») сюда НЕ входит: система отработала как задумана.
_REFUSALS = (
    ("зависание",    re.compile(r"причина=heartbeat_timeout|причина=run_timeout|"
                                r"ПК-театр не отвечает|ПК-таймаут одиночки")),
    ("потеря",       re.compile(r"claude\s+(?:-p\s+)?упал \(exit=|claude exit=|"
                                r"процесс убит извне")),
    ("тихий отказ",  re.compile(r"причина=model_refusal|причина=unbacked_red")),
    ("халт",         re.compile(r"думатель:\s*halt|🛑 самопочинка не помогла")),
)
# Терминалы, которые отказом НЕ являются, хотя стоят в failed. Проверяются ПЕРВЫМИ: ответ
# владельца — воля (её считает ветка карточек), снятая дежурным карточка до владельца не дошла
# вовсе, пропуск сиблинга — следствие чужого обрыва, а не свой.
_NOT_REFUSAL = re.compile(r"отклонено Филиппом|КАРТОЧКА СНЯТА ДЕЖУРНЫМ|⏭ пропущен")


def refusal(status, result):
    """(статус, текст терминала) → вид необъяснённого отказа | ''. Не failed → ''."""
    if str(status or "") != "failed":
        return ""
    t = str(result or "")
    if _NOT_REFUSAL.search(t):
        return ""
    for name, rx in _REFUSALS:
        if rx.search(t):
            return name
    return ""


