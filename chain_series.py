# (155 таких окон в корпусе 28.07–11.08, 492 записи очереди, 307 цепочек):
#
#   наблюдаемых внутри окна из 30 чистых:  min 0 · p10 2 · МЕДИАНА 17 · p90 23 · max 26
#   доля веса там, где наблюдаемых ≥ 10:   МИН 35.0 % · медиана 57.9 % · max 75.0 % (118 окон)
#   окон живой работы ниже 20/25/30/33 %:  0 / 0 / 0 / 0        ниже 40 %: 1 (то самое, 35.0 %)
