"""Точечно дописать в KB_RULES раздел 8 — доктрина подтверждений (02.07.2026). Зелёная зона
(живой свод ведёт Claude Code через write_doc). Защита от затирки: пишем ТОЛЬКО если read ok."""
from dotenv import load_dotenv
load_dotenv()
from bridge_client import BridgeClient

SECTION = """
════════════════════════════════════════════════════════════════════
8. ДОКТРИНА ПОДТВЕРЖДЕНИЙ — ЗАЧЕМ ВООБЩЕ КНОПКА «ДА» (заведено 02.07.2026)
════════════════════════════════════════════════════════════════════
Кнопка/ask имеет смысл ТОЛЬКО там, где владелец добавляет информацию, которой нет у машины —
БИЗНЕС-РЕШЕНИЯ: тот ли клиент / та ли сумма / тот ли байк, запись в Лист1/CRM, деньги, деструктив
(удаление/перезапись чужого труда). Там «да» Филиппа несёт реальную проверку фактов из жизни.
ТЕХНИЧЕСКУЮ корректность проверяют тесты+гейт (gate.py, бэкап, прописанный откат, отчёт постфактум),
а НЕ человеческое «да» — Филипп не программист, его «да» на технике = слепое дакание, ничего не
проверяет и только тормозит. Подтверждения на технические операции (restart / push / тесты / конфиг)
НЕ создавать.
КРИТЕРИЙ при сомнении «нужен ли ask»: что именно владелец проверит своим «да»? Ответ «ничего, он не
может это оценить» → ask не нужен, нужны тесты и откат. Ответ «факт из жизни (клиент/сумма/байк/
намерение)» → ask обязателен. Действует для всех контуров: Splinter-кнопки, дев-бот 328, hooks Termux.
"""

c = BridgeClient()
r = c._call("read_doc", name="rules")
if not r.get("ok"):
    print("READ FAIL — НЕ пишу:", r)
    raise SystemExit(1)

old = r.get("text", "")
if "ДОКТРИНА ПОДТВЕРЖДЕНИЙ" in old:
    print("Уже есть раздел — НЕ дублирую.")
    raise SystemExit(0)

new = old.rstrip("\n") + "\n" + SECTION
w = c.write_doc(text=new, name="rules")
print("WRITE:", w.get("ok"), "| old_len:", len(old), "new_len:", len(new))
