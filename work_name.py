#: Голые отметки о завершении и подтверждения: работу они не называют («готово», «เสร็จแล้ว»).
BARE_DONE = frozenset(("да", "ок", "окей", "ok", "okay", "yes", "готово", "сделал", "сделали",
                       "сделано", "закончил", "закончили", "всё", "все", "done", "ready",
                       "เสร็จ", "เสร็จแล้ว", "เรียบร้อย", "เรียบร้อยแล้ว", "แล้ว", "ครับ", "ค่ะ"))
#: Слова о самом пробеге: «пробег 29859 км» — это число, а не работа.
KM_WORDS = frozenset(("км", "км.", "km", "kms", "กม", "กม.", "пробег", "пробега", "одометр",
                      "одометра", "odo", "mileage", "ไมล์", "เลขไมล์"))


def enabled(raw):
    """Ветка жива? Пусто/не задано → ДА (дефолт 1). Ровно «0» → нет. Парсер как у `undo_last`."""
    return str(raw if raw is not None else "1").strip() not in ("0", "false", "no", "off")


def words_of(kind, works, kind_of):
    """Слова механика, относящиеся к ЭТОМУ виду. Порядок сказанного сохранён, дубли сняты.

    Пустой список = механик работу этого вида словами не назвал (вид пришёл сканом свободного
    текста `_SP_TEXT_KINDS` либо из заявленного `declared`). Классификатор чужой (`kind_of`):
    судить «моё ли это слово» своей копией правил значило бы завести второй словарь видов.
    """
    out = []
    for w in (works or []):
        if not w:
            continue        # пустое/None словом не становится: `str(None)` дало бы «None» в таблицу
        s = str(w).strip()
        if not s or s in out:
            continue
        try:
            k = kind_of(s)
        except Exception:
            continue        # классификатор споткнулся о слово → это слово молчит, а не решает
        if k == kind:
            out.append(s)
    return out


def date_human(raw):
    """Дата работы → «ДД.ММ.ГГГГ», либо '' (не разобрали — даты в строке нет, а не выдуманная).

    Принимает ровно то, что приносят руки: «2026-10-13» (`msg_date`, `str(msg.date.date())`),
    «2026-10-13T07:59:40Z» (`created_at` моста) и уже готовое «13.10.2026»."""
    s = str(raw or "").strip()
    if len(s) >= 10 and s[4] == "-" and s[7] == "-" and (s[:4] + s[5:7] + s[8:10]).isdigit():
        y, m, d = s[:4], s[5:7], s[8:10]
    elif len(s) >= 10 and s[2] == "." and s[5] == "." and (s[:2] + s[3:5] + s[6:10]).isdigit():
        d, m, y = s[:2], s[3:5], s[6:10]
    else:
        return ""
    if not ("01" <= m <= "12" and "01" <= d <= "31"):
        return ""
    return f"{d}.{m}.{y}"


def note_line(body, km, date=""):
    """«<работа> — <км> км · ДД.ММ.ГГГГ», урезанная под `NOTE_CAP`.

    РЕЖУТСЯ СЛОВА, А НЕ ХВОСТ: километры держат разбор карточки (`splinter._SVC_HIST_RE`,
    `^(.+?)\\s*—\\s*(\\d+)\\s*(?:км|กม)`), и дата стоит ПОСЛЕ них ровно поэтому — разбор
    нежадный, хвоста не видит и о него не спотыкается. Строка без пробега перестала бы быть
    записью обслуживания, а недоговорённое название всё ещё называет работу. Даты нет или она
    не разобрана → строка БАЙТ-В-БАЙТ прежняя."""
    tail = f" — {km} км" if str(km or "").strip() else ""
    dh = date_human(date)
    if dh:
        tail += DATE_SEP + dh
    body = str(body or "").strip()
    room = NOTE_CAP - len(tail)
    if len(body) > room:
        body = body[:max(0, room - 1)].rstrip() + "…"
    return body + tail


def words_from_text(text):
    """Название работы из ОДНОЙ фразы человека → [фраза] или [] (названия нет).

    Осторожно и в одну сторону: лучше переспросить, чем записать в историю не работу. Пустым
    выходит сообщение, где после снятия чисел, слов о пробеге и упоминаний @ не осталось слов
    («29859», «пробег 29859 км»); вопрос («менялось масло?»); план или просьба («нужно
    заменить колодки», «…сразу можно»); голая отметка о завершении («готово», «เสร็จแล้ว»).
    Число вместе с предлогом перед ним уходит («Замена масла на 1200» → «Замена масла»)."""
    s = " ".join(str(text or "").split())
    if not s or "?" in s:
        return []
    low = s.lower() + " "
    if any(m in low for m in PLAN_MARKERS):
        return []
    toks = s.split(" ")
    keep = []
    for i, t in enumerate(toks):
        bare = t.strip(".,;:!()[]«»\"'—–-").lower()
        if not bare or t.startswith("@") or bare in KM_WORDS:
            continue
        if any(ch.isdigit() for ch in bare):
            continue
        nxt = toks[i + 1] if i + 1 < len(toks) else ""
        if bare in ("на", "at", "ที่") and any(ch.isdigit() for ch in nxt):
            continue            # «на 1200» — предлог при числе, а не часть названия
        keep.append(t)
    out = " ".join(keep).strip(" ,.;:!—–-")
    core = out.lower()
    for suf in ("ครับ", "ค่ะ", "คะ", "นะ"):
        if core.endswith(suf):
            core = core[:-len(suf)].strip()   # тайская вежливая частица работы не называет
    if sum(1 for ch in out if ch.isalpha()) < 4 or core in BARE_DONE:
        return []
    if len(out) > WORDS_CAP:
        out = out[:WORDS_CAP - 1].rstrip() + "…"
    return [out]


def history_note(kind, works, km, labels, kind_of, on=True, date=""):
    """→ {'text', 'named', 'source', 'why'} — что написать в `notes` строки истории.

    `text` готов к записи (уже с километрами, датой работы и урезан под `NOTE_CAP`). `named` —
    назвал ли механик работу словами; `source` и `why` идут в журнал, чтобы разница была видна не
    только в таблице. `date` — день работы (см. `note_line`); пусто → строка как до 25.10.2026.

    `on=False` (ручка `WORK_NAME=0`) → прежний путь: ярлык, слова не разбираются, даты нет.
    """
    lbl = (labels or {}).get(kind, (kind, kind))[1]
    tail = f" — {km} км" if str(km or "").strip() else ""
    if not on:
        return {"text": (lbl + tail)[:NOTE_CAP], "named": False, "source": "ярлык",
                "why": f"ветка выключена ({FLAG_ENV}=0) — путь прежний"}
    mine = words_of(kind, works, kind_of)
    if not mine:
        return {"text": note_line(lbl, km, date), "named": False, "source": "ярлык",
                "why": f"механик работу вида «{kind}» словами не назвал"}
    # Слова урезаются ПОД километры и дату, а не наоборот (см. `note_line`).
    text = note_line(JOIN.join(mine), km, date)
    return {"text": text, "named": True, "source": "слова механика",
            "why": f"названо словами ({len(mine)}): {JOIN.join(mine)[:NOTE_CAP]}"}
