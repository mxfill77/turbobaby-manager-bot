"""ВИД ЗАПИСИ ВХОДЯЩЕЙ ОЧЕРЕДИ WhatsApp — чистая функция «поля таблицы → чем эта запись является».

ЗАЧЕМ. Очередь `wa_inbox` копит в ОДНОЙ таблице события четырёх разных родов, и различить их
можно только по полям — не по тексту:

    входящее клиента   человек написал нам             → карточка менеджеру и контекст
    эхо менеджера      наше же исходящее вернулось     → контекст, но НЕ карточка
    история            досинхрон старой переписки      → контекст, но НЕ карточка
    квитанция доставки sent/delivered/read/failed      → НИ карточки, НИ контекста

Четвёртый род — тот, о который ломается наивное «всё, что пришло, показать менеджеру»: каждое
«доставлено» и «прочитано» породило бы карточку о сообщении, которое менеджер сам же и отправил.
Отличается он ОДНИМ полем — `msg_type == 'status'`, — а не догадкой по тексту: в `text` квитанции
лежит слово состояния (`delivered`), и судить по нему значило бы принять клиента, написавшего
«delivered», за квитанцию.

ТРЕТИЙ ИСХОД ОБЯЗАТЕЛЕН И ОН НЕ ЗАПАСНОЙ. Запись, чей вид не опознан, становится `unknown`, а НЕ
входящим. Направление сомнения здесь ОБРАТНОЕ гарду и выбрано намеренно: гард решает, исполнится
ли команда, а тут решается, ПОКАЖЕТСЯ ли клиенту живой человек. Молчаливое приведение неизвестного
к «входящему» даёт карточку там, где её быть не должно, — то есть менеджер отвечает на квитанцию
или на собственное эхо. Цена названа прямо: НОВЫЙ вид клиентского сообщения (WhatsApp заводит их
сам — `order`, `button`; `reaction` с 01.10.2026 — свой вид) до внесения в `INBOUND_TYPES` поедет как `unknown` и карточки
не даст; он будет ВИДЕН неопознанным, и это лучше, чем невидимая ложная карточка.

ИМЕНА ПОЛЕЙ — ТЕ ЖЕ, ЧТО В ТАБЛИЦЕ (`echo`, `history`, `msg_type`), чтобы у одной вещи не стало
двух имён.

ИМПОРТОВ НОЛЬ. Ни базы, ни сети, ни часов: всё, чем решается вид, приносит вызывающий из СВОЕЙ
строки. Будь у решения база — оно спросило бы очередь само, и вид зависел бы от того, КАК спросили,
а не от строки, которую выдают; будь у него сеть — рядом с решением завёлся бы второй путь наружу.
Стережёт `WA_KIND_PURE` в `invariants_check.py` (ast, в гейте).
"""

# ─── виды ──────────────────────────────────────────────────────────────────────────────

KIND_INBOUND = "inbound"     # написал клиент
KIND_ECHO    = "echo"        # наше же исходящее вернулось эхом
KIND_HISTORY = "history"     # досинхрон старой переписки
KIND_RECEIPT = "receipt"     # квитанция доставки/прочтения
KIND_REACTION = "reaction"   # реакция на сообщение (клиента или наша с телефона) — 01.10.2026
KIND_UNKNOWN = "unknown"     # вид не опознан — третий исход

KINDS = (KIND_INBOUND, KIND_ECHO, KIND_HISTORY, KIND_RECEIPT, KIND_REACTION, KIND_UNKNOWN)

# Значение `msg_type`, которым нормализация метит квитанции. ОДНО поле, а не разбор текста.
RECEIPT_TYPE = "status"

# Реакция (WAREACTNAME0110): эмодзи и wamid цели, не слово человека. Карточки НЕ даёт и окно
# суток НЕ открывает; чья она — по `echo`, который едет рядом. Своим видом, а не `inbound`.
REACTION_TYPE = "reaction"

# Типы, которые может нести НАСТОЯЩЕЕ сообщение человека. Отвечает на вопрос «бывает ли такой род
# у клиентского сообщения», а НЕ на вопрос «где у него лежит media_id» (на второй отвечает
# `wa_webhook._MEDIA_TYPES`, и это другой вопрос, а не вторая копия этого списка). Что media-типы
# не разъедутся с этим набором в опасную сторону, стережёт отдельный тест.
INBOUND_TYPES = frozenset((
    "text",
    "image", "audio", "video", "document", "sticker", "voice",
    "location",
    "interactive",
    "contacts",
))

# ─── что с видом делать ────────────────────────────────────────────────────────────────
#
# Распоряжение — ЧИСТАЯ функция вида, а не второй источник правды: правило «квитанция не даёт ни
# карточки, ни контекста» обязано жить в ОДНОМ месте, и это место здесь, рядом с тем, кто виды и
# различает. ПК не держит своей копии правила.

DISP_CARD    = "card"        # карточка менеджеру + в контекст переписки
DISP_CONTEXT = "context"     # в контекст переписки, карточки НЕТ
DISP_DROP    = "drop"        # ни карточки, ни контекста
DISP_REVIEW  = "review"      # карточки НЕТ; показать как неопознанное

_DISPOSITION = {
    KIND_INBOUND: DISP_CARD,
    KIND_ECHO:    DISP_CONTEXT,
    KIND_HISTORY: DISP_CONTEXT,
    KIND_RECEIPT: DISP_DROP,
    KIND_REACTION: DISP_DROP,     # ни карточки, ни контекста: эмодзи без цели — не реплика
    KIND_UNKNOWN: DISP_REVIEW,
}


def disposition_of(kind) -> str:
    """Что делать с записью этого вида. Незнакомый вид → `review` (молча карточки не заводим)."""
    return _DISPOSITION.get(kind, DISP_REVIEW)


# ─── эхо с телефона и пауза агента (WAPAUSEMEDIA0410) ──────────────────────────────────
#
# Решение владельца 05.10.2026 (вопрос Б, «Вариант б»): фото и файлы, присланные клиенту С ТЕЛЕФОНА, агента
# на паузу НЕ ставят, текст ставит. Список ЗАКРЫТЫЙ и узкий — ровно названное: фото, видео, документ (с
# подписью или без — тип один). Голосовое и стикер владелец не назвал — пауза, как прежде. Пустой, незнакомый
# и всякий иной тип — пауза: сомнение решается в сторону прежнего поведения, а не молча в сторону «без паузы».

ECHO_NO_PAUSE_TYPES = frozenset(("image", "video", "document"))


def echo_pauses(msg_type) -> bool:
    """Ставит ли живое эхо с телефона этого типа паузу агенту. Нет — только у `ECHO_NO_PAUSE_TYPES`."""
    return _type(msg_type) not in ECHO_NO_PAUSE_TYPES


# ─── разбор полей ──────────────────────────────────────────────────────────────────────


def _flag(value):
    """Трёхзначно: True · False · None («не записано / не разобрано»).

    NULL и мусор НЕ приводятся к нулю: «не знаю, наше ли это» и «точно не наше» — разные миры, и
    первый обязан кончиться `unknown`, а не карточкой. Тот же знаменатель, что у `scan_result`.
    """
    if value is None:
        return None
    if isinstance(value, bool):
        return value
    if isinstance(value, int):
        return value != 0
    if isinstance(value, float):
        return value != 0.0
    if isinstance(value, str):
        s = value.strip().lower()
        if s in ("1", "true", "yes", "y", "t"):
            return True
        if s in ("0", "false", "no", "n", "f", ""):
            return False
    return None


def _type(value) -> str:
    return (value or "").strip().lower() if isinstance(value, str) else ""


def kind_of(msg_type, echo, history) -> str:
    """Вид записи по трём полям строки очереди. Один из `KINDS`, всегда.

    ПОРЯДОК РЕШАЮЩИЙ И ОН НАЗВАН:

    1. КВИТАНЦИЯ решается первой и одним полем. Даже если её остальные поля — мусор, квитанция
       обязана остаться квитанцией: она не должна дать карточку ни при каком состоянии соседей.
    2. НЕРАЗОБРАННЫЙ ФЛАГ → `unknown`. Не знаем, наше ли сообщение и не досинхрон ли это — значит
       не знаем и вида. Приведение к нулю здесь и было бы тем самым молчаливым «входящее».
    2а. РЕАКЦИЯ — своим видом и сильнее эха: реакция с телефона менеджера и реакция клиента
       одинаково не реплики (01.10.2026); кто поставил — по `echo`, он едет в выдаче сырым.
    3. ЭХО сильнее ИСТОРИИ. `echo` — ось «чьё сообщение», и ровно её сервер уже применяет у живой
       двери окна суток (`echo = 0 AND msg_type <> 'status'` в `wa_send.last_inbound_ts`); держа
       её главной, ярлык и боевой фильтр судят по одним и тем же осям. Обе величины едут в выдаче
       СЫРЫМИ рядом с ярлыком, поэтому выбор порядка ничего не прячет.
    4. ВХОДЯЩИМ становится только известный тип при обоих нулях.
    5. Всё прочее — `unknown`.
    """
    t = _type(msg_type)
    if t == RECEIPT_TYPE:
        return KIND_RECEIPT

    is_echo = _flag(echo)
    is_history = _flag(history)
    if is_echo is None or is_history is None:
        return KIND_UNKNOWN

    if t == REACTION_TYPE:
        return KIND_REACTION
    if is_echo:
        return KIND_ECHO
    if is_history:
        return KIND_HISTORY
    if t in INBOUND_TYPES:
        return KIND_INBOUND
    return KIND_UNKNOWN
