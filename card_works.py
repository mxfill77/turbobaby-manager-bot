# ── ИСХОД ПОЗИЦИИ ────────────────────────────────────────────────────────────────────────────
PENDING = "ждёт"          # работа в мире не найдена — остаётся в списке
WRITTEN = "записано"      # мир САМ назвал её записанной — уходит из списка
UNKNOWN = "неизвестно"    # спросить не удалось — ОСТАЁТСЯ в списке (незнание ≠ зелёное)
STATES = (PENDING, WRITTEN, UNKNOWN)

# ── ЧЕМ ДОКАЗАНА ЗАПИСЬ ──────────────────────────────────────────────────────────────────────
BY_REGISTER = "регистр"           # клетка Лист1 (I/J/K/L) стоит на пробеге заявки
BY_HISTORY = "история"            # строка «события» с тем же контентным ключом на том же пробеге
BY_HISTORY_KIND = "история/вид"   # позиция без слов — история несёт работу того же ВИДА
BY_HISTORY_WIDE = "история/уточнение"   # обобщённая форма покрыта уточнённой записью того же стема
PROOFS = (BY_REGISTER, BY_HISTORY, BY_HISTORY_KIND, BY_HISTORY_WIDE)


def _num(x):
    """Целое из значения клетки/пробега или None. Пусто, мусор, дробь → None (не ноль!):
    «нуль по неразбору» здесь означал бы «регистр стоит на нуле», то есть ложное сравнение."""
    s = str(x if x is not None else "").strip().replace(" ", "").replace(",", "")
    return int(s) if s.isdigit() else None


def _call(fn, arg, default=""):
    """Позвать переданное правило (классификатор вида / контентный ключ). Правило споткнулось →
    значение по умолчанию: чужая ошибка не вправе объявить работу записанной."""
    if fn is None:
        return default
    try:
        return fn(arg) or default
    except Exception:
        return default


def position(kind, word=""):
    """Позиция списка «в работе»: машинный ВИД + дословное СЛОВО механика (может быть пустым)."""
    return {"kind": str(kind or "").strip() or "other", "word": str(word or "").strip()}


def merge(kinds, works, kind_of, key_of):
    """ЕДИНЫЙ список позиций на ОБЕ половины: виды заявки + дословные слова ноты, без дублей.

    Вид, у которого есть СЛОВА, представлен своими словами и ярлыком не дублируется — иначе
    «поменял масло» дало бы две позиции об одной работе. Порядок: сперва виды заявки (порядок
    `declared` — им заявка себя и назвала), затем слова в порядке, в каком их сказал механик.
    Дубли слов снимаются по КОНТЕНТНОМУ ключу: «замена передней шины» и «передняя резина» —
    одна работа, названная дважды, а не две."""
    worded, seen_key, tail = set(), set(), []
    for w in (works or []):
        s = str(w or "").strip()
        if not s:
            continue
        k = _call(key_of, s, default=s.lower())
        if k in seen_key:
            continue
        seen_key.add(k)
        kind = _call(kind_of, s, default="other") or "other"
        worded.add(kind)
        tail.append(position(kind, s))
    head, seen_kind = [], set()
    for k in (kinds or []):
        k = str(k or "").strip()
        if not k or k in worded or k in seen_kind:
            continue
        seen_kind.add(k)
        head.append(position(k, ""))
    return head + tail


def verdict(pos, *, col_kinds=(), registers=None, history=None, odo=None,
            kind_of=None, key_of=None):
    """Исход одной позиции: (состояние, почему, чем доказано, каким текстом мира).

    `registers` — {вид: последний км} из строки парка; None = строка НЕ прочитана.
    `history`   — [{work, km}] из «событий» байка;    None = история НЕ прочитана.
    `odo`       — пробег заявки: без него привязать запись не к чему."""
    kind = str((pos or {}).get("kind") or "")
    word = str((pos or {}).get("word") or "")
    km = _num(odo)
    if kind in tuple(col_kinds or ()):
        # КОЛОНОЧНЫЙ ВИД: его адрес — клетка Лист1, и только она свидетельствует о записи.
        if registers is None:
            return UNKNOWN, "строка парка не прочитана — регистр не спросить", "", ""
        if km is None:
            return UNKNOWN, "у заявки нет пробега — сверять регистр не с чем", "", ""
        cell = _num((registers or {}).get(kind))
        if cell is None:
            return PENDING, "регистр числа не назвал — записанной работа не доказана", "", ""
        if cell == km:
            return WRITTEN, "регистр стоит на пробеге заявки", BY_REGISTER, str(cell)
        return PENDING, f"регистр на {cell}, а заявка о {km}", "", ""
    # СОБЫТИЙНЫЙ ВИД: его адрес — история байка.
    if history is None:
        return UNKNOWN, "история байка не прочитана — сверять не с чем", "", ""
    if km is None:
        return UNKNOWN, "у заявки нет пробега — строку истории не привязать", "", ""
    rows = [r for r in history if _num((r or {}).get("km")) == km]
    if not rows:
        return PENDING, "на этом пробеге история о работах молчит", "", ""
    if not word:
        # Слов у позиции нет (вид пришёл из перечня заявки) — судим ВИДОМ живого классификатора.
        for r in rows:
            if _call(kind_of, r.get("work"), default="") == kind:
                return WRITTEN, "история несёт работу этого вида на том же пробеге", \
                       BY_HISTORY_KIND, str(r.get("work"))
        return PENDING, "работ этого вида на этом пробеге в истории нет", "", ""
    mine = _call(key_of, word, default=word.lower())
    for r in rows:
        if _call(key_of, r.get("work"), default="\x00") == mine:
            return WRITTEN, "контентный ключ совпал с записанной работой", BY_HISTORY, str(r.get("work"))
    if "/" not in mine:
        # СТУПЕНЬ 2 — и только в эту сторону: общее покрывается конкретным, конкретное общим — нет.
        for r in rows:
            rk = _call(key_of, r.get("work"), default="\x00")
            if "/" in rk and rk.split("/", 1)[0] == mine:
                return WRITTEN, "обобщённая форма покрыта уточнённой записью того же стема", \
                       BY_HISTORY_WIDE, str(r.get("work"))
    return PENDING, "той же работы на этом пробеге в истории нет", "", ""


def pending(kinds, works, *, kind_of, key_of, col_kinds=(), registers=None, history=None, odo=None):
    """ОДИН список для обеих половин + перечень снятого с ожидания.

    `show` — что показываем (PENDING и UNKNOWN: незнание оставляет работу на виду);
    `gone` — что мир доказал записанным (у каждой позиции названо, ЧЕМ и КАКОЙ строкой)."""
    show, gone = [], []
    for p in merge(kinds, works, kind_of, key_of):
        st, why, proof, said = verdict(p, col_kinds=col_kinds, registers=registers,
                                       history=history, odo=odo, kind_of=kind_of, key_of=key_of)
        rec = dict(p)
        rec.update({"state": st, "why": why, "proof": proof, "said": said})
        (gone if st == WRITTEN else show).append(rec)
    return {"show": show, "gone": gone}


def words_gone(res):
    """Дословные слова снятых позиций — их и вычёркивает нота заявки (у ярлыков слов нет)."""
    return [r["word"] for r in (res or {}).get("gone", []) if r.get("word")]


def line(res):
    """Строка журнала: сколько показано, сколько снято и чем именно."""
    show = (res or {}).get("show", [])
    gone = (res or {}).get("gone", [])
    what = "; ".join(f"{r.get('word') or r.get('kind')} ← {r.get('proof')}"
                     f"{(' «' + r['said'] + '»') if r.get('said') else ''}" for r in gone)
    unk = sum(1 for r in show if r.get("state") == UNKNOWN)
    return (f"карточка «в работе»: показано {len(show)} (из них неизвестно {unk}), "
            f"снято записанных {len(gone)}" + (f" — {what}" if what else ""))
