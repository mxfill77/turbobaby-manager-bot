"""РАЗДЕЛЕНИЕ КАНАЛОВ, часть 2: отчёт задачи в 328 = итог + ссылка, тело — в артефакт.

ЗАЧЕМ (замер 05.08.2026 по снимку очереди, 298 терминальных задач за 28.07–05.08):
средняя длина `result` 2096 символов, медиана 2050, потолок 4500 — и **72 % отчётов длиннее
600 символов**. Каждый такой отчёт девбот вываливал в тему 328 целиком (при 3500 симв. — ещё и
двумя сообщениями), поэтому последовательность задач нельзя было увидеть одним взглядом: между
двумя номерами лежало по экрану текста. Правило то же, что у журнала: длинное тело уходит в
артефакт, в чат едет номер задачи, одна строка сути и ссылка.

ЧТО ЗДЕСЬ. Чистая функция «тело → что показать в чате». Импорт РОВНО один (`re`) — ни файлов, ни
сети, ни Telegram: решение о форме карточки обязано быть проверяемым юнитом на дословных телах
боевых отчётов, а руки (запись артефакта, кнопка, отправка) живут в devbot.

ПОРОГ ДВУСТОРОННИЙ И ЭТО ГЛАВНОЕ СВОЙСТВО: тело ≤ CHAT_BODY_MAX проходит БАЙТ-В-БАЙТ прежним
путём (`digest()` возвращает None) — короткий отчёт ничего не теряет и никуда не переезжает.
Режется только то, что мерилось как простыня.

СУТЬ БЕРЁТСЯ ПОЗИЦИЕЙ, А НЕ УГАДЫВАНИЕМ СМЫСЛА (тот же приём, что у позиции заявления 05.08):
преамбула демона требует от исполнителя «первая строка — сводка результата, уйдёт в тему 328»,
значит первая содержательная строка И ЕСТЬ итог по построению. Мы не пересказываем отчёт своими
словами и не выбираем «самое важное» — берём строку, которую исполнитель сам назначил сводкой.
Рядом с ней сохраняются РОВНО две вещи, и обе — не пересказ, а факт о самом отчёте:
  · строка `FACT:` — живое доказательство эффекта (класс R11–R15). Без неё карточка «done»
    неотличима от заявления о done; ради одной строки владельцу не должно требоваться нажатие.
  · строка `✂️` — исполнитель сам упёрся в потолок result. Едет ДОСЛОВНО, вместе с числами
    (полная длина, сколько срезано): молча спрятать её в артефакт значит выдать обрубок за полный
    отчёт, а пересказать своими словами — потерять числа, ради которых пометка и заводилась.
"""
import re

CHAT_BODY_MAX = 600      # тело длиннее — в чат едет итог + ссылка (порог владельца, 05.08.2026)
GIST_MAX = 400           # столько же, сколько преамбула демона отводит первой строке отчёта
FACT_MAX = 240
TRUNC_MAX = 400          # пометка обрезки едет ДОСЛОВНО: числа в ней и есть её смысл
TRUNC_MARK = "✂️"

# Строка-декорация (рамка/разделитель) сутью не является: у отчётов встречаются «────», «===».
_DECOR_RE = re.compile(r"^[\s\-=_~·•*#>+|─━—]+$")
# FACT в ЗАЯВЛЯЮЩЕЙ позиции — начало строки, перед ним допустима лишь разметка списка/выделения
# (зеркало _NA_DECOR из позиции заявления: слово посреди прозы фактом задачи не объявляет).
_FACT_RE = re.compile(r"^[\s\-*•>#]{0,6}(?:\*\*|__|`)?FACT\s*:", re.IGNORECASE)


def _clean(line, cap):
    """Строка карточки: без хвостовых пробелов, без разрыва на середине (обрезка помечается)."""
    s = str(line or "").strip()
    if len(s) > cap:
        s = s[:cap].rstrip() + "…"
    return s


def gist_line(body):
    """Первая СОДЕРЖАТЕЛЬНАЯ строка тела = сводка, назначенная самим исполнителем. Пусто → ''."""
    for line in str(body or "").splitlines():
        if line.strip() and not _DECOR_RE.match(line):
            return _clean(line, GIST_MAX)
    return ""


def fact_line(body):
    """Строка `FACT:` (живое доказательство эффекта) или '' — ищется в заявляющей позиции."""
    for line in str(body or "").splitlines():
        if _FACT_RE.match(line):
            return _clean(line, FACT_MAX)
    return ""


def trunc_line(body):
    """Пометка обрезки (`✂️ РЕЗУЛЬТАТ ОБРЕЗАН…`) ДОСЛОВНО или ''.

    Своими словами её пересказывать нельзя: смысл пометки — ЧИСЛА (полная длина исходного отчёта,
    сколько срезано, чей потолок). Синтетическая замена вида «отчёт был обрезан» вернула бы ровно
    тот дефект, который пометка и закрывает: карточка говорит «обрезан», а насколько — неизвестно."""
    for line in str(body or "").splitlines():
        if line.lstrip().startswith(TRUNC_MARK):
            return _clean(line, TRUNC_MAX)
    return ""


def digest(body, limit=CHAT_BODY_MAX):
    """Тело отчёта → текст для карточки 328, либо None = «показывать как раньше, целиком».

    None возвращается ровно тогда, когда тело помещается в порог: путь короткого отчёта не
    меняется ни на символ. Иначе — итог (+ FACT, + пометка обрезки), тело остаётся в артефакте
    и в очереди, откуда его достаёт кнопка «📄 отчёт»."""
    text = str(body or "")
    if len(text) <= max(0, int(limit)):
        return None
    out = []
    gist = gist_line(text)
    if gist:
        out.append(gist)
    fact = fact_line(text)
    if fact and fact != gist:
        out.append(fact)
    cut = trunc_line(text)
    if cut:
        out.append(cut)
    if not out:                       # тело из одних разделителей — не выдаём пустоту за итог
        out.append("(итог не назван первой строкой — весь текст в артефакте)")
    return "\n".join(out)


def artifact_text(qid, status, task_text, body):
    """Полное тело отчёта для файла-артефакта. Ничего не теряет: ТЗ + отчёт дословно."""
    head = f"# Задача {qid} — {status}\n\n## ТЗ\n\n{str(task_text or '').strip()}\n\n## Отчёт\n\n"
    return head + str(body or "")
