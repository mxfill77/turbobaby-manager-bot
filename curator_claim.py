"""ПОЗИЦИЯ ЗАЯВКИ: имя операции под отрицанием или в описании вариантов выбора просьбой не
является — чистая функция «текст пункта + вхождения операций → что заявлено, а что лишь названо».

ЗАЧЕМ (класс карточек 349, 357, 358; 06.08.2026). Пункт куратора цели 344 говорил ДОСЛОВНО:
«…нужно твоё «да» на отложенный рестарт демона `systemd-run --on-active=10s systemctl restart
orchestrator-daemon` (правило самомодификации, splinter не трогаем)…» — развод пункта на операции
вытащил имя splinter из фразы «splinter НЕ трогаем» и выписал владельцу отдельную карточку 349 на
перезапуск splinter. Владелец её отклонил. Через десять часов то же повторилось на цели 355, где
оба имени стояли в ОПИСАНИИ ВАРИАНТОВ выбора («Дальше нужен твой выбор: какой вариант … — любой
автоматический рестарт splinter/orchestrator-daemon на живых процессах это красное и без твоего
«да» не заводится; вариант «read-only детектор дрейфа без рестарта» тоже требует твоего решения») —
карточки 357 и 358, обе отклонены. Из четырёх карточек, которые развод выписал за всё время своей
жизни, три были фантомами.

КЛАСС ТОТ ЖЕ, что закрыт для литерала в теле скрипта (40c8425), для имени секрета в аргументе
(05c110b) и правилом исполняющей позиции (5ca761d): решение принималось по СОВПАДЕНИЮ СЛОВА, а не
по позиции, в которой слово стоит. Здесь он жил в разводе пункта на операции.

ЧТО РЕШАЕТ МОДУЛЬ. Для КАЖДОГО вхождения имени — стоит ли оно в позиции заявки. По умолчанию
СТОИТ: правило умеет только ДЕМОТИРОВАТЬ, и лишь по явному признаку в своей клаузе (отрицание
действия, слово запрета) либо в своём предложении (описание вариантов выбора). Семья операции
демотируется, только если НИ ОДНО её вхождение не осталось заявкой — иначе «рестарт splinter (в
задаче он был запрещён)» терял бы настоящую просьбу из-за придаточного рядом.

ПОЧЕМУ ЭТО БЕЗОПАСНО В ОБЕ СТОРОНЫ — и это главное свойство, а не обещание. Модуль умеет снять
РАЗВОД, но не умеет снять КАРТОЧКУ: любая демотировка означает «пункт едет владельцу ЦЕЛИКОМ одной
карточкой», ровно тем видом, каким он ездил до 05.08. Поэтому ошибка модуля стоит гранулярности и
видимой пометки в карточке, но НЕ может съесть «да»: ни одна операция не теряет возможности быть
одобренной, потому что весь пункт остаётся под одной кнопкой. Обратная ошибка (не заметили
отрицания) возвращает ровно сегодняшнее поведение — фантомную карточку, не хуже.

ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Тип пункта («разрешение» против «принял к сведению») по-прежнему НЕ
угадывается — модуль отвечает на фактический вопрос «названо ли имя в позиции просьбы», а не на
вопрос о намерении. Списка «правильных» просьб (белого списка оборотов) тоже нет: он молча съедал
бы честные пункты, написанные иначе, а направление ошибки здесь обязано быть противоположным.

ЧИСТОТА. Импорт ровно один (`re`): ни файлов, ни сети, ни моста, ни очереди — модуль ничего не
может сделать с миром, он только читает текст. Стережёт это не докстринг, а инвариант
`CURATOR_CLAIM_PURE` в `invariants_check.py` (ast, в гейте).
"""
import re

_F = re.IGNORECASE | re.UNICODE

# --- Клауза -----------------------------------------------------------------------------------
# Единица, в которой ищется отрицание. Скобка ОТКРЫВАЕТ свою клаузу и закрывает внешнюю: живой
# случай 344 — «(правило самомодификации, splinter не трогаем)» — целиком парентеза, и её
# содержимое не должно смешиваться с просьбой, стоящей ПЕРЕД скобкой. Запятая делит наравне с
# точкой с запятой: без этого «splinter не перезапущен, рестарт запрещало само ТЗ» (карточка 196 —
# настоящая просьба) попало бы под слово запрета из соседнего оборота.
_CLAUSE_CUT = set(";:,.!?\n\r—–")
_PAREN_OPEN = set("([{")
_PAREN_CLOSE = set(")]}")

# --- Отрицание ДЕЙСТВИЯ -----------------------------------------------------------------------
# «не»/«ни» + слово. Форма слова решает, отрицается ДЕЙСТВИЕ или констатируется СОСТОЯНИЕ:
#   «splinter не ТРОГАЕМ»     — личная форма, отказ от действия      → не заявка (цель 344);
#   «… «да» не ЗАВОДИТСЯ»     — личная форма, запрет                 → не заявка (цель 355);
#   «splinter не ПЕРЕЗАПУЩЕН» — краткое причастие, состояние прода   → ЗАЯВКА (карточка 196,
#     именно этим состоянием пункт и обосновывает просьбу — демотировать его нельзя).
# Краткое причастие бьёт личную форму: сомнение решается в сторону «это заявка».
_RE_NOT = re.compile(r"\b(?:не|ни)\s+([а-яё]{3,})\b", _F)
# «нут»/«ыт» стоят рядом с личным «-ут» намеренно: «не ТРОНУТ» — причастие (состояние), а
# «не берУТ» — личная форма. Причастие проверяется ПЕРВЫМ и побеждает, поэтому столкновение
# окончаний решается в сторону «это заявка» — туда же, куда все прочие сомнения модуля.
_PART_END = ("ен", "ена", "ено", "ены", "ён", "ёна", "ёно", "ёны",
             "ан", "ана", "ано", "аны", "ыт", "ыта", "ыто", "ыты",
             "нут", "нута", "нуто", "нуты")
_ACT_END = ("ем", "ешь", "ете", "ёте", "ём", "ют", "ут", "им", "ите", "ят", "ат",
            "ится", "ятся", "ается", "аются", "уется", "уются", "аем", "аю", "ает", "ают",
            "ать", "ять", "ить", "еть", "уть", "ться", "ай", "яй")
# Слово запрета — тот же смысл, названный прямо. Ищется в КЛАУЗЕ имени (см. `_CLAUSE_CUT`):
# в живом корпусе «прямо запретило» стоит в СОСЕДНЕМ обороте настоящих просьб (94, 114, 272, 382),
# и клауза — единственное, что отделяет запрет НА ИМЯ от запрета, которым просьба обоснована.
_RE_FORBID = re.compile(r"\bнельзя\b|запрещ\w*|запрет\w*|\bвне\s+области\b", _F)

# --- Описание вариантов выбора ----------------------------------------------------------------
# Предложение (а не клауза): выбор описывается ЦЕЛЫМ предложением, и в живом случае 355 слова
# «выбор»/«вариант» стоят в соседних клаузах того же предложения, а не рядом с именами.
_RE_CHOICE = re.compile(r"\bвариант\w*|\bвыбор\w*|\bвыбрать\b|\bвыбира\w*|"
                        r"\bчто из перечисленного\b", _F)
_RE_SENT_CUT = re.compile(r"[.!?]+[\s»)]+(?=[А-ЯЁA-Z«(])|\n+")

WHY_NEGATION = "под отрицанием"
WHY_CHOICE = "в описании вариантов выбора"


def _spans(text, cuts, parens=True):
    """Границы кусков текста: режем по `cuts`, скобка открывает свой кусок и закрывает внешний."""
    out, start = [], 0
    for i, ch in enumerate(text):
        if parens and (ch in _PAREN_OPEN or ch in _PAREN_CLOSE):
            out.append((start, i))
            start = i + 1
        elif ch in cuts:
            out.append((start, i))
            start = i + 1
    out.append((start, len(text)))
    return [(a, b) for a, b in out if b > a]


def _sent_spans(text):
    """Предложения: точка режет только перед заглавной буквой — иначе «29.07 09:32:15» и
    «v1.0.0» рвали бы предложение на куски и прятали слова выбора от имени."""
    out, start = [], 0
    for m in _RE_SENT_CUT.finditer(text):
        out.append((start, m.start()))
        start = m.end()
    out.append((start, len(text)))
    return [(a, b) for a, b in out if b > a]


def _pick(spans, pos):
    """Кусок, внутри которого стоит позиция. Позиция может попасть НА разделитель — так бывает у
    `.env`, где литерал начинается с точки (живой пункт 263): тогда берём кусок, начинающийся
    сразу за ним, иначе имя осталось бы вне всякой клаузы и правило молча онемело бы на нём."""
    for probe in (pos, pos + 1):
        for a, b in spans:
            if a <= probe < b:
                return a, b
    return None


def _negated(chunk):
    """В куске отрицается ДЕЙСТВИЕ (а не констатируется состояние) либо назван запрет."""
    if _RE_FORBID.search(chunk):
        return True
    for m in _RE_NOT.finditer(chunk):
        w = m.group(1).lower()
        if w.endswith(_PART_END):          # краткое причастие — состояние, не отказ
            continue
        if w.endswith(_ACT_END):
            return True
    return False


def why_not_claim(text, pos):
    """Вхождение имени в позиции `pos` заявкой НЕ является → причина; является → None."""
    t = str(text or "")
    if not (0 <= pos < len(t)):
        return None
    cl = _pick(_spans(t, _CLAUSE_CUT), pos)
    if cl and _negated(t[cl[0]:cl[1]]):
        return WHY_NEGATION
    sn = _pick(_sent_spans(t), pos)
    if sn and _RE_CHOICE.search(t[sn[0]:sn[1]]):
        return WHY_CHOICE
    return None


def filter_claims(text, occurrences):
    """Вхождения операций → (заявленные вхождения, демотированные семьи).

    Семья демотируется, только если НИ ОДНО её вхождение не осталось заявкой. Демотированная
    семья возвращается как {"key","label","literal","why"} — вызывающий код обязан НАЗВАТЬ её
    владельцу в карточке: молча из пункта не исчезает ничего.
    """
    occs = list(occurrences or [])
    t = str(text or "")
    verdicts = []
    for o in occs:
        try:
            why = why_not_claim(t, int(o.get("pos", -1)))
        except (TypeError, ValueError):
            why = None                      # позиции нет → сомнение в сторону заявки
        verdicts.append(why)
    claimed = set(o["key"] for o, why in zip(occs, verdicts) if why is None)
    kept = [o for o, why in zip(occs, verdicts) if why is None]
    demoted, seen = [], set()
    for o, why in zip(occs, verdicts):
        if why is None or o["key"] in claimed or o["key"] in seen:
            continue
        seen.add(o["key"])
        demoted.append({"key": o["key"], "label": o.get("label"),
                        "literal": o.get("literal"), "why": why})
    return kept, demoted
