BUDGET_ENV = "INFO_CARD_BUDGET_SEC"
BUDGET_DEFAULT = 60.0     # см. вывод величины в шапке: честный максимум 37.9 с, пустой промежуток 37.9…122.5
LEG_MIN = 1.0             # короче этого плечо не начинаем: 0.2 с не хватит и на рукопожатие — только сожжёт остаток

# Источники карточки: ключ действия моста → (тайский ярлык, русский ярлык). Ярлык говорит, ЧТО
# именно пропало из карточки, а не как называется действие: механик читает карточку, не код.
SOURCES = {
    "fleet": ("ข้อมูลรถจากตารางหลัก (สถานะ, เช่า, วันเซอร์วิส)",
              "строка байка в Лист1 (статус, аренда, отметки ТО)"),
    "service_list": ("ไมล์ปัจจุบัน", "текущий пробег (свой одометр)"),
    "read_events": ("ประวัติงานตามไมล์", "история работ на пробеге"),
    "service_pending_get": ("งานที่กำลังทำอยู่", "заявка в работе"),
    "service_pending_list": ("ประวัติเซอร์วิสล่าสุด", "последний закрытый сервис"),
    "read_doc": ("ระยะเซอร์วิสตามคู่มือ", "книга интервалов ТО"),
}

# Порядок вывода — как в самой карточке (сверху вниз), чтобы список не выглядел случайным.
SOURCE_ORDER = ("fleet", "service_list", "read_events", "service_pending_get",
                "service_pending_list", "read_doc")


def parse_budget(raw, default=BUDGET_DEFAULT):
    """Значение ручки → бюджет карточки в секундах.

    Пусто/не задано → `default` (боевое поведение). Ноль или отрицательное → 0.0, то есть ветка
    ВЫКЛЮЧЕНА (задокументированный откат). Мусор («abc») → `default`, а не ноль: опечатка в .env
    не должна МОЛЧА снимать предохранитель — направление сомнения здесь в сторону дедлайна."""
    if raw is None:
        return float(default)
    text = str(raw).strip().replace(",", ".")
    if text == "":
        return float(default)
    try:
        value = float(text)
    except (TypeError, ValueError):
        return float(default)
    if value <= 0:
        return 0.0
    return value


def deadline_at(now, budget):
    """Момент (в той же шкале, что `now`), к которому сборка обязана закончиться.
    Бюджет 0/отрицательный/не число → None = дедлайна нет вовсе."""
    try:
        budget = float(budget)
        now = float(now)
    except (TypeError, ValueError):
        return None
    if budget <= 0:
        return None
    return now + budget


def remaining(deadline, now):
    """Остаток бюджета в секундах. None — дедлайн НЕ ОТКРЫТ.

    None, а не 0.0, намеренно: «бюджета нет» (ветка выключена, работаем как раньше) и «бюджет
    кончился» (пора останавливаться) — противоположные решения, и различать их обязан тип."""
    if deadline is None:
        return None
    try:
        return float(deadline) - float(now)
    except (TypeError, ValueError):
        return None


def expired(deadline, now):
    """Бюджет исчерпан? Дедлайн не открыт → False (прежнее поведение)."""
    left = remaining(deadline, now)
    if left is None:
        return False
    return left <= 0


def leg_timeout(deadline, now, base, leg_min=LEG_MIN):
    """Сколько секунд дать ОДНОМУ HTTP-плечу: не больше прежнего `base` и не больше остатка.

    Иначе плечо, начатое за 2 с до дедлайна, честно провисит все 60 и перекроет общий потолок в
    30 раз — то есть потолок был бы на бумаге. Ниже `leg_min` не опускаемся: плечо, которому дали
    0.05 с, гарантированно не долетит, а остаток сожжёт."""
    left = remaining(deadline, now)
    try:
        base = float(base)
    except (TypeError, ValueError):
        return float(leg_min)
    if left is None:
        return base
    if left < leg_min:
        return float(leg_min)
    return min(base, left)


def may_start_leg(deadline, now, leg_min=LEG_MIN):
    """Начинать ли ещё одно плечо. Дедлайн не открыт → да (прежнее поведение)."""
    left = remaining(deadline, now)
    if left is None:
        return True
    return left >= leg_min


def may_wait(deadline, now, pause, leg_min=LEG_MIN):
    """Хватит ли остатка на паузу backoff И на плечо после неё.

    Ждать, чтобы потом упереться в исчерпанный бюджет, — чистая потеря времени человека: именно
    так лестница и сжигала 405.5 с из 578.2 в замере."""
    left = remaining(deadline, now)
    if left is None:
        return True
    try:
        pause = float(pause)
    except (TypeError, ValueError):
        pause = 0.0
    return left >= pause + leg_min


def source_label(key, th=False):
    """Человеческий ярлык источника. Незнакомый ключ называем ИМ САМИМ, а не «прочее»: новый
    источник карточки должен быть виден в списке потерь с первого же дня, а не растворяться."""
    pair = SOURCES.get(key)
    if pair is None:
        return str(key)
    return pair[0] if th else pair[1]


def missing_block(missing, th=False, budget=None, spent=None, deadline_hit=False):
    """Блок «НЕ ПРОЧИТАНО» для карточки — список строк (без хвостового перевода строки).

    `missing` — ключи источников, которые НЕ ОТВЕТИЛИ (порядок карточки восстанавливаем сами).
    Пусто → пустой список: у полной карточки блока нет вовсе, её вид не меняется ни на символ.

    Последняя строка — главное, ради чего блок существует: сказать, что пустое место в карточке
    это «не смог прочитать», а НЕ «нет данных». Без неё механик прочтёт пропуск как «всё в
    порядке» — та же ложь, только молчаливая."""
    keys = [k for k in SOURCE_ORDER if k in set(missing or ())]
    keys += [k for k in (missing or ()) if k not in SOURCE_ORDER and k not in keys]
    if not keys:
        return []
    if th:
        out = ["⚠️ <b>ข้อมูลไม่ครบ — อ่านบางส่วนไม่ได้</b>"]
        if deadline_hit:
            out.append(f"⏱ หมดเวลา {_num(budget)} วิ (ใช้ไป {_num(spent)} วิ) — สะพานข้อมูลตอบไม่ทัน")
        out += [f"• {source_label(k, True)}" for k in keys]
        out.append("↻ ไม่ใช่ว่า «ไม่มี» แต่ «อ่านไม่ได้» — กดปุ่มใหม่อีกครั้ง")
        return out
    out = ["⚠️ <b>ДАННЫЕ НЕПОЛНЫЕ — часть источников не прочитана</b>"]
    if deadline_hit:
        out.append(f"⏱ бюджет {_num(budget)} с исчерпан (ушло {_num(spent)} с) — мост не успел ответить")
    out += [f"• {source_label(k, False)}" for k in keys]
    out.append("↻ это НЕ «нет данных», это «не смог прочитать» — нажми кнопку ещё раз")
    return out


def _num(value):
    """Число для человека: 60 вместо 60.0, 12.4 вместо 12.400000000000002. Не число → «?»."""
    try:
        value = float(value)
    except (TypeError, ValueError):
        return "?"
    if abs(value - round(value)) < 0.05:
        return str(int(round(value)))
    return f"{value:.1f}"
