"""ОТМЕНА ПОСЛЕДНЕЙ ЗАПИСИ ОБСЛУЖИВАНИЯ — чистая функция «расписка моста → назван ли объект и
можно ли ещё отменять» (14.08.2026).

КЛАСС. Записать факт ТО система умеет, СКАЗАТЬ «эта запись неверна» человек не мог ничем: отмены
не было ни одной командой, ни одной кнопкой. `edit_event` задеплоен и лежит в `bridge_client`
(1218) — вызовов ноль; `splinter._rollback_km_events` (2337) чинит СТРОКИ СОБЫТИЙ по одометру, а
не регистр Лист1, и на путь фазы 2 не выходит вовсе.

ЖИВОЙ СЛУЧАЙ (splinter.log, тема 83, XADV 750 GREY 2478):
    15.07 11:17:51  → ТО фаза2 запись по «да» @turbophuket1: written=['oil'] failed=[] odo=24997
    15.07 11:20:39  → мозг: «Не верно, моторное масло на 24500»          (через 2 м 48 с)
    15.07 11:21:29  → ТО фаза2 запись по «да» @turbophuket1: written=['oil'] failed=[] odo=24997
Человек сказал ДОСЛОВНО, что последняя запись неверна, — и система ответила ВТОРОЙ записью того
же неверного числа. Правильное 24500 в кол.I так и не легло.

ЧТО СИСТЕМА ЗНАЕТ О ТОЛЬКО ЧТО СДЕЛАННОЙ ЗАПИСИ — ВСЁ, И ВЫБРАСЫВАЕТ. Расписка успешной записи
(`bridge_prod/ReadFleet.js`, `setFleetOil_` 377-378 и `setFleetService_` 461-463) несёт
`number`, `bike_name`, `row`, `old_oil`/`old_km`, `new_oil`/`new_km`, `full_address`,
`verified`. В живом журнале это видно дословно:
    'ok': True, 'number': '4957', 'bike_name': 'NMAX 155CC GREEN-B PHUKET 4957', 'row': 16,
    'old_oil': 30800, 'new_oil': 37000, 'full_address': '… | Лист1 | I16'
А читается из неё РОВНО ОДИН флаг — `splinter.py:6372` `if r.get("ok") or …`. Байк, регистр,
строка, прежнее и новое число доезжают до кода и умирают в нём. Поэтому механизм не платит НИ
ОДНОГО лишнего обращения к мосту: журнал отмены заполняется из той же расписки.

ПРЕЖНЕЕ ЗНАЧЕНИЕ, РАВНОЕ НУЛЮ, ОБЪЕКТОМ НЕ ЯВЛЯЕТСЯ. Мост складывает в `old_*` ТРИ разных мира
(`ReadFleet.js` 285-286 и 432-433): пустую клетку, нечисловую («35200 Km, 05.07.2026») и
настоящий ноль. Это тот же «нуль по неразбору», ради которого написан `fleet_cell`, — и вернуть
клетку «на ноль» значит выдать незнание за число. Такая позиция в карточку НЕ идёт, а если
названных позиций не осталось ни одной — карточки не выписывается ВОВСЕ и кнопки не показывается.
ЖИВАЯ ПЕРЕПИСЬ ПАРКА 14.08 (read-only `fleet(cells=1)`, 38 строк): клеток ТО 152, назвали бы
прежнее значение 97, не назвали бы 55 (пусто 47, не число 6, настоящий ноль 2).

ЗАМКИ, И КАЖДЫЙ НА ФАКТЕ, А НЕ НА ВЕЖЛИВОСТИ:
    ПОСЛЕДНЯЯ  токен нажатой кнопки обязан совпасть с токеном последнего акта темы; после новой
               записи прежняя кнопка отвечает «это не последняя», а не молчит;
    СВОЯ       журнал ключуется темой акта, и токен рождается вместе с квитанцией В НЕЙ ЖЕ —
               кнопки чужой темы у нажавшего нет физически;
    ОКНО       3 часа (`TTL_DEFAULT`, то же окно, что у журнала км-строк
               `splinter._KM_EVENTS_TTL`; второго срока о том же смысле не заводим). Старше —
               отказ, и он ЧЕСТНЫЙ: запись мы ещё помним, но не ручаемся, что она всё ещё
               последняя, — Лист1 живой, там пишут руками, а наша память знает только НАШИ
               записи. Отказ НАЗЫВАЕТ объект, чтобы человек донёс его владельцу сам;
    ОДИН РАЗ   отмена отмены запрещена: отправленная просьба метится, повтор отвечает «уже
               отправил». Самой отмене отменяться нечем — она НИЧЕГО не пишет.

КРАСНАЯ ЗОНА НЕ ИСПОЛНЯЕТСЯ ЗДЕСЬ ВООБЩЕ. Отмена правит живую таблицу Лист1, а это «да»
владельца (доктрина: «да» решает там, где владелец добавляет знание, которого у машины нет).
Модуль только СОБИРАЕТ карточку с названным объектом — байк, регистр, строка, какое число
убираем и на что возвращаем — и называет, чем возврат вообще возможен:
    кол.I (масло)      — ветка исправления `setFleetOil_` (нужны названные причина и автор);
    кол.J/K/L (ТО)     — понижения мост НЕ УМЕЕТ вовсе (`setFleetService_` 446 → km_decreasing),
                         вернуть можно только рукой в клетке.
Возможность, которой нет, не изображается: карточка говорит это прямо.

ГРАНИЦА УСТРОЙСТВОМ: импортов РОВНО НОЛЬ. Ни сети, ни файлов, ни времени, ни отправки — «сейчас»,
порог и расписку приносят руки (`splinter._sp_write_done`, `splinter.handle_service_button`).
Будь у модуля отправка, рядом с решением завёлся бы второй путь наружу, и владелец мог бы
получить карточку о том, чего решение не решало. Проверяется разбором (ast) инвариантом
`UNDO_LAST_PURE`, а не докстрингом.

ОТКАТ: `SERVICE_UNDO=0` в .env + рестарт splinter → кнопки нет, журнал не ведётся, путь записи
байт-в-байт прежний. Тесты `tests/test_undo_last.py`.
"""

#: Ручка в .env. Пусто/мусор → включено; «0»/«off»/«no»/«false» → ветка мертва.
FLAG_ENV = "SERVICE_UNDO"

#: Окно памяти, сек. То же, что у журнала км-строк (`splinter._KM_EVENTS_TTL`): 3 часа.
TTL_DEFAULT = 3 * 3600

STATE_CARD = "card"       # объект назван, окно живо → карточка владельцу
STATE_STALE = "stale"     # старше окна: помним, но не ручаемся, что запись всё ещё последняя
STATE_NONE = "none"       # нечего отменять: не последняя / бот перезапускался
STATE_ASKED = "asked"     # просьба уже отправлена; отмены отмены не бывает
STATE_BLIND = "blind"     # запись есть, объект не назван — карточки не будет

#: Почему ноль в `old_*` не годится в объект. Формулировка одна на журнал и на ответ человеку.
ZERO_WHY = ("мост отдаёт прежнее значение нулём и в пустой клетке, и в нечисловой, и в настоящем "
            "нуле — возвращать не на что")

#: Чем возврат вообще возможен. Зеркало ЗАДЕПЛОЕННОГО `ReadFleet.js`, а не наших намерений.
LOWER_BY_KIND = {
    "oil": ("понижение кол.I мост умеет ТОЛЬКО веткой исправления записи масла — нужны "
            "названные причина и автор (fix_reason + fixed_by); без них он отвечает "
            "oil_decreasing и не пишет"),
}
LOWER_NONE = ("понижения этого регистра мост НЕ умеет вовсе — у планового ТО ветки исправления "
              "нет (setFleetService_ → km_decreasing); вернуть можно только рукой в клетке")


def enabled(raw):
    """Ветка жива? Пусто/мусор → да (ручка не должна включаться опечаткой в обратную сторону);
    явные «0/off/no/false» → нет."""
    if raw is None:
        return True
    s = str(raw).strip().lower()
    if not s:
        return True
    return s not in ("0", "off", "no", "false", "нет")


def _num(x):
    """Число или None. Логическое числом не считается: True — это `true`, а не километр."""
    if isinstance(x, bool) or x is None:
        return None
    try:
        return int(float(str(x).strip().replace(" ", "").replace(",", "")))
    except (TypeError, ValueError):
        return None


def _pick(answer, keys):
    for k in keys:
        if k in answer:
            v = _num(answer.get(k))
            if v is not None:
                return v
    return None


def position(kind, column, answer, want_km=None):
    """Расписка УСПЕШНОЙ записи → позиция отмены либо (None, почему объект не назван).

    `column` — буква колонки Лист1, её приносят руки (`fleet_cell.FIELD_COL`): выводить её
    здесь значило бы завести второй словарь о том же. `want_km` — число, которое мы просили
    записать; расписка о ДРУГОМ числе объектом нашей записи не является."""
    if not isinstance(answer, dict):
        return None, "расписки нет вовсе — мост ответил не словарём"
    if not answer.get("ok"):
        return None, "мост запись не подтвердил — прежнего значения он не называл"
    new = _pick(answer, ("new_oil", "new_km"))
    if new is None:
        return None, "мост не назвал записанное число"
    want = _num(want_km)
    if want is not None and want != new:
        return None, f"расписка о числе {new}, а писали {want} — это не наша запись"
    old = _pick(answer, ("old_oil", "old_km"))
    if old is None:
        return None, "мост не назвал прежнее значение"
    if old == 0:
        return None, ZERO_WHY
    if old == new:
        return None, "прежнее и новое число совпали — отменять нечего"
    return {"kind": str(kind), "column": str(column or ""), "row": _num(answer.get("row")),
            "old": old, "new": new,
            "address": str(answer.get("full_address") or ""),
            "bike_name": str(answer.get("bike_name") or ""),
            "number": str(answer.get("number") or "")}, ""


def act(tok, ts, chat, topic, bike, plate, by, odo, positions, blind=0):
    """Запись журнала — один акт подтверждения (кнопка «да» пишет несколько позиций разом)."""
    return {"tok": tok, "ts": ts, "chat": chat, "topic": topic, "bike": str(bike or ""),
            "plate": str(plate or ""), "by": str(by or ""), "odo": str(odo or ""),
            "pos": list(positions or []), "blind": int(blind or 0), "asked": False}


def verdict(entry, tok, last_tok, now, ttl=TTL_DEFAULT):
    """Факты → вердикт. Все замки здесь, ни одного в руках: разойтись им тогда негде."""
    out = {"state": STATE_NONE, "age": None, "ttl": ttl, "entry": entry}
    if not isinstance(entry, dict):
        out["entry"] = None
        return out
    if entry.get("tok") != tok or last_tok != tok:
        return out
    age = None
    try:
        age = float(now) - float(entry.get("ts") or 0)
    except (TypeError, ValueError):
        age = None
    out["age"] = age
    if age is None or (ttl and age > ttl):
        out["state"] = STATE_STALE
        return out
    if entry.get("asked"):
        out["state"] = STATE_ASKED
        return out
    if not entry.get("pos"):
        out["state"] = STATE_BLIND
        return out
    out["state"] = STATE_CARD
    return out


def _age_ru(sec):
    if sec is None:
        return "неизвестно сколько"
    m = int(sec // 60)
    return f"{m // 60} ч {m % 60} мин" if m >= 60 else f"{m} мин"


def _age_th(sec):
    if sec is None:
        return "ไม่ทราบ"
    m = int(sec // 60)
    return f"{m // 60} ชม. {m % 60} นาที" if m >= 60 else f"{m} นาที"


def _short(entry):
    """Объект одной строкой по-русски: байк · кол.X · было → станет."""
    pos = (entry or {}).get("pos") or []
    if not pos:
        return (entry or {}).get("bike", "")
    parts = [f"кол.{p['column']} {p['new']} → {p['old']} км" for p in pos]
    return f"{entry.get('bike') or entry.get('plate') or '?'} · " + " · ".join(parts)


def _short_th(entry):
    """Тот же объект для ТАЙСКОЙ половины — БЕЗ кириллицы.

    Не украшение: аудитор ловит кириллицу в тайском блоке отдельным правилом
    (`splinter.log`: «АУДИТ Splinter [style_issue] кириллица в тайском блоке»), а механик
    читает именно эту половину. Имя байка латинское, поэтому едет как есть."""
    pos = (entry or {}).get("pos") or []
    if not pos:
        return (entry or {}).get("bike", "")
    parts = [f"คอลัมน์ {p['column']} {p['new']} → {p['old']} กม." for p in pos]
    return f"{entry.get('bike') or entry.get('plate') or '?'} · " + " · ".join(parts)


def how_back(kind):
    """Чем возврат ВООБЩЕ возможен для этого регистра. Возможность, которой нет, не изображаем."""
    return LOWER_BY_KIND.get(str(kind or ""), LOWER_NONE)


def card(v, asked_by="", labels=None):
    """Карточка владельцу: названный объект + чем возврат возможен. Пусто = карточки нет вовсе.

    `labels` — словарь `вид → (тайский ярлык, русский ярлык)` (`splinter._SP_KIND_LABEL`);
    имя работы либо названо, либо названо неопределённым — пустого тире тут не бывает."""
    if (v or {}).get("state") != STATE_CARD:
        return ""
    e = v["entry"]
    lines = ["🔴 ЖИВАЯ ТАБЛИЦА — просят отменить последнюю запись ТО",
             "",
             f"Байк: {e.get('bike') or '?'}" + (f" (номер {e['plate']})" if e.get("plate") else "")]
    for p in e["pos"]:
        name = ((labels or {}).get(p["kind"]) or (None, None))[1] or p["kind"]
        addr = f" · {p['address']}" if p["address"] else ""
        row = f", строка {p['row']}" if p["row"] else ""
        lines.append(f"Убрать: Лист1 кол.{p['column']}{row} — сейчас там {p['new']} км "
                     f"(работа: {name}){addr}")
        lines.append(f"Вернуть на: {p['old']} км")
        lines.append(f"Как вернуть: {how_back(p['kind'])}")
    if e.get("blind"):
        lines.append(f"⚠️ Ещё позиций в этой записи: {e['blind']} — прежнего значения по ним мост "
                     f"не назвал ({ZERO_WHY}), в карточку они НЕ вошли.")
    lines += ["",
              f"Записал: {e.get('by') or '?'} · одометр акта {e.get('odo') or '?'} км",
              f"Просит отменить: {asked_by or '?'} · тема {e.get('topic')}",
              f"Прошло с записи: {_age_ru(v.get('age'))}",
              "",
              "Я НЕ ПИСАЛ и не буду: отмена правит живую таблицу — это твоё «да». Проверь, что "
              "после записи клетку не меняли руками."]
    return "\n".join(lines)


def reply(v, labels=None):
    """Ответ человеку в теме — ОБЕ половины из ОДНОГО вердикта (урок `service_receipt`).

    Возвращает (тайская, русская). Порознь половины не выдаются намеренно."""
    st = (v or {}).get("state")
    e = (v or {}).get("entry") or {}
    obj, obj_th = _short(e), _short_th(e)
    ttl_h = int((v or {}).get("ttl", TTL_DEFAULT) // 3600) or 1
    if st == STATE_CARD:
        return (f"✅ ส่งให้เจ้าของแล้วครับ: ขอยกเลิกบันทึกล่าสุด — {obj_th} "
                f"ผมไม่แก้ตารางเองครับ รอเจ้าของ",
                f"✅ Отправил владельцу: просьба отменить последнюю запись — {obj}. "
                f"Живую таблицу сам не правлю — ждём его.")
    if st == STATE_STALE:
        return (f"⚠️ บันทึกนี้ทำไว้ {_age_th(v.get('age'))} แล้ว (เกิน {ttl_h} ชม.) — "
                f"ผมยกเลิกให้ไม่ได้ครับ บอกเจ้าของเองนะครับ: {obj_th}",
                f"⚠️ Эта запись сделана {_age_ru(v.get('age'))} назад (окно {ttl_h} ч) — сам "
                f"отменить не могу: за это время клетку могли поменять руками. Скажи владельцу: "
                f"{obj}")
    if st == STATE_ASKED:
        return ("ℹ️ ส่งให้เจ้าของไปแล้วครับ รอเจ้าของ — ยกเลิกซ้ำไม่ได้",
                "ℹ️ Уже отправил владельцу — ждём его. Отмену отмены я не делаю.")
    if st == STATE_BLIND:
        return ("⚠️ ยกเลิกไม่ได้: ไม่ทราบค่าก่อนหน้าในคอลัมน์ — ไม่รู้ว่าจะคืนเป็นเลขอะไร "
                "บอกเจ้าของเองครับ",
                "⚠️ Отменить не могу: прежнее значение регистра неизвестно — не на что "
                "возвращать. Скажи владельцу сам.")
    return ("⚠️ ยกเลิกไม่ได้: ไม่ใช่บันทึกล่าสุด (มีบันทึกใหม่กว่า หรือบอทรีสตาร์ท) — "
            "ยกเลิกได้เฉพาะบันทึกล่าสุดครับ",
            "⚠️ Отменить нечего: это не последняя запись (после неё была ещё одна либо бот "
            "перезапускался). Отменяю только последнюю.")


#: Подпись кнопки на квитанции: обе половины в одной подписи — как у прочих кнопок фазы 2.
BUTTON_LABEL = "↩️ บันทึกผิด / Запись неверна"


def say(v):
    """Одна строка в журнал — чем кончилась просьба об отмене."""
    st = (v or {}).get("state")
    e = (v or {}).get("entry") or {}
    if st == STATE_CARD:
        return f"карточка владельцу: {_short(e)} (прошло {_age_ru(v.get('age'))})"
    if st == STATE_STALE:
        return f"отказ: старше окна {int(v.get('ttl', TTL_DEFAULT) // 3600)} ч ({_age_ru(v.get('age'))}), объект {_short(e)}"
    if st == STATE_ASKED:
        return f"отказ: просьба уже отправлена, {_short(e)}"
    if st == STATE_BLIND:
        return "отказ: объект не назван — прежнего значения нет"
    return "отказ: не последняя запись (журнала по этому токену нет)"
