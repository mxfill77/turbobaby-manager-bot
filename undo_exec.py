def reply(v):
    """ОДИН вердикт → (тайская половина, русская половина). Врозь половины не выдаются.

    Тайская половина без кириллицы ни в одной ветке: её читает механик, а кириллицу в ней ловит
    аудитор отдельным правилом."""
    v = v or {}
    items = v.get("items") or []
    ru = [i["ru"] for i in items]
    th = [i["th"] for i in items]
    if v.get("cell") == CELL_LEFT:
        ru.insert(0, CELL_LEFT_RU)
        th.insert(0, CELL_LEFT_TH)
    return "\n".join(th), "\n".join(ru)


def say(v):
    """Одна строка в журнал — чем кончилось исполнение. Коды живут ЗДЕСЬ, а не у человека."""
    v = v or {}
    items = v.get("items") or []
