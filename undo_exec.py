def _fill(tpl, facts):
    """Подставить числа. Не названо — «?»: дырка в фактах не имеет права стать пустым местом."""
    try:
        return str(tpl).format(**{k: ("?" if v in (None, "") else v) for k, v in facts.items()})
    except (KeyError, IndexError, ValueError):
        return str(tpl)


def _cell_of(answer):
    """Что дверь сказала О КЛЕТКЕ. `compensated` есть → она её ТРОГАЛА; False → не вернула."""
    if not isinstance(answer, dict):
        return CELL_UNKNOWN
    if answer.get("ok") is True:
        return CELL_RESTORED
    if "compensated" in answer:
        return CELL_INTACT if answer.get("compensated") else CELL_LEFT
    code = str(answer.get("error") or "").strip()
    if not code or (code not in _SAY and not is_settled(code)) or code in DOOR_UNSETTLED:
        return CELL_UNKNOWN
    return CELL_INTACT


def one(what, answer):
    """ОДИН ответ двери → что об этом сказать. `what` — объект строкой (байк · кол. · было → станет).

    Ответа нет вовсе (дверь не позвали, запрос сорвался) → НЕИЗВЕСТНО, а не «не вернул»."""
    facts = {"what": what or "?"}
    if isinstance(answer, dict) and answer.get("ok") is True:
        return {"state": DONE, "cell": CELL_RESTORED, "what": what, "log": "ok",
                "ru": f"✅ Вернул: {what}", "th": f"✅ คืนค่าแล้ว: {what}"}
    code = str((answer or {}).get("error") or "").strip() if isinstance(answer, dict) else ""
    cell = _cell_of(answer)
    if code in _SAY:
        what_ru, do_ru, what_th, do_th = _SAY[code]
        state = UNKNOWN if code in DOOR_UNSETTLED else REFUSED
        ru = f"{_fill(what_ru, facts)}. Что делать: {_fill(do_ru, facts)}."
        th = f"{_fill(what_th, facts)} · {_fill(do_th, facts)}"
    else:
        # Кода у двери отмены нет — спрашиваем ПОЛ ОТВЕТА: общие коды дверей записи он уже знает,
        # а незнакомому всё равно даёт действие. Своего второго списка о том же не заводим.
        said = _floor_say(code, facts)
        state = UNKNOWN if (not code or not is_settled(code)) else REFUSED
        ru, th = said["ru"], said["th"]
    return {"state": state, "cell": cell, "what": what, "log": code or "(пусто)",
            "ru": f"⚠️ {what}: {ru}", "th": f"⚠️ {what}: {th}"}


def verdict(results, refusals=None):
    """Ответы двери по КАЖДОЙ позиции акта + позиции, звать по которым нечем → ОДИН вердикт.

    Кнопка «да» пишет несколько регистров разом, поэтому у акта бывает несколько позиций и у
    каждой СВОЙ ключ. Частичный исход — законный: одна позиция вернулась, другая нет, и оба факта
    обязаны доехать до человека. Общее слово за ответ говорит САМЫЙ ГРОМКИЙ исход (порядок силы
    «не знаю» > «отказ» > «вернул»), потому что именно он требует действия."""
    items = []
    for what, answer in (results or []):
        items.append(one(what, answer))
    for what, why in (refusals or []):
        # Звать дверь нечем — это ОТКАЗ ВЫНЕСЕННЫЙ (мы даже не спрашивали), и причина уже
        # сформулирована человеку в `undo_last`; второй раз её здесь не переписываем.
        items.append({"state": REFUSED, "cell": CELL_INTACT, "what": what, "log": "not_callable",
                      "ru": f"⚠️ {what}: {why}", "th": f"⚠️ {what}: {why}"})
    state = DONE if items else UNKNOWN
    cell = CELL_INTACT if items else CELL_UNKNOWN
    for it in items:
        if _FORCE[it["state"]] > _FORCE[state]:
            state = it["state"]
        if _CELL_FORCE[it["cell"]] > _CELL_FORCE[cell]:
            cell = it["cell"]
    if not items:
        # Позиций нет вовсе: сказать «вернул» не на чем, промолчать нельзя.
        items = [{"state": UNKNOWN, "cell": CELL_UNKNOWN, "what": "", "log": "no_positions",
                  "ru": "⚠️ Отменять оказалось нечего — объект не назван. Что делать: "
                        "посмотри строку байка ГЛАЗАМИ.",
                  "th": "⚠️ ไม่มีรายการให้ยกเลิกครับ · รบกวนเปิดดูแถวของรถนะครับ"}]
    return {"state": state, "cell": cell, "items": items,
            "done": [i for i in items if i["state"] == DONE],
            "bad": [i for i in items if i["state"] != DONE]}


