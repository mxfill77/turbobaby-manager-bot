def _fill(tpl, facts):
    """Подставить числа. Не названо — «?»: дырка в фактах не имеет права стать пустым местом."""
    class _Q(dict):
        def __missing__(self, key):
            return "?"
    try:
        return str(tpl).format_map(_Q(facts or {}))
    except (ValueError, IndexError, KeyError):
        return str(tpl)


def is_settled(code):
    """Мост вынес отказ САМ (исход определён)? Вокабуляр берётся у `write_fact`, не заводится свой."""
    return str(code or "") in SETTLED_ERRORS


def refusal(code, facts=None):
    """Код отказа + числа → что сказать человеку. Кода в тексте НЕТ ни в одной ветке.

    Возврат: `state` (NAMED/UNSETTLED/UNNAMED), `ru`/`th` — человеку, `log` — журналу.
    Пустой код тоже получает текст: «отказ без имени» — это тоже отказ, и молчать о нём нельзя."""
    c = str(code or "").strip()
    f = dict(facts or {})
    if c in _SAY:
        what_ru, do_ru, what_th, do_th = _SAY[c]
        state = NAMED
    elif c and not is_settled(c):
        what_ru, do_ru, what_th, do_th = _UNSETTLED_SAY
        state = UNSETTLED
    else:
        what_ru, do_ru, what_th, do_th = _UNNAMED_SAY
        state = UNNAMED
    return {
        "state": state,
        "log": c or "(пусто)",
        # Знак тревоги НЕ здесь: его ставят руки в своём шаблоне, иначе он задвоится.
        "ru": f"{_fill(what_ru, f)}. Что делать: {_fill(do_ru, f)}.",
        "th": f"{_fill(what_th, f)} · {_fill(do_th, f)}",
    }


