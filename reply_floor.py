"""ПОЛ ОТВЕТА: БОТ НЕ МОЛЧИТ И НЕ ОТКАЗЫВАЕТ ГЛУХО (23.08.2026, правила владельца 1 и 2).

ПРАВИЛО 1 — НИКОГДА НЕ МОЛЧАТЬ. На любое сообщение в теме байка бот отвечает хоть чем-то. Не
понял — говорит, что не понял, и ЧТО прислать. Не может — говорит, ЧЕГО именно не может.
Молчание запрещено как исход.

ПРАВИЛО 2 — ОТКАЗ ОБЯЗАН ГОВОРИТЬ, ЧТО ДЕЛАТЬ. Формулировки вида «мост не принял запись» и
внутренние коды человеку не показываются. Вместо них — что случилось, какие числа не сошлись,
какое действие исправит.

ЧТО БЫЛО ДО. Молчание было ИСХОДОМ ПО УМОЛЧАНИЮ: у `splinter._handle_servicing` нет ни ветки
«не понял», ни `else` в конце — сообщение, не подошедшее ни одной двери, просто дочитывалось до
конца функции; вдобавок `splinter.handle` ловит любое исключение в `except Exception:
log.exception(...)`, то есть упавший заход НЕ ОТЛИЧИМ для человека от проигнорированного. Отказы
же печатали код моста дословно: `f"не удалось записать ({err or 'ошибка'})"` — человеку уезжали
`verify_failed`, `receipt_unknown`, `oil_drop_needs_trusted`.

ГДЕ ПРОХОДИТ ГРАНИЦА МОЛЧАНИЯ. Есть молчание ЗАКОННОЕ — чужая тема, чужая группа, чужой контур,
служебное сообщение: там бот не собеседник и говорить ему не о чем. Эти ворота стоят ВЫШЕ
(`bot.is_ignored_thread`, `splinter.GROUPS`, фильтры роутера) и этим модулем не судятся вовсе:
решение сюда попадает уже ПОСЛЕ них. Судится ровно один вопрос — «нас позвали, мы отработали и
не сказали ни слова».

ТРИ ИСХОДА ОТКАЗА, И ТРЕТИЙ НЕ ЗАПАСНОЙ (тот же замок, что у О3, `write_fact`, `scan_result`):
    NAMED       код знаком — говорим, что случилось, какие числа и что делать
    UNSETTLED   исход НЕИЗВЕСТЕН (молчание транспорта) — «не знаю, легло или нет;
                проверь лист ПЕРЕД повтором» — повтор вслепую положил бы вторую запись
    UNNAMED     код незнаком — человеку ВСЁ РАВНО говорим действие, а сам код уходит в журнал
«Не знаю» — отдельное слово, а не вежливое «не записал»: 13.08 обе величины в Лист1 ЛЕГЛИ при
отказе расписки, и «не записал» там было бы ложью, которая зовёт на второй заход.

«ОПРЕДЕЛЁН ЛИ ИСХОД» БЕРЁТСЯ ГОТОВЫМ. Единственный импорт — `write_fact`: его `SETTLED_ERRORS`
уже отвечает ровно на этот вопрос («мост вынес отказ САМ» против «молчание транспорта»), и
второго списка о том же смысле здесь не заводится — разойдясь, они дали бы человеку два разных
ответа об одном отказе. Берём вокабуляр, а не руки: `needs_verify` отсюда не зовётся.

КОД НЕ ВЫТЕКАЕТ УСТРОЙСТВОМ. Ни одна ветка не кладёт `code` в `ru`/`th`; сам код возвращается
ОТДЕЛЬНЫМ полем `log` — для журнала, не для человека. Замок держит тест: он гоняет ВСЕ известные
коды плюс выдуманные и проверяет, что ни один не встретился в тексте человеку.

ГРАНИЦА УСТРОЙСТВОМ: импорт РОВНО ОДИН (`write_fact`, сам чистый). Ни сети, ни файлов, ни
отправки: что произошло — приносят руки (`splinter`), а модуль только решает, ЧТО об этом
сказать. Будь у него отправка, «бот не молчит» зависело бы от того, дошло ли сообщение, а не от
того, есть ли что сказать. Проверяется разбором (ast) инвариантом `REPLY_FLOOR_PURE`.

Тесты `tests/test_never_silent.py`. Артефакт `docs/artifacts/2026-08-23-never-silent-and-lower.md`.
"""
