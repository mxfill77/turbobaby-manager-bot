def parse_seen(parsed):
    """Разбор сообщения (словарь разборщика) → свидетель для пола. Не бросает никогда.

    Вердикт разборщика бывает РОВНО двух видов (`type`: `event` | `none`, промпт
    `splinter.SERVICING_SYSTEM`); всё прочее — пустой словарь, `None`, чужое слово — значит,
    что вердикта НЕТ, и это `PARSE_FAILED`, а не «болтовня»: сбой разбора не имеет права
    читаться как «человек болтал»."""
    try:
        t = str((parsed or {}).get("type") or "").strip().lower()
    except Exception:
        return PARSE_FAILED
    if t == "event":
        return PARSE_EVENT
    if t == "none":
        return PARSE_CHATTER
    return PARSE_FAILED


def has_content(text):
    """Есть ли в тексте хоть одно слово, кроме тегов людей и ссылок. Без `re` намеренно:
    импорт решения ровно один (`write_fact`, страж `REPLY_FLOOR_PURE`). Тайская буква —
    буква (`isalnum`), эмодзи и знаки — нет."""
    for tok in str(text or "").split():
        if tok.startswith("@") or tok.lower().startswith(("http://", "https://", "t.me/")):
            continue
        if any(ch.isalnum() for ch in tok):
            return True
    return False


def should_speak(facts=None):
    """Пол промолчал бы → говорить ли ему? Возврат `{"speak": bool, "why": str}`. Не бросает.

    ОДНОСТОРОННЕ: «нет» приходит только при ПОЛОЖИТЕЛЬНОМ знании, что сообщение не запись и
    ответа не ждёт; всякая дырка в фактах — «да», то есть прежний путь. Порядок — от сильного:
      заход упал                      → говорим (запись не сделана, человек обязан знать);
      к боту обратились прямо          → говорим (явный вопрос не остаётся без ответа);
      снимок: приборка / не разобран  → говорим (цифры или снимок — наш провал, не его);
      снимок назван, не приборка      → молчим, если подпись не осталась неразобранной;
      текст без слов (только теги)    → молчим;
      разборщик: болтовня / событие / карточка недавно → молчим;
      разбора не было или он не дал вердикта → говорим (незнание — не тишина)."""
    f = dict(facts or {})
    if f.get("crashed"):
        return {"speak": True, "why": "заход упал"}
    # РАЗГОВОР ЛЮДЕЙ (26.09.2026, правило Штаба): ответ на сообщение бота с ДРУГИМ адресатом
    # (тег человека, вопрос или цена для людей) и согласие/план людей — не обращение к боту.
    # Оба факта кладут руки только при включённой ручке `TALK_STAGE`; нет факта — путь прежний.
    if str(f.get("parse") or "") == PARSE_PEOPLE:
        return {"speak": False, "why": "согласие или план людей — не факт работ, ход за людьми"}
    if f.get("other") and not f.get("photo"):
        return {"speak": False, "why": f"ответ на сообщение бота, но адресат другой: {f.get('other')}"}
    if f.get("addressed"):
        return {"speak": True, "why": "обратились к боту"}
    seen = str(f.get("parse") or PARSE_UNKNOWN)
    text = f.get("text") or ""
    open_words = seen in (PARSE_UNKNOWN, PARSE_FAILED) and has_content(text)
    if f.get("photo"):
        kind = str(f.get("photo_kind") or "").strip().lower()
        if kind == DASHBOARD:
            return {"speak": True, "why": "приборка, числа не прочитаны"}
        if kind not in _PHOTO_SEEN:
            return {"speak": True, "why": "снимок не разобран"}
        if open_words:
            return {"speak": True, "why": "подпись к снимку не разобрана"}
        return {"speak": False, "why": f"снимок назван ({kind}), приборки нет — не запись"}
    if not has_content(text):
        return {"speak": False, "why": "в тексте только теги или знаки"}
    if seen == PARSE_CHATTER:
        return {"speak": False, "why": "разборщик: болтовня"}
    if seen == PARSE_EVENT:
        return {"speak": False, "why": "разборщик: событие — пишется строкой событий, не вопрос"}
    if seen == PARSE_STATUS:
        return {"speak": False, "why": "запрос карточки, карточка ушла недавно"}
    if seen == PARSE_FAILED:
        return {"speak": True, "why": "текст не разобран"}
    return {"speak": True, "why": "разбора не было (прежний путь)"}
