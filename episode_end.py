#!/usr/bin/env python3
"""КОГДА ЭПИЗОД ОЖИДАНИЯ ПЕРЕСТАЁТ БЫТЬ ЭПИЗОДОМ (22.08.2026). Чистая функция:
«открытый эпизод + факты → идёт · поднять до владельца · снять как НЕИЗВЕСТНО».

ПОВОД, ИЗМЕРЕННЫЙ, А НЕ ПОЧУВСТВОВАННЫЙ. На 22.08.2026 09:24 UTC в состоянии рук открыты ДВА
эпизода, и оба не могут кончиться:
  · `o7l|1787118120` — идёт 63 ч, наблюдений 123, владельцу не сказано ни разу (вес лёгкий);
  · `o3|7e348d4`     — идёт 283 ч (11.8 суток), заведён прежней редакцией 10.08.
За всё наблюдение слоя журнал мозга знает 27 закрытых эпизодов, и САМЫЙ ДОЛГИЙ из них прожил
19 ч 28 мин. То есть оба живых эпизода лежат за пределами всего, что когда-либо заканчивалось.

ПРАВИЛА ОКОНЧАНИЯ ЭПИЗОДА В СЛОЕ НЕ БЫЛО ВОВСЕ, кроме одного — ПО ФАКТУ ВЫЗДОРОВЛЕНИЯ
(`expectations.closures`). Правила по времени нет; правила по числу пересмотров нет: поле
`ticks` только пишется и печатается («наблюдений 123»), НИ ОДНА ветка его не читает. Отсюда два
рода вечных эпизодов, и оба живут в проде прямо сейчас:
  (А) ЗАКРЫВАЮЩИЙ ФАКТ БОЛЬШЕ НЕ МОЖЕТ ПОЯВИТЬСЯ. `o3_delivered_keys` отбрасывает коммиты старше
      окна судейства (`deliver_window`, 48 ч), а `_o3` старше окна не выносит вовсе. Значит
      коммит, переваливший окно, ОДНОВРЕМЕННО выпал и из нарушений, и из закрытий: эпизод не
      судится и не закрывается НИКОГДА. Ровно это и есть `o3|7e348d4` — он вышел из окна 12.08 и
      с тех пор просто лежит.
  (Б) ИСТОЧНИК ЖИВ И ПРОДОЛЖАЕТ МОЛЧАТЬ О ПРЕДМЕТЕ. Ключ `o7l|<ts последней публикации>` меняется
      только новой публикацией, и оба пути закрытия (`ch_st != CH_UNKNOWN`; `not lost and ts`)
      требуют её же. Публикации нет — эпизод вечен по построению.

ЧТО ЗДЕСЬ РЕШАЕТСЯ И ЧТО НЕ РЕШАЕТСЯ. Вердикты не трогаются ни одним полем; пороги существующих
ожиданий не трогаются ни одним значением. Здесь решается СУДЬБА УЖЕ ОТКРЫТОГО ЭПИЗОДА, и решается
она ФАКТОМ, а не длительностью: длительность — калибровка, факт — условие.

── ВЕТКА А: СНЯТЬ КАК НЕИЗВЕСТНО ────────────────────────────────────────────────────────────
УСЛОВИЕ — АРИФМЕТИЧЕСКОЕ ДОКАЗАТЕЛЬСТВО, ЧТО ЗАКРЫВАЮЩЕГО ФАКТА БЫТЬ НЕ МОЖЕТ, и источник для
него НЕ СПРАШИВАЕТСЯ ВОВСЕ. Эпизод О3 заводится, только когда возраст коммита уже перевалил порог
`deliver`, значит `ct < first - deliver`; отсюда `now - ct > (now - first) + deliver`. Если это
число больше окна судейства — коммит ГАРАНТИРОВАННО вне окна, и `o3_delivered_keys` его не вернёт
ни при каком ответе git.

ПОЧЕМУ ИСТОЧНИК НЕ СПРАШИВАЕТСЯ — ЭТО ЗАМОК, А НЕ ЭКОНОМИЯ. Спроси мы git, и его молчание
(«коммита в выборке нет») выглядело бы точно так же, как уход предмета из окна, — то есть мёртвый
git закрывал бы эпизоды пачкой. Тот же ложный зелёный, против которого стоит весь слой. Чистая
арифметика по СОБСТВЕННОЙ записи эпизода и СОБСТВЕННЫМ порогам прибора обмануться источником не
может физически.

СНИМАЕТСЯ СЛОВОМ «НЕИЗВЕСТНО», А НЕ «ВЫЗДОРОВЕЛ». Доставка так и не была доказана; притвориться,
что коммит доехал, значило бы сменить один ложный ответ на другой. `expectations.closures` этой
ветке не отдан намеренно: он отвечает на вопрос «выздоровело ли», и ответ «предмет ушёл» в него
не помещается.

── ВЕТКА Б: ПОДНЯТЬ ВЕС И ДОЙТИ ДО ВЛАДЕЛЬЦА ────────────────────────────────────────────────
УСЛОВИЕ — ПОЛОЖИТЕЛЬНЫЙ ФАКТ О ЖИВОМ ИСТОЧНИКЕ, а не истёкший срок. Владельцу адресуется не
«строки нет уже долго» (это по-прежнему отсутствие сведений, решать нечего), а ДРУГОЕ утверждение:
«полоса ЖИВА и ПИШЕТ, но прибора о детях в её записях больше нет» — то есть наблюдение за детьми
клиентского контура ПОТЕРЯНО. Это факт о мире, и он его.

Три факта, все из одного свежего снимка, ни один не является длительностью:
  1. нарушение продолжается (эпизод стоит в живом вердикте);
  2. снимок журнала СВЕЖ (`now - fetched <= pc_fresh`) — иначе судился бы кэш;
  3. производитель ДОКАЗАННО ЖИВ И ПИШЕТ ПОСЛЕ пропавшего предмета: последняя запись полосы
     МОЛОЖЕ последней публикации о детях. Это и есть различитель «умер» / «жив, но ослеп»:
     замолчи полоса целиком — предмет был бы О4, и вторая заметка о том же была бы дублем.
Калибровка (и только она) — время: отсутствие держится дольше `mult` ПЕРИОДОВ, ОБЪЯВЛЕННЫХ САМИМ
ПРОИЗВОДИТЕЛЕМ в той же строке («период 360 мин»). Период не назван → НЕ СУДИМ: своего числа
вместо его числа не подставляем.

ПОЧЕМУ ПЕРИОД ПРОИЗВОДИТЕЛЯ, А НЕ НАША КОНСТАНТА. Порог О7 (2 периода) отвечает на вопрос
«опоздал ли»; ветка Б отвечает на другой — «есть ли ещё прибор». Выразить второй в единицах
первого значит сказать: «дважды пропустить публикацию — опоздание, вчетверо — потеря». Наша
секунда тут ничего не измеряет, его период — измеряет.

MULT = 4 ВЗЯТ ЗАМЕРОМ. Самый долгий ЗАКОНЧИВШИЙСЯ эпизод слоя за всё наблюдение — 19 ч 28 мин
(27 закрытых эпизодов, журнал мозга); при объявленном периоде 360 мин это 3.24 периода. Четыре
периода — первое ЦЕЛОЕ число периодов выше всего, что когда-либо заканчивалось само, и ровно
вдвое больше порога О7, который при этом НЕ ТРОГАЕТСЯ. Историческая цена: из 27 закрытых эпизодов
порог 4 периода (24 ч при сегодняшнем периоде) не перешагнул НИ ОДИН — ноль лишних сообщений.

ЧЕСТНАЯ ОГОВОРКА О ЧИСЛЕ: корпуса «публикация опоздала и ВЕРНУЛАСЬ» не существует вовсе — строка
о детях жила 17 часов (26 публикаций 18.08 12:22 → 19.08 05:42) и с тех пор не выходила ни разу.
Поэтому 4 калибруется по тому, что ЕСТЬ (длительность закончившихся эпизодов слоя), а не по тому,
чего нет. Накопится история возвратов — число перемерить тем же приёмом, что у О3 и О5.

── ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО ─────────────────────────────────────────────────────────────────
Ни одна ветка не умеет объявить нарушение, снять вердикт, тронуть очередь или что-то починить:
исходов ровно три, и все три — о СУДЬБЕ ЗАПИСИ ЭПИЗОДА. ИМПОРТОВ НОЛЬ — ни файлов, ни сети, ни
моста, ни подпроцессов, ни времени своего: пороги приходят готовым `cfg`, факты готовым `facts`,
«сейчас» приносят руки. Стережёт `EPISODE_END_PURE` (ast, в гейте).
"""

GOING, RAISE, DROP, NOT_JUDGED = "идёт", "поднять", "снять", "не судим"

# Множитель ОБЪЯВЛЕННОГО ПРОИЗВОДИТЕЛЕМ периода для ветки Б. Замер: самый долгий закончившийся
# эпизод слоя — 3.24 периода; 4 — первое целое выше него. 0 → ветка Б мертва.
LOST_PERIODS = 4.0

# Виды, у которых ветка А доказуема АРИФМЕТИЧЕСКИ (у прибора есть окно судейства предмета).
# Список ЗАКРЫТЫЙ и ведётся руками: незнакомый вид → «не судим», то есть прежнее поведение
# байт-в-байт. Направление ошибки здесь безопасное — эпизод остаётся открытым, как оставался.
WINDOWED_KINDS = ("o3",)
# Виды, у которых ветка Б имеет ПОЛОЖИТЕЛЬНЫЙ факт о живом источнике и объявленный период.
INSTRUMENT_KINDS = ("o7l",)


def _f(x, default=0.0):
    """Число или default. Мусор нулём не притворяется — им становится только явный ноль."""
    try:
        return float(x)
    except (TypeError, ValueError):
        return float(default)


def kind_of(key):
    """Ключ эпизода → его короткий вид («o3|7e348d4» → «o3»)."""
    return str(key or "").split("|", 1)[0]


# ═══════════════════════ ВЕТКА А: ЗАКРЫВАЮЩЕГО ФАКТА БЫТЬ НЕ МОЖЕТ ═══════════════════════════
def unreachable(key, rec, cfg, now):
    """Доказано ли АРИФМЕТИЧЕСКИ, что закрывающий факт этого эпизода больше не появится?
    → (да/нет, причина). Источника не спрашивает вовсе — см. шапку, замок ветки А.

    ЛОЖЬ ВОЗВРАЩАЕТСЯ ВЕЗДЕ, ГДЕ ДОКАЗАТЕЛЬСТВА НЕТ: незнакомый вид · порог выключен · окна нет ·
    начала эпизода нет. «Не доказано» и «доказано, что нет» — разные вещи, и вторая обязана
    стоить арифметики."""
    kind = kind_of(key)
    if kind not in WINDOWED_KINDS:
        return False, "вид «%s» окна судейства предмета не имеет — не судим" % kind
    cfg = cfg if isinstance(cfg, dict) else {}
    window = _f(cfg.get("deliver_window"))
    limit = _f(cfg.get("deliver"))
    if window <= 0 or limit <= 0:
        return False, "окно судейства или порог доставки выключены — ветка мертва"
    first = _f((rec or {}).get("first"))
    if first <= 0:
        return False, "начала эпизода в записи нет — арифметике не на что опереться"
    now = _f(now)
    if now <= first:
        return False, "время эпизода не растёт — судить нечем"
    # Эпизод О3 заводится, только когда возраст коммита УЖЕ перевалил `limit`, значит
    # ct < first - limit, а тогда (now - ct) > (now - first) + limit. НИЖНЯЯ оценка возраста
    # коммита — она и сравнивается с окном: доказывать надо «точно вне», а не «наверное вне».
    floor = (now - first) + limit
    if floor <= window:
        return False, ("коммит может ещё лежать в окне судейства (нижняя оценка возраста %s "
                       "при окне %s)" % (_age(floor), _age(window)))
    return True, ("коммит гарантированно вне окна судейства: возраст не меньше %s при окне %s — "
                  "ни нарушением, ни закрытием он больше не станет"
                  % (_age(floor), _age(window)))


# ═══════════════════ ВЕТКА Б: ИСТОЧНИК ЖИВ, А ПРИБОРА О ПРЕДМЕТЕ БОЛЬШЕ НЕТ ══════════════════
def lost_instrument(key, facts, cfg, now, mult=None):
    """Живой источник продолжает молчать о предмете дольше `mult` его СОБСТВЕННЫХ периодов?
    → (да/нет, причина, число замера).

    ТРЕТИЙ ИСХОД ЖИВЁТ В «НЕТ» И НАЗЫВАЕТ СЕБЯ ПРИЧИНОЙ: снимок несвежий · журнал не прочитан ·
    период не объявлен · производитель НЕ доказан живым — всё это «не судим», и ни одно из них
    не есть «прибор потерян». Замок против ложной тревоги ровно тот же, что у слоя против ложного
    зелёного, только направленный в другую сторону."""
    kind = kind_of(key)
    if kind not in INSTRUMENT_KINDS:
        return False, "вид «%s» объявленного периода не имеет — не судим" % kind, ""
    mult = LOST_PERIODS if mult is None else _f(mult)
    if mult <= 0:
        return False, "ветка Б выключена (множитель периодов 0)", ""
    cfg = cfg if isinstance(cfg, dict) else {}
    now = _f(now)
    p = (facts or {}).get("pc")
    if not isinstance(p, dict) or not p.get("ok"):
        return False, "журнал полосы не прочитан — о живости источника сказать нечего", ""
    fetched = _f(p.get("fetched"))
    fresh = _f(cfg.get("pc_fresh"))
    if fetched <= 0 or (fresh > 0 and now - fetched > fresh):
        # СВЕЖИЙ СЛЕД ПОКОЙНИКА. Кэшированный снимок показывает записи, и источник ВЫГЛЯДИТ живым;
        # судить по нему значило бы поднять тревогу (или снять её) по картинке, а не по миру.
        return False, "срез журнала устарел (%s назад) — судился бы кэш, а не источник" % _age(
            now - fetched if fetched > 0 else 0), ""
    ch = p.get("children")
    if not isinstance(ch, dict):
        return False, "разбора строки о предмете нет вовсе — судить нечем", ""
    ts = ch.get("ts")
    if ts is None:
        return False, "публикации о предмете в снимке нет вовсе — периода она не объявляла", ""
    ts = _f(ts)
    period = _f(ch.get("period"))
    if period <= 0:
        return False, "производитель периода не объявил — своего числа вместо его не ставим", ""
    period_sec = period * 60.0
    # ПОЛОЖИТЕЛЬНЫЙ ФАКТ: полоса пишет ПОСЛЕ пропавшей публикации. Замолчи она целиком — это
    # предмет О4, а не потеря прибора, и говорить о ней здесь было бы дублем.
    last = _f(p.get("last")) or _f(ch.get("span_to"))
    if last <= ts:
        return False, ("источник не доказан живым: записей ПОСЛЕ последней публикации о предмете "
                       "в снимке нет — это молчание полосы целиком, предмет другого ожидания"), ""
    age = now - ts
    need = mult * period_sec
    if age <= need:
        return False, ("отсутствие держится %s при %g периодах = %s — ещё опоздание, а не потеря"
                       % (_age(age), mult, _age(need))), ""
    num = ("публикации о детях нет %s = %.1f объявленных периодов по %g мин; полоса при этом "
           "пишет, последняя её запись моложе пропавшей публикации на %s"
           % (_age(age), age / period_sec, period, _age(last - ts)))
    return True, ("источник ЖИВ и пишет, а прибора о предмете в его записях нет %s при пороге "
                  "потери %g периодов (%s)" % (_age(age), mult, _age(need))), num


# ═══════════════════════════════ ОБЩИЙ ВХОД ══════════════════════════════════════════════════
def state(key, rec, facts, cfg, now, in_live, mult=None):
    """СУДЬБА ОТКРЫТОГО ЭПИЗОДА → (исход, причина, число).

    Порядок разбора назван и не случаен: СНЯТИЕ судится только у того, кто ВЫПАЛ из вердикта, а
    ПОДЪЁМ — только у того, кто в нём стоит. Пересечься они не могут: одно и то же нарушение не
    бывает одновременно продолжающимся и невозможным."""
    if in_live:
        ok, why, num = lost_instrument(key, facts, cfg, now, mult)
        return (RAISE if ok else GOING), why, num
    ok, why = unreachable(key, rec, cfg, now)
    return (DROP if ok else GOING), why, ""


def drop_text(key, rec, why, lane="VPS", now=0.0):
    """Строка о СНЯТИИ — та, что уходит и в мозг, и (если владельцу объявляли) ему.

    Говорит «НЕИЗВЕСТНО», а не «выздоровел», и называет обе величины: сколько эпизод прожил и
    почему кончился. Слово «доставлен» тут не появляется ни при каком исходе."""
    rec = rec if isinstance(rec, dict) else {}
    first = _f(rec.get("first"))
    # ПРОЖИЛ — до СЕГОДНЯ, а не до последнего наблюдения: эпизод, выпавший из вердикта, перестал
    # пересматриваться, и `last` у него застыл. Считать по нему значило бы занизить срок молчания.
    last = max(_f(rec.get("last")), _f(now), first)
    return ("🔚 эпизод снят как НЕИЗВЕСТНО · %s · %s · прожил %s, наблюдений %s · %s · "
            "выздоровление НЕ доказано и доказано быть уже не может"
            % (lane, key, _age(last - first), rec.get("ticks") or "?", why))


def raise_text(key, why, num, lane="VPS"):
    """Строка о ПОДЪЁМЕ. Владельцу адресуется НОВЫЙ смысл, а не старое число: не «строки нет
    долго», а «наблюдение потеряно» — и прямо сказано, чем это отличается от опоздания."""
    return ("🔎 НАБЛЮДЕНИЕ ПОТЕРЯНО · %s · %s · %s · %s · это уже не опоздание публикации: "
            "предмет ожидания перестал быть наблюдаемым, и пока прибор не вернётся, о нём не "
            "скажет никто · рестарта и правок не делаю — это решение владельца"
            % (lane, key, num or "число не записано", why))


def _age(sec):
    """«9 мин» / «10 ч 42 мин» / «2 сут 15 ч». Зеркало `expect_journal._age`: строки этих двух
    модулей читаются рядом, и разные единицы в них сбивали бы глаз. НЕТ факта → «?»."""
    if sec is None:
        return "?"
    s = max(0, int(_f(sec)))
    h, rest = divmod(s, 3600)
    m = rest // 60
    if h >= 24:
        return "%d сут %d ч" % divmod(h, 24)
    return ("%d ч %d мин" % (h, m)) if h else ("%d мин" % m)
