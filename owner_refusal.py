# ДОСЛОВНО ТО, ЧТО ПИШЕТ devbot. Двух написаний нет: «(кнопка)» — хвост той же строки, а не
# второй маркер, поэтому сверяется ОДИН префикс.
MARK = "отклонено Филиппом"

# Декорация форматирования — зеркало `_NA_DECOR` (orchestrator_daemon.py:1381): пробелы, пункт
# списка, выделение, решётка заголовка. Обратная кавычка, кавычки, «|» ячейки, «>» цитаты, любая
# буква или цифра означают, что маркер стоит ВНУТРИ чужого текста, и заявлением он не является.
DECOR = " \t -–—•*+_#"

REFUSAL = "отклонена владельцем"     # исход учёта: решение человека
FAILURE = "упала"                    # исход учёта: сбой (прежнее имя, менять его нечем)
NOTE = ("это РЕШЕНИЕ владельца, а не сбой системы: работа не начиналась либо остановлена его "
        "волей, переотправке не подлежит")


def said(text):
    """Стоит ли маркер отказа в ЗАЯВЛЯЮЩЕЙ позиции — в начале ПЕРВОЙ непустой строки.

    Первая непустая, а не «любая»: девбот пишет отказ ЦЕЛИКОМ и один, а любая другая строка
    в теле — это уже отчёт задачи о себе, где маркер может быть процитирован."""
    for line in str(text or "").splitlines():
        if not line.strip():
            continue
        i = line.find(MARK)
        if i < 0:
            return False
        return not line[:i].strip(DECOR)     # перед маркером есть ТЕКСТ → цитата, а не заявление
    return False


def outcome(status, result):
    """(статус строки, её текст) → REFUSAL | FAILURE | "" (не терминал падения — судить нечего)."""
    if str(status or "") != "failed":
        return ""
    return REFUSAL if said(result) else FAILURE


def regrade(prev_outcome, why):
    """ЛЕГАСИ-ЗАПИСЬ УЧЁТА, снятая до разреза, → её исход сегодня.

    Реестр закрытых живёт 48 часов и переживает эту правку: записи, снятые вчерашним кодом, несут
    `упала` и ПЕРВУЮ СТРОКУ терминала в поле «почему» — а у отказа владельца первая строка И ЕСТЬ
    маркер. Пересуживаем ОДНОСТОРОННЕ (только `упала` → `отклонена владельцем`) и только по тому
    же доказательству: обратного хода нет, «сдана» и «не сверен» не трогаются вовсе."""
    if str(prev_outcome or "") == FAILURE and said(why):
        return REFUSAL
    return str(prev_outcome or "")
