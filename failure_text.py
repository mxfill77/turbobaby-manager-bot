#!/usr/bin/env python3
"""ДОСЛОВНЫЙ ОТВЕТ ВНЕШНЕЙ СИСТЕМЫ ИЗ ТЕЛА УПАВШЕЙ СТРОКИ (19.08.2026). Чистая функция:
«тело `result` → что ответила внешняя система, или честное „причина наша"».

ПОВОД (разведка 18.08, `docs/artifacts/2026-08-18-external-failure-recon.md`, коммит 2dfd4fd).
Дословный ответ внешней системы СОХРАНЯЕТСЯ — он лежит в поле `result` упавшей строки очереди и
в артефакте отчёта. Наблюдатель яруса 2 читает это поле ОБЕИХ полос одним GET, за который уже
заплачено (`expectations_run.failed_facts`). И до владельца этот текст не доезжает: тело
режется `[:400]` при чтении, а слепок очереди берёт из него ПЕРВУЮ строку (`queue_state.head`)
и режет её до 160 символов.

ЗАМЕР (живой корпус артефактов отчётов, 24 упавших тела; замер этого захода):
  · внешним отказом упало 5, нашей причиной 19;
  · во ВСЕХ ПЯТИ дословная строка стоит за срезом: символы 406 · 463 · 530 · 534 · 641 при
    срезе 400, и НИ В ОДНОМ она не попадает в первую строку тела — 5 из 5 машинных строк лежат
    ТРЕТЬИМИ, а первой идёт пересказ думателя;
  · у task-4 (18.08) пересказ и заявление живут в ОДНОМ теле: маркер на символе 105 внутри
    фразы думателя «(API Error: … при exit=1)» и он же на символе 534 после машинного зачина.
    Сегодня владельцу достаётся РОВНО пересказ, обрезанный на полуслове.

ПОЗИЦИЯ ДАЁТ ОТРЕЗОК, ВОКАБУЛЯР РЕШАЕТ, ЧЕЙ ОТКАЗ. Правило позиции то же, что у
`expectations.lane_err` (класс 5ca761d/6a7baf9/40c8425): смотрим ТОЛЬКО туда, где машина сама
объявила, что дальше идёт вывод внешнего инструмента, — после МАШИННОГО ЗАЧИНА. Слова в чужой
фразе («…причина: Провал инфраструктурный (API Error: … при exit=1)») отрезком не являются и
заявлением отказа не становятся.

ПОЧЕМУ ОДНОГО МАРКЕРА `API Error:` НЕ ХВАТИЛО — доказано живой очередью 19.08. Первая редакция
искала только его, и на строке #23 полосы ПК промолчала бы, а там дословно:
«claude exit=1: **Failed to authenticate: OAuth session expired and could not be refreshed.**»
— то есть ровно ИСТЁКШАЯ СЕССИЯ, один из трёх случаев, ради которых заход и делается (перегрузка
проходит сама, кончившиеся деньги и истёкшая сессия — нет). Внешняя система вправе отказать не
теми словами, которые мы выучили.

Поэтому «чей отказ» решает ГОТОВЫЙ вокабуляр `status_truth._MODEL_NEEDLES` — тот самый, которым
система уже отвечает на этот же вопрос в `classify_exec`. Второго списка о том же смысле не
заводится: он бы разошёлся с первым молча. ВАЖНО: вокабуляр здесь ЧИТАЕТСЯ, а не применяется как
классификатор — мы не повторяем и не уточняем вывод `classify_exec` о ПРИЧИНЕ (он схлопывает
перегрузку, кредиты и сессию в один код `model_refusal`, и это его честный предел). Здесь список
отвечает ровно на одно: отказала внешняя сторона или процесс убили мы (`exit=143` — SIGTERM по
нашему таймауту/рестарту, и это НАША причина при живом машинном зачине).

Своя здесь только ПОВЕРХНОСТЬ: тело `result`, а не строка журнала, и у неё есть то, чего в
журнале нет вовсе, — зачин `_fail_card` демона, его же разделитель между сводкой задачи и хвостом
stderr, и ХВОСТ наших собственных следов работы, который `status_truth.fail_result` дописывает
после чужого текста. Все три замкнуты на ЖИВЫХ производителей тестом (`tests/test_failure_text.py`,
секция 2): сменится их форма — покраснеет гейт, а не молча испортится цитата.

СУЖДЕНИЯ О ПРИЧИНЕ ЗДЕСЬ НЕТ НИ ОДНОГО СЛОВА, и это главное свойство. Перегрузка сервера
проходит сама, кончившиеся деньги и истёкшая сессия — нет; система их не различает (все виды
внешнего отказа схлопнуты в один код `status_truth.classify_exec`, а на полосе ПК тот же 529
кодируется вообще другим кодом). Различает владелец, и различает он ПО ТЕКСТУ. Поэтому модуль
только цитирует.

ИСХОДА ТРИ, а не два — тот же замок против ложного зелёного, что у О3, `write_fact` и
`scan_result`: «внешний отказ» возвращается РОВНО ОДНИМ путём (маркер в заявляющей позиции), всё
прочее — «причина наша» либо «тела нет». Пересказ, цитата в прозе, наш таймаут и наш красный
маркер внешним отказом НЕ становятся: сказать «внешняя система ответила» там, где она молчала,
значило бы снять вину с себя чужим именем.
"""
import expectations
import status_truth

# ── ИСХОДЫ ────────────────────────────────────────────────────────────────────────────────────
EXTERNAL = "внешний отказ"        # внешняя система ответила отказом, и вот её слова
OURS = "наша причина"             # тело есть, заявления внешнего отказа в нём нет
NOTHING = "тела нет"              # читать нечего

# ЖУРНАЛЬНЫЕ зачины — вокабуляр `expectations`, готовым. Здесь они НЕ переопределяются.
HEADS = expectations.LANE_ERR_HEADS
# СЛОВА, КОТОРЫМИ СИСТЕМА УЖЕ УЗНАЁТ ОТКАЗ ВНЕШНЕЙ СТОРОНЫ. Читается готовым у `status_truth`
# (там же, где ими пользуется `classify_exec`) — второго списка о том же смысле не заводится.
NEEDLES = status_truth._MODEL_NEEDLES

# ЗАЧИН ПОВЕРХНОСТИ `result` полосы VPS: `orchestrator_daemon._fail_card` собирает карточку
# провала как f"claude -p упал (exit={rc}): {body}". Код возврата подставляется живым, поэтому
# зачин здесь — форма, а не литерал; сама форма замкнута на живой `_fail_card` тестом.
VPS_HEAD = "claude -p упал (exit="
VPS_HEAD_TAIL = "): "
VPS_RC_MAX = 12                   # сколько символов кода возврата допускаем («-9», «143», «1»)
# Разделитель ТОЙ ЖЕ карточки между СВОДКОЙ задачи (первая строка stdout) и хвостом stderr.
# Сводку пишет исполнитель, хвост — инструмент; выдать первую за «ответ внешней системы» значило
# бы то же, что выдать за него наш разбор следов.
CARD_SEP = " | "

# ХВОСТ НАШИХ СЛЕДОВ. `status_truth.fail_result` дописывает к чужому тексту наш разбор окна
# задачи. Он идёт ПОСЛЕ ответа внешней системы и в кавычки попадать не смеет: выдать свои слова
# за чужие — тот же подлог, что и назвать наш отказ внешним, только тише.
TRACE_HEADS = ("СЛЕДОВ РАБОТЫ в окне ", "СЛЕДЫ в окне ")

# Потолок цитаты. ТОТ ЖЕ, что у `expectations.lane_err` и у показа О8 (`render`, «дословно: «…»»):
# один факт — один вид. На живом корпусе он ничего не режет: длиннейший ответ 137 символов
# (529 Overloaded …status.claude.com.), короче потолка вдвое.
TEXT_MAX = 200


def _segment(raw):
    """→ (символ начала отрезка, отрезок) | (None, "").

    Отрезок — то, что машина объявила выводом внешнего инструмента: всё ПОСЛЕ машинного зачина.
    Зачинов два рода: журнальные (готовые у `lane_err`) и зачин карточки провала демона. Берётся
    ПОСЛЕДНИЙ: думатель и самопочинка дописывают свои строки СВЕРХУ, машинная ложится последней
    (5 из 5 в живом корпусе)."""
    best = None
    for h in HEADS:
        i = raw.rfind(h)
        if i >= 0 and (best is None or i + len(h) > best):
            best = i + len(h)
    i = raw.rfind(VPS_HEAD)
    while i >= 0:
        j = raw.find(VPS_HEAD_TAIL, i + len(VPS_HEAD))
        if 0 <= j - (i + len(VPS_HEAD)) <= VPS_RC_MAX:
            start = j + len(VPS_HEAD_TAIL)
            if best is None or start > best:
                best = start
            break
        i = raw.rfind(VPS_HEAD, 0, i)
    return (best, raw[best:]) if best is not None else (None, "")


def _said_refusal(text):
    """Сказала ли внешняя сторона, что отказывает. → bool. Судит ГОТОВЫЙ вокабуляр, своего
    суждения о ПРИЧИНЕ отказа здесь нет ни одного слова."""
    low = text.lower()
    return any(n in low for n in NEEDLES)


def _own_tail(raw):
    """Где начинается НАШ разбор следов работы. → индекс | len(raw).

    СНИМАЕТСЯ ПЕРВЫМ ДЕЛОМ, И ЭТО НЕ ПОРЯДОК РАДИ ПОРЯДКА. Наш хвост ЦИТИРУЕТ строки журнала, а
    в них живут те же машинные зачины («…DONE …: ✅ Code-сессия завершена: Источник цены…»). Ищи
    зачин раньше — и последним в теле окажется зачин ИЗ НАШЕЙ ЖЕ ЦИТАТЫ, а «ответом внешней
    системы» станет обрывок нашего отчёта. Поймано живьём на телах #5 и #9 (19.08): правило
    позиции било само себя, пока хвост не снимали первым."""
    end = len(raw)
    for h in TRACE_HEADS:
        i = raw.find(h)
        if 0 <= i < end:
            end = i
    return end


def verdict(result_text):
    """Тело `result` упавшей строки → что ответила внешняя система.

    → {"kind": EXTERNAL|OURS|NOTHING, "text": дословно|"", "at": символ|None,
       "cut": чем обрезано|"", "quoted": был ли маркер ВНЕ позиции, "why": одной строкой}

    Судится ПОСЛЕДНЕЕ заявление тела: думатель и самопочинка дописывают свои строки СВЕРХУ, а
    машинная строка ложится последней (5 из 5 в корпусе). «Последняя внешняя ошибка» — это она.

    Исключений не бросает НИКОГДА: кривое тело — это «причина наша», а не падение наблюдателя."""
    try:
        raw = str(result_text or "")
    except Exception:                                                # noqa: BLE001
        return {"kind": NOTHING, "text": "", "at": None, "cut": "", "quoted": False,
                "why": "тело не читается"}
    if not raw.strip():
        return {"kind": NOTHING, "text": "", "at": None, "cut": "", "quoted": False,
                "why": "тело пусто — читать нечего"}
    own = _own_tail(raw)
    clean = raw[:own]
    at, seg = _segment(clean)
    # ЦИТАТА РЯДОМ — слова отказа ЕСТЬ в теле, но вне отрезка (пересказ думателя, ячейка таблицы,
    # проза отчёта). Она ничего не решает и заявлением не становится; названа затем, что по ней
    # видно, работает ли правило позиции на живом теле.
    quoted = _said_refusal(clean if at is None else clean[:at])
    if at is None:
        return {"kind": OURS, "text": "", "at": None, "cut": "", "quoted": quoted,
                "why": ("слова отказа в теле есть, но машина не объявляла вывод инструмента — "
                        "это пересказ, а не ответ внешней системы") if quoted else
                       "машинного зачина в теле нет — сказать о внешней стороне нечего"}
    cut = "наш разбор следов работы" if own < len(raw) else ""
    nl = seg.find("\n")
    if nl >= 0:
        seg, cut = seg[:nl], cut or "конец строки"
    text = seg
    # СВОДКА ЗАДАЧИ ОТДЕЛЯЕТСЯ ОТ ХВОСТА ИНСТРУМЕНТА: карточка провала склеивает их своим
    # разделителем, и если отказ назван ПОСЛЕ него — цитируем ровно хвост. Иначе первыми словами
    # «ответа внешней системы» встал бы текст, который написали мы сами.
    if CARD_SEP in text:
        tail = text.rsplit(CARD_SEP, 1)[1]
        if _said_refusal(tail) and not _said_refusal(text[:len(text) - len(tail)]):
            text = tail
            cut = "сводка задачи перед разделителем карточки" + ((" + " + cut) if cut else "")
    text = text.strip()
    if not text:
        # Зачин есть, слов за ним нет. Это НЕ «внешняя система ответила пустотой» — цитировать
        # нечего, а значит и заявлять нечего: направление сомнения то же, что у всего слоя.
        return {"kind": OURS, "text": "", "at": at, "cut": "", "quoted": quoted,
                "why": "после машинного зачина нет ни слова — цитировать нечего"}
    if not _said_refusal(text):
        # ЗАЧИН ЕСТЬ, ОТКАЗА НЕТ. Так выглядит НАША причина при живой машинной строке: «exit=143»
        # это SIGTERM по нашему таймауту или рестарту. Назвать её внешней значило бы снять с себя
        # вину чужим именем — ровно то, что запрещает отрицательный тест (б).
        return {"kind": OURS, "text": "", "at": at, "cut": "", "quoted": quoted,
                "why": "машина объявила вывод инструмента, но отказа в нём нет — причина наша"}
    if len(text) > TEXT_MAX:
        text, cut = text[:TEXT_MAX], "потолок цитаты %d" % TEXT_MAX
    return {"kind": EXTERNAL, "text": text, "at": at, "cut": cut, "quoted": quoted,
            "why": "внешняя система ответила дословно"}


def external(result_text):
    """Короткая дверь для рук: дословный ответ | "" (его нет). Своего правила не заводит."""
    v = verdict(result_text)
    return v.get("text") if v.get("kind") == EXTERNAL else ""
