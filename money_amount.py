"""НОЛЬ НЕ ОТ ХРАНИЛИЩА НЕ СТАНОВИТСЯ ДЕНЬГАМИ (21.09.2026).

КЛАСС. Тот же, что закрыт у фиксации баланса коммитом `fe66881`, только с другого конца. Там
ноль подставлялся вместо НЕПОЛУЧЕННОГО баланса и уходил в лист поправкой на всю сумму. Здесь он
подставляется вместо НЕНАЗВАННОЙ суммы движения — и уходит в лист настоящей строкой.

ПОДСТАНОВКА ЖИВЁТ В ДВУХ МЕСТАХ, И ОНИ РАЗНЫЕ. Это и есть причина, по которой отказов здесь два,
а не один: причину обязан называть СЛЕД, а причины у них не совпадают.

  · НАШ `.get("amount", 0)` — ключа в движении нет вовсе (`splinter._record_transaction`);
  · МОСТОВОЙ `Number(p.amount) || 0` — ключ есть, но значение числом не является: `null`,
    строка, логическое (`bridge_prod/BotData.js:484`). Наш `.get` такое пропускает МИМО себя
    (ключ-то есть), и ноль рождается уже за сетью — а ответ приходит `{ok:true, saved:true}`,
    то есть неотличимый от честной записи.

ПОЧЕМУ ЭТО ХУЖЕ ОБЫЧНОЙ ОШИБКИ. Сумма движения приходит от РАЗБОРА, а не от хранилища: её
называет модель по тексту человека. Хранилище тут не спрашивают вовсе — значит ни один слой
ниже не может заметить, что числа не было: лист примет ноль, баланс от нуля не сдвинется,
расписка скажет «записал», человек услышит «Записал +0 ฿» и пойдёт дальше. Строка при этом
ЛЯЖЕТ и будет неотличима от настоящей проводки на ноль.

СУДИТСЯ ПОДСТАНОВКА, А НЕ ЗНАЧЕНИЕ. Ноль, КОТОРЫЙ НАЗВАЛИ, — число как всякое другое, и модуль
его пропускает: «0» в разборе есть ответ, а не его отсутствие. Отказывает он ровно там, где
числа не было и его собирались ПОДСТАВИТЬ. Это прямое следствие предмета: класс не про величину,
а про происхождение.

ТРИ ИСХОДА, А НЕ ДВА — тот же замок против ложного зелёного, что у `balance_fact`, О3 и
контракта клетки: «сумма названа» возвращается РОВНО ОДНИМ путём (значение разбирается в
КОНЕЧНОЕ число), всё прочее — названный отказ, и отказа два, потому что мест подстановки два.

ГРАНИЦА УСТРОЙСТВОМ: импорт РОВНО ОДИН — `balance_fact` (у него свой один, `write_fact`).
Различитель «это число?» берётся у него ГОТОВЫМ (`balance_fact._num`: логическое числом не
считается — `True` это `true`, а не сумма), второго способа сказать то же самое здесь не
заводится — тот же приём, которым `tests/test_undo_door.py` берёт `mirror_sync._is_num`. Своё
здесь ровно одно и оно денежное: БЕСКОНЕЧНОСТЬ И НЕ-ЧИСЛО СУММОЙ НЕ БЫВАЮТ, а `float("nan")`
разбирается молча и в листе стал бы пустой ячейкой. Рук у модуля нет: ни моста, ни файла, ни
времени — факты приносит вызывающий. Проверяется разбором (ast) инвариантом `MONEY_AMOUNT_PURE`,
а не докстрингом.

Руки — `splinter._record_transaction` (ворота записи и переноса) и `splinter._handle_money`
(ветки `undo` и `balance_check`). Тесты `tests/test_money_amount.py`.
"""
import balance_fact

#: Исход, при котором деньги пишутся. Один.
STATE_SAID = "said"
#: Отказ 1: поля нет вовсе — ноль подставил бы НАШ `.get(<поле>, 0)`, не доехав до сети.
STATE_ABSENT = "absent"
#: Отказ 2: поле есть, числом не является — ноль подставил бы МОСТ (`Number(x) || 0`).
STATE_UNPARSED = "unparsed"

#: Поле, которым сумма зовётся и в движении разбора, и в ответах моста (`void_last`).
FIELD = "amount"

_INF = float("inf")


class Amount:
    """Что система вправе сказать о сумме. Читать `.said`, произносить `.say()`.

    `value` есть ТОЛЬКО у `said` — у отказов его нет и придумать его нечем: ровно это и было
    дефектом. `raw` хранится не ради значения, а ради следа: отказ обязан назвать, ЧТО пришло
    вместо числа, иначе журнальная строка не отличит `null` от строки «пятьсот».
    """

    __slots__ = ("state", "value", "raw", "where")

    def __init__(self, state, value=None, raw=None, where=""):
        self.state = state
        self.value = value
        self.raw = raw
        self.where = str(where or "")

    @property
    def said(self):
        """ТОЛЬКО разобранное конечное число. Подстановка сюда не попадает по построению."""
        return self.state == STATE_SAID

    def say(self):
        """Одна строка для журнала — всегда называет, ГДЕ подставился бы ноль.

        Место подстановки и есть причина: по нему видно, чей это ноль — наш или мостовой, — а
        значит и что чинить, если строка появится снова."""
        who = f" [{self.where}]" if self.where else ""
        if self.state == STATE_SAID:
            return f"сумма названа числом: {self.value}{who}"
        if self.state == STATE_ABSENT:
            return (f"сумма НЕ НАЗВАНА — поля «{FIELD}» нет вовсе{who}; "
                    f"ноль подставил бы наш .get(\"{FIELD}\", 0), и в лист ушла бы строка на 0")
        return (f"сумма НЕ ЧИСЛО ({self.raw!r}){who}; наш .get её пропускает — ключ есть, — "
                f"а ноль подставил бы мост (Number(x) || 0) и ответил бы «записал»")

    def __repr__(self):
        return f"Amount({self.state}: value={self.value!r}, raw={self.raw!r}, where={self.where!r})"


def verdict(src, field=FIELD, where=""):
    """Движение разбора ИЛИ ответ моста → `Amount`. Судит ТОЛЬКО принесённое.

    Один вход на оба случая намеренно: и движение кассы, и ответ `void_last` называют сумму
    одним и тем же полем, и подстановка в них одна и та же. Два судьи о том же смысле разошлись
    бы — ровно тот класс, против которого стоит весь модуль.

    Источник не словарь → `ABSENT`: поля нет ни в каком смысле, и это честнее, чем выдумывать
    для него третий отказ."""
    if not isinstance(src, dict):
        return Amount(STATE_ABSENT, None, None, where)
    if field not in src:
        return Amount(STATE_ABSENT, None, None, where)
    raw = src.get(field)
    num = balance_fact._num(raw)
    if num is None:
        return Amount(STATE_UNPARSED, None, raw, where)
    # Бесконечность и не-число деньгами не бывают: `float("nan")` разбирается молча, доезжает
    # до листа и становится там ПУСТОЙ ячейкой — то есть тем же исчезнувшим числом, только без
    # нуля. Проверяется без `math`: импорт здесь ровно один, и он не про арифметику.
    if num != num or num == _INF or num == -_INF:
        return Amount(STATE_UNPARSED, None, raw, where)
    return Amount(STATE_SAID, num, raw, where)
