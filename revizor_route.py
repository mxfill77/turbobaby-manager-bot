#!/usr/bin/env python3
"""НАХОДКА ПО ЗАМОРОЖЕННОМУ КОНТУРУ НЕ РОЖДАЕТ КАРТОЧКУ — ЧИСТОЕ РЕШЕНИЕ, БЕЗ ВВОДА-ВЫВОДА.

ОСНОВАНИЕ (живой факт). Сводная карточка ревизора 244 копилась 30.3 ч (03.08 13:20 → 04.08
19:37), приехала владельцу списком из 24 находок и была отклонена кнопкой 06.08 13:16 —
подтверждать было нечего: 16 находок из 24 несут метку производителя «[клиентский контур, нужна
твоя отмашка…]», а клиентский контур ЗАМОРОЖЕН решением владельца. По рамке такие находки идут
в СПИСОК, не в работу; список — не вопрос, значит и кнопки у него быть не должно.

╔══════════════════════════════════════════════════════════════════════════════════════════╗
║ ГЛАВНОЕ СВОЙСТВО: ЭТО ПРАВИЛО УМЕЕТ ТОЛЬКО НЕ СПРАШИВАТЬ. ОНО НИЧЕГО НЕ РАЗРЕШАЕТ.        ║
║                                                                                          ║
║ Возврат — разбор ТЕКСТА карточки на «что уходит заметкой» и «что остаётся вопросом».      ║
║ Слова «approved», моста, очереди и Telegram здесь нет физически (импорт ровно один — re), ║
║ поэтому худший исход ошибки — «находка уехала в ленту вместо кнопки», а не «операция      ║
║ прошла без спроса». Ревизор при этом НЕ глушится: он продолжает находить и складывать     ║
║ находки в ту же карточку, его спул на ПК правило не видит и видеть не может.              ║
╚══════════════════════════════════════════════════════════════════════════════════════════╝

КОНТУР НЕ УГАДЫВАЕТСЯ — ЕГО НАЗЫВАЕТ ПРОИЗВОДИТЕЛЬ. Ревизор сам пишет в строку находки
аннотацию `[клиентский контур, нужна твоя отмашка; клиентские файлы: suggest.py]` (либо
`…; файлы не названы — контур неопределим, держим по fail-closed`). Мы читаем ЕГО метку, а не
ищем «клиентские» слова в цитате клиента: метка признаётся ТОЛЬКО в аннотирующей позиции —
открывающей квадратной скобке (то же правило исполняющей позиции, что у маркера NEEDS_APPROVAL
и у имён операций в гарде). Цитата клиента, где эти слова стоят просто текстом, находкой по
замороженному контуру НЕ считается.

ЗАМОРОЗКА — ФАКТ, КОТОРЫЙ МЕНЯЕТСЯ, ПОЭТОМУ ОНА РУЧКА, А НЕ КОНСТАНТА. `frozen_keys()` читает
строку окружения (`CONTOUR_FREEZE`, дефолт `client` = сегодняшнее состояние по решению
владельца). Пусто/`0`/`off`/незнакомый ключ → пустое множество → `route()` отдаёт тело
БАЙТ-В-БАЙТ и `changed=False`, то есть поведение прежнее до последнего символа. Разморозил
контур — правило умерло одной строкой в .env и рестартом, код трогать не нужно.

ГРАНИЦА «НЕЗАМОРОЖЕННЫЕ ВЕДУТ СЕБЯ КАК ПРЕЖДЕ» — устройством, а не обещанием: строка без метки
контура не трогается вовсе (она остаётся в карточке на своём месте и в своём порядке), а
карточка, где таких строк не осталось, гаснет ЦЕЛИКОМ только если в ней не осталось ни одной
находки-вопроса.
"""
import re

# Ключ контура → (имя для человека, метка производителя в АННОТИРУЮЩЕЙ позиции).
# Метка живая, снята со снимка очереди 06.08.2026 (карточка 244, 16 строк из 24):
#   «• [класс в] окно 690197908: [клиентский контур, нужна твоя отмашка; клиентские файлы: …]»
# Требование открывающей скобки — и есть позиция: так пишет МАШИНА-производитель, а в цитате
# клиента эти слова стоят голым текстом.
_CONTOURS = {
    "client": ("клиентский", re.compile(r"\[\s*клиентск\w*\s+контур\b", re.I)),
}
# Строка-находка = маркированный пункт списка. Шапка карточки («🔍 Ревизор: находки — требуют
# твоего решения…») пунктом не является и остаётся в карточке всегда.
_BULLET_RE = re.compile(r"^\s*[•·‣∙*\-–—]\s+\S")
_BULLET_STRIP = re.compile(r"^\s*[•·‣∙*\-–—]\s+")     # снять маркер, СОДЕРЖИМОЕ не тронуть
_CLASS_RE = re.compile(r"^\s*[•·‣∙*\-–—]\s*\[\s*класс\s+([^\]]{1,20})\]")
_WINDOW_RE = re.compile(r"\bокно\s+(\d+)")
_OFF = ("", "0", "off", "no", "none", "нет", "-")     # ручка выключена → правила нет вовсе
_LINE_CAP = 150              # телефонная строка заметки; полный текст — в артефакте
NOTE_TOP = 3                 # сколько находок показываем в заметке поимённо


def frozen_keys(value):
    """Строка ручки → множество ключей ЗАМОРОЖЕННЫХ контуров.

    Пусто / `0` / `off` / незнакомый ключ → пустое множество: правило мертво, карточки идут как
    раньше. Ошибаться безопаснее в сторону «не заморожено»: лишняя карточка владельцу — шум,
    а лишнее молчание — потерянный вопрос."""
    s = str(value if value is not None else "").strip().lower()
    if s in _OFF:
        return frozenset()
    return frozenset(k for k in re.split(r"[,;\s]+", s) if k in _CONTOURS)


def contour_name(key):
    """Человеческое имя контура по ключу («client» → «клиентский»); неизвестный ключ → он сам."""
    return _CONTOURS[key][0] if key in _CONTOURS else str(key)


def contour_of(line, frozen):
    """Ключ ЗАМОРОЖЕННОГО контура, названный в строке-находке производителем, иначе None.
    Не находка (шапка, пустая строка, хвост) → None ВСЕГДА: чужие строки правило не трогает."""
    if not frozen or not _BULLET_RE.match(str(line or "")):
        return None
    for key in sorted(frozen):
        spec = _CONTOURS.get(key)
        if spec and spec[1].search(line):
            return key
    return None


def fingerprint(line):
    """Ключ дедупа находки: пробелы схлопнуты, маркер пункта снят. Одна и та же строка,
    приехавшая в карточке второй раз, второй заметки не рождает."""
    s = " ".join(str(line or "").split())
    return _BULLET_STRIP.sub("", s, count=1).strip()


def _trim(line, cap=_LINE_CAP):
    s = " ".join(str(line or "").split())
    return s if len(s) <= cap else s[:cap - 1] + "…"


def _display(line):
    """Строка находки для ЗАМЕТКИ: снят маркер пункта (заметка ставит свой) и снята аннотация
    контура — заголовок заметки и так говорит, что все находки в ней по этому контуру, а в
    строке она съедала полтекста. Это сжатие ПОКАЗА, а не потеря: артефакт несёт строки
    ДОСЛОВНО, и путь к нему стоит в самой заметке."""
    s = _BULLET_STRIP.sub("", " ".join(str(line or "").split()), count=1)
    for _name, mark in _CONTOURS.values():
        s = re.sub(mark.pattern + r"[^\]]*\]\s*", "", s, flags=re.I)
    return _trim(s.strip())


def _plural(n):
    """«1 находка / 2 находки / 16 находок» — карточку читает человек, а не парсер."""
    n = abs(int(n))
    if 11 <= n % 100 <= 14:
        return "находок"
    if n % 10 == 1:
        return "находка"
    if 2 <= n % 10 <= 4:
        return "находки"
    return "находок"


def _tally(findings):
    """Классы и окна находок → короткая строка-раскладка («классы: в×6, д×4 · окон 7»)."""
    classes, windows = {}, set()
    for line, _key in findings:
        m = _CLASS_RE.match(line)
        cls = m.group(1).strip() if m else "?"
        classes[cls] = classes.get(cls, 0) + 1
        w = _WINDOW_RE.search(line)
        if w:
            windows.add(w.group(1))
    part = ", ".join(f"{k}×{n}" for k, n in
                     sorted(classes.items(), key=lambda kv: (-kv[1], kv[0])))
    out = []
    if part:
        out.append("классы: " + part)
    if windows:
        out.append(f"окон {len(windows)}")
    return " · ".join(out)


def route(body, frozen):
    """Тело сводной карточки ревизора → куда что едет.

    → {"frozen": [(строка, ключ), …], "card": текст карточки | None, "changed": bool}

    changed=False  — находок замороженного контура нет: `card` = тело БАЙТ-В-БАЙТ, вызывающий
                     обязан вести себя как раньше (граница «незамороженные как прежде»).
    card=None      — вопросов в карточке не осталось вовсе: карточке взяться неоткуда.
    card=текст     — карточка из тех же строк в том же порядке МИНУС уехавшие в ленту, плюс одна
                     служебная строка о том, сколько их и куда они делись (молча из карточки не
                     исчезает ничего)."""
    text = str(body or "")
    lines = text.splitlines()
    out_frozen, kept = [], []
    for ln in lines:
        key = contour_of(ln, frozen)
        if key:
            out_frozen.append((ln.strip(), key))
        else:
            kept.append(ln)
    if not out_frozen:
        return {"frozen": [], "card": text, "changed": False}
    if not any(_BULLET_RE.match(l) for l in kept):
        return {"frozen": out_frozen, "card": None, "changed": True}
    names = sorted({contour_name(k) for _l, k in out_frozen})
    tail = (f"🔕 Ещё {len(out_frozen)} {_plural(len(out_frozen))} этой карточки — "
            f"по ЗАМОРОЖЕННОМУ контуру "
            f"({', '.join(names)}): они уехали заметкой в ленту, решения не требуют и здесь не "
            f"спрашиваются. Кнопка ниже — только про находки выше.")
    return {"frozen": out_frozen, "card": "\n".join(kept).rstrip() + "\n\n" + tail,
            "changed": True}


def note(findings, window_label="", artifact="", top=NOTE_TOP):
    """Суточная сводка для ленты: сколько находок, чего они касаются, три поимённо, где целиком.

    Заметка НЕ содержит ни номера карточки, ни слова «да», ни кнопок — на неё не отвечают
    (правило ленты). Поимённо показываем `top` строк: остальное названо числом и лежит в
    артефакте — иначе список из 16 строк превратил бы ленту в ту же простыню, из-за которой
    правило и заводится."""
    if not findings:
        return ""
    names = sorted({contour_name(k) for _l, k in findings})
    head = (f"🔕 Ревизор · находки по ЗАМОРОЖЕННОМУ контуру ({', '.join(names)}): "
            f"{len(findings)}")
    second = ("Контур заморожен решением владельца — в работу такие находки не идут. Это список "
              "на потом, ответа не требует.")
    third = " · ".join(x for x in (window_label, _tally(findings)) if x)
    body = [head, second] + ([third] if third else [])
    shown = [f"• {_display(l)}" for l, _k in findings[:max(0, int(top or 0))]]
    body += shown
    rest = len(findings) - len(shown)
    if rest > 0 or artifact:
        line = f"…ещё {rest}" if rest > 0 else "список целиком"
        body.append(line + (f" — целиком: {artifact}" if artifact else " — только здесь"))
    return "\n".join(body)


def artifact_text(findings, window_label=""):
    """Полный список находок для файла-артефакта (в чат едет итог, тело — в артефакт)."""
    head = [f"# Находки ревизора по замороженному контуру — {len(findings)}"]
    if window_label:
        head.append(window_label)
    head.append("")
    head.append("Контур заморожен решением владельца: в работу эти находки не идут, кнопки у них "
                "нет. Разморозится контур — они здесь и будут списком того, что копилось.")
    head.append("")
    return "\n".join(head + [f"- {' '.join(str(l).split())}" for l, _k in findings]) + "\n"
