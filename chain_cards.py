# -*- coding: utf-8 -*-
"""ЖУРНАЛ РОЖДЕНИЯ КАРТОЧЕК — то, чего не хватает при РАЗБОРЕ, сохраняется при РОЖДЕНИИ
(11.08.2026, цель «снизить долю цепочек с неразобранным сортом»).

────────────────────────────────────────────────────────────────────────────────────────────
ЗАЧЕМ. Сорт вмешательства (`chain_series.sort_card`) считается ПО ОПЕРАЦИИ, которую карточка
называла. Спросить об этом можно только у ТЕЛА карточки, а очередь его ЗАТИРАЕТ своим же
вердиктом: у записи, дошедшей до владельца, `result` держал карточку, пока она висела, а после
ответа там лежит «отклонено Филиппом» либо рапорт конверта. Замер 11.08.2026 (снимок очереди,
489 записей, 304 закрытых цепочки) назвал цену числом: неразобранных цепочек **64**, и **58 из
них** держатся ровно на затёртом теле — 41 полосы pc и 17 полосы vps. Остальные 6 — операционные
семьи, состояние которых с этой машины не наблюдается вовсе; их не лечит ничто, и они честно
остаются «неизвестно».

ПОЧЕМУ ОТДЕЛЬНЫЙ ЖУРНАЛ, А НЕ ФАЙЛ СОСТОЯНИЯ. `chain_series.json` — состояние ЖИВОГО счёта: оно
урезается по `SERIES_KEEP`, его сверяет `--verify`, и в нём нет и не должно быть полосы pc (её
цепочки VPS не исполняет, терминалов их он не видит — цепочка никогда бы не закрылась). Журнал
же — ФАКТ МИРА, записанный единственным свидетелем, который был на месте в момент события. Ровно
так замер уже относится к `orchestrator_daemon.log`: окна METRICS он берёт из журнала демона и
без них не судит ремонт руками.

ЧТО ХРАНИМ. Ровно то, что нужно СОРТУ, и ни байтом больше: номер записи, метка (когда карточку
увидели живой), полоса, откуда узнали, ПЕРЕЧЕНЬ ОПЕРАЦИЙ (их называет `curator_ops` — тот же
словарь, которым машина зовёт операции сама) и первые 200 символов тела — человеку, чтобы можно
было глазами проверить, о чём была карточка. Тело целиком не храним: сорту оно не нужно, а
журнал не должен становиться второй копией очереди.

ЗАДНИМ ЧИСЛОМ ЖУРНАЛ НЕ ЗАПОЛНЯЕТСЯ НИКОГДА. В нём есть только то, что записано в момент
события; карточка, родившаяся до появления журнала, останется неразобранной — и это правильно:
догадка о сорте хуже пустоты.

ЖИЗНЬ КАРТОЧКИ, А НЕ ТОЛЬКО ЕЁ РОЖДЕНИЕ (16.08.2026, зеркало ПК-коммита cc1c779). У записи два
вида: РОЖДЕНИЕ (`src`, тело головой) и ТЕРМИНАЛ (`end` — исход одним словом, объект ярлыком
операции). Оба вида живут в ОДНОМ файле: у карточки одна жизнь, и её конец нельзя искать в другом
месте, помня о существовании второго места. Читателей всё равно два и они не путаются —
`load()["cards"]` отдаёт РОВНО рождения (контракт замера не изменился ни на поле), `ends()` —
РОВНО терминалы.

ЗАМОК. Промах чтения и пустой журнал — РАЗНЫЕ ответы: `load` отдаёт `None`, если журнал НЕ
ПРОЧИТАН, и словарь (пусть и пустой), если прочитан. `note` при неудаче НЕ возвращает `False`:
ложь неотличима от честного «писать было нечего» — он бросает, а решать, что делать с провалом,
обязан вызывающий (у демона на это своя ветка: цепочка помечается «не разобрана»). Тот же счёт
слепоты, что ведёт `blind_readers`.
"""
import json
import os

REPO = os.path.dirname(os.path.abspath(__file__))
CARDS_FILE = os.path.join(REPO, "chain_cards.jsonl")
KEEP = 5000                    # строк журнала (≈8 карточек в сутки — год с запасом)
HEAD = 200                     # символов тела: человеку на глаз, машине хватает `ops`

BORN = "рождение"              # карточку записал тот, кто её создал (полоса vps)
SEEN = "первый вид"            # карточку увидели живой в чужой полосе (pc): раньше нельзя

# ── ТЕРМИНАЛ КАРТОЧКИ (16.08.2026, зеркало класса, закрытого на полосе ПК коммитом cc1c779) ──
# ЗАЧЕМ. Рождение карточки журнал знал, а КОНЕЦ её жизни — нет: «да» и «нет» владельца не
# оставляли строки нигде (замер этой полосы 16.08.2026 — в шапке артефакта
# docs/artifacts/2026-08-16-guard-terminal-log-vps.md). Вопрос «чем кончилась карточка N» после
# ответа владельца не отвечал никто: очередь ЗАТИРАЕТ тело карточки её же вердиктом, а devbot,
# который «да»/«нет» применяет, не пишет о них ни слова.
#
# ИСХОД — ОДНО СЛОВО ИЗ ЗАКРЫТОГО СЛОВАРЯ, и слов ЧЕТЫРЕ, а не три: четвёртое — честное «закрыто»
# для случая, когда карточка перестала висеть, а доказательства исхода у нас нет. Догадка здесь
# была бы хуже незнания (тот же замок против ложного зелёного, что у О3 и `write_fact`): «отказ»,
# выведенный из «раз не одобрено, значит отклонено», выдал бы за факт чужое молчание.
FIELD = "end"                  # поле, по которому терминал отличается от рождения
APPROVED = "разрешено"         # владелец ответил «да» — доказано статусом approved в очереди
REJECTED = "отказ"             # владелец ответил «нет» — доказано вердиктом devbot в поле result
EXPIRED = "истекло"            # подтверждение сгорело по часам — сделал сам демон (hard-cap 24ч)
CLOSED = "закрыто"             # карточка ушла из needs_approval, исход НЕ ДОКАЗАН — так и пишем
OUTCOMES = (APPROVED, REJECTED, EXPIRED, CLOSED)


def entry(tid, at, lane, src, ops, body):
    """Одна запись журнала. Форма зафиксирована ЗДЕСЬ и только здесь — у формата один хозяин,
    иначе писатель и читатель разойдутся молча (класс «одна команда, две реализации»)."""
    return {
        "id": int(tid),
        "at": str(at or ""),
        "lane": str(lane or "vps"),
        "src": str(src or BORN),
        "ops": [str(o) for o in (ops or [])],
        "head": str(body or "")[:HEAD],
    }


def end_entry(tid, at, lane, outcome, ops):
    """Запись ТЕРМИНАЛА карточки: номер · исход одним словом · время · объект операции.

    ПОЛЯ ДЛЯ СВОБОДНОГО ТЕКСТА ЗДЕСЬ НЕТ ВОВСЕ, и это не аккуратность, а устройство: «объект»
    называется ЯРЛЫКОМ семьи операции (`curator_ops`: `service:splinter`, `set_fleet_oil`,
    `sheet:I16`, `git_push`…) — тем же словарём, которым машина зовёт операции сама. Тело команды,
    путь к файлу секретов и содержимое конфигов положить сюда НЕКУДА: у записи нет поля, в
    которое они поместились бы (у рождения такое поле есть — `head`, 200 символов тела, — и
    именно поэтому терминал его НЕ повторяет). Объекта не назвали → пустой список, и читатель
    видит честное «объект не назван», а не выдуманное имя."""
    if outcome not in OUTCOMES:
        raise ValueError("исход карточки назван словом вне словаря: %r" % (outcome,))
    return {
        "id": int(tid),
        "at": str(at or ""),
        "lane": str(lane or "vps"),
        FIELD: str(outcome),
        "ops": [str(o) for o in (ops or [])],
    }


def _read(path):
    """Сырые записи журнала В ПОРЯДКЕ ФАЙЛА | None — журнал НЕ ПРОЧИТАН (файла нет, доступа нет).

    Один читатель на два вида записей: рождение и терминал живут в ОДНОМ журнале — у карточки
    одна жизнь, и смотреть её конец в другом файле пришлось бы, помня о существовании второго
    файла. Битые строки считаются, а не пропускаются молча."""
    try:
        with open(path or CARDS_FILE, encoding="utf-8") as f:
            raw = f.readlines()
    except OSError:
        return None
    recs, broken = [], 0
    for line in raw:
        s = line.strip()
        if not s:
            continue
        try:
            d = json.loads(s)
            int(d["id"])                      # номер обязателен обоим видам записей
            recs.append(d)
        except (ValueError, TypeError, KeyError):
            broken += 1
    return {"recs": recs, "lines": len(raw), "broken": broken}


def load(path=None):
    """Журнал → {"cards": {id: РОЖДЕНИЕ}, "lines": прочитано, "broken": не разобрано} | None.

    `None` = ЖУРНАЛ НЕ ПРОЧИТАН (файла нет, доступа нет). Пустой словарь `cards` = журнал есть и
    он пуст. Разница обязательна: «не знаю» и «ничего не было» — разные ответы, и второй нельзя
    выдавать за первый (тот же класс «нуль по неразбору»). Битые строки не молчат — их считают.

    16.08.2026: `cards` — по-прежнему РОВНО записи рождения. Терминалы (поле `end`) сюда не
    попадают вовсе: у замера контракт «карточка → её тело и операции при рождении», и запись об
    исходе, севшая на тот же номер, молча подменила бы его. Терминалы отдаёт `ends`."""
    r = _read(path)
    if r is None:
        return None
    cards, broken = {}, r["broken"]
    for d in r["recs"]:
        if FIELD in d:
            continue
        cards[int(d["id"])] = d
    return {"cards": cards, "lines": r["lines"], "broken": broken}


def ends(path=None):
    """Журнал → {id: ТЕРМИНАЛ} | None («не прочитан», та же разница, что у `load`)."""
    r = _read(path)
    if r is None:
        return None
    out = {}
    for d in r["recs"]:
        if FIELD in d:
            out[int(d["id"])] = d
    return out


def _rewrite(path, recs, line):
    """Урезка: журнал не растёт вечно. Режем СТАРОЕ — новое дороже, а разобранная цепочка уже
    унесла свой сорт в состояние счёта. Порядок ФАЙЛА сохраняется, поэтому терминал уезжает
    вместе со своим рождением, а не остаётся исходом без карточки."""
    keep = [json.dumps(r, ensure_ascii=False) for r in recs][-(KEEP - 1):]
    tmp = str(path) + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(keep + [line]) + "\n")
    os.replace(tmp, path)


def note(path, tid, at, lane, src, ops, body):
    """Записать рождение карточки. → True (записано ИЛИ уже было). Неудача НЕ ВОЗВРАЩАЕТСЯ
    пустым значением, а БРОСАЕТ: `False` здесь неотличим от честного «нечего писать», а решение,
    чем платить за провал, принадлежит вызывающему, а не журналу.

    Повтор по тому же номеру записи не плодит строк: полосу pc демон видит каждый оборот, и без
    этого журнал рос бы копиями одной карточки."""
    have = _read(path)
    if have is not None and any(FIELD not in d and int(d["id"]) == int(tid)
                                for d in have["recs"]):
        return True
    rec = entry(tid, at, lane, src, ops, body)
    line = json.dumps(rec, ensure_ascii=False)
    if have is not None and have["lines"] + 1 > KEEP:
        _rewrite(path, have["recs"], line)
        return True
    with open(path, "a", encoding="utf-8") as f:
        f.write(line + "\n")
    return True


def note_end(path, tid, at, lane, outcome, ops):
    """Записать ТЕРМИНАЛ карточки. → True (записано ИЛИ уже было). Контракт тот же, что у `note`:
    неудача БРОСАЕТ, а не отдаёт пустое — «не смогли» и «нечего писать» обязаны различаться.

    Дедуп по номеру: у карточки один конец. Первое записанное слово и остаётся — доказанный исход
    приходит раньше честного «закрыто» по построению (см. `_card_end_flush` в демоне: «закрыто»
    выкладывается САМОЙ ПОСЛЕДНЕЙ строкой оборота, когда все доказательства уже сказали своё)."""
    have = _read(path)
    if have is not None and any(FIELD in d and int(d["id"]) == int(tid) for d in have["recs"]):
        return True
    rec = end_entry(tid, at, lane, outcome, ops)
    line = json.dumps(rec, ensure_ascii=False)
    if have is not None and have["lines"] + 1 > KEEP:
        _rewrite(path, have["recs"], line)
        return True
    with open(path, "a", encoding="utf-8") as f:
        f.write(line + "\n")
    return True
