"""РАБОТЫ БЫЛИ НА ДРУГОМ ПРОБЕГЕ — ТРЕТИЙ ИСХОД КАРТОЧКИ ПОДТВЕРЖДЕНИЯ (25.08.2026).

ПОВОД, НАЗВАННЫЙ ВЛАДЕЛЬЦЕМ. Он вносит работы РАЗНЫХ дней, а все они цепляются к одному
текущему числу: пробег в разговоре ОДИН на тему, и у отдельной работы своего пробега нет вовсе
(проверено чтением кода, см. §«ЧТО БЫЛО ДО»). Выхода у него было два — подтвердить всё на
текущем числе либо не подтверждать ничего; третьего («это было на другом пробеге») не было.

ПРАВИЛО ВЛАДЕЛЬЦА (узел мозга `business_rules`, прочитан ЖИВЬЁМ этим заходом, разделы
«ОБЯЗАТЕЛЬНЫЕ ПОЛЯ РАБОТЫ 23.08.2026» и «ПОЛНОТА ИСТОРИИ РАБОТ 23.08.2026»), дословно по сути:
у КАЖДОЙ записанной работы обязательны ДАТА и ПРОБЕГ, нет любого из двух — работа НЕ
записывается; несколько работ одной датой — норма, каждая пишется своей строкой; сумма
необязательна и ОТДЕЛЬНЫМ вопросом не спрашивается. Тот же узел прямо называет эту дыру:
«Внесение работ ЗАДНИМ ЧИСЛОМ — с их настоящими датами и пробегами — этим правилом не описано и
на 23.08 не построено». Заход строит РОВНО это и ничего сверх.

ЧТО БЫЛО ДО (факты кода, а не пересказ). Буфер работ `splinter._PENDING_WORKS` ключуется ТЕМОЙ
и держит у позиции только ТЕКСТ и возраст — поля пробега у позиции нет ни одного. Единая дверь
выгрузки `_km_door(bridge, chat, topic, bike, km, …)` дописывает ВЕСЬ буфер ОДНИМ числом `km`.
Карточка фазы 2 (`_sp_advance_to_confirm`) кладёт в токен ОДИН `odo`, и `_sp_write_done` пишет
им КАЖДУЮ позицию партии. Дата же не называлась НИКОГДА: во все двери едет `msg_date` =
`str(msg.date.date())`, то есть день сообщения.

ЗАМОК ПРОТИВ ЛОЖНОГО ЗЕЛЁНОГО (тот же, что у `write_fact`, О3 и `odo_lower`): исход `READY`
возвращается РОВНО ОДНИМ путём — разобран ПРОБЕГ и разобрана ДАТА, оба в допустимых границах.
Всё прочее — отказ, и КАЖДЫЙ отказ говорит человеку, ЧТО прислать, а не диагноз. Направление
сомнения — в сторону НЕ ПИСАТЬ: правило владельца запрещает запись без любого из двух полей,
поэтому непонятый ответ не становится «наверное, сегодня».

ДОРОГА ПОНИЖЕНИЯ НЕ ИЗОБРЕТАЕТСЯ ВТОРОЙ РАЗ, и это устройством: `odo_lower` импортируется, и у
него берутся ГОТОВЫМИ и различитель расхождения (`diff`), и приёмка письменного пояснения
(`explanation_verdict`), и потолок хранимого текста (`EXPLANATION_MAX`), и словарь односложного
согласия внутри них. Второго набора исходов о том же смысле здесь нет — разойдясь, они дали бы
человеку два разных ответа на одно пояснение.

ЧЕМ БАТЧ ОТЛИЧАЕТСЯ ОТ ПОНИЖЕНИЯ, И ПОЧЕМУ ТЕКСТ ВОПРОСА СВОЙ. `odo_lower` спрашивает о
ПОНИЖЕНИИ ТЕКУЩЕГО ПРОБЕГА, и его руки (`splinter._odo_lower_commit`) в конце зовут
`_odo_confirmed` → `_odo_store`, то есть двигают одометр байка. Здесь одометр НЕ двигается ни в
одной ветке (требование владельца), поэтому переиспользуется РЕШЕНИЕ дороги, а не её руки; текст
вопроса свой, потому что и вопрос другой — не «понизить ли пробег», а «эти работы были на
пробеге ниже нынешнего, объясни». Судится и режется пояснение ТЕМ ЖЕ кодом.

ГРАНИЦА УСТРОЙСТВОМ: импортов РОВНО ТРИ и каждый назван — `re` (разобрать число и дату из
свободного текста), `datetime` (существует ли такая дата в календаре; СВОИХ ЧАСОВ НЕТ, «сегодня»
приносят руки параметром `today`), `odo_lower` (готовая дорога понижения). Ни сети, ни записи,
ни моста: спросить мир нечем, значит и записать мимо правила нечем. Проверяется разбором (ast)
инвариантом `BATCH_ODO_PURE`, а не докстрингом.

Тесты `tests/test_batch_odo.py` (решение) и `tests/test_batch_odo_path.py` (путь целиком, на
ВЫДУМАННЫХ байках). Артефакт `docs/artifacts/2026-08-25-works-own-mileage.md`.
"""
import re
import datetime

import odo_lower

#: Ручка отката. `BATCH_ODO=0` → третьей кнопки нет вовсе и путь мёртв ДО разбора чего-либо.
FLAG_ENV = "BATCH_ODO"

#: Исходы разбора ответа человека. `READY` — один, остальные отказы, и каждый называет действие.
READY = "ready"
NEED_BOTH = "need_both"
NEED_KM = "need_km"
NEED_DATE = "need_date"
BAD_KM = "bad_km"
BAD_DATE = "bad_date"

#: Границы пробега — ЗЕРКАЛО живого валидатора одометра `splinter` (`\d{3,6}` в ветке записи
#: масла задним числом). Своих границ не заводим: разойдясь, две мерки одного числа пропустили
#: бы в историю то, что регистр не примет.
KM_MIN = 100
KM_MAX = 999999

#: Насколько глубоко в прошлое принимаем дату партии. Год — потому что история байка живёт
#: годами, а всё, что дальше, вероятнее опечатка в году, чем настоящая работа.
MAX_AGE_DAYS = 400

#: Метка кнопки на карточке подтверждения работ (тайский первым — тайцы основные в обслуживании).
BUTTON_TH = "🗓 คนละเลขไมล์"
BUTTON_RU = "Работы на другом пробеге"
BUTTON_LABEL = f"{BUTTON_TH} / {BUTTON_RU}"

_TODAY_WORDS = ("сегодня", "сегодняшн", "วันนี้", "today")
_YESTERDAY_WORDS = ("позавчера", "вчера", "เมื่อวาน", "เมื่อวานนี้", "yesterday")

#: Дата: от самой длинной формы к самой короткой. Первая совпавшая ПОБЕЖДАЕТ и её кусок
#: ВЫРЕЗАЕТСЯ из текста до разбора пробега — иначе год «2026» уехал бы в километры.
_DATE_PATTERNS = (
    ("iso", re.compile(r"(?<!\d)(\d{4})-(\d{1,2})-(\d{1,2})(?!\d)")),
    ("dmy4", re.compile(r"(?<!\d)(\d{1,2})[./](\d{1,2})[./](\d{4})(?!\d)")),
    ("dmy2", re.compile(r"(?<!\d)(\d{1,2})[./](\d{1,2})[./](\d{2})(?!\d)")),
    ("dm", re.compile(r"(?<!\d)(\d{1,2})[./](\d{1,2})(?!\d)")),
)

#: Число пробега: цифры, между которыми человек волен ставить пробел или запятую («24 500»).
_NUM = re.compile(r"(?<!\d)\d[\d\s  ,]*\d(?!\d)|(?<!\d)\d(?!\d)")
_DIGITS = re.compile(r"\d")


def enabled(raw):
    """Ветка жива? Разбор — тот же, что у соседних ручек (`STEP_SELFHEAL`, `WORK_NAME`)."""
    return str(raw if raw is not None else "1").strip().lower() not in ("0", "", "нет", "no", "off")


def _int(x):
    """Целое из текста человека или None. Логическое числом не считается."""
    if isinstance(x, bool) or x is None:
        return None
    try:
        return int(re.sub(r"[\s  ,]", "", str(x)))
    except (TypeError, ValueError):
        return None


def _mk_date(y, m, d):
    """Дата или None. Календарь судит `datetime`, а не наша арифметика: «30.02» не существует."""
    try:
        return datetime.date(int(y), int(m), int(d))
    except (TypeError, ValueError):
        return None


def _word_date(low, today):
    """Дата, названная СЛОВОМ. «позавчера» проверяется ПЕРЕД «вчера» — оно его содержит."""
    if not isinstance(today, datetime.date):
        return None
    for w in _TODAY_WORDS:
        if w in low:
            return today
    if "позавчера" in low:
        return today - datetime.timedelta(days=2)
    for w in _YESTERDAY_WORDS:
        if w in low:
            return today - datetime.timedelta(days=1)
    return None


def find_date(text, today=None):
    """Дата партии из свободного текста → (дата | None, кусок текста, который она заняла).

    Год у формы «дд.мм» берётся ТЕКУЩИЙ, а если так дата оказалась бы в БУДУЩЕМ — прошлый:
    работа декабря, внесённая в январе, иначе читалась бы как ещё не случившаяся. Ошибиться тут
    можно только в сторону прошлого, а прошлое — ровно то, ради чего заход и делается."""
    raw = str(text or "")
    for kind, rx in _DATE_PATTERNS:
        m = rx.search(raw)
        if not m:
            continue
        if kind == "iso":
            d = _mk_date(m.group(1), m.group(2), m.group(3))
        elif kind == "dmy4":
            d = _mk_date(m.group(3), m.group(2), m.group(1))
        elif kind == "dmy2":
            d = _mk_date(2000 + (_int(m.group(3)) or 0), m.group(2), m.group(1))
        else:
            year = today.year if isinstance(today, datetime.date) else 1970
            d = _mk_date(year, m.group(2), m.group(1))
            if d is not None and isinstance(today, datetime.date) and d > today:
                d = _mk_date(year - 1, m.group(2), m.group(1))
        # Кусок вырезаем ВСЕГДА, даже когда дата не сложилась: «31.02.2026» это ПОПЫТКА даты, и
        # цифры из неё не должны потом сойти за километры.
        return d, raw[m.start():m.end()]
    w = _word_date(raw.lower(), today)
    return (w, "") if w else (None, "")


def find_km(text):
    """Пробег из свободного текста → (число | None, было ли вообще число).

    Второй член ответа отличает «числа не назвал» от «назвал негодное»: первому отвечают
    «пришли пробег», второму — числом, ЧТО именно не годится."""
    raw = str(text or "")
    nums = [n for n in (_int(m.group(0)) for m in _NUM.finditer(raw)) if n is not None]
    if not nums:
        return None, False
    fit = [n for n in nums if KM_MIN <= n <= KM_MAX]
    # Берём ПОСЛЕДНЕЕ годное: человек пишет «работы 15.07 на 24500» — число пробега идёт за
    # словами, а не перед ними. Годного нет — возвращаем первое названное, чтобы отказ мог
    # назвать его человеку.
    return (fit[-1] if fit else nums[0]), True


def verdict(text, today=None):
    """Ответ человека на вопрос «какой пробег и какая дата у этой партии» → исход.

    ЗАМОК: `READY` приходит РОВНО ОДНИМ путём — есть пробег в границах И есть существующая дата
    не из будущего и не старше `MAX_AGE_DAYS`. Всё прочее — отказ с названным действием."""
    raw = str(text or "")
    date, span = find_date(raw, today)
    rest = raw.replace(span, " ", 1) if span else raw
    km, had_num = find_km(rest)
    km_ok = km is not None and KM_MIN <= km <= KM_MAX
    bad_date_named = bool(span) and date is None

    if isinstance(today, datetime.date) and date is not None:
        if date > today:
            return _say(BAD_DATE, km=km if km_ok else None, date=None,
                        ru=(f"Дата {_human(date)} ещё не наступила — работы задним числом "
                            f"пишутся прошедшим днём. Пришли настоящую дату партии."),
                        th=(f"วันที่ {_human(date)} ยังมาไม่ถึงครับ งานย้อนหลังต้องเป็นวันที่ผ่านมาแล้ว "
                            f"ช่วยส่งวันที่จริงของงานชุดนี้"))
        if (today - date).days > MAX_AGE_DAYS:
            return _say(BAD_DATE, km=km if km_ok else None, date=None,
                        ru=(f"Дата {_human(date)} старше года — похоже на опечатку в годе. "
                            f"Пришли дату партии ещё раз."),
                        th=(f"วันที่ {_human(date)} เก่ากว่าหนึ่งปี น่าจะพิมพ์ปีผิดครับ "
                            f"ช่วยส่งวันที่ของงานชุดนี้อีกครั้ง"))

    if bad_date_named:
        return _say(BAD_DATE, km=km if km_ok else None, date=None,
                    ru=(f"Такой даты нет в календаре: «{span}». Пришли дату партии в виде "
                        f"дд.мм.гггг."),
                    th=(f"ไม่มีวันที่นี้ในปฏิทินครับ «{span}» ช่วยส่งวันที่แบบ วว.дд.ปปปป "
                        f"(วัน.เดือน.ปี)"))

    if had_num and not km_ok:
        return _say(BAD_KM, km=None, date=date,
                    ru=(f"Пробег {km} км не похож на правду (ждём от {KM_MIN} до {KM_MAX} км). "
                        f"Пришли пробег партии числом."),
                    th=(f"เลขไมล์ {km} กม. ดูไม่ถูกต้อง (รับตั้งแต่ {KM_MIN} ถึง {KM_MAX} กม.) "
                        f"ช่วยส่งเลขไมล์ของงานชุดนี้เป็นตัวเลข"))

    if km_ok and date is not None:
        return _say(READY, km=km, date=date, ru="", th="")

    if not km_ok and date is None:
        return _say(NEED_BOTH, km=None, date=None,
                    ru=("Нужны ДВА числа: пробег партии и её дата. Пришли одной строкой, "
                        "например: 24500 15.07.2026"),
                    th=("ต้องการสองอย่างครับ เลขไมล์ของงานชุดนี้ และวันที่ ส่งมาบรรทัดเดียวได้เลย "
                        "เช่น 24500 15.07.2026"))
    if not km_ok:
        return _say(NEED_KM, km=None, date=date,
                    ru=(f"Дату записал ({_human(date)}), не хватает ПРОБЕГА партии. "
                        f"Пришли его числом."),
                    th=(f"รับวันที่แล้วครับ ({_human(date)}) ยังขาดเลขไมล์ของงานชุดนี้ "
                        f"ช่วยส่งเป็นตัวเลข"))
    return _say(NEED_DATE, km=km, date=None,
                ru=(f"Пробег записал ({km} км), не хватает ДАТЫ партии. Пришли её "
                    f"в виде дд.мм.гггг."),
                th=(f"รับเลขไมล์แล้วครับ ({km} กม.) ยังขาดวันที่ของงานชุดนี้ "
                    f"ช่วยส่งแบบ วว.дд.ปปปป"))


def _human(date):
    """Дата человеку — дд.мм.гггг. Не дата → пустая строка (в текст отказа она и не попадёт)."""
    return date.strftime("%d.%m.%Y") if isinstance(date, datetime.date) else ""


def _iso(date):
    """Дата в запись — YYYY-MM-DD, ровно тот вид, в котором её ждёт `add_event(msg_date=…)`."""
    return date.strftime("%Y-%m-%d") if isinstance(date, datetime.date) else ""


def _say(state, km, date, ru, th):
    """Один вид ответа на все ветки: исход · разобранное · что сказать человеку."""
    return {
        "state": state,
        "ok": state == READY,
        "km": km if (km is not None and KM_MIN <= km <= KM_MAX) else None,
        "date": date if isinstance(date, datetime.date) else None,
        "date_iso": _iso(date),
        "date_human": _human(date),
        "say_ru": ru,
        "say_th": th,
    }


def question(bike, works=(), current_km=None):
    """Вопрос человеку после нажатия третьей кнопки: какой пробег и какая дата у этой партии.

    Текущее число НАЗЫВАЕТСЯ, и это не украшение: человек должен видеть, ОТ ЧЕГО он отступает,
    иначе «другой пробег» решается вслепую. Суммы отдельным вопросом НЕ спрашиваем — прямой
    запрет правила владельца («лишний оборот запрещён»)."""
    names = [str(w) for w in (works or []) if str(w or "").strip()]
    lst = ", ".join(names)
    b_ru = f" по {bike}" if bike else ""
    b_th = f" ({bike})" if bike else ""
    cur = _int(current_km)
    cur_ru = f" Сейчас на байке записано {cur} км." if cur else ""
    cur_th = f" ตอนนี้ในระบบคือ {cur} กม." if cur else ""
    ru = (f"🗓 Работы{b_ru} были на ДРУГОМ пробеге."
          + (f" Партия: {lst}." if lst else "")
          + cur_ru
          + " Пришли одной строкой ПРОБЕГ и ДАТУ этой партии — например: 24500 15.07.2026."
            " Текущий пробег байка я НЕ трогаю.")
    th = (f"🗓 งาน{b_th} ทำที่เลขไมล์อื่นครับ"
          + (f" ชุดนี้: {lst}." if lst else "")
          + cur_th
          + " ช่วยส่งเลขไมล์และวันที่ของงานชุดนี้มาบรรทัดเดียว เช่น 24500 15.07.2026"
            " เลขไมล์ปัจจุบันของรถผมไม่แตะครับ")
    return {"ru": ru, "th": th}


def lowering(recorded, named):
    """Названный пробег партии НИЖЕ записанного? Различитель берётся ГОТОВЫМ у `odo_lower.diff`.

    Своего сравнения здесь нет намеренно: разойдясь, две мерки «ниже ли» открыли бы понижение
    там, где дорога пояснения его не открывает, — то есть мимо правила владельца."""
    d = odo_lower.diff(recorded, named)
    return {"known": bool(d["known"]), "lower": bool(d["lower"]),
            "recorded": d["recorded"], "named": d["sent"], "drop": d["drop"]}


def explanation_ask(bike, low):
    """Спросить письменное пояснение, когда партия ложится НИЖЕ записанного числа.

    Расхождение показывается ЧИСЛОМ (прямое требование правила владельца), а сам вопрос свой:
    здесь не понижают одометр, здесь датируют работы прошлым — и обещание «текущий пробег не
    трогаю» повторяется, чтобы человек не решил, что соглашается на скрутку."""
    b_ru = f" по {bike}" if bike else ""
    b_th = f" ({bike})" if bike else ""
    rec, named, drop = low.get("recorded"), low.get("named"), low.get("drop")
    ru = (f"📟 Партия{b_ru} ложится на {named} км, а на байке записано {rec} км "
          f"(на {drop} км меньше). Это нормально для работ прошлым числом — но напиши своими "
          f"словами, что это была за партия и почему пробег ниже. Текущий пробег байка "
          f"я НЕ меняю.")
    th = (f"📟 งานชุดนี้{b_th} จะลงที่ {named} กม. แต่ในระบบบันทึกไว้ {rec} กม. "
          f"(น้อยกว่า {drop} กм.) งานย้อนหลังเป็นแบบนี้ได้ครับ แต่ช่วยพิมพ์เป็นคำพูดของคุณว่า "
          f"งานชุดนี้คืออะไรและทำไมเลขไมล์ต่ำกว่า เลขไมล์ปัจจุบันของรถผมไม่เปลี่ยนครับ")
    return {"ru": ru, "th": th}


def explanation_verdict(text):
    """Приёмка письменного пояснения — ЦЕЛИКОМ дорога `odo_lower`, без единой своей проверки.

    Возвращается его же словарь; отсюда даром получается, что односложное согласие («да»,
    «ใช่») пояснением не станет и здесь, а порог букв и словарь согласия остаются в ОДНОМ месте."""
    return odo_lower.explanation_verdict(text)


def receipt(bike, written, lost, km, date_human, explanation="", current_km=None, registers=()):
    """Квитанция партии. ОБЕ ПОЛОВИНЫ ИЗ ОДНОГО ИСХОДА (класс 14.08.2026: русская половина несла
    отрицательную ветку, тайская печатала успех безусловно — в одной строке механик читал
    «записано», владелец «не записано»).

    Исходов ТРИ, и третий не запасной: записано · не записано · записано НЕ ВСЁ. Потеря
    называется ПОИМЁННО — молча не исчезает ни одна работа (правило полноты истории 23.08).

    `registers` — виды партии, у которых ЕСТЬ регистр Лист1 (масло, редуктор, ABS, фильтр).
    Партия прошлым числом ложится ТОЛЬКО в историю, срок следующего ТО она не двигает, и это
    говорится вслух: умолчание читалось бы как «регистр обновлён», то есть как ложное зелёное."""
    ok = [str(w) for w in (written or [])]
    bad = [str(w) for w in (lost or [])]
    regs = [str(r) for r in (registers or []) if str(r or "").strip()]
    b_ru = f" · 📌 {bike}" if bike else ""
    cur = _int(current_km)
    keep_ru = (f" Текущий пробег байка не тронут ({cur} км)." if cur
               else " Текущий пробег байка не тронут.")
    keep_th = (f" เลขไมล์ปัจจุบันของรถไม่เปลี่ยน ({cur} กม.)" if cur
               else " เลขไมล์ปัจจุบันของรถไม่เปลี่ยนครับ")
    expl_ru = f" Пояснение сохранил: «{explanation}»." if explanation else ""
    expl_th = f" บันทึกเหตุผลไว้แล้ว: «{explanation}»" if explanation else ""
    if regs:
        keep_ru += (f" Срок следующего ТО не сдвигал ({', '.join(regs)}) — партия прошлым числом "
                    f"живёт историей, регистр держит последнюю запись.")
        keep_th += (f" ไม่ได้เลื่อนกำหนดเซอร์วิสถัดไป ({', '.join(regs)}) — งานย้อนหลังอยู่ในประวัติ "
                    f"ทะเบียนยังถือค่าล่าสุดครับ")
    if ok and not bad:
        state = "written"
        ru = (f"✅ Записал{b_ru} на {km} км, дата {date_human}: {', '.join(ok)}."
              + keep_ru + expl_ru)
        th = (f"✅ บันทึกแล้ว{b_ru} ที่ {km} กм. วันที่ {date_human}: {', '.join(ok)}"
              + keep_th + expl_th)
    elif ok and bad:
        state = "partial"
        ru = (f"⚠️ Записал{b_ru} на {km} км, дата {date_human}: {', '.join(ok)}. "
              f"НЕ легло: {', '.join(bad)} — впиши руками." + keep_ru + expl_ru)
        th = (f"⚠️ บันทึกแล้ว{b_ru} ที่ {km} กม. วันที่ {date_human}: {', '.join(ok)} "
              f"ยังไม่ได้บันทึก: {', '.join(bad)} — ต้องกรอกมือครับ" + keep_th + expl_th)
    else:
        state = "failed"
        ru = (f"⚠️ НЕ записал{b_ru} на {km} км, дата {date_human}: "
              f"{', '.join(bad) or 'работы партии'} — впиши руками." + keep_ru)
        th = (f"⚠️ ยังไม่ได้บันทึก{b_ru} ที่ {km} กм. วันที่ {date_human}: "
              f"{', '.join(bad) or 'งานชุดนี้'} — ต้องกรอกมือครับ" + keep_th)
    return {"state": state, "ru": ru, "th": th, "written": ok, "lost": bad}
