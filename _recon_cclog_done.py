lines = old.split("\n")
ins = 0
for i, ln in enumerate(lines[:80]):
    s = ln.strip()
    if s and set(s) == {"═"}:
        ins = i + 1
new = "\n".join(lines[:ins]) + ("\n" if ins else "") + note + "\n" + "\n".join(lines[ins:])
w = c.write_doc(text=new, name="cc_log")
print("WRITE cc_log:", w.get("ok"), "| old_len:", len(old), "new_len:", len(new), "| insert_at_line:", ins)

pulse = (ts + " | 🟢 | разведка CRM под капы low season снята read-only: памятка=узкий текст-мемо (кол.A, "
         "уже цены текстом), цены альт=таблица A..I (J..Z пусто), Календарь K..T пусто; код QuotePrice.js "
         "читает капы ТОЛЬКО из Календарь K3:M15 (Модель|Кап|Активен, 12 моделей) — это и есть безопасное место "
         "| ничего не жду | детали→cc_log запись «разведка капы " + ts[:10] + "»")
p = c.write_doc(text=pulse, name="pulse")
print("WRITE pulse:", p.get("ok"))
