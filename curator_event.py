"""СОБЫТИЕ, А НЕ ОБЛАСТЬ: тождество проверяемого факта между РАЗНЫМИ целями.

Куратор независим на каждом терминале: он видит СВОЮ цель и не знает, что ТОТ ЖЕ факт
уже проверяет (или уже проверила) соседняя цель. Живой класс 05.08.2026: ТЗ владельца
пришло дважды (цели 320 и 324 — дословно один заголовок, 319 и 323 — тоже), и каждая
цель родила СВОЮ журнальную проверку одного события: 330/336 и 327/334. Все четыре
холостые: «премиса не подтвердилась, запись была с самого начала».

ТОЖДЕСТВО СЧИТАЕТСЯ ПО СОБЫТИЮ, А НЕ ПО НОМЕРУ ЦЕЛИ И НЕ ПО ОБЛАСТИ:

    событие = (ВИД проверяемого факта) × (ПРЕДМЕТ — как факт НАЗВАН)

ОБЛАСТЬ (файл, модуль, сервис) предметом НЕ является НАМЕРЕННО: две цели вправе править
ОДИН файл РАЗНЫМИ правками — это разные события, запрещать их нельзя. Поэтому в предмет
идут только ИМЕНА события: коммит-хеши, имена в «кавычках» (так этот проект называет
вещи) и ЗАГОЛОВОК цели — то, как саму работу назвал владелец. Имя файла не даёт
тождества никогда; заголовок даёт, потому что повтор заголовка = повтор той же работы.

ВИД отделяет факт от факта на одном предмете: «коммит X доехал в прод» и «в журнале есть
строка о X» — РАЗНЫЕ факты об одном предмете, и дедупить их друг о друга нельзя.

Событием считается только ПРОВЕРКА (есть check-глагол в тексте). Задача-действие
(«почини», «допиши», «выложи») события не образует и под правило не попадает вовсе —
узко намеренно: цена ложного запрета выше цены лишнего холостого захода.

Чистая функция: единственный импорт — re. Ни файлов, ни сети, ни моста, ни времени.
Решение «ставить/не ставить» принимает вызывающий код (orchestrator_daemon).
"""
import re

# --- нормализация ------------------------------------------------------------
_MARK_RE = re.compile(r"^\s*\[куратор[^\]]*\](\[глубина 2\])?\s*")
_NONWORD_RE = re.compile(r"[^\w\s]", re.UNICODE)
_SPACE_RE = re.compile(r"\s+")

# Строки-директивы режима мышления: это НЕ заголовок работы, а ручка усилия.
_DIRECTIVES = {"ultrathink", "ultracode", "think", "think hard", "thinking",
               "тз", "dev", "задача", "оркестратор"}

# --- вид проверяемого факта --------------------------------------------------
# Вид отвечает на вопрос «факт О ЧЁМ», а не «о каком предмете». Один текст может нести
# несколько видов (проверь гейт И журнал) — тогда видов несколько, тождество требует
# пересечения хотя бы по одному.
_KINDS = (
    ("journal", re.compile(r"(?i)(cc_log|cclog|журнал|пульс|\bpulse\b|read_doc)")),
    ("prod", re.compile(r"(?i)(в\s+проде|живо\w*\s+(процесс|демон|splinter)|доехал|"
                        r"main\s*pid|\bpid\b|execmainstart|держит\s+стар\w+\s+код|"
                        r"в\s+памяти\s+процесса|рестарт|перезапуск)")),
    ("push", re.compile(r"(?i)(origin/main|запушен|выложен|git\s+log\s+origin|git\s+push|"
                        r"branch\s+-r)")),
)
# ГЕЙТ ВИДОМ НЕ ЯВЛЯЕТСЯ НАМЕРЕННО. «Гейт зелёный» — состояние дерева НА МОМЕНТ, а не
# факт о предмете: его обязаны прогонять заново после каждой правки, дедупить нельзя.
# Замер это подтвердил живьём: единственный ложный запрет реплея (задача 332 — правка
# CLAUDE.md — против 327) держался ровно на общем виде «гейт» и на коммите, названном
# в 332 ОБРАЗЦОМ формы, а не предметом. Убрали вид — ложный запрет исчез, оба настоящих
# совпадения (334, 336) остались.

# Признак ПРОВЕРКИ. Нет его — задача не образует события (см. докстринг).
_CHECK_RE = re.compile(r"(?i)(провер|сверь|сверить|сверк|убедис|есть\s+ли|доехал|"
                       r"подтверд|премис|выясни|прочитай|read_doc|зелён|не\s+названа|"
                       r"уже\s+есть|найди,?\s+есть)")

# --- предмет -----------------------------------------------------------------
# Коммит-хеш: 7–40 hex, отбитый неалфанумериком. Чисто цифровой принимается ТОЛЬКО
# длиной 7 (короткий git-хеш вида 9906598 — живой случай), 8+ цифр без буквы — это
# скорее дата (20260805) и предметом не считается.
_HASH_RE = re.compile(r"(?<![0-9a-zA-Z])([0-9a-f]{7,40})(?![0-9a-zA-Z])")
_HEX_LETTER_RE = re.compile(r"[a-f]")
# Имя в «кавычках» — как этот проект называет фикс/класс/правило.
_QUOTE_RE = re.compile(r"«([^»]{4,140})»")

_MIN_QUOTE = 8      # короче — не имя, а частица («да», «нет»)
_MIN_HEAD = 12      # короче — не заголовок работы
_HEAD_CUT = 100
_HEAD_LINES = 6     # заголовок ищем в первых строках ТЗ, ниже начинается тело


def _norm(s):
    """lowercase → спецсимволы в пробелы → collapse. Пусто → ''."""
    try:
        t = _NONWORD_RE.sub(" ", str(s or "").lower())
        return _SPACE_RE.sub(" ", t).strip()
    except Exception:
        return ""


def strip_marker(text):
    """Снимает кураторский маркер «[куратор цели G, шаг m]» с начала текста."""
    return _MARK_RE.sub("", str(text or ""))


def goal_head(goal):
    """ЗАГОЛОВОК цели: первая содержательная строка ТЗ, нормализованная. Строки-директивы
    режима («ultrathink») и слишком короткие пропускаются. Нет заголовка → ''."""
    for raw in str(goal or "").splitlines()[:_HEAD_LINES]:
        n = _norm(strip_marker(raw))
        if not n or n in _DIRECTIVES or len(n) < _MIN_HEAD:
            continue
        return n[:_HEAD_CUT]
    return ""


def kinds(text):
    """Виды проверяемого факта в тексте → frozenset (может быть пустым)."""
    t = str(text or "")
    return frozenset(name for name, rx in _KINDS if rx.search(t))


def is_check(text):
    """Текст говорит о ПРОВЕРКЕ факта (а не только о действии)?"""
    return bool(_CHECK_RE.search(str(text or "")))


def subjects(task_text, goal=""):
    """ПРЕДМЕТ события: коммит-хеши и имена в «кавычках» ИЗ ТЕКСТА ЗАДАЧИ + заголовок
    ЦЕЛИ. Имена файлов/модулей сюда НЕ входят — это область, а не событие.
    Из ЦЕЛИ берётся только заголовок: тело ТЗ называет десятки имён, и они бы склеили
    несвязанные проверки."""
    out = set()
    t = strip_marker(task_text)
    for h in _HASH_RE.findall(t):
        if len(h) == 7 or _HEX_LETTER_RE.search(h):
            out.add("коммит:" + h.lower())
    for q in _QUOTE_RE.findall(t):
        n = _norm(q)
        if len(n) >= _MIN_QUOTE:
            out.add("имя:" + n[:_HEAD_CUT])
    head = goal_head(goal)
    if head:
        out.add("цель:" + head)
    return frozenset(out)


def event_of(task_text, goal=""):
    """Событие задачи → {"kinds", "subjects"} или None.

    None (события нет, правило не применяется) когда: текст пуст; это не проверка;
    вид факта не распознан; предмет не назван. «Не назвал — не сравниваем» — то же
    правило, что у объектного гейта карточек: сравнить можно только НАЗВАННОЕ."""
    t = strip_marker(task_text)
    if not t.strip() or not is_check(t):
        return None
    k = kinds(t)
    if not k:
        return None
    s = subjects(task_text, goal)
    if not s:
        return None
    return {"kinds": k, "subjects": s}


def same_event(a, b):
    """Одно и то же событие? Пересечение ПО ВИДУ и ПО ПРЕДМЕТУ одновременно.
    Любой None → False (событие не образовано — запрещать нечего)."""
    if not a or not b:
        return False
    try:
        return bool(a["kinds"] & b["kinds"]) and bool(a["subjects"] & b["subjects"])
    except Exception:
        return False


def shared_subject(a, b):
    """Общий предмет двух событий (для объяснения владельцу) или ''."""
    if not a or not b:
        return ""
    try:
        common = sorted(a["subjects"] & b["subjects"])
    except Exception:
        return ""
    return common[0] if common else ""
