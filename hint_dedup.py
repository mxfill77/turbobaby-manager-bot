"""ЗАМОК ПОВТОРНЫХ ПОДСКАЗОК В ТЕМАХ БАЙКОВ (22.08.2026).

ОДНО решение на ВСЕ 14 мест, где Splinter сам шлёт совет в тему байка, — не 14 заплат.
Правило одно и читается вслух: **одна и та же подсказка по одному байку не уходит второй
раз, пока не изменилось состояние, её породившее**.

КЛЮЧ ПОВТОРА — три вещи, и все три обязательны:
  * АДРЕС   — чат + тема (тема = байк по договорённости) + имя байка;
  * ВИД     — какая именно подсказка (буквы переписи: C · D · A1 · A2 · A3 · B · E · E2 ·
              F · G · H · I · J · L);
  * СОСТОЯНИЕ — то, ЧТО эту подсказку породило, названное САМИМ местом отправки: у висяка
              это заявка (её рождение, статус и перечень работ), у повреждения — что назвал
              vision, у просрочки — пара «текущий пробег · следующий». Возраст, попытка и
              время СОСТОЯНИЕМ НЕ ЯВЛЯЮТСЯ: они меняются сами по себе, и подсказка, которая
              на них опирается, выглядит новой каждый час, ничего нового не сообщая.

ПРАВО НА ПОВТОР ПРИ ДОЛГО ДЕРЖАЩЕМСЯ СОСТОЯНИИ — `repeat_h`, боевое значение 24 ч.
Число выведено из корпуса (60 суток журнала группы обслуживания), а не взято с потолка:
  * снизу — РАБОЧАЯ СМЕНА. Часы с хоть одним сообщением людей: 03…19 UTC (плотное ядро
    03:00–12:59 = 10 ч, ночь 20:00–02:59 — ноль сообщений за все 60 суток). Самая длинная
    смена окна = 17 ч, значит повтор короче 17 ч читают ТЕ ЖЕ люди, которые уже видели первый;
  * сверху — 26 ч: за этой отметкой в распределении пауз между сообщениями людей идёт
    ПУСТОЙ промежуток 26…34 ч (корзины по 2 ч: 24…26 — шесть пауз, 26…34 — НИ ОДНОЙ,
    34…36 — одна). То есть перерыв длиннее 26 ч в этой группе означает уже пропущенные
    СУТКИ, а не ночь; ставить право на повтор дальше — молчать целый рабочий день;
  * внутри (17, 26) берём 24 — ЕДИНСТВЕННОЕ значение, кратное суткам, а значит сохраняющее
    ФАЗУ: подсказка, ушедшая в рабочее время, повторится в рабочее время. При 21 ч утренний
    повод уехал бы в мёртвую ночь, при 18 ч — тем более.
  Устойчивость измерена: на живых сериях висяка T = 18 · 20 · 24 · 27 · 30 ч дают ОДИН
  результат (8 отправок из 19), то есть ±6 ч ничего не меняют.

ГРАНИЦА, КОТОРУЮ ДЕРЖИТ УСТРОЙСТВО: **импортов НОЛЬ** (страж `HINT_DEDUP_PURE`, ast, в
гейте). Ни времени, ни диска, ни сети, ни моста у решения нет — «сейчас», прошлую запись и
пороги приносят руки (`splinter._hint_send`). Иначе замок сам ходил бы за состоянием, и
«изменилось ли оно» зависело бы от того, КАК спросили, а не от мира.

НАПРАВЛЕНИЕ СОМНЕНИЯ — В ОТПРАВКУ, и это обратно гарду намеренно. Гард решает, исполнится
ли команда; здесь не исполняется ничего — решается, УЗНАЕТ ли человек. Поэтому любая дырка
(замок выключен · адреса нет · состояние не названо · прошлая запись не читается · часы
ушли назад) даёт **отправку**, как было до замка. Замолчать по незнанию нельзя.

ЧЕГО ЗАМОК НЕ УМЕЕТ И НЕ ДОЛЖЕН: он не добавляет подсказок, не отключает ни одной и не
судит, по делу ли повод, — он умеет РОВНО не повторять. Первая отправка любого состояния
проходит ВСЕГДА.
"""

# --- исходы (словами, а не булевыми) ---------------------------------------------------
OFF = "замок выключен"
FIRST = "первая подсказка этого вида по байку"
CHANGED = "состояние изменилось"
DUE = "право на повтор: состояние держится дольше порога"
REPEAT = "повтор того же состояния"
NO_ADDR = "адрес не назван (ни темы, ни байка)"
NO_STATE = "состояние не названо"
NO_PREV = "прошлая запись не читается"
BACKWARD = "часы ушли назад"

#: сколько часов одно и то же состояние держит подсказку закрытой (обоснование — в докстринге)
REPEAT_H_DEFAULT = 24.0
#: горизонт памяти: запись старше не судится вовсе (тогда подсказка — снова «первая»)
KEEP_H_DEFAULT = 24.0 * 7

#: виды переписи 22.08.2026 — закрытый список, чтобы опечатка в месте отправки не завела
#: молча пятнадцатый «вид» со своей отдельной памятью
KINDS = (
    "A1",  # просьба фото одометра по масло-контексту
    "A2",  # переспрос одометра, фаза 2
    "A3",  # E2b-заявка без одометра
    "B",   # переспрос «что сделал»
    "C",   # совет помыть / воск / чехол
    "D",   # не хватает фото топлива и пробега
    "E",   # ТО просрочено (закреп)
    "E2",  # ТО просрочено по gear/abs/воздушному фильтру
    "F",   # висяк-напоминание
    "G",   # висяк-эскалация
    "H",   # вопрос кнопками «После замены / Просто пробег»
    "I",   # принял работы — пришли пробег
    "J",   # на фото повреждения — глянь
    "L",   # подтверди цифру пробега
)


def _norm(v):
    """Одно значение состояния → короткая устойчивая строка.

    Регистр и лишние пробелы съедаются (тот же вердикт vision, перерисованный иначе, —
    то же состояние), длина режется: состояние — ОТПЕЧАТОК, а не вторая копия сообщения.
    """
    if v is None:
        return ""
    if v is True:
        return "1"
    if v is False:
        return "0"
    if isinstance(v, (list, tuple, set, frozenset)):
        # порядок перечня работ значением не является: ['oil','gear'] и ['gear','oil'] — одно
        return ",".join(sorted(_norm(x) for x in v if _norm(x)))
    s = str(v).strip().lower()
    return " ".join(s.split())[:120]


def state_fingerprint(state):
    """Состояние (что угодно из места отправки) → отпечаток. Пусто → пустая строка."""
    if state is None:
        return ""
    if not isinstance(state, (list, tuple)):
        state = (state,)
    parts = [_norm(x) for x in state]
    if not any(parts):
        return ""
    return "|".join(parts)[:400]


def key(chat_id, topic_id, bike, kind):
    """Адрес + вид. Пустой ответ = адреса нет вовсе (тогда судить не по чему)."""
    k = _norm(kind)
    if not k:
        return ""
    addr = "%s/%s/%s" % (_norm(chat_id), _norm(topic_id), _norm(bike))
    if not _norm(topic_id) and not _norm(bike):
        return ""
    return addr + "#" + k


def verdict(kind, bike, state, prev, now, chat_id=None, topic_id=None,
            repeat_h=REPEAT_H_DEFAULT, enabled=True):
    """Решение «слать ли подсказку» — чистая функция.

    prev — прошлая запись по этому ключу: `{"fp": <отпечаток>, "ts": <секунды>}` или None.
    now  — «сейчас» в секундах, приносят руки. Возвращает словарь:
        send  — слать ли;
        why   — исход СЛОВАМИ (одна из констант модуля);
        key   — ключ памяти (пустой = адреса нет);
        fp    — отпечаток состояния;
        age_h — сколько часов прошло с прошлой отправки того же состояния (или None).
    """
    k = key(chat_id, topic_id, bike, kind)
    fp = state_fingerprint(state)
    out = {"send": True, "why": OFF, "key": k, "fp": fp, "age_h": None}
    if not enabled:
        return out
    if not k:
        out["why"] = NO_ADDR
        return out
    if not fp:
        out["why"] = NO_STATE
        return out
    if not isinstance(prev, dict):
        out["why"] = FIRST if prev is None else NO_PREV
        return out
    if prev.get("fp") != fp:
        out["why"] = CHANGED
        return out
    try:
        age_h = (float(now) - float(prev.get("ts"))) / 3600.0
    except (TypeError, ValueError):
        out["why"] = NO_PREV
        return out
    out["age_h"] = age_h
    if age_h < 0:
        out["why"] = BACKWARD
        return out
    try:
        limit = float(repeat_h)
    except (TypeError, ValueError):
        out["why"] = OFF
        return out
    if limit <= 0:
        out["why"] = OFF          # порог снят ручкой → замок не держит ничего
        return out
    if age_h >= limit:
        out["why"] = DUE
        return out
    out["send"] = False
    out["why"] = REPEAT
    return out


def prune(seen, now, keep_h=KEEP_H_DEFAULT):
    """Память старше горизонта выбрасывается: подсказка после этого снова «первая».
    Ошибка здесь стоит ОДНОЙ лишней подсказки, а не молчания, — направление то же."""
    if not isinstance(seen, dict):
        return {}
    try:
        edge = float(now) - float(keep_h) * 3600.0
    except (TypeError, ValueError):
        return dict(seen)
    out = {}
    for k, rec in seen.items():
        if not isinstance(rec, dict):
            continue
        try:
            if float(rec.get("ts")) >= edge:
                out[k] = rec
        except (TypeError, ValueError):
            continue
    return out
